#!/bin/sh
# Builds the differential test of port chunk P05 (the 51 functions of the Resampler hierarchy of dsplibs.o: Resampler, ResamplerTimingOffset,
# ResamplerTiming, V90Resampler; src/dsp/dsp_resampler.cpp, REAL C++ compiled with -fno-exceptions -fno-rtti) and runs every scenario in its OWN process:
#   blob      test/dsp/dsp_resampler.main.c + a copy of dsplibs.o in which `edprintf` is WEAK (the harness' recorder wins)       (gcc -m32 -no-pie)
#   port -O0  test/dsp/dsp_resampler.main.c + g++ -m32 -O0 P05 port object + P03 port object (LowPassFIR, mean, Var; LINKED WITH gcc: no libstdc++)
#   port -O2  same at -O2
#   port -m64 (NO64=1 skips) the same harness and the port compiled for x86-64 (SSE float default; FP64_FLAGS="-mfpmath=387" for the x87 variant);
#             its output is diffed against the 32-bit BLOB's output (the golden dump)
# The ONE harness source has no #ifdef around the code under test: the functions are reached through __asm__ labels with the mangled names.  A scenario
# exits 2 if its own coverage counters fail, 3 if a harness assumption / independent model is violated; either fails this script.
# Also checked here: the 51 blob symbols (name + binding) are defined by the port object; the 4 vtables of the port are the blob's (test/dsp/dsp_resampler.vtable_cmp.py:
# slot order, the function in every slot, size, binding); the harness mirror structs (generated by tools/layout_gen.py from test/p05.layout) equal the port
# headers' real class layouts (layout probe, every binary).
# "MATCH" is only printed if every scenario matched AND reached its branches.
#
# Env: PORT_P05 (port source under test, mutation testing), SCENARIOS, NOO2=1, NO64=1, TPREFIX (output prefix, parallel mutation runs), P05_SEED (alternative
# input stream), GOLDEN_UPDATE=1 (rewrite test/golden/p05_blob32*.out from this blob run), FP64_FLAGS (extra flags of the x86-64 port build).
# Scenarios 7 (the EXTENDED return values: 80-bit patterns, i386 only) and 8 (special values: NaN payloads, signalling NaNs; the NaN payload chosen by an SSE
# operation differs from the x87's) form the x87-only golden (test/golden/dsp/dsp_resampler.blob32.x87.out): 7 is never run on x86-64, 8 is compared on x86-64 only with
# FP64_FLAGS="-mfpmath=387".  Scenarios 0-6 (test/golden/dsp/dsp_resampler.blob32.out) must reproduce with the default SSE flags.
#
# Usage: sh test/dsp/dsp_resampler.sh   (run from slmodemd/dsplibs-port/)

set -e
cd "$(dirname "$0")/../.."
. test/blob.sh   # BLOB_O: the blob oracle (dsplibs.o), see test/blob.sh

PORT_P05="${PORT_P05:-src/dsp/dsp_resampler.cpp}"
PORT_P03="${PORT_P03:-src/dsp/dsp_window_fft_psd.cpp}"
T="${TPREFIX:-test/.build/dsp/dsp_resampler}"
mkdir -p "$(dirname "$T")"
CF="-m32 -Wall -Wextra -Wno-unused-function -O0 -g"
HCF="-m32 -Wall -Wextra -Wno-unused-function -O2 -g"
CXXF="-Wall -Wextra -fno-exceptions -fno-rtti -Isrc"
LD32="-no-pie"
SCENARIOS="${SCENARIOS:-0 1 2 3 4 5 6 7 8}"
case "$T" in /*) R="";; *) R="./";; esac   # absolute TPREFIX (mutation / coverage tools) needs no "./"

# the shared stubs, with the allocator and the debug printf renamed (the harness owns sysdep_malloc / sysdep_free: allocation table + log; dsplibs_debug_printf: recorder)
SRENAME="-Dsysdep_malloc=stub_env_unused_malloc -Dsysdep_free=stub_env_unused_free -Ddsplibs_debug_printf=stub_env_unused_dbgprintf"
gcc $CF $SRENAME -c test/stub_env.c -o ${T}_stub_env.o
g++ -m32 $CXXF -O2 -c test/p05_layout_probe.cpp -o ${T}_probe.o
gcc $HCF -c test/harness/harness.c -o ${T}_harness.o     # the shared harness library (test/harness/, plain C)
objcopy --weaken-symbol=edprintf $BLOB_O ${T}_dsplibs_weak.o

gcc $HCF $LD32 -o ${T}_test_blob test/dsp/dsp_resampler.main.c ${T}_harness.o ${T}_stub_env.o ${T}_probe.o ${T}_dsplibs_weak.o

g++ -m32 $CXXF -O0 -g -c $PORT_P05 -o ${T}_port_o0.o
# the P03 port object (LowPassFIR / mean / Var) is cached: rebuilt only when its sources are newer (mutation runs build this script hundreds of times)
P03C=test/.build/dsp/dsp_resampler_p03cache   # not under ${T}: shared by the mutation runs, which set TPREFIX
mkdir -p "$(dirname "$P03C")"
p03dep() { [ ! -f "$1" ] || [ "$PORT_P03" -nt "$1" ] || [ src/core/dsp_math.h -nt "$1" ] || [ src/dsp/dsp_window_fft_psd.h -nt "$1" ] || [ src/core/dsp_cxx.h -nt "$1" ]; }
p03dep ${P03C}_o0.o && g++ -m32 $CXXF -O0 -g -c $PORT_P03 -o ${P03C}_o0.o
gcc $HCF $LD32 -o ${T}_test_port test/dsp/dsp_resampler.main.c ${T}_harness.o ${T}_stub_env.o ${T}_probe.o ${T}_port_o0.o ${P03C}_o0.o
if [ -z "$NOO2" ]; then
  g++ -m32 $CXXF -O2 -g -c $PORT_P05 -o ${T}_port_o2.o
  p03dep ${P03C}_o2.o && g++ -m32 $CXXF -O2 -g -c $PORT_P03 -o ${P03C}_o2.o
  gcc $HCF $LD32 -o ${T}_test_port_o2 test/dsp/dsp_resampler.main.c ${T}_harness.o ${T}_stub_env.o ${T}_probe.o ${T}_port_o2.o ${P03C}_o2.o
fi

# symbol check: every symbol of the 4 classes in the blob exists, with the same name and binding, in the port object
BLOBSYMS=$(nm --defined-only $BLOB_O | grep -E '_Z(N|NK)(9Resampler|21ResamplerTimingOffset|15ResamplerTiming|12V90Resampler)' | awk '{print $2" "$3}' | sort)
PORTSYMS=$(nm --defined-only ${T}_port_o2.o 2>/dev/null || nm --defined-only ${T}_port_o0.o)
MISSING=$(echo "$BLOBSYMS" | while read b s; do echo "$PORTSYMS" | grep -q " $b $s\$" || echo "$b $s"; done)
NBLOB=$(echo "$BLOBSYMS" | wc -l)
if [ -n "$MISSING" ]; then echo "SYMBOL MISMATCH (blob symbol missing / different binding in the port object):"; echo "$MISSING"; exit 1; fi
echo "SYMBOLS: all $NBLOB blob symbols (name + binding) are defined by the port object"
python3 test/dsp/dsp_resampler.vtable_cmp.py $BLOB_O ${T}_port_o2.o >/dev/null 2>&1 || python3 test/dsp/dsp_resampler.vtable_cmp.py $BLOB_O ${T}_port_o0.o >/dev/null
python3 test/dsp/dsp_resampler.vtable_cmp.py $BLOB_O ${T}_port_o0.o > /dev/null || { echo "VTABLE MISMATCH (-O0)"; python3 test/dsp/dsp_resampler.vtable_cmp.py $BLOB_O ${T}_port_o0.o; exit 1; }
[ -n "$NOO2" ] || python3 test/dsp/dsp_resampler.vtable_cmp.py $BLOB_O ${T}_port_o2.o > /dev/null || { echo "VTABLE MISMATCH (-O2)"; python3 test/dsp/dsp_resampler.vtable_cmp.py $BLOB_O ${T}_port_o2.o; exit 1; }
echo "VTABLES: the 4 vtables of the port (-O0 and -O2) have the blob's size, binding, slot order and slot functions"

if [ -z "$NO64" ]; then
  g++ -m64 $CXXF -O2 $FP64_FLAGS -c $PORT_P05 -o ${T}_port64.o
  if [ ! -f ${P03C}_64.o ] || [ "$FP64_FLAGS" != "$(cat ${P03C}_64.flags 2>/dev/null)" ] || p03dep ${P03C}_64.o; then g++ -m64 $CXXF -O2 $FP64_FLAGS -c $PORT_P03 -o ${P03C}_64.o; echo "$FP64_FLAGS" > ${P03C}_64.flags; fi
  g++ -m64 $CXXF -O2 -c test/p05_layout_probe.cpp -o ${T}_probe64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 $SRENAME -c test/stub_env.c -o ${T}_stub_env64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 -c test/harness/harness.c -o ${T}_harness64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 -no-pie -o ${T}_test_port64 test/dsp/dsp_resampler.main.c ${T}_harness64.o ${T}_stub_env64.o ${T}_probe64.o ${T}_port64.o ${P03C}_64.o
fi

# scenarios are independent processes: run them concurrently in groups, then concatenate in order
rm -f ${T}_s*.out
rc=0
pids=""
njobs=0
for i in $SCENARIOS; do
  ( ${R}${T}_test_blob "$i" > ${T}_s$i.blob.out ) & pids="$pids $!"
  ( ${R}${T}_test_port "$i" > ${T}_s$i.port.out ) & pids="$pids $!"
  if [ -z "$NOO2" ]; then ( ${R}${T}_test_port_o2 "$i" > ${T}_s$i.o2.out ) & pids="$pids $!"; fi
  if [ -z "$NO64" ] && [ "$i" != 7 ]; then ( ${R}${T}_test_port64 "$i" > ${T}_s$i.p64.out ) & pids="$pids $!"; fi
  njobs=$((njobs + 1))
  if [ $njobs -ge 2 ]; then for p in $pids; do wait $p || rc=1; done; pids=""; njobs=0; fi
done
for p in $pids; do wait $p || rc=1; done
: > ${T}_blob.out; : > ${T}_port.out; : > ${T}_port_o2.out; : > ${T}_port64.out; : > ${T}_blob64ref.out; : > ${T}_blob_x87.out
for i in $SCENARIOS; do
  if [ "$i" = 7 ] || [ "$i" = 8 ]; then
    cat ${T}_s$i.blob.out >> ${T}_blob_x87.out
    case "$FP64_FLAGS" in *387*) if [ -z "$NO64" ] && [ "$i" = 8 ]; then cat ${T}_s$i.p64.out >> ${T}_port64.out; cat ${T}_s$i.blob.out >> ${T}_blob64ref.out; fi;; esac
  else
    cat ${T}_s$i.blob.out >> ${T}_blob.out
    if [ -z "$NO64" ]; then cat ${T}_s$i.p64.out >> ${T}_port64.out; cat ${T}_s$i.blob.out >> ${T}_blob64ref.out; fi
  fi
  cat ${T}_s$i.port.out >> ${T}_port.out
  if [ -z "$NOO2" ]; then cat ${T}_s$i.o2.out >> ${T}_port_o2.out; fi
done
# the 32-bit ports (-O0 / -O2) are compared with the blob scenario by scenario (scenario 7 included): rebuild the blob reference in the same order
: > ${T}_blob_all.out
for i in $SCENARIOS; do cat ${T}_s$i.blob.out >> ${T}_blob_all.out; done
rm -f ${T}_s*.out
if [ $rc -ne 0 ]; then echo "SCENARIO FAILURE (non-zero exit: coverage, harness assertion / model violation or crash)"; exit 1; fi

diff -u ${T}_blob_all.out ${T}_port.out
if [ -z "$NOO2" ]; then diff -u ${T}_blob_all.out ${T}_port_o2.out; fi
if [ -z "$NO64" ]; then diff -u ${T}_blob64ref.out ${T}_port64.out; fi
ALL="0 1 2 3 4 5 6 7 8"
if [ -n "$GOLDEN_UPDATE" ]; then mkdir -p test/golden/dsp; cp ${T}_blob.out test/golden/dsp/dsp_resampler.blob32.out; cp ${T}_blob_x87.out test/golden/dsp/dsp_resampler.blob32.x87.out; echo "golden updated"; fi
if [ -z "$TPREFIX" ] && [ "$SCENARIOS" = "$ALL" ] && [ -f test/golden/dsp/dsp_resampler.blob32.out ] && [ -z "$P05_SEED" ]; then
  if diff -u test/golden/dsp/dsp_resampler.blob32.out ${T}_blob.out && diff -u test/golden/dsp/dsp_resampler.blob32.x87.out ${T}_blob_x87.out; then echo "GOLDEN: the 32-bit blob runs equal test/golden/dsp/dsp_resampler.blob32.out and dsp/dsp_resampler.blob32.x87.out"
  else echo "STALE GOLDEN: the blob output differs from test/golden/p05_blob32*.out (GOLDEN_UPDATE=1 rewrites them)"; exit 1; fi
fi
echo "MATCH: P05 C++ port ($([ -z "$NOO2" ] && echo '-O0 and -O2' || echo '-O0')$([ -z "$NO64" ] && echo " + x86-64 [$FP64_FLAGS] vs the 32-bit blob output")) is behaviorally identical to dsplibs.o for this test"
