#!/bin/sh
# Builds the differential test of port chunk P04 (the 11 tone-detector functions of dsplibs.o: GenericToneDetector C1 C2 D1 D2 process(float)
# process(float*, unsigned) reset, ANSamToneDetector C1 C2 D1 D2, plus the 4 coefficient tables; src/dsp/dsp_tone_detectors.cpp, REAL C++ compiled
# with -fno-exceptions -fno-rtti) and runs every scenario in its OWN process:
#   blob      test/dsp/dsp_tone_detectors.main.c + dsplibs.o                                      (gcc -m32 -no-pie)
#   port -O0  test/dsp/dsp_tone_detectors.main.c + g++ -m32 -O0 P04 port object + P02 port object  (the GenericIIR; LINKED WITH gcc: no libstdc++)
#   port -O2  same at -O2
#   port -m64 (NO64=1 skips) the same harness and the port compiled for x86-64 (SSE float default; FP64_FLAGS="-mfpmath=387" for the
#             x87 variant); its output is diffed against the 32-bit BLOB's output (the golden dump)
# The ONE harness source has no #ifdef: the functions are reached through __asm__ labels with the mangled names.  A scenario exits
# 2 if its own coverage counters fail, 3 if a harness assumption / independent model is violated; either fails this script.
# "MATCH" is only printed if every scenario matched AND reached its branches.
#
# Also checked here: the 11 blob symbols (name + binding) are all defined by the port object; the harness mirror structs (generated by
# tools/layout_gen.py from test/dsp/dsp_tone_detectors.layout and test/p02.layout) equal the port headers' real class layouts (the layout probes, every binary).
#
# Env: PORT_P04 (port source under test, mutation testing), SCENARIOS, NOO2=1, NO64=1, TPREFIX (output prefix, parallel mutation runs),
# P04_SEED (alternative input stream), GOLDEN_UPDATE=1 (rewrite test/golden/p04_blob32*.out from this blob run), FP64_FLAGS (extra flags of the
# x86-64 port build, e.g. -mfpmath=387).
# Scenarios: 0 process(float) vs model, 1 process(float*, n) vs model, 2 both on one object (generic filters), 3 ANSamToneDetector through the Generic
# interface (real tables, rates 8000 / 9600 / other), 4 exact-arithmetic trials (identity filter, small integers, power-of-two periods:
# equality boundaries), 5 constructor / reset / destructor details, 6 non-finite / special data and coefficients.
#
# Usage: sh test/dsp/dsp_tone_detectors.sh   (run from slmodemd/dsplibs-port/)

set -e
cd "$(dirname "$0")/../.."
. test/blob.sh   # BLOB_O: the blob oracle (dsplibs.o), see test/blob.sh

PORT_P04="${PORT_P04:-src/dsp/dsp_tone_detectors.cpp}"
PORT_P02="${PORT_P02:-src/dsp/dsp_float_filters.cpp}"
T="${TPREFIX:-test/.build/dsp/dsp_tone_detectors}"
mkdir -p "$(dirname "$T")"
CF="-m32 -Wall -Wextra -Wno-unused-function -O0 -g"
HCF="-m32 -Wall -Wextra -Wno-unused-function -O2 -g"
CXXF="-Wall -Wextra -fno-exceptions -fno-rtti -Isrc"
LD32="-no-pie"
SCENARIOS="${SCENARIOS:-0 1 2 3 4 5 6}"
case "$T" in /*) R="";; *) R="./";; esac   # absolute TPREFIX (mutation / coverage tools) needs no "./"

# the shared stubs, with the allocator renamed (the harness owns sysdep_malloc / sysdep_free: allocation table + log)
gcc $CF -Dsysdep_malloc=stub_env_unused_malloc -Dsysdep_free=stub_env_unused_free -c test/stub_env.c -o ${T}_stub_env.o
g++ -m32 $CXXF -O2 -c test/dsp/dsp_tone_detectors_layout_probe.cpp -o ${T}_probe.o
g++ -m32 $CXXF -O2 -c test/p02_layout_probe.cpp -o ${T}_probe02.o
gcc $HCF -c test/harness/harness.c -o ${T}_harness.o     # the shared harness library (test/harness/, plain C)

gcc $HCF $LD32 -o ${T}_test_blob test/dsp/dsp_tone_detectors.main.c ${T}_harness.o ${T}_stub_env.o ${T}_probe.o ${T}_probe02.o $BLOB_O

g++ -m32 $CXXF -O0 -g -c $PORT_P04 -o ${T}_port_o0.o
g++ -m32 $CXXF -O0 -g -c $PORT_P02 -o ${T}_p02_o0.o
gcc $HCF $LD32 -o ${T}_test_port test/dsp/dsp_tone_detectors.main.c ${T}_harness.o ${T}_stub_env.o ${T}_probe.o ${T}_probe02.o ${T}_port_o0.o ${T}_p02_o0.o
if [ -z "$NOO2" ]; then
  g++ -m32 $CXXF -O2 -g -c $PORT_P04 -o ${T}_port_o2.o
  g++ -m32 $CXXF -O2 -g -c $PORT_P02 -o ${T}_p02_o2.o
  gcc $HCF $LD32 -o ${T}_test_port_o2 test/dsp/dsp_tone_detectors.main.c ${T}_harness.o ${T}_stub_env.o ${T}_probe.o ${T}_probe02.o ${T}_port_o2.o ${T}_p02_o2.o
fi

# symbol check: every symbol of the 2 classes in the blob exists, with the same name and binding, in the port object
BLOBSYMS=$(nm --defined-only $BLOB_O | grep -E '_ZN(19GenericToneDetector|17ANSamToneDetector)' | awk '{print $2" "$3}' | sort)
PORTSYMS=$(nm --defined-only ${T}_port_o2.o 2>/dev/null || nm --defined-only ${T}_port_o0.o)
MISSING=$(echo "$BLOBSYMS" | while read b s; do echo "$PORTSYMS" | grep -q " $b $s\$" || echo "$b $s"; done)
NBLOB=$(echo "$BLOBSYMS" | wc -l)
if [ -n "$MISSING" ]; then echo "SYMBOL MISMATCH (blob symbol missing / different binding in the port object):"; echo "$MISSING"; exit 1; fi
echo "SYMBOLS: all $NBLOB blob symbols (name + binding) are defined by the port object"

if [ -z "$NO64" ]; then
  g++ -m64 $CXXF -O2 $FP64_FLAGS -c $PORT_P04 -o ${T}_port64.o
  g++ -m64 $CXXF -O2 $FP64_FLAGS -c $PORT_P02 -o ${T}_p02_64.o
  g++ -m64 $CXXF -O2 -c test/dsp/dsp_tone_detectors_layout_probe.cpp -o ${T}_probe64.o
  g++ -m64 $CXXF -O2 -c test/p02_layout_probe.cpp -o ${T}_probe02_64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 -Dsysdep_malloc=stub_env_unused_malloc -Dsysdep_free=stub_env_unused_free \
      -c test/stub_env.c -o ${T}_stub_env64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 -c test/harness/harness.c -o ${T}_harness64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 -no-pie -o ${T}_test_port64 test/dsp/dsp_tone_detectors.main.c ${T}_harness64.o ${T}_stub_env64.o ${T}_probe64.o ${T}_probe02_64.o ${T}_port64.o ${T}_p02_64.o
fi

# scenarios are independent processes: run them concurrently in groups, then concatenate in order
rm -f ${T}_s*.out
rc=0
pids=""
njobs=0
for i in $SCENARIOS; do
  ( ${R}${T}_test_blob "$i" > ${T}_s$i.blob.out ) & pids="$pids $!"
  ( ${R}${T}_test_port "$i" > ${T}_s$i.port.out ) & pids="$pids $!"
  if [ -z "$NOO2" ]; then ( ${R}${T}_test_port_o2 "$i" > ${T}_s$i.o2.out ) & pids="$pids $!"; fi
  if [ -z "$NO64" ]; then ( ${R}${T}_test_port64 "$i" > ${T}_s$i.p64.out ) & pids="$pids $!"; fi
  njobs=$((njobs + 1))
  if [ $njobs -ge 2 ]; then for p in $pids; do wait $p || rc=1; done; pids=""; njobs=0; fi
done
for p in $pids; do wait $p || rc=1; done
: > ${T}_blob.out; : > ${T}_port.out; : > ${T}_port_o2.out; : > ${T}_port64.out; : > ${T}_blob64ref.out
for i in $SCENARIOS; do
  cat ${T}_s$i.blob.out >> ${T}_blob.out
  cat ${T}_s$i.port.out >> ${T}_port.out
  if [ -z "$NOO2" ]; then cat ${T}_s$i.o2.out >> ${T}_port_o2.out; fi
  if [ -z "$NO64" ]; then cat ${T}_s$i.p64.out >> ${T}_port64.out; cat ${T}_s$i.blob.out >> ${T}_blob64ref.out; fi
done
rm -f ${T}_s*.out
if [ $rc -ne 0 ]; then echo "SCENARIO FAILURE (non-zero exit: coverage, harness assertion / model violation or crash)"; exit 1; fi

diff -u ${T}_blob.out ${T}_port.out
if [ -z "$NOO2" ]; then diff -u ${T}_blob.out ${T}_port_o2.out; fi
if [ -z "$NO64" ]; then diff -u ${T}_blob64ref.out ${T}_port64.out; fi
if [ -n "$GOLDEN_UPDATE" ]; then mkdir -p test/golden/dsp; cp ${T}_blob.out test/golden/dsp/dsp_tone_detectors.blob32.out; echo "golden updated"; fi
if [ -z "$TPREFIX" ] && [ "$SCENARIOS" = "0 1 2 3 4 5 6" ] && [ -f test/golden/dsp/dsp_tone_detectors.blob32.out ] && [ -z "$P04_SEED" ]; then
  if diff -u test/golden/dsp/dsp_tone_detectors.blob32.out ${T}_blob.out; then echo "GOLDEN: the 32-bit blob runs equal test/golden/dsp/dsp_tone_detectors.blob32.out"; else echo "STALE GOLDEN: the blob output differs from test/golden/dsp/dsp_tone_detectors.blob32.out (GOLDEN_UPDATE=1 rewrites it)"; exit 1; fi
fi
echo "MATCH: P04 C++ port ($([ -z "$NOO2" ] && echo '-O0 and -O2' || echo '-O0')$([ -z "$NO64" ] && echo " + x86-64 [$FP64_FLAGS] vs the 32-bit blob output")) is behaviorally identical to dsplibs.o for this test"
