/*
 * Shared differential-test harness library for the C++ chunks (P01 onwards), extracted from test/p01_diff_main.c.
 * PLAIN C (C99, no C++), so that it links with 32-bit (-m32 -no-pie, against dsplibs.o or the port) and 64-bit builds.
 *
 *   - PRNG with a bijective finaliser (h_rnd / h_rmod / h_rrange / h_rpct) and a SEPARATE object-fill generator
 *     (the random fill of an object must not depend on sizeof, which differs between i386 and x86-64);
 *   - canonical output: every line is hashed (FNV-1a 64) and optionally printed; the last line of a scenario is
 *     "HASH <h> lines <n>", so the stdout of one scenario is architecture independent and the 32-bit BLOB run is the
 *     golden a 64-bit port run is diffed against;
 *   - coverage counters (h_cov_define / h_cov_hit; h_cov_finish exits 2 when a REQUIRED counter is zero);
 *   - h_die3: harness / independent-model violation (exit 3);
 *   - sysdep_malloc / sysdep_free (DEFINED here: link without test/stub_env.c's versions, i.e. build that with
 *     -Dsysdep_malloc=stub_env_unused_malloc -Dsysdep_free=stub_env_unused_free): deterministic bump allocator in an
 *     arena that is mmap-ed so that 0x80000000 lies 4 MB inside it (signed pointer compares), 48-byte poisoned red
 *     zones, freed blocks poisoned, allocation TABLE (sorted by address) and LOG ("M id size" / "F id", hashed);
 *   - object pool (h_obj_new: random-filled, NOT logged), pointer normalisation ("A<id>+<off>", never a raw address);
 *   - field-wise object dump from a per-class field table (HFld; the tables are generated by tools/layout_gen.py for
 *     new classes), with the heap blocks the object owns, and the malloc-time snapshot probe (which fields were
 *     already stored when a constructor called sysdep_malloc);
 *   - float helpers: floats are printed as BIT PATTERNS, never with %f (NaN payloads, signed zero, denormals).
 *
 * Field kinds (HFld.kind):
 *   'b' u8   'h' u16   'u' u32   'i' i32   'f' float32 (printed as 8 hex digits)   'd' double (16 hex digits)
 *   'p' pointer into / to a heap block, normalised to "A<id>+<off>" / "NULL" / "WILD"
 *   'o' OWNING heap pointer: like 'p', and the whole block it points to is appended to the line (hex up to 192 bytes, else a hash)
 *   'e' pointer to an EMBEDDED sub-object / into the object itself: "E+<byte offset from the object base>"
 *   'v' vptr: "V:<registered vtable name>+<off>" (h_register_vtable) or "V:?"
 *   'x' unknown region of `count` bytes (hex, hashed above 64 bytes)
 * `count` > 1 makes a scalar kind an array of `count` elements (printed in brackets).
 */
#ifndef H_HARNESS_H
#define H_HARNESS_H

#include <stddef.h>
#include <stdint.h>
#include <string.h>

typedef unsigned long long u64;

/* ---- PRNG ---- */
void h_seed_xor(unsigned int seed_word);   /* g_lcg ^= seed_word * 2654435761 (the P01_SEED hook) */
unsigned int h_rnd(void);
unsigned int h_rmod(unsigned int m);
int h_rrange(int lo, int hi);
int h_rpct(int pct);

/* ---- output ---- */
void h_die3(const char *fmt, ...) __attribute__((noreturn, format(printf, 1, 2)));
void h_emit(int show, const char *fmt, ...) __attribute__((format(printf, 2, 3)));
void h_hash_bytes(const void *p, size_t n);
int h_sample(unsigned long *ctr, unsigned long first, unsigned long k);
uint32_t h_garbage_hi(uint32_t lo8);       /* garbage in the upper 24 bits of a byte argument */
uint32_t h_bits_of(float f);
float h_float_from_bits_quiet(uint32_t b); /* keeps the bits except that a signalling NaN is made quiet */
float h_float_from_bits(uint32_t b);       /* bits exactly (memcpy; a by-value use may still go through the x87 on i386!) */

/* x87 environment: the blob never changes the precision control; asserts (exit 3) that the control word is the process default
 * (64-bit mantissa, round to nearest) on i386 / x86-64, a no-op elsewhere */
void h_x87_check(void);

/* ---- coverage ---- */
#define H_COV_MAX 128
#define H_COV_STRADDLE 60                  /* reserved ids: trials with the block around 2^31 / dtor with a NULL block pointer */
#define H_COV_DTOR_NULL 61
extern unsigned char h_covreq[H_COV_MAX];
void h_cov_define(int id, const char *name);
void h_cov_hit(int id);
void h_cov_finish(void);                   /* prints the COV lines + HASH line; exit(2) if a required counter is zero */

/* ---- allocator ---- */
typedef struct {
  uint8_t *p;
  uint32_t size;
  uint32_t id;
  int freed;
} HAl;
extern HAl *h_al;                          /* allocation table of the current trial (sorted by address) */
extern unsigned h_last_alloc;              /* table index of the most recent allocation */
extern unsigned long h_nmalloc, h_nfree;
extern int h_rz_by_id;                    /* 1: the red-zone bytes depend on the block id (a copy of one block's red zone into another's is then detected); default 0 = all 0xCC */
extern unsigned h_log_next_size;           /* one-shot: the next sysdep_malloc logs this size in the "M id size" line (sizeof of an object with pointers differs on x86-64); 0 = off */
void h_log_map_add(unsigned from, unsigned to); /* persistent (P29): up to 8 further (from -> to) log-size pairs for several pointer-holding classes (default: none); h_log_map_clear() removes them */
void h_log_map_clear(void);
extern unsigned h_log_map_from, h_log_map_to; /* persistent: a sysdep_malloc of exactly h_log_map_from bytes is logged as h_log_map_to bytes (several heap objects with pointers); 0 = off */
extern unsigned h_fail_malloc_n;           /* set to n: the n-th next sysdep_malloc returns NULL (once; 1 = the next one); used to fail a constructor's LAST allocation */
extern int h_fail_next_malloc;             /* set to 1: the next sysdep_malloc returns NULL (once); used where the blob tests a malloc result */
extern unsigned h_live;
extern unsigned h_wild;                    /* number of WILD pointers seen by h_fmt_ptr since the last reset by the harness */
void h_arena_init(void);
void h_scenario_begin(int elem4);          /* elem4: blocks hold 4-byte elements (alignment of the 2^31 straddle); 2: only 2-byte alignment (P42) */
void h_trial_end(const char *what);        /* red zones, leak report, next independent trial (heap + object pool reset) */
void h_check_redzones(void);
void h_check_not_wild(const char *what);
void *h_obj_new(size_t sz);                /* random-filled object memory (own generator), 16-aligned */
void h_pool_reset(void);
int h_maybe_null_first_ptr(void *o, int pct); /* dtor-with-NULL-block probe; returns 1 if it did */
HAl *h_find_al(const void *q, int allow_end);
void h_fmt_ptr(char *out, const void *p);  /* out >= 48 bytes */
void *sysdep_malloc(unsigned size);
void sysdep_free(void *q);

/* ---- field tables / dump ---- */
typedef struct {
  const char *name;
  size_t off;      /* platform offset (offsetof of the harness mirror struct) */
  char kind;
  unsigned count;  /* 0 / 1 = scalar, > 1 = array of `count`; for 'x' the byte length */
} HFld;
#define HFLD(T, m, k) { #m, offsetof(T, m), k, 0 }
#define HFLDN(T, m, k, n) { #m, offsetof(T, m), k, n }
void h_dump_obj(int show, const char *tag, const void *obj, const HFld *f, int nf);
void h_register_vtable(const void *vt, const char *name);

/* malloc-time probe: while the ctor runs, every sysdep_malloc records which fields of the object were already stored */
extern const uint8_t *h_mp_obj, *h_mp_shadow;
extern const void *h_mp_flds;
extern int h_mp_nf;
#define H_CTOR_PROBE(o, flds, nf, sz, call)                                                                      \
  do {                                                                                                          \
    uint8_t shadow_[(sz)];                                                                                      \
    memcpy(shadow_, (o), (sz));                                                                                 \
    h_mp_obj = (const uint8_t *)(o); h_mp_shadow = shadow_; h_mp_flds = (flds); h_mp_nf = (nf);                 \
    call;                                                                                                       \
    h_mp_obj = NULL;                                                                                            \
  } while (0)

/* ---- layout cross-check (the generated tables of tools/layout_gen.py use it) ---- */
/* compares two unsigned arrays (mirror vs probe); dies naming the class on the first difference */
void h_layout_compare(const char *cls, const unsigned *mirror, const unsigned *probe, unsigned n);

#endif /* H_HARNESS_H */
