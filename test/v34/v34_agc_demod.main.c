/*
 * Differential test harness for V.34 "tier 2" hand-cleaned functions
 * (src/v34/v34_agc_demod.c): bitreverse, V34agc, V34demodulate (LOCAL in the blob,
 * reached by symbol-address arithmetic - see call_demod), V34ModulatorProcess,
 * V34GiveProbeResults, v34FreezeEcho, V34SetINFO0dBits, V34GiveINFO0dBits,
 * V34GiveINFO1aBits, V34SetINFO0aBits, V34InitializeImplementationSpecific.
 *
 * One source, two binaries (same convention as test/v34/v34_dsp_primitives.main.c):
 *   v34_tier2_test_blob  - linked against the real dsplibs.o, built with -DTEST_BLOB
 *   v34_tier2_test_port  - linked against src/v34/v34_agc_demod.c + src/v34/v34_dsp_primitives.c
 *                          + src/v34/v34_timing_hilbert_tables.c + src/fpm/fpm_tables.c
 * Each scenario runs in its OWN process (argv[1]) - the real blob shows an
 * intermittent segfault when many scenarios share a process (see
 * test/build_and_diff_v32_primitives.sh).
 *
 * tagV34Object is not laid out as a struct: the harness builds a fake object
 * (OBJSZ bytes, deterministically random-filled so stray writes anywhere in
 * it are caught) and pokes byte offsets through the accessor macros below.
 * Pointer-bearing state is hashed with the in-object pointer slots
 * NORMALISED to offsets (raw addresses differ between the two processes) and
 * the external-pointer slots zeroed - hash_obj(). Buffers reached through
 * pointers (tables, ctx sub-objects, output buffers) are hashed by contents.
 *
 * Every scenario keeps COVERAGE COUNTERS, derived from observable
 * before/after state (not from the code under test's internals), prints
 * them, and exits 2 if a branch class the scenario is supposed to reach was
 * never reached.
 */

