    V34SetINFO0dBits(o, sinfo);
    V34I_UNREG(sinfo);
    V34SetINFO0aBits(o, info);
    printf("set: %04x %04x %04x %04x\n", info[0], info[1], info[2], info[3]);
    V34GiveINFO0dBits(o, info);
