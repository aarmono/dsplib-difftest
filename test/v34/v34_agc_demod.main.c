#define OBJSZ 0xb400u

/* ---- deterministic LCG ---- */
static unsigned int g_lcg = 0x34345a5au;
static unsigned int lcg_next(void) {
  g_lcg = g_lcg * 1103515245u + 12345u;
  return g_lcg;
}
static short lcg_short(void) { return (short)(lcg_next() >> 16); }
static unsigned int lcg_mod(unsigned int m) { return (lcg_next() >> 8) % m; }

static unsigned int fnv(unsigned int h, const void *p, size_t n) {
  const unsigned char *b = (const unsigned char *)p;
  size_t i;
  for (i = 0; i < n; i++) {
    h ^= b[i];
    h *= 16777619u;
  }
  return h;
}
#define FNV0 2166136261u

static void fill_random(void *p, size_t n) {
  unsigned char *b = (unsigned char *)p;
  size_t i;
  for (i = 0; i < n; i++) b[i] = (unsigned char)(lcg_next() >> 16);
}

/* in-object pointer slots: normalised to offsets in hash_obj */
static const unsigned int k_inobj_slots[] = {0x4,    0x130,  0x2074, 0x80b8, 0x80bc, 0x80c0, 0x80c4,
                                            0x80c8, 0x9138, 0x913c, 0x9140, 0x9144, 0x9148};
/* external pointer slots: zeroed in hash_obj (never modified by the functions under test) */
static const unsigned int k_ext_slots[] = {0x10, 0x1b4, 0xc24, 0xcb0, 0x3548, 0xac18};

/* fill_random can (rarely, ~1e-5 per slot) produce a value that lands inside this process's object and would be
 * normalised to an offset in only one of the two processes; scrub every hashed pointer slot to a value in an
 * unmapped range (0x0dxxxxxx) after any random fill. */
static void scrub_slots(unsigned char *o) {
  size_t i;
  for (i = 0; i < sizeof k_inobj_slots / sizeof k_inobj_slots[0]; i++) U32(o, k_inobj_slots[i]) = 0x0d000000u | (lcg_next() & 0xffffffu);
  for (i = 0; i < sizeof k_ext_slots / sizeof k_ext_slots[0]; i++) U32(o, k_ext_slots[i]) = 0x0d000000u | (lcg_next() & 0xffffffu);
}

static unsigned int hash_obj(const unsigned char *obj) {
  unsigned char tmp[OBJSZ];
  size_t i;
  memcpy(tmp, obj, OBJSZ);
  for (i = 0; i < sizeof k_inobj_slots / sizeof k_inobj_slots[0]; i++) {
    uint32_t v;
    memcpy(&v, tmp + k_inobj_slots[i], 4);
    if ((uintptr_t)v >= (uintptr_t)obj && (uintptr_t)v < (uintptr_t)obj + OBJSZ) v = 0x80000000u | (uint32_t)((uintptr_t)v - (uintptr_t)obj);
    memcpy(tmp + k_inobj_slots[i], &v, 4);
  }
  for (i = 0; i < sizeof k_ext_slots / sizeof k_ext_slots[0]; i++) memset(tmp + k_ext_slots[i], 0, 4);
  return fnv(FNV0, tmp, OBJSZ);
}

static int g_fail = 0;
static void need(const char *name, long v) {
  printf("  coverage %s = %ld\n", name, v);
  if (v <= 0) {
    fprintf(stderr, "COVERAGE FAILURE: %s never reached\n", name);
    g_fail = 1;
  }
}

/* ===================== scenario 0: bitreverse ===================== */
static void scen_bitreverse(void) {
  static const short special_n[] = {-32768, -1000, -40, -17, -16, -2, -1, 100, 300, 1000, 32767};
  unsigned int h;
  int n;
  size_t i;
  long calls = 0;
  /* exhaustive over x for the in-range widths */
  for (n = 0; n <= 16; n++) {
    unsigned int x;
    h = FNV0;
    for (x = 0; x < 65536; x++) {
      unsigned short r = bitreverse((unsigned short)x, (short)n);
      h = fnv(h, &r, 2);
      calls++;
    }
    printf("bitreverse nbits=%d exhaustive hash=%08x r(1)=%04x r(0x8000)=%04x r(0xffff)=%04x\n", n, h,
           bitreverse(1, (short)n), bitreverse(0x8000, (short)n), bitreverse(0xffff, (short)n));
  }
  /* out-of-range / negative widths (blob behaviour matched, not assumed) */
  for (n = -20; n <= 40; n++) {
    int k;
    h = FNV0;
    for (k = 0; k < 400; k++) {
      unsigned short x = (unsigned short)(k < 8 ? (k == 0 ? 0 : k == 1 ? 0xffff : k == 2 ? 0x8000 : k == 3 ? 1 : k == 4 ? 0x5555 : k == 5 ? 0xaaaa : k == 6 ? 0x7fff : 0x0100) : lcg_next() >> 16);
      unsigned short r = bitreverse(x, (short)n);
      h = fnv(h, &r, 2);
      calls++;
    }
    printf("bitreverse nbits=%d random hash=%08x r(0xffff)=%04x r(0x8001)=%04x\n", n, h, bitreverse(0xffff, (short)n),
           bitreverse(0x8001, (short)n));
  }
  for (i = 0; i < sizeof special_n / sizeof special_n[0]; i++) {
    int k;
    h = FNV0;
    for (k = 0; k < 200; k++) {
      unsigned short x = (unsigned short)(lcg_next() >> 16);
      unsigned short r = bitreverse(x, special_n[i]);
      h = fnv(h, &r, 2);
      calls++;
    }
    printf("bitreverse nbits=%d special hash=%08x r(0xffff)=%04x\n", (int)special_n[i], h, bitreverse(0xffff, special_n[i]));
  }
  printf("bitreverse total calls=%ld\n", calls);
}

