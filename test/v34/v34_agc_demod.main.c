#define TABPAD 1024
#define TABN 4096
static short *g_tab_alloc;
static short *g_tab;

/* Seeds the AGC/demod front-end fields of `o` with a randomly chosen regime. */
/* the agc/demod seed only randomises bytes [0,0x260): scrub the slots in that range */
static void scrub_slots_low(unsigned char *o) {
  U32(o, 0x4) = 0x0d000000u | (lcg_next() & 0xffffffu);
  U32(o, 0x130) = 0x0d000000u | (lcg_next() & 0xffffffu);
  U32(o, 0x10) = 0x0d000000u | (lcg_next() & 0xffffffu);
  U32(o, 0x1b4) = 0x0d000000u | (lcg_next() & 0xffffffu);
}

static void agc_seed(unsigned char *o, int demod) {
  unsigned int regime = lcg_mod(6);
  unsigned int shift = lcg_mod(16);
  int i;
  fill_random(o, 0x260);
  scrub_slots_low(o);
  S16(o, 0) = lcg_short();
  /* input pair buffer [0x0c,0x10c) */
  for (i = 0; i < 64; i++) {
    S16(o, 0x0c + 4 * i) = (short)(lcg_short() >> (regime == 0 ? 0 : (regime == 1 ? 12 : shift)));
    S16(o, 0x0c + 4 * i + 2) = (short)(lcg_short() >> (regime == 0 ? 0 : (regime == 1 ? 12 : shift)));
  }
  PTR(o, 4) = OB(o, 0x0c + 4 * lcg_mod(64));
  /* 36-entry ring */
  for (i = 0; i < 36; i++) {
    unsigned int m = lcg_mod(8);
    S16(o, 0x13c + 2 * i) = (m == 0) ? 0 : (m == 1) ? (short)(lcg_short() >> 14) : (short)(lcg_short() >> (regime == 2 ? 0 : shift));
  }
  if (regime == 3) memset(OB(o, 0x13c), 0, 72); /* E == 0 */
  if (regime == 4) for (i = 0; i < 36; i++) S16(o, 0x13c + 2 * i) = (short)((lcg_next() & 1) ? 30000 + (int)lcg_mod(2700) : -30000 - (int)lcg_mod(2700)); /* E >= 0x20000000, n==0 */
  S16(o, 0x19c) = (short)lcg_mod(36);
  /* gain */
  switch (lcg_mod(6)) {
    case 0: S16(o, 0x136) = (short)(0x10 + lcg_mod(0x300)); break;
    case 1: S16(o, 0x136) = (short)(0x300 + lcg_mod(0x300)); break;
    case 2: S16(o, 0x136) = (short)(0x6000 + lcg_mod(0x2000)); break; /* near/above 0x6a00 */
    case 3: S16(o, 0x136) = (short)(0x7000 + lcg_mod(0xfff)); break;
    case 4: S16(o, 0x136) = lcg_short(); break; /* any, incl. negative */
    default: S16(o, 0x136) = (short)(0x100 + lcg_mod(0x7000)); break;
  }
  /* level (smoothed): around 4000 +- 3000 (so |L-4000|>0x4b0 both ways) or arbitrary */
  switch (lcg_mod(4)) {
    case 0: S16(o, 0x134) = (short)(4000 + (int)lcg_mod(6001) - 3000); break;
    case 1: S16(o, 0x134) = (short)(4000 + (int)lcg_mod(1000) - 500); break; /* inside the dead band */
    case 2: S16(o, 0x134) = lcg_short(); break;
    default: S16(o, 0x134) = (short)(0x7000 + lcg_mod(0xf00)); break;
  }
  /* gain-loop integrator / coefficient */
  S16(o, 0x138) = (lcg_mod(2) ? (short)((int)lcg_mod(1200) - 600) : lcg_short());
  S16(o, 0x13a) = (lcg_mod(3) ? (short)(lcg_mod(0x7fff)) : lcg_short());
  /* flags: AGC frozen (bit 0x200) about 1/5 of the time */
  U16(o, 0x122) = (uint16_t)(lcg_next() >> 16);
  if (lcg_mod(5) == 0) U16(o, 0x122) |= 0x200; else U16(o, 0x122) &= ~0x200;
  if (demod) {
    unsigned int mod = 4 + lcg_mod(197);
    S16(o, 0x12a) = (short)(lcg_mod(6) - 1); /* -1..4 */
    U32(o, 0x12c) = (lcg_mod(3) == 0) ? lcg_next() : (lcg_next() >> lcg_mod(32));
    PTR(o, 0x130) = OB(o, 0x300 + 2 * lcg_mod(20));
    PTR(o, 0x1b4) = g_tab;
    U16(o, 0x1ba) = (uint16_t)mod;
    U16(o, 0x1b8) = (uint16_t)(lcg_mod(3) ? lcg_mod(mod) : lcg_mod(mod + 8));
    if (lcg_mod(10)) S16(o, 0x1bc) = (short)lcg_mod(mod); else S16(o, 0x1bc) = (short)((int)lcg_mod(mod + 100) - 50);
  }
}

static void tab_init(void) {
  int i;
  g_tab_alloc = (short *)malloc(sizeof(short) * (TABN + 2 * TABPAD));
  for (i = 0; i < TABN + 2 * TABPAD; i++) g_tab_alloc[i] = lcg_short();
  g_tab = g_tab_alloc + TABPAD;
}

static void scen_agc(int demod) {
  unsigned char *o = (unsigned char *)calloc(1, OBJSZ);
  V34I_REGW(o, OBJSZ, 0x264); /* x86-64: o is the RX front-end sub-object b (= object offset 0x264) */
  int calls = 6000, c;
  long n_sat = 0, n_frozen = 0, n_upd = 0, n_skip = 0, n_up = 0, n_dn = 0, n_hold = 0, n_clamp = 0, n_nodec = 0, n_cnt4 = 0, n_cntlt = 0;
  unsigned int all = FNV0;
  int need_reseed = 1;
  if (demod) tab_init();
  for (c = 0; c < calls; c++) {
    short g0, gain1, lvl1;
    int frozen, upd;
    unsigned int h, ext = FNV0;
    short cnt0 = 0;
    if (need_reseed || lcg_mod(3) == 0) {
      agc_seed(o, demod);
      need_reseed = 0;
    } else {
      /* keep evolving state, but feed fresh input samples */
      int i;
      unsigned int sh = lcg_mod(16);
      for (i = 0; i < 128; i++) S16(o, 0x0c + 2 * i) = (short)(lcg_short() >> sh);
      PTR(o, 4) = OB(o, 0x0c + 4 * lcg_mod(64));
      if (demod) PTR(o, 0x130) = OB(o, 0x300 + 2 * lcg_mod(20));
    }
    g0 = S16(o, 0x136);
    frozen = (U16(o, 0x122) & 0x200) != 0;
    if (!demod) U32(o, 0x12c) = 0xa5a5a5a5u; /* sentinel: agc stores here only when r > 0x1f */
    if (demod) cnt0 = S16(o, 0x12a);
    if (demod) {
      call_demod(o);
      ext = fnv(ext, OB(o, 0x240), 4);
    } else {
      V34agc(o);
    }
    gain1 = S16(o, 0x136);
    lvl1 = S16(o, 0x134);
    if (demod) {
      /* update happened iff count was >=3 (before +1) and not frozen and r>0x1f; observable: 0x12c reset, so
         infer "update" from a gain/level/integrator change on a count>=4 call */
      upd = ((short)(cnt0 + 1) >= 4) && !frozen;
      if ((short)(cnt0 + 1) >= 4) n_cnt4++; else n_cntlt++;
    } else {
      upd = (U32(o, 0x12c) != 0xa5a5a5a5u);
    }
    if (frozen) n_frozen++;
    if (upd) {
      n_upd++;
      if (gain1 > g0) n_up++; else if (gain1 < g0) n_dn++; else n_hold++;
      if (lvl1 == 0x7f00) n_clamp++;
      if (gain1 == g0 && S16(o, 0x138) == 0 && g0 > 0x6a00) n_nodec++;
    } else if (!frozen && !demod) {
      n_skip++;
    }
    if (!demod) {
      int i;
      for (i = 0; i < 4; i++) {
        short w = S16(o, 0x10c + 2 * i);
        if (w == 0x7f00 || w == (short)0x8100) { n_sat++; break; }
      }
    } else {
      short si = *(short *)((char *)PTR(o, 0x130) - 2);
      if (si == 0x7f00 || si == (short)0x8100) n_sat++;
    }
    /* demod: next call must start from a valid rotation index */
    if (demod) {
      short ix = S16(o, 0x1bc);
      if (ix < 0 || ix >= (short)U16(o, 0x1ba)) need_reseed = 1;
    }
    h = hash_obj(o);
    all = fnv(all, &h, 4);
    all = fnv(all, &ext, 4);
    printf("%s call %d hash=%08x\n", demod ? "demod" : "agc", c, h);
  }
  printf("%s all=%08x\n", demod ? "demod" : "agc", all);
  need("saturation-branch", n_sat);
  need("frozen", n_frozen);
  need("level/gain-update-reached", n_upd);
  if (!demod) need("update-skipped(r<=0x1f, not frozen)", n_skip);
  need("gain-up", n_up);
  need("gain-down", n_dn);
  need("level-clamp-0x7f00", n_clamp);
  need("gain-decrease-blocked(gain>0x6a00)", n_nodec);
  if (demod) {
    need("count>=4 calls", n_cnt4);
    need("count<4 calls", n_cntlt);
  }
  printf("  (hold=%ld)\n", n_hold);
  free(o);
}

/* ===================== scenario 3: V34ModulatorProcess ===================== */
/* T07: scen_mod(1) = scenario 10: taps <= 11 and stride + idx + taps <= 135, so the history channels (stride shorts apart, idx + taps deep) stay inside the 136
 * shorts in front of the tx block's pointer slots (obj+0x2220/0x2224) and the output does not depend on the i386 / x86-64 layout behind them; scen_mod(0) is
 * the original scenario 3 */
static void scen_mod(int inrange) {
  unsigned char *o = (unsigned char *)calloc(1, OBJSZ);
  V34I_REGW(o, OBJSZ, 0x1450); /* x86-64: o is the modulator sub-object m (= object offset 0x1450) */
  short *bank = (short *)malloc(sizeof(short) * 64 * 24);
  short *tab = (short *)malloc(sizeof(short) * 2 * 128 + 64);
  short *coef = (short *)malloc(sizeof(short) * 16);
  short outbuf[64];
  int c, calls = 6000;
  long n_zero_taps = 0, n_zero_out = 0, n_out = 0, n_wrap = 0, n_negtaps = 0, n_shift = 0, n_multi = 0;
  unsigned int all = FNV0;
  for (c = 0; c < calls; c++) {
    int taps, stride, idx, limit, step, phase, len, tp, tp0;
    unsigned int h, hh = FNV0;
    int nout, i, bank_amp = (int)lcg_mod(16);
    fill_random(o, OBJSZ);
    scrub_slots(o);
    for (i = 0; i < 64 * 24; i++) bank[i] = (short)(lcg_short() >> (bank_amp > 8 ? 4 : 0));
    for (i = 0; i < 2 * 128 + 32; i++) tab[i] = lcg_short();
    for (i = 0; i < 16; i++) coef[i] = (short)(lcg_short() >> lcg_mod(3));
    switch (lcg_mod(8)) {
      case 0: taps = 0; break;
      case 1: taps = -(int)lcg_mod(5) - 1; break;
      case 2: taps = 64; break;
      default: taps = 1 + (int)lcg_mod(64); break;
    }
    stride = 70 + (int)lcg_mod(60);
    idx = (int)lcg_mod(6);
    if (inrange) {
      if (taps > 11) taps = 1 + taps % 11;
      stride = 70 + (stride - 70) % (66 - taps - idx);
    }
    limit = 1 + (int)lcg_mod(16);
    step = 1 + (int)lcg_mod(limit + 3);
    switch (lcg_mod(4)) {
      case 0: phase = limit + (int)lcg_mod(4); break; /* phase >= limit: zero-output path (stale-carry: 0) */
      default: phase = (int)lcg_mod(limit); break;
    }
    len = 1 + (int)lcg_mod(128);
    tp = (lcg_mod(4) == 0) ? len - 1 : (int)lcg_mod(len);
    tp0 = tp;
    I32(o, 0) = taps;
    I32(o, 4) = step;
    I32(o, 8) = limit;
    I32(o, 0xc) = phase;
    PTR(o, 0x10) = tab;
    I32(o, 0x14) = len;
    I32(o, 0x18) = tp;
    PTR(o, 0xc24) = bank;
    PTR(o, 0xcb0) = coef;
    I32(o, 0xdbc) = idx;
    I32(o, 0xdc0) = stride;
    memset(outbuf, 0x5a, sizeof outbuf);
    nout = V34ModulatorProcess(o, lcg_next(), outbuf);
    hh = fnv(hh, &nout, 4);
    hh = fnv(hh, outbuf, sizeof outbuf);
    h = hash_obj(o);
    all = fnv(all, &h, 4);
    all = fnv(all, &hh, 4);
    printf("mod call %d nout=%d hash=%08x out=%08x\n", c, nout, h, hh);
    if (taps <= 0) n_zero_taps++;
    if (taps < 0) n_negtaps++;
    if (nout == 0) { n_zero_out++; if (taps > 0) n_shift++; } else { n_out++; if (taps > 0) n_shift++; }
    if (nout > 1) n_multi++;
    if (nout > 0 && I32(o, 0x18) != tp0 + nout && len > 0) n_wrap++;
  }
  printf("mod all=%08x\n", all);
  need("zero-output call with taps>0 (stale carry = 0)", n_zero_out);
  need("output-producing call", n_out);
  need("multi-output call", n_multi);
  need("tp wraparound", n_wrap);
  need("taps<=0 (no shift-in)", n_zero_taps);
  need("taps<0", n_negtaps);
  need("shift-in ran", n_shift);
  free(o); free(bank); free(tab); free(coef);
}

/* ===================== scenario 4: V34GiveProbeResults ===================== */
static void scen_probe(void) {
  unsigned char *o = (unsigned char *)calloc(1, OBJSZ);
  unsigned char probe[0x20 + 0x2c * 25 + 16];
  int c;
  long n_copy = 0, n_skip = 0, n_snan = 0;
  unsigned int all = FNV0;
  for (c = 0; c < 400; c++) {
    int rc, i;
    unsigned int h;
    fill_random(o, OBJSZ);
    scrub_slots(o);
    fill_random(probe, sizeof probe);
    /* force NaN/sNaN/qNaN/denormal/inf/zero patterns into some records */
    for (i = 0; i < 25; i++) {
      uint64_t v;
      unsigned int k = lcg_mod(12);
      memcpy(&v, probe + 0x20 + 0x2c * i, 8);
      switch (k) {
        case 0: v = 0x7ff0000000000001ull | ((uint64_t)lcg_next() << 8); break;              /* sNaN */
        case 1: v = 0xfff0000000000000ull | ((uint64_t)(lcg_next() & 0x7ffff) << 20) | 1; break; /* -sNaN */
        case 2: v = 0x7ff8000000000000ull | lcg_next(); break;                                 /* qNaN */
        case 3: v = ((uint64_t)lcg_next() << 32 | lcg_next()) & 0x800fffffffffffffull; break; /* denormal */
        case 4: v = 0x7ff0000000000000ull; break;                                             /* inf */
        case 5: v = 0; break;
        default: break;
      }
      memcpy(probe + 0x20 + 0x2c * i, &v, 8);
      if (k <= 1) n_snan++;
    }
    switch (lcg_mod(4)) {
      case 0: I32(o, 0x24c) = 0; I32(o, 0x250) = 0; break;
      case 1: I32(o, 0x24c) = (int)lcg_next() | 1; I32(o, 0x250) = 0; break;
      case 2: I32(o, 0x24c) = 0; I32(o, 0x250) = (int)lcg_next() | 1; break;
      default: I32(o, 0x24c) = 1; I32(o, 0x250) = 2; break;
    }
    if (I32(o, 0x24c) != 0 || I32(o, 0x250) != 0) n_copy++; else n_skip++;
    rc = V34GiveProbeResults(o, probe);
    h = hash_obj(o);
    all = fnv(all, &h, 4);
    all = fnv(all, &rc, 4);
    printf("probe call %d rc=%d hash=%08x\n", c, rc, h);
  }
  printf("probe all=%08x\n", all);
  need("copy path", n_copy);
  need("skip path", n_skip);
  need("signalling-NaN records", n_snan);
  free(o);
}

/* ===================== scenario 5: V34InitializeImplementationSpecific + v34FreezeEcho ===================== */
static void scen_init_freeze(void) {
  unsigned char *o = (unsigned char *)calloc(1, OBJSZ);
  int c;
  long n_junk_old = 0, n_ptr_old = 0, n_nz_coef = 0, n_z_coef = 0, n_flag_clear = 0, n_flag_set = 0;
  unsigned int all = FNV0;
  for (c = 0; c < 200; c++) {
    unsigned int h;
    fill_random(o, OBJSZ);
    scrub_slots(o);
    /* "old" base fields: junk (never an in-object address) or a real in-object pointer (re-init) */
    if (lcg_mod(2)) { U32(o, 0x80bc) = 0x0e000000u | (lcg_next() & 0xffffffu); U32(o, 0x913c) = 0x0e000000u | (lcg_next() & 0xffffffu); n_junk_old++; }
    else { PTR(o, 0x80bc) = OB(o, 0x100 + 2 * lcg_mod(100)); PTR(o, 0x913c) = OB(o, 0x100 + 2 * lcg_mod(100)); n_ptr_old++; }
    V34InitializeImplementationSpecific(o);
    h = hash_obj(o);
    all = fnv(all, &h, 4);
    printf("init call %d hash=%08x\n", c, h);
    /* now freeze: seed coefficient banks (some all-zero, some nonzero at random positions), random flag word */
    {
      short *hi0 = (short *)PTR(o, 0x80c0);
      short *hi1 = (short *)PTR(o, 0x9140);
      unsigned int mode = lcg_mod(4);
      int i;
      unsigned int h2;
      /* coefHi regions are 0x90 shorts each (the init'd N) */
      memset(hi0, 0, 0x90 * 2);
      memset(hi1, 0, 0x90 * 2);
      if (mode & 1) { hi0[lcg_mod(0x90)] = lcg_short() | 1; }
      if (mode & 2) { hi1[lcg_mod(0x90)] = lcg_short() | 1; }
      if (mode == 0) n_z_coef++; else n_nz_coef++;
      for (i = 0; i < 3; i++) (void)i;
      U16(o, 0x25c2) = (uint16_t)(lcg_mod(3) == 0 ? (lcg_next() & ~4u) : (lcg_next() | 4u));
      if (U16(o, 0x25c2) & 4) n_flag_set++; else n_flag_clear++;
      v34FreezeEcho(o);
      h2 = hash_obj(o);
      all = fnv(all, &h2, 4);
      printf("freeze call %d flag=%04x hash=%08x\n", c, U16(o, 0x25c2), h2);
    }
  }
  printf("init_freeze all=%08x\n", all);
  need("init with junk old-base", n_junk_old);
  need("init with in-object old-base", n_ptr_old);
  need("freeze with nonzero coefficients", n_nz_coef);
  need("freeze with all-zero coefficients", n_z_coef);
  need("freeze with flag already set", n_flag_set);
  need("freeze with flag clear", n_flag_clear);
  free(o);
}

/* ===================== INFO scenarios: shared fake ctx ===================== */
typedef struct Fake {
  unsigned char *o;
  unsigned char *ctx;   /* >= 0x6200 bytes */
  unsigned char *p612c; /* ctx+0x612c target */
  unsigned char *p1760; /* ctx+0x1760 target */
  unsigned char *k56;   /* obj+0xac18 target */
} Fake;
#define CTXSZ 0x6200u
#define SUBSZ 0x40u

static void fake_alloc(Fake *f) {
  f->o = (unsigned char *)calloc(1, OBJSZ);
  f->ctx = (unsigned char *)calloc(1, CTXSZ);
  V34I_REGC(f->ctx, CTXSZ, ctx);
  f->p612c = (unsigned char *)calloc(1, SUBSZ);
  f->p1760 = (unsigned char *)calloc(1, SUBSZ);
  f->k56 = (unsigned char *)calloc(1, SUBSZ);
}
static void fake_seed(Fake *f) {
  fill_random(f->o, OBJSZ);
  scrub_slots(f->o);
  fill_random(f->ctx, CTXSZ);
  fill_random(f->p612c, SUBSZ);
  fill_random(f->p1760, SUBSZ);
  fill_random(f->k56, SUBSZ);
  PTR(f->o, 0x3548) = f->ctx;
  PTR(f->o, 0xac18) = f->k56;
  PTRX_SET(f->ctx, 0x612c, f->p612c);
  PTRX_SET(f->ctx, 0x1760, f->p1760);
}
static unsigned int fake_hash(const Fake *f) {
  unsigned char tmp[CTXSZ];
  unsigned int h = hash_obj(f->o);
  memcpy(tmp, f->ctx, CTXSZ);
  memset(tmp + 0x612c, 0, 4);
  memset(tmp + 0x1760, 0, 4);
  h = fnv(h, tmp, CTXSZ);
  h = fnv(h, f->p612c, SUBSZ);
  h = fnv(h, f->p1760, SUBSZ);
  h = fnv(h, f->k56, SUBSZ);
  return h;
}
/* random role/mode flags. role: 0, 1, or other nonzero incl. negative/0x100 */
static void fake_flags(Fake *f, int *role_o, int *pcm_o, int *k56_o) {
  int role, pcm, k56;
  switch (lcg_mod(5)) { case 0: role = 0; break; case 1: role = 1; break; case 2: role = 0x100; break; case 3: role = -1; break; default: role = (int)(lcg_next() | 1); break; }
  switch (lcg_mod(4)) { case 0: pcm = 0; break; case 1: pcm = 1; break; case 2: pcm = (int)lcg_next() | 0x100; break; default: pcm = 1; break; }
  switch (lcg_mod(3)) { case 0: k56 = 0; break; case 1: k56 = 2; break; default: k56 = (int)lcg_next() | 1; break; }
  I32(f->ctx, 0x6120) = role;
  I32(f->o, 0x24c) = pcm;
  I32(f->o, 0x250) = k56;
  *role_o = role; *pcm_o = pcm; *k56_o = k56;
}
/* shorts used as flags: 0, small, and values whose low byte is zero but nonzero as a short */
static short rand_flag16(void) {
  switch (lcg_mod(4)) { case 0: return 0; case 1: return 1; case 2: return (short)0x100; default: return lcg_short(); }
}

