static unsigned char td_b[0x200];
static unsigned char td_det[0x50];
static short td_coef[24];
static unsigned short td_smp[192];
static unsigned short td_smpsnap[192];
static short td_coefsnap[24];

typedef struct {
  int mode, armed, state, counter, thr, low, high, E, bflag;
  int nsamp; /* signed distance end - p */
} td_pre_t;

static long td_cov_straddle, td_cov_straddle_inv, td_cov_loop, td_cov_eq, td_cov_gt, td_cov_s1neg, td_cov_s1ok, td_cov_m0_hold, td_cov_m0_arm, td_cov_m0_inc,
    td_cov_m0_reset, td_cov_mN_low, td_cov_mN_high, td_cov_mN_both, td_cov_mN_mid, td_cov_ret1, td_cov_ret0cmp,
    td_cov_clr, td_cov_eqthr, td_cov_arm_bit, td_cov_neg_state, td_cov_mode_hi;

static void td_capture(td_pre_t *p, int nsamp) {
  p->mode = S16(td_det, 4);
  p->armed = S16(td_det, 6);
  p->state = S16(td_det, 0xc);
  p->counter = S16(td_det, 8);
  p->thr = S16(td_det, 0xa);
  p->low = S16(td_det, 0xe);
  p->high = S16(td_det, 0x10);
  p->E = S16(td_det, 0x12);
  p->bflag = (U16(td_b, 0x122) & 0x200) != 0;
  p->nsamp = nsamp;
}
static void td_account(const td_pre_t *p, int ret) {
  int Epost = S16(td_det, 0x12);
  int s1neg = 0, reached_cmp = 1;
  if (p->nsamp > 0) td_cov_loop++;
  else if (p->nsamp == 0) td_cov_eq++;
  else td_cov_gt++;
  if (p->state == 1) {
    if (((p->counter + 1) & 0x8000) != 0) {
      td_cov_s1neg++;
      s1neg = 1;
      if (S16(td_det, 0xc) != 1 || ret != 0) die("tone_detect model: state-1 negative counter did not return 0 with state kept");
    } else {
      td_cov_s1ok++;
      if (S16(td_det, 0xc) != 2) die("tone_detect model: state 1 -> 2 transition missing");
    }
  }
  if (p->state != 1 && p->state < 0) td_cov_neg_state++;
  if (p->mode > 0x4000) td_cov_mode_hi++;
  if (s1neg) return;
  if (p->mode == 0) {
    if (p->armed == 0) {
      reached_cmp = 0;
      if (Epost <= 0x100) {
        td_cov_m0_hold++;
        if (S16(td_det, 6) != 0 || ret != 0) die("tone_detect model: unarmed hold");
      } else {
        td_cov_m0_arm++;
        if (S16(td_det, 6) != 1 || S16(td_det, 8) != 0 || ret != 0 || (U16(td_b, 0x122) & 0x200) != 0)
          die("tone_detect model: arming");
        if (p->bflag) td_cov_clr++;
      }
    } else if (Epost > (int)p->high) {
      td_cov_m0_inc++;
    } else {
      td_cov_m0_reset++;
    }
  } else {
    int lo = Epost < p->low, hi = Epost > p->high;
    if (lo && hi) td_cov_mN_both++;
    else if (lo) td_cov_mN_low++;
    else if (hi) td_cov_mN_high++;
    else td_cov_mN_mid++;
  }
  if (reached_cmp) {
    int c = S16(td_det, 8);
    if (c == S16(td_det, 0xa)) td_cov_eqthr++;
    if (ret) td_cov_ret1++;
    else td_cov_ret0cmp++;
    if (ret != (c > S16(td_det, 0xa))) die("tone_detect model: return value != (counter > threshold)");
  }
  if (p->armed == 0 && p->mode == 0 && S16(td_det, 6) == 1) td_cov_arm_bit++;
}

static unsigned int td_hash(int ret) {
  unsigned int h = FNV0;
  h = fnv32(h, (uint32_t)ret);
  h = fnv(h, td_b, sizeof td_b);
  h = fnv(h, td_det + 4, sizeof td_det - 4);
  h = fnv(h, td_coef, sizeof td_coef);
  h = fnv(h, td_smp, sizeof td_smp);
  h = fnv(h, (const void *)(uintptr_t)HI_WIN, 0x400);
  /* the coefficient tables and the pointer slot must be untouched */
  if (memcmp(td_smp, td_smpsnap, sizeof td_smp) || memcmp(td_coef, td_coefsnap, sizeof td_coef)) h ^= 0xdeadbeefu;
  return h;
}
static const short *td_p_override;
static const short *td_end_override;
static int td_call(const short *coefp, int nsamp) {
  const short *p = td_p_override ? td_p_override : (const short *)(td_smp + 40);
  const short *end = td_p_override ? td_end_override : p + nsamp;
  PTRS_SET(td_det, 0, coefp);
  memcpy(td_smpsnap, td_smp, sizeof td_smp);
  memcpy(td_coefsnap, td_coef, sizeof td_coef);
  return tone_detect(td_b, td_det, p, end);
}

static void td_pick_coef(const short **cp) {
  int i;
  switch (lcg_mod(9)) {
    case 0: *cp = c1200_; break;
    case 1: *cp = c2400_; break;
    case 2:
    case 3:
    case 4:
      for (i = 0; i < 8; i++) td_coef[i] = rshort();
      *cp = td_coef;
      break;
    case 5:
      for (i = 0; i < 8; i++) td_coef[i] = (lcg_next() & 1) ? 32767 : -32768;
      *cp = td_coef;
      break;
    case 6:
      for (i = 0; i < 8; i++) td_coef[i] = (short)rr(-300, 300);
      *cp = td_coef;
      break;
    case 7:
      for (i = 0; i < 8; i++) td_coef[i] = -32768;
      *cp = td_coef;
      break;
    default:
      for (i = 0; i < 8; i++) td_coef[i] = (short)(16384 + rr(-2000, 2000) * ((i & 1) ? -1 : 1));
      *cp = td_coef;
      break;
  }
}

static int td_pick_counter(void) {
  switch (lcg_mod(9)) {
    case 0: return -1;
    case 1: return 0x7fff;
    case 2: return 0x7ffe;
    case 3: return 0;
    case 4: return 1;
    case 5: return -32768;
    case 6: return rr(-6, 6);
    default: return (short)rnd16();
  }
}

