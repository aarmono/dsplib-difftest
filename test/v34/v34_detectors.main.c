static unsigned char g_obj[OBJSZ + 64];
static unsigned char g_tpl[OBJSZ + 64];
static unsigned char g_snap[OBJSZ + 64];
#define SCR_GUARD 0x100u
#define SCR_SZ 0x800u
#define SCR_TOT (SCR_GUARD + SCR_SZ)
static unsigned char g_scr[SCR_TOT + 64];
static unsigned char g_scrsnap[SCR_TOT + 64];
static unsigned char g_scrtpl[SCR_TOT + 64];
static const unsigned int k_slot_words[] = {0x80c4 / 4};
static int g_scr_in_obj; /* scratch pointer mode of the current case */

static uint32_t norm_ptr(uint32_t v) {
  uintptr_t a = (uintptr_t)v;
  if (a >= (uintptr_t)g_obj && a < (uintptr_t)g_obj + OBJSZ) return 0x80000000u | (uint32_t)(a - (uintptr_t)g_obj);
  if (a >= (uintptr_t)g_scr && a < (uintptr_t)g_scr + sizeof g_scr) return 0x7d000000u | (uint32_t)(a - (uintptr_t)g_scr);
  return v;
}

static unsigned int diff_words(const unsigned char *cur, const unsigned char *old, size_t nbytes, int normslot) {
  unsigned int h = FNV0;
  size_t i;
  for (i = 0; i < nbytes / 4; i++) {
    uint32_t a, b;
    memcpy(&a, cur + 4 * i, 4);
    memcpy(&b, old + 4 * i, 4);
    if (normslot && i == k_slot_words[0]) {
      a = norm_ptr(a);
      b = norm_ptr(b);
    }
    if (a != b) {
      uint32_t idx = (uint32_t)i;
      h = fnv(h, &idx, 4);
      h = fnv(h, &a, 4);
      if (g_verbose > 1) printf("   diffword off=%05x new=%08x\n", (unsigned int)(4 * i), a);
    }
  }
  return h;
}

static unsigned int g_scr_off; /* 0 or 2: external scratch at a 2 mod 4 address (the blob does not care) */
static unsigned char *scratch_ptr(void) { return g_scr_in_obj ? g_obj + 0x80d8 : g_scr + SCR_GUARD + g_scr_off; }

/* Prepare g_obj from g_tpl (+ scratch) and snapshot it */
static void obj_prepare(void) {
  memcpy(g_scr, g_scrtpl, sizeof g_scr);
  memcpy(g_obj, g_tpl, OBJSZ);
  PTRS_SET(g_obj, 0x80c4, scratch_ptr());
  memcpy(g_snap, g_obj, OBJSZ);
  memcpy(g_scrsnap, g_scr, sizeof g_scr);
}
static unsigned int obj_hash(void) {
  unsigned int h = diff_words(g_obj, g_snap, OBJSZ, 1);
  h = fnv32(h, diff_words(g_scr, g_scrsnap, SCR_TOT + 64 - ((SCR_TOT + 64) & 3), 0));
  return h;
}

/* ---- sample generators (integer only) ---- */
static int cosq(unsigned int phase16) { return H_COSTBL[(phase16 >> 8) & 0xff]; }
static void gen_samples(unsigned short *dst, int n, int kind) {
  int i;
  static unsigned int ph;
  int amp = 1 + (int)lcg_mod(32767);
  unsigned int step = 1 + lcg_mod(0x3000);
  for (i = 0; i < n; i++) {
    switch (kind) {
      case 0: dst[i] = rnd16(); break;                                      /* full-range random */
      case 1: dst[i] = (unsigned short)(short)rr(-64, 64); break;           /* small */
      case 2: dst[i] = 0; break;                                            /* silence */
      case 3: dst[i] = (lcg_next() & 1) ? 0x8000u : 0x7fffu; break;         /* extremes */
      case 4: ph += step; dst[i] = (unsigned short)(short)((cosq(ph) * amp) >> 14); break;
      default: dst[i] = (unsigned short)(short)rr(-2000, 2000); break;
    }
  }
}

