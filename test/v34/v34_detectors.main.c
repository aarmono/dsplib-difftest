/* ---- fskdemodulate ---- */
static long fm_early, fm_run, fm_take, fm_skip, fm_pat_le0, fm_pat_gt0, fm_reset_thr, fm_cross_pn, fm_cross_np, fm_same_nn, fm_same_pp,
    fm_prev0, fm_cur0, fm_c1wrap, fm_pneg, fm_bits_max, fm_early_lowbyte0, fm_sr_carry, fm_prev_neg_init;

/* independent model of the fskdemodulate control flow given loc[]; updates a copy of st and coverage */
static void fm_model(unsigned char *st, const short *loc) {
  int prev = S16(st, 0x14), i, cur = 0;
  int P = S16(st, 8);
  int thr = P << 8;
  for (i = 0; i < 3; i++) {
    int cnt = U16(st, 0xc), nxt = U16(st, 0xe);
    int c1;
    if ((int16_t)cnt >= (int16_t)nxt) {
      unsigned int pat;
      fm_take++;
      if (prev > 0) {
        pat = U16(st, 6);
        fm_pat_gt0++;
      } else {
        pat = U16(st, 4);
        fm_pat_le0++;
      }
      if (U16(st, 0x12) & 0x8000) fm_sr_carry++;
      U16(st, 0x12) = (uint16_t)((U16(st, 0x12) * 2) | pat);
      U16(st, 0x10) = (uint16_t)(U16(st, 0x10) + 1);
      U16(st, 0xe) = (uint16_t)(nxt + P);
    } else {
      fm_skip++;
    }
    c1 = cnt + 1;
    if (cnt == 0xffff) fm_c1wrap++;
    if ((int16_t)c1 >= thr) {
      fm_reset_thr++;
      c1 = 0;
      U16(st, 0xe) = U16(st, 0xa);
    }
    if (P < 0) fm_pneg++;
    cur = loc[i];
    if (prev == 0) fm_prev0++;
    if (cur == 0) fm_cur0++;
    if (prev < 0 && cur < 0) {
      fm_same_nn++;
      U16(st, 0xc) = (uint16_t)c1;
    } else if (prev >= 0 && cur >= 0) {
      fm_same_pp++;
      U16(st, 0xc) = (uint16_t)c1;
    } else {
      if (prev < 0) fm_cross_np++;
      else fm_cross_pn++;
      U16(st, 0xc) = 0;
      U16(st, 0xe) = U16(st, 0xa);
    }
    prev = cur;
  }
  S16(st, 0x14) = (int16_t)cur;
}

static unsigned char fm_stbuf[0x40], fm_stsnap[0x40], fm_stmodel[0x40];

/* run one fskdemodulate call on the current g_obj/g_st state (g_snap etc. already taken) and return the hash */
static unsigned int fm_run_one(void) {
  short loc[14] = {0};
  unsigned char objcopy[OBJSZ + 64];
  unsigned char scrcopy[sizeof g_scr];
  int early = S16(g_obj, 0x402) != 0;
  unsigned int h;
  memcpy(fm_stsnap, fm_stbuf, sizeof fm_stbuf);
  memcpy(fm_stmodel, fm_stbuf, sizeof fm_stbuf);
  if (!early) {
    /* compute loc with a private copy of the object/scratch (fskdetect is deterministic) */
    unsigned char *savedptr = (unsigned char *)PTRS_GET(g_obj, 0x80c4);
    memcpy(objcopy, g_obj, OBJSZ);
    memcpy(scrcopy, g_scr, sizeof g_scr);
    fskdetect(g_obj, g_in, loc, (const short *)fm_stbuf);
    /* restore for the real call */
    memcpy(g_obj, objcopy, OBJSZ);
    memcpy(g_scr, scrcopy, sizeof g_scr);
    PTRS_SET(g_obj, 0x80c4, savedptr);
    fm_model(fm_stmodel, loc);
    fm_run++;
  } else {
    fm_early++;
    if ((S16(g_obj, 0x402) & 0xff) == 0) fm_early_lowbyte0++;
  }
  fskdemodulate(g_obj, g_in, fm_stbuf);
  if (memcmp(fm_stbuf, fm_stmodel, 0x16)) die("fskdemodulate: independent model disagrees with the implementation under test");
  if (memcmp(fm_stbuf + 0x16, fm_stsnap + 0x16, sizeof fm_stbuf - 0x16)) die("fskdemodulate wrote beyond st[0x15]");
  h = fnv(FNV0, fm_stbuf, sizeof fm_stbuf);
  h = fnv32(h, obj_hash());
  if (U16(fm_stbuf, 0x10) > 0x7000) fm_bits_max++;
  if (S16(fm_stsnap, 0x14) < 0) fm_prev_neg_init++;
  return h;
}

