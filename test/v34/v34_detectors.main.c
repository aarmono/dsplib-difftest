/*
 * Differential test harness for V.34 "tier 5c" (src/v34/v34_detectors.c): the detectors
 *   tone_detect, dftupdate, dftenergy, fskdetect, fskdemodulate
 *
 * One source, two binaries (same convention as test/v34/v34_tx_symbol.main.c):
 *   v34_tier5c_test_blob - linked against the real dsplibs.o (-DTEST_BLOB)
 *   v34_tier5c_test_port - linked against src/v34/v34_detectors.c + tables
 * Each scenario runs in its OWN process (argv[1]).
 *
 * FLOATING POINT: dftupdate / dftenergy use the x87 FPU with 80-bit intermediates (see the
 * header of src/v34/v34_detectors.c).  All results (sumI, sumQ, energy) are compared BITWISE (raw
 * 8-byte patterns, so NaN payloads, signed zeros, denormals and infinities are all compared).
 * The harness itself never does floating-point arithmetic that the two binaries could see
 * differently (doubles are built from bit patterns; the only FP arithmetic in the harness is
 * the strict-SSE2 "what would a pure-double implementation give" oracle, which is used for
 * COVERAGE COUNTING only - it proves that the designed inputs really distinguish 80-bit
 * intermediates from pure double arithmetic).  Start-up asserts that the x87 control word has
 * 64-bit-mantissa precision and round-to-nearest (else exit 3).
 *
 * Objects: tagV34Object is not a struct.  fskdetect / fskdemodulate get a random fake object
 * (OBJSZ = 0xb400 bytes) whose scratch-pointer slot obj+0x80c4 (the near echo canceller's coefLo
 * field, which fskdetect uses as private scratch) points either at a harness buffer (with guard
 * margins on both sides, random-filled, hashed) or into the object itself at obj+0x80d8 (the real
 * configuration).  Results are the hash of the DIFF (word index + new value of every changed word)
 * of the object and of the scratch buffer, so a stray write anywhere is caught; pointer slots are
 * normalised (in-object -> offset, harness buffer -> offset), raw addresses are never compared.
 * INPUT ORACLE: fskdetect's tap index st[0] is unchecked; the harness keeps p+0x14+2*st[0] inside
 * the harness-owned scratch (external mode: [-0x100,+0x800) around p; in-object mode: small
 * range) - "in range" for the blob is 0..48, out-of-range values inside the owned memory are
 * exercised and compared too.
 *
 * Scenarios: 0 tone_detect random single, 1 tone_detect streaming chain, 2 dftupdate designed
 * (double-rounding / big sums), 3 dftupdate special doubles (NaN/inf/denormal/...), 4 dftupdate
 * reachable chain up to 2^54+ sums, 5 dftenergy integer/designed, 6 dftenergy special doubles,
 * 7 dftupdate+dftenergy realistic chain, 8 fskdetect single, 9 fskdetect chain, 10 fskdemodulate
 * single, 11 fskdemodulate chain.
 * Every scenario keeps COVERAGE COUNTERS (from input predicates / observable before-after state)
 * and exits 2 if a branch class was never reached; exit 3 = harness assumption violated.
 */

