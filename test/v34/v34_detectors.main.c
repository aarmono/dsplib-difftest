static void fsk_history_kind(int kind) {
  int k;
  for (k = 0; k < 13; k++) {
    short v;
    switch (kind) {
      case 0: v = rshort(); break;
      case 1: v = (short)rr(-100, 100); break;
      case 2: v = 0; break;
      case 3: v = (lcg_next() & 1) ? -32768 : 32767; break;
      default: v = (short)rr(-8000, 8000); break;
    }
    S16(g_tpl, 0xaae6 + 2 * k) = v;
  }
  for (k = 0; k < 80; k++) {
    short v;
    switch (kind) {
      case 0: v = rshort(); break;
      case 1: v = (short)rr(-100, 100); break;
      case 2: v = 0; break;
      case 3: v = (lcg_next() & 1) ? -32768 : 32767; break;
      default: v = (short)rr(-8000, 8000); break;
    }
    S16(g_tpl, 0xab00 + 2 * k) = v;
  }
}
static int pick_st0(void) {
  int r = (int)lcg_mod(20);
  if (g_scr_in_obj) {
    if (r < 12) return rr(0, 48);
    if (r == 12) return 0;
    if (r == 13) return 48;
    if (r == 14) return 49;
    if (r == 15) return -1;
    return rr(-8, 200);
  }
  if (r < 10) return rr(0, 48);
  if (r == 10) return 0;
  if (r == 11) return 48;
  if (r == 12) return 49;
  if (r == 13) return -1;
  if (r == 14) return -0x50; /* p+0x14-0xa0 = p-0x8c: inside the front guard */
  if (r == 15) return 0x1b0;  /* p+0x14+0x360: inside the owned range */
  return rr(-0x70, 0x1b0);
}
static void account_st0(int st0) {
  fd_calls++;
  if (st0 >= 0 && st0 <= 48) fd_st0_range++;
  if (st0 == 0) fd_st0_zero++;
  if (st0 == 48) fd_st0_48++;
  if (st0 == 49) fd_st0_49++;
  if (st0 < 0) fd_st0_neg++;
  if (st0 > 49 || st0 < -1) fd_st0_wide++;
}

