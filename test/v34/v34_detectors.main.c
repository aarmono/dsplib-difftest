#define BIN 0x2c
#define MAXBINS 8
static unsigned char g_binbuf[MAXBINS * BIN + 64];
static short g_samples[32768 + 16];

static long dc_designedI, dc_designedQ, dc_sse_diff, dc_sse_same, dc_nan_out, dc_inf_out, dc_den_out, dc_big53, dc_big63,
    dc_nan_in, dc_zero_bins, dc_neg_bins, dc_align0, dc_align2, dc_align4, dc_calls_bins;
static long de_norm[21], de_e_neg, de_hi_nonzero, de_sse_diff, de_ge27, de_ge53, de_shift_hi, de_nan_in, de_inf_out, de_zero_bins;

static unsigned char *bins_at(int aoff) { return g_binbuf + aoff; }

/* find (idx, x) with costbl[c_index(idx)] * x within the tie band for exponent e (p sign as requested);
 * returns 1 and sets the outputs, or 0 */
static int find_px(int e, int negp, int isq, unsigned int *idx_out, int *x_out) {
  long long hi = (1ll << (e - 1)) - 1, lo = (1ll << (e - 1)) - (1ll << (e - 12)) + 1;
  unsigned int start = lcg_mod(256), t;
  if (e < 13 || e > 30) return 0;
  for (t = 0; t < 256; t++) {
    unsigned int idx = (start + t) & 0xff;
    long long c = H_COSTBL[isq ? ((idx + 0x40) & 0xff) : idx];
    long long xlo, xhi, x;
    if (c == 0) continue;
    /* p = c*x must lie in [lo,hi] (positive band) or [-hi,-lo] (negative) */
    {
      long long plo = negp ? -hi : lo, phi = negp ? -lo : hi;
      long long a = plo, b = phi;
      if (c > 0) {
        xlo = (a >= 0) ? (a + c - 1) / c : -((-a) / c);
        xhi = (b >= 0) ? b / c : -((-b + c - 1) / c);
      } else {
        long long cc = -c;
        /* c*x in [a,b]  <=>  cc*(-x) in [a,b]... solve for y = -x: cc*y in [a,b] */
        long long ylo = (a >= 0) ? (a + cc - 1) / cc : -((-a) / cc);
        long long yhi = (b >= 0) ? b / cc : -((-b + cc - 1) / cc);
        xlo = -yhi;
        xhi = -ylo;
      }
    }
    if (xlo > xhi) continue;
    x = xlo;
    if (x < -32768 || x > 32767) {
      x = xhi;
      if (x < -32768 || x > 32767) continue;
    }
    if (c * x < (negp ? -hi : lo) || c * x > (negp ? -lo : hi)) continue;
    *idx_out = idx;
    *x_out = (int)x;
    return 1;
  }
  return 0;
}


/* whole-buffer hash incl. guard bytes after the bins: stray writes past the last bin are caught */
static unsigned int binbuf_hash(void) { return fnv(FNV0, g_binbuf, sizeof g_binbuf); }

static void dc_account_out(const unsigned char *bin) {
  uint64_t a = ld64(bin + 0x10), b = ld64(bin + 0x18);
  if (is_nan_bits(a) || is_nan_bits(b)) dc_nan_out++;
  if (((a >> 52) & 0x7ff) == 0x7ff && !is_nan_bits(a)) dc_inf_out++;
  if (((a >> 52) & 0x7ff) == 0 && (a & 0xfffffffffffffull)) dc_den_out++;
  if (((a >> 52) & 0x7ff) >= 1023 + 53) dc_big53++;
  if (((a >> 52) & 0x7ff) >= 1023 + 63 && ((a >> 52) & 0x7ff) != 0x7ff) dc_big63++;
}

/* one dftupdate call over nb bins at alignment aoff; returns the hash of the whole buffer */
static unsigned int du_call(int aoff, int nb, int ns, int garbage) {
  unsigned char *bins = bins_at(aoff);
  int a = garbage ? gar16(nb) : nb, b = garbage ? gar16(ns) : ns;
  switch (aoff) {
    case 0: dc_align0++; break;
    case 2: dc_align2++; break;
    case 4: dc_align4++; break;
    default: break;
  }
  dftupdate(bins, a, g_samples, b);
  return binbuf_hash();
}

/* scenario 2: designed cases */
static int scen_du_designed(void) {
  logger_t lg = {"du_designed", FNV0, 0, 2000};
  long i;
  const long N = 60000;
  for (i = 0; i < N; i++) {
    int aoff = (int)(2 * lcg_mod(4)), nb = rr(0, 4), b;
    unsigned char *bins;
    int family = (int)lcg_mod(6); /* 0 I-designed, 1 Q-designed, 2 exact ints, 3 mixed big, 4 fractional/random, 5 multi-sample */
    int ns = 1;
    int design_bin = -1, design_isq = 0, design_p = 0, design_e = -1;
    uint64_t sbits_pre = 0;
    fill_random(g_binbuf, sizeof g_binbuf);
    bins = bins_at(aoff);
    if (family == 5) ns = rr(1, 12);
    fill_random(g_samples, 64 * 2);
    if (nb < 1) nb = 1;
    for (b = 0; b < nb; b++) {
      unsigned char *bin = bins + BIN * b;
      unsigned int phase = rnd16(), step = rnd16();
      unsigned int target;
      int e, isq, negp, x;
      unsigned int idx;
      switch (family) {
        case 0:
        case 1:
          if (b == 0) {
            isq = family == 1;
            for (;;) {
              e = rr(13, 30);
              negp = (int)(lcg_next() & 1);
              if (find_px(e, negp, isq, &idx, &x)) break;
            }
            target = (idx << 6) | lcg_mod(64);
            step = ((target - phase) & 0x3fffu) | (rnd16() & 0xc000u);
            g_samples[0] = (short)x;
            st64(bin + (isq ? 0x18 : 0x10), make_odd_mant(e, (int)(lcg_next() & 1)));
            st64(bin + (isq ? 0x10 : 0x18), make_int_double(rr(0, 70), (int)(lcg_next() & 1)));
            design_bin = 0;
            design_isq = isq;
            design_e = e;
            design_p = (int)H_COSTBL[isq ? ((idx + 0x40) & 0xff) : idx] * x;
            sbits_pre = ld64(bin + (isq ? 0x18 : 0x10));
            if (isq) dc_designedQ++;
            else dc_designedI++;
          } else {
            st64(bin + 0x10, gen_special_bits());
            st64(bin + 0x18, make_int_double(rr(0, 80), (int)(lcg_next() & 1)));
          }
          break;
        case 2:
          st64(bin + 0x10, make_int_double(rr(0, 53), (int)(lcg_next() & 1)));
          st64(bin + 0x18, make_int_double(rr(0, 53), (int)(lcg_next() & 1)));
          break;
        case 3:
          st64(bin + 0x10, make_int_double(rr(50, 90), (int)(lcg_next() & 1)));
          st64(bin + 0x18, make_int_double(rr(50, 90), (int)(lcg_next() & 1)));
          break;
        default:
          st64(bin + 0x10, gen_special_bits());
          st64(bin + 0x18, gen_special_bits());
          break;
      }
      if (family == 0 || family == 1) {
        if (b == 0) {
          U16(bin, 0) = (uint16_t)phase;
          U16(bin, 2) = (uint16_t)step;
        } else {
          U16(bin, 0) = rnd16();
          U16(bin, 2) = rnd16();
        }
      } else {
        U16(bin, 0) = (uint16_t)phase;
        U16(bin, 2) = (uint16_t)step;
      }
    }
    if (family >= 2) {
      int j;
      for (j = 0; j < ns; j++) g_samples[j] = (short)rr(-32768, 32767);
      if (lcg_mod(4) == 0) for (j = 0; j < ns; j++) g_samples[j] = (lcg_next() & 1) ? -32768 : 32767;
    }
    {
      unsigned int h = du_call(aoff, nb, ns, 1);
      dc_calls_bins += nb;
      if (design_bin == 0 && ns == 1) {
        /* strict-double oracle on the designed sum */
        uint64_t got = ld64(bins + (design_isq ? 0x18 : 0x10));
        uint64_t sse = sse_add_int_dbl(design_p, sbits_pre);
        if (got != sse) dc_sse_diff++;
        else dc_sse_same++;
        (void)design_e;
      }
      dc_account_out(bins);
      log_call(&lg, h, nb, ns);
    }
  }
  log_done(&lg);
  need("du designed I", dc_designedI);
  need("du designed Q", dc_designedQ);
  need("du designed: pure-double result differs", dc_sse_diff);
  need("du sum > 2^53 out", dc_big53);
  need("du sum > 2^63 out", dc_big63);
  need("du nan out", dc_nan_out);
  need("du inf out", dc_inf_out);
  need("du align 0", dc_align0);
  need("du align 2", dc_align2);
  need("du align 4", dc_align4);
  return 0;
}

