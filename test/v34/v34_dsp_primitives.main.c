/* T06: V34descrambler takes the RX sub-object (V34Rx, = object offset 0x264) and V34PremptxCopy the modulator (V34Mod, = object offset 0x1450) of the native V34Obj;
   the harness' scratch buffer is an i386 IMAGE of each (a window of the object image): marshalled around the call (test/v34/v34_img.h) */
#define BIGOBJ_RX_BASE 0x264
#define BIGOBJ_MOD_BASE 0x1450
static short V34descrambler_img(unsigned char *buf, unsigned short inputBits, short numBits) {
  short r;
  V34I_REGW(buf, 0xd00, BIGOBJ_RX_BASE);
  v34i_enter();
  r = V34descrambler(v34i_in(buf), inputBits, numBits);
  v34i_leave();
  return r;
}
static void V34PremptxCopy_img(unsigned char *buf, const void *ptr) {
  V34I_REGW(buf, 0xd00, BIGOBJ_MOD_BASE);
  v34i_enter();
  V34PremptxCopy(v34i_in(buf), ptr);
  v34i_leave();
}
