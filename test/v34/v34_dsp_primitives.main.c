/*
 * Differential test harness for V.34's 25 hand-cleaned leaf DSP primitives
 * (src/v34/v34_dsp_primitives.c) - everything from porting/decompiled/dp/v34_primitives.c's
 * 26-function inventory EXCEPT `V34EchoHistoryBackwardClean`, which remains
 * unresolved/deferred (see NOTES.md).
 *
 * Same pattern as test/fpm_diff_main.c: this ONE source compiles into two
 * binaries - v34_primitives_test_blob (linked directly against the real
 * dsplibs.o, whose V34* functions are all globally exported per `nm
 * dsplibs.o`, confirmed before writing this harness) and
 * v34_primitives_test_port (linked against src/v34/v34_dsp_primitives.c +
 * src/v34/v34_timing_hilbert_tables.c, NOT dsplibs.o). The 12 Timing/Hilbert coefficient
 * tables referenced by V34Timing-family/V34HilbertFilter are GLOBAL symbols
 * in dsplibs.o (confirmed via readelf during the table-extraction pass), so
 * they are read directly by both sides' own V34Timing-family/
 * V34HilbertFilter implementations - this harness never touches them itself, sidestepping
 * any duplicate-symbol linking issue the same way fpm_diff_main.c's header
 * comment describes for its own config fixtures.
 *
 * Struct layouts (EchoAdaptState/PreFilterState/EqualizerState/TimingState)
 * are declared privately here, byte-for-byte identical to
 * src/v34/v34_dsp_primitives.c's own definitions - this harness is compiled
 * against BOTH sides, so it cannot #include the port header (there isn't
 * one; the struct defs live in the .c file) nor rely on dsplibs.o exposing
 * them (it doesn't - they're purely a calling convention, not real ELF
 * types).
 *
 * All test inputs are generated by a small deterministic LCG (no rand(),
 * so both binaries see byte-identical inputs without depending on libc RNG
 * behavior/seeding) - same discipline as test/v32_vtb_decoder_diff_main.c's
 * synthetic I/Q sequences.
 */

