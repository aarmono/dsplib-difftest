static unsigned int ms_hash_call(unsigned char *o, const unsigned char *snap) {
  unsigned int h = diff_obj(o, snap);
  return fnv32(h, hash_ext());
}

static void scen_modem_serrint(void) {
  logger_t lg = {"modem_serrint", FNV0, 0, 499};
  ms_cov_t cv;
  unsigned char *o = G_OBJ;
  long c;
  long alias_flag_cleared = 0, alias_flag_kept = 0;
  slot_off(0x394);
  slot_off(0x418);
  memset(&cv, 0, sizeof cv);
  for (c = 0; c < 40000; c++) {
    ms_par_t p;
    unsigned int h;
    int r;
    ms_setup(o, &p, 0, 0);
    ms_classify(o, &p, &cv);
    memcpy(G_SNAP, o, OBJSZ);
    r = modem_serrint(o);
    if (r != 0) die("modem_serrint returned non-zero");
    h = ms_hash_call(o, G_SNAP);
    if (p.fmode == 1 && p.place == 2 && !p.frozen) {
      /* did the re-read flags word still have bit 0x800? (observable: RX ring entry {x,0} vs Hilbert pair) */
      unsigned char *wr = (unsigned char *)PTRS(G_SNAP, 0x26c);
      if (S16(wr, 2) == 0 && (U16(o, 0x386) & 0x800)) alias_flag_kept++;
      else alias_flag_cleared++;
    }
    log_call(&lg, h, (long)p.c0, (long)p.fmode * 10 + p.place);
  }
  log_done(&lg);
  ms_report(&cv, 0);
  if (!g_t07) need("modem_serrint aliased flags word cleared by the FIR loop (Hilbert after FIR)", alias_flag_cleared);
  if (!g_t07) need("modem_serrint aliased flags word still 0x800 after the FIR loop", alias_flag_kept);
}

/* chain: the counter runs from -6 through 0x90, 45-multiples, 700, 843 (far energy), 2700.. and 18000 */
static void scen_modem_serrint_chain(void) {
  logger_t lg = {"modem_serrint-chain", FNV0, 0, 1999};
  ms_cov_t cv;
  unsigned char *o = G_OBJ;
  int trial, total = 5;
  slot_off(0x394);
  slot_off(0x418);
  memset(&cv, 0, sizeof cv);
  for (trial = 0; trial < total; trial++) {
    int32_t k;
    int nsteps = 18120;
    ms_par_t p;
    seed_obj(o, trial % 3);
    junk_word(o, 0x394);
    junk_word(o, 0x418);
    memset(&p, 0, sizeof p);
    p.fmode = trial % 3;
    p.place = 0;
    p.hz = (trial == 2) ? 0 : 1;
    U16(o, 0xa23c) = (uint16_t)p.hz;
    p.echo = 1;
    U16(o, 0x25c2) = (uint16_t)((U16(o, 0x25c2) | 0x200) & ~4);
    {
      uint16_t fl = rnd16();
      if (p.fmode == 0) fl |= 0x8000u;
      else if (p.fmode == 1) fl = (uint16_t)((fl & ~0x8000u) | 0x800u);
      else fl = (uint16_t)(fl & ~0x8800u);
      U16(o, 0x386) = fl;
    }
    S16(o, 0x2aa6) = (int16_t)rr(0, 597);
    S16(o, 0x2aa4) = (int16_t)rr(0, 297);
    I32(o, 0x354c) = -6;
    S16(o, 0x3550) = rshort();
    S16(o, 0x3552) = rshort();
    for (k = 0; k < nsteps; k++) {
      unsigned int h;
      p.d = (k % 53 == 52) ? -rr(1, 20) : rr(0, 30);
      set_delay(o, p.d);
      p.c0 = I32(o, 0x354c);
      p.frozen = 0;
      if (k % 2500 >= 2000 && k % 2500 < 2060) { /* echo off episodes */
        U16(o, 0x25c2) = (uint16_t)(U16(o, 0x25c2) & ~0x200);
        p.echo = 0;
      } else {
        U16(o, 0x25c2) = (uint16_t)(U16(o, 0x25c2) | 0x200);
        p.echo = 1;
      }
      if (k % 4093 == 4092) { /* short frozen episodes */
        U8(o, 0x25c2) |= 4;
        p.frozen = 1;
      } else {
        U8(o, 0x25c2) &= (uint8_t)~4;
      }
      if (k % 3001 == 3000) { /* switch the RX mode mid-run */
        p.fmode = (p.fmode + 1) % 3;
        U16(o, 0x386) = (uint16_t)(p.fmode == 0 ? 0x8000u : (p.fmode == 1 ? 0x0800u : 0));
      }
      if (!p.frozen) {
        int32_t c1 = (int32_t)((uint32_t)p.c0 + 1u);
        int sh = (int16_t)((uint32_t)p.c0 - 699u);
        int near = (c1 == 0x90), far = (c1 != 0 && sh == 0x90 && p.hz);
        if (near || far) guard_energy(o, p.d, 1, p.hz, near, far);
      }
      ms_classify(o, &p, &cv);
      if (modem_serrint(o) != 0) die("modem_serrint returned non-zero");
      h = hash_obj(o);
      log_call(&lg, h, (long)p.c0, (long)I32(o, 0x354c));
    }
  }
  log_done(&lg);
  ms_report(&cv, 1);
}

