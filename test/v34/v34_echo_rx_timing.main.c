static const char *k_tags[4] = {"NE", "FE", "", "x%d"};

/* x that terminates (never 0x80000000) and does not divide by zero (never [0xffff8000, 0xffffffff]) */
static uint32_t pick_x(void) {
  uint32_t x;
  for (;;) {
    switch (lcg_mod(16)) {
      case 0: x = 0; break;
      case 1: x = 1u << rr(0, 30); break;
      case 2: {
        int k = rr(0, 30);
        x = (1u << k) | (lcg_next() & ((1u << k) - 1u));
        break;
      }
      case 3: x = 0x40000000u | (lcg_next() & 0x3fffffffu); break;
      case 4: x = 0xc0000000u | (lcg_next() & 0x3fffffffu); break;
      case 5: x = 0x7fff8000u + (unsigned)rr(0, 0x7fff); break;
      case 6: x = 0xffff0000u + (unsigned)rr(0, 0x7fff); break;
      case 7: x = 0x80000000u | (lcg_next() & 0x7fffffffu); break;
      case 8: x = 0x7fffffffu - (unsigned)rr(0, 3); break;
      case 9: x = (unsigned)rr(1, 20); break;
      default: x = lcg_next() >> lcg_mod(31); break;
    }
    if (x == 0x80000000u || x >= 0xffff8000u) continue;
    return x;
  }
}

static const unsigned int k_levels[6] = {0u, 1u, 2u, 3u, 0x80000000u, 0xffffffffu};

/* x whose NORMALISED value x' has a low half at the rounding boundary of (x' + 0x8000) >> 16 */
static uint32_t pick_x_boundary(void) {
  uint32_t xp, x;
  int n = 0;
  uint32_t low;
  switch (lcg_mod(5)) {
    case 0: low = 0x8000u; n = rr(0, 15); break;
    case 1: low = 0x7fffu; n = 0; break;
    case 2: low = 0x8001u; n = 0; break;
    case 3: low = 0x7ffeu; n = rr(0, 1); break;
    default: low = 0x8000u; n = 0; break;
  }
  xp = 0x40000000u | ((lcg_next() & 0x3fffu) << 16) | low;
  if (n == 0 && lcg_mod(3) == 0) xp |= 0x80000000u; /* n == 0 with bit 31 set: the negative x' */
  x = xp >> n;
  if (x == 0x80000000u || x >= 0xffff8000u) x = 0x40008000u;
  return x;
}
/* k with (q*k) & 0x7fff == target, or -1 */
static int solve15(int q, int target) {
  int k;
  for (k = 0; k < 32768; k++)
    if (((q * k) & 0x7fff) == target) return k;
  return -1;
}
/* independent model of updateAlpha's first stage: returns the new alpha (after the k1 stage) for x != 0, or old */
static int ua_model_q(uint32_t x, int *qout) {
  uint32_t xs = x;
  int n = 0;
  int32_t dv, dn;
  int16_t q16;
  int q;
  if (x == 0) return 0;
  while (!(xs & 0x40000000u)) {
    n++;
    xs += xs;
  }
  dv = (int32_t)(xs + 0x8000u) >> 16;
  dn = (int32_t)(1u << ((n + 21) & 31));
  q16 = (int16_t)(dn / dv);
  q = q16 < 0 ? 0x2000 : q16;
  *qout = q;
  return 1;
}

static void scen_updatealpha(void) {
  logger_t lg = {"updateAlpha", FNV0, 0, 251};
  long designed = 0;
  long seen_n[32], zero = 0, flagb = 0, both = 0, negq = 0, trunc16 = 0, lvl1 = 0, huge = 0, printed = 0, quiet = 0, negalpha = 0,
       k1real = 0, alpha_wrap = 0, flagb_lowzero = 0, xbig = 0;
  int c, i;
  short abuf[8];
  memset(seen_n, 0, sizeof seen_n);
  for (c = 0; c < 60000; c++) {
    uint32_t x = pick_x();
    int flagB, k1, k2;
    unsigned int lvl = k_levels[c % 6];
    const char *tag = k_tags[lcg_mod(4)];
    long before = g_total_prints;
    unsigned int h;
    switch (lcg_mod(6)) {
      case 0: flagB = 0; break;
      case 1: flagB = 1; break;
      case 2: flagB = 0x100; break;
      case 3: flagB = (int)0x80000000u; break;
      case 4: flagB = -1; break;
      default: flagB = rint32(); break;
    }
    switch (lcg_mod(6)) {
      case 0: k1 = 0x7999; k2 = 0x7f5c; break;
      case 1: k1 = 0x6666; k2 = 0x7f5c; break;
      case 2: k1 = 0x2b84; k2 = 0x7f5c; break;
      case 3: k1 = 32767; k2 = -32768; break;
      case 4: k1 = -32768; k2 = 32767; break;
      default: k1 = rint32() >> lcg_mod(20); k2 = rint32() >> lcg_mod(20); break;
    }
    for (i = 0; i < 8; i++) abuf[i] = rshort();
    if (lcg_mod(8) == 0) abuf[3] = (lcg_mod(2) ? -32768 : 32767);
    if (lcg_mod(5) == 0) {
      /* designed input: rounding boundaries of the divisor add, the k1 product and the k2 product */
      int q, mid;
      x = pick_x_boundary();
      if (ua_model_q(x, &q)) {
        int t1 = lcg_mod(2) ? 0x5fff : 0x6000;
        int k = solve15(q, t1);
        if (k < 0) k = solve15(q, t1 == 0x5fff ? 0x6000 : 0x5fff);
        if (k >= 0) k1 = k + 32768 * rr(-2, 2);
        mid = (int16_t)(-((int32_t)((uint32_t)q * (uint32_t)k1 + 0x2000u) >> 15));
        {
          int t2 = lcg_mod(2) ? 0x3fff : 0x4000;
          int k2s = solve15(mid, t2);
          if (k2s < 0) k2s = solve15(mid, t2 == 0x3fff ? 0x4000 : 0x3fff);
          if (k2s >= 0) k2 = k2s + 32768 * rr(-2, 2);
        }
        if (flagB == 0) flagB = 1;
        designed++;
      }
    }
    dsplibs_debug_level = lvl;
    {
      short guard_before[8];
      memcpy(guard_before, abuf, sizeof abuf);
      updateAlpha(&abuf[3], x, flagB, k1, k2, tag);
      for (i = 0; i < 8; i++)
        if (i != 3 && abuf[i] != guard_before[i]) die("updateAlpha wrote outside *alpha");
    }
    dsplibs_debug_level = 0;
    h = fnv(FNV0, abuf, sizeof abuf);
    log_call(&lg, h, (long)x, (long)abuf[3]);
    /* coverage from an independent model of the normalise/divide */
    if (x == 0) {
      zero++;
    } else {
      uint32_t xs = x;
      int n = 0;
      int32_t dv, dn;
      while (!(xs & 0x40000000u)) {
        n++;
        xs += xs;
      }
      seen_n[n]++;
      dv = (int32_t)(xs + 0x8000u) >> 16;
      dn = (int32_t)(1u << ((n + 21) & 31));
      if ((int16_t)(dn / dv) < 0) negq++;
      if (dn / dv != (int16_t)(dn / dv)) trunc16++;
      if (x >= 0x80000000u) xbig++;
    }
    if (flagB) flagb++;
    if (flagB && x) both++;
    if (flagB && !(flagB & 0xff)) flagb_lowzero++;
    if (abuf[3] < 0) negalpha++;
    if (k1 == 0x7999 || k1 == 0x6666 || k1 == 0x2b84) k1real++;
    if (k1 == 32767 || k1 == -32768) alpha_wrap++;
    if (lvl == 1) lvl1++;
    if (lvl >= 0x80000000u) huge++;
    if (g_total_prints > before) printed++; else quiet++;
  }
  log_done(&lg);
  need("updateAlpha designed rounding-boundary inputs", designed);
  need("updateAlpha x == 0", zero);
  for (i = 0; i <= 30; i++) {
    char nm[48];
    sprintf(nm, "updateAlpha normalise shift n == %d", i);
    need(nm, seen_n[i]);
  }
  need("updateAlpha x with bit 31 set (n == 0 negative x or wrapped)", xbig);
  need("updateAlpha flagB != 0", flagb);
  need("updateAlpha flagB != 0 with a zero low byte", flagb_lowzero);
  need("updateAlpha flagB != 0 and x != 0", both);
  need("updateAlpha negative quotient (0x2000 substitute)", negq);
  need("updateAlpha quotient truncated to 16 bits", trunc16);
  need("updateAlpha negative resulting alpha", negalpha);
  need("updateAlpha real constants", k1real);
  need("updateAlpha extreme k", alpha_wrap);
  need("updateAlpha level == 1", lvl1);
  need("updateAlpha unsigned-huge level", huge);
  need("updateAlpha printed", printed);
  need("updateAlpha quiet", quiet);
}

