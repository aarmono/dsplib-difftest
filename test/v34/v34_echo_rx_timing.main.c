/* Object placement (scenario id / 100): 0 the static buffer; 1 / 2 an mmap()ed object placed so that the 2 GiB boundary
 * (0x80000000) falls inside the tx history ring [obj+0x2228, obj+0x25c0) / the RX ring [obj+0x270, obj+0x370): the
 * machine's ring-end compares are UNSIGNED (`cmp end,next ; ja`), so a signed compare would misfire exactly there. */
static void place_object(int placement) {
  uintptr_t want, page, len;
  void *m;
  if (placement == 0) {
    g_objp = g_objbuf;
    return;
  }
  want = (placement == 1) ? (uintptr_t)0x80000000u - 0x23c0u : (uintptr_t)0x80000000u - 0x2f0u;
  page = want & ~(uintptr_t)0xfff;
  len = ((want + OBJSZ + 64u - page) + 0xfffu) & ~(uintptr_t)0xfff;
#if defined(__x86_64__)
  /* x86-64: the IMAGE stays in the static buffer; the port works on the SHADOW, which is mapped so that 0x80000000 falls at the same ring offset */
  (void)page; (void)len; (void)m; (void)want;
  g_objp = g_objbuf;
  V34I_PLACE(g_objp, OBJSZ, (placement == 1) ? 0x23c0u : 0x2f0u, (uintptr_t)0x80000000u);
#else
  m = mmap((void *)page, len, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS | MAP_FIXED_NOREPLACE, -1, 0);
  if (m != (void *)page) die("cannot map the object around 0x80000000");
  g_objp = (unsigned char *)want;
#endif
}

typedef struct {
  const unsigned char *base;
  size_t size;
} ext_t;
static ext_t g_ext[8];
static int g_next;
static void ext_reg(const void *p, size_t sz) {
  g_ext[g_next].base = (const unsigned char *)p;
  g_ext[g_next].size = sz;
  g_next++;
}

/* table identities (V34TimingFiltersInit stores &V34TimingPrefilterCoeff / &V34TimingHPFilterCoeff into the TimingState) */
extern const short V34TimingPrefilterCoeff[];
extern const short V34TimingHPFilterCoeff[];
static uint32_t norm_val(const unsigned char *obj, uint32_t v) {
  int i;
  uintptr_t a = (uintptr_t)v;
  if (a == (uintptr_t)V34TimingPrefilterCoeff) return 0x7f000001u;
  if (a == (uintptr_t)V34TimingHPFilterCoeff) return 0x7f000002u;
  if (a >= (uintptr_t)obj && a < (uintptr_t)obj + OBJSZ) return 0x80000000u | (uint32_t)(a - (uintptr_t)obj);
  for (i = 0; i < g_next; i++)
    if (a >= (uintptr_t)g_ext[i].base && a < (uintptr_t)g_ext[i].base + g_ext[i].size)
      return 0x7d000000u | ((uint32_t)i << 16) | (uint32_t)(a - (uintptr_t)g_ext[i].base);
  return v;
}

/* offsets (in the fake object) of every 4-byte slot that may hold a pointer */
static const unsigned int k_slots[] = {0x2220, 0x2224, 0x268,  0x26c,  0x394,  0x418,  0x508,  0x35b0, 0x1460, 0x2074, 0x20cc, 0x2100,
                                       0x2a28, 0x620, 0x624, 0x80b8, 0x80bc, 0x80c0, 0x80c4, 0x80c8, 0x9138, 0x913c, 0x9140, 0x9144, 0x9148};
#define NSLOTS (sizeof k_slots / sizeof k_slots[0])
static unsigned char g_isslot[OBJSZ / 4];
static void slots_init(void) {
  size_t i;
  for (i = 0; i < NSLOTS; i++) g_isslot[k_slots[i] / 4] = 1;
}
static void scrub_slots(unsigned char *o) {
  size_t i;
  for (i = 0; i < NSLOTS; i++) U32(o, k_slots[i]) = 0x0d000000u | (lcg_next() & 0xffffffu);
}

static unsigned int diff_obj(const unsigned char *obj, const unsigned char *snap) {
  unsigned int h = FNV0;
  size_t i;
  for (i = 0; i < OBJSZ / 4; i++) {
    uint32_t a, b;
    memcpy(&a, obj + 4 * i, 4);
    memcpy(&b, snap + 4 * i, 4);
    if (g_isslot[i]) {
      a = norm_val(obj, a);
      b = norm_val(obj, b);
    }
    if (a != b) {
      uint32_t idx = (uint32_t)i;
      h = fnv(h, &idx, 4);
      h = fnv(h, &a, 4);
      if (g_verbose > 1) printf("   diffword off=%05x new=%08x\n", (unsigned int)(4 * i), a);
    }
  }
  return h;
}
static unsigned int hash_obj(const unsigned char *obj) {
  unsigned int h = FNV0;
  size_t i;
  for (i = 0; i < OBJSZ / 4; i++) {
    uint32_t a;
    memcpy(&a, obj + 4 * i, 4);
    if (g_isslot[i]) a = norm_val(obj, a);
    h = fnv(h, &a, 4);
  }
  return h;
}
/* everything outside the object that a function under test may write */
static unsigned int hash_ext(void) {
  unsigned int h = FNV0;
  h = fnv(h, g_scrbuf, sizeof g_scrbuf);
  h = fnv(h, g_cfir, sizeof g_cfir);
  h = fnv(h, g_tabbuf, sizeof g_tabbuf);
  h = fnv(h, g_src, sizeof g_src);
  h = fnv(h, g_cdes, sizeof g_cdes);
  return h;
}

/* ============================================================================
 * stubs: sysdep_memset (event hash) and dsplibs_debug_printf (level flip)
 * ========================================================================== */
static unsigned int g_ms_h = FNV0;
static long g_ms_calls, g_ms_skipped, g_ms_real;
void *sysdep_memset(void *dst, int c, size_t len) {
  /* x86-64: the port calls with a SHADOW pointer; V34I_IMGP(dst) is the image address (= dst at -m32) */
  uint32_t nd = norm_val(G_OBJ, (uint32_t)(uintptr_t)V34I_IMGP(dst));
  g_ms_h = fnv32(fnv32(fnv32(g_ms_h, nd), (uint32_t)c), (uint32_t)len);
  g_ms_calls++;
  if (len <= OBJSZ && (uintptr_t)V34I_IMGP(dst) >= (uintptr_t)G_OBJ && (uintptr_t)V34I_IMGP(dst) + len <= (uintptr_t)G_OBJ + OBJSZ) {
    memset(dst, c, len);
    g_ms_real++;
  } else {
    g_ms_skipped++;
  }
  return dst;
}

static int g_flip_after = -1; /* after the k-th (0-based) print of a call, set the level to g_flip_to */
static unsigned int g_flip_to;
static int g_nprint;
static long g_total_prints;
int dsplibs_debug_printf(const char *fmt, ...) {
  va_list ap;
  int ret;
  va_start(ap, fmt);
  ret = vprintf(fmt, ap);
  va_end(ap);
  g_total_prints++;
  if (g_flip_after >= 0 && g_nprint == g_flip_after) dsplibs_debug_level = g_flip_to;
  g_nprint++;
  return ret;
}

