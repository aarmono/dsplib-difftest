static int32_t pick_n_ae(void) {
  switch (lcg_mod(14)) {
    case 0: return rr(-5, 0);
    case 1: return 0x8f;
    case 2: return 0x90;
    case 3: return 0x90;
    case 4: return rr(1, 0x8f);
    case 5: return rr(0x91, 0x130);
    case 6: return 10 * rr(15, 60);
    case 7: return 10 * rr(15, 20);
    case 8: return rr(0x91, 5000);
    case 9: return (int32_t)0x80000000u; /* wrapped INT_MAX + 1 */
    case 10: return 0x7fffffff;
    case 11: return 10 * rr(1000, 100000);
    case 12: return -rr(100, 100000);
    default: return 0x91 + 9 + 10 * rr(0, 30); /* multiple of 10 above 0x90 */
  }
}
static uint32_t pick_e2(void) {
  static const uint32_t b[] = {0, 1, 2499999u, 2500000u, 2499998u, 11000000u, 11000001u, 10999999u, 13000000u, 13000001u, 12999999u,
                               0xffffffffu, 0x80000000u, 0x7fffffffu};
  if (lcg_mod(3) == 0) return lcg_next() >> lcg_mod(20);
  return b[lcg_mod(sizeof b / sizeof b[0])];
}
static int32_t pick_beta(void) {
  static const int32_t b[] = {-1, 0, 1, 2, 3, 4, 5, 6, 7, 8, 100, 0x7fffffff, (int32_t)0x80000000u};
  return b[lcg_mod(sizeof b / sizeof b[0])];
}

static void ae_setup(unsigned char *o, ae_par_t *p, int level_is_zero) {
  int amp = (int)lcg_mod(10);
  (void)level_is_zero;
  amp = amp < 4 ? 0 : (amp < 6 ? 1 : (amp < 8 ? 2 : 3));
  seed_obj(o, amp);
  switch (lcg_mod(6)) {
    case 0: p->d = -rr(1, 60); break;
    case 1: p->d = 0; break;
    default: p->d = rr(0, 1500); break;
  }
  set_delay(o, p->d);
  p->frozen = lcg_mod(7) == 0;
  if (p->frozen) U8(o, 0x25c2) |= 4; else U8(o, 0x25c2) &= (uint8_t)~4;
  p->n = pick_n_ae();
  I32(o, 0x354c) = (int32_t)((uint32_t)p->n - 1u);
  if (p->n > 0x90) {
    switch (lcg_mod(5)) {
      case 0: p->thr = p->n - 1; break;
      case 1: p->thr = p->n; break;
      case 2: p->thr = p->n + 1; break;
      case 3: p->thr = rint32(); break;
      default: p->thr = 0; break;
    }
  } else {
    p->thr = rint32() >> lcg_mod(30);
  }
  I32(o, 0x3554) = p->thr;
  p->beta = pick_beta();
  I32(o, 0x355c) = p->beta;
  p->e2 = pick_e2();
  U32(o, 0x3560) = p->e2;
  I32(o, 0x3558) = (lcg_mod(3) == 0) ? 0x7f5c : (rint32() >> lcg_mod(20));
  S16(o, 0x3550) = (lcg_mod(6) == 0) ? (int16_t)(lcg_mod(2) ? 32767 : -32768) : rshort();
  if (lcg_mod(8) == 0) {
    steer_echo(o, p->d, 0);
    ae_steered++;
  } else if (lcg_mod(9) == 0) {
    steer_echo2(o, p->d);
    ae_steered++;
  }
  if (!p->frozen && p->n <= 0x8f && lcg_mod(5) == 0) {
    /* rounding boundary of the V34EchoAdapt argument: pick alpha so that alpha*beta*e is 0x1fff or 0x2000 (mod 0x4000), with e the
     * value the call itself computes (dry run of the echo filter on a snapshot) */
    int r, f, e, tries;
    uint32_t target = lcg_mod(2) ? 0x1fffu : 0x2000u;
    unsigned int start = lcg_next() & 0xffffu;
    memcpy(G_SNAP, o, OBJSZ);
    r = V34EchoFilter(OB(o, 0x80b8), (short)p->d);
    memcpy(o, G_SNAP, OBJSZ);
    f = (int16_t)(U16(o, 0x260) + U16(o, 0xa23e));
    e = (int16_t)((uint32_t)f + (uint32_t)((int32_t)((uint32_t)r * 4u + 0x8000u) >> 16));
    for (tries = 0; tries < 65536; tries++) {
      int a = (int16_t)(start + (unsigned)tries);
      if ((((uint32_t)a * (uint32_t)p->beta * (uint32_t)e) & 0x3fffu) == target) {
        S16(o, 0x3550) = (int16_t)a;
        ae_arg_steered++;
        break;
      }
    }
  }
  if (!p->frozen && p->n == 0x90) guard_energy(o, p->d, 1, 0, 1, 0);
}

static void ae_classify(const unsigned char *o, const ae_par_t *p, ae_cov_t *c) {
  uint32_t E;
  c->calls++;
  if (p->d < 0) c->dneg++; else c->dpos++;
  if (p->d == 0) c->d_zero++;
  if (p->frozen) {
    c->frozen++;
    return;
  }
  if (p->n <= 0x8f) {
    c->acc_path++;
    if (p->n < 0) c->acc_neg_n++;
    if (p->n == 0x8f) c->acc_n8f++;
    if (p->n == (int32_t)0x80000000u) c->n_intmin++;
    return;
  }
  c->n_gt90 += (p->n != 0x90);
  if (p->n > p->thr && p->n % 10 == 0) c->b3_true++;
  else if (p->n > p->thr) c->b3_gt_not_mult++;
  else if (p->n % 10 == 0) c->b3_mult_not_gt++;
  if (p->thr < 0) c->thr_neg++;
  if (I32(o, 0x3558) < 0) c->k2_neg++;
  if (p->n == 0x90) {
    uint32_t e2 = p->e2;
    c->n90++;
    E = 0;
    (void)E;
    if (p->beta > 4 && e2 <= 2499999u) c->beta_lt4x++;
    else if (p->beta > 5 && e2 > 11000000u) c->beta_5x++;
    else if (p->beta > 2) c->beta_c13_only++;
    else c->beta_le2++;
    if ((p->beta > 2) && e2 > 13000000u) c->e13_store2++;
    if (e2 == 2499999u || e2 == 2500000u || e2 == 11000000u || e2 == 11000001u || e2 == 13000000u || e2 == 13000001u) c->e2_boundary++;
  }
}

