/*
 * Differential test harness for V.34 "tier 5b" (src/v34/v34_echo_rx_timing.c): the echo / RX sample path
 *   updateAlpha, adaptecho, modem_serrint, V34EchoHistoryBackwardClean, rxreadqueue,
 *   txwritequeue, rxtiming, rxtiminginit
 *
 * One source, two binaries (same convention as test/v34/v34_tx_symbol.main.c):
 *   v34_tier5b_test_blob - linked against the real dsplibs.o (-DTEST_BLOB)
 *   v34_tier5b_test_port - linked against src/v34/v34_echo_rx_timing.c + the already verified ports
 * Each scenario runs in its OWN process (argv[1]).
 *
 * Objects: tagV34Object is not a struct. A random fake object (OBJSZ = 0xb400 bytes, static at a
 * fixed address for the whole process) is refreshed per call (single-call scenarios; result = hash
 * of the DIFF: word index + new value of every changed word, so a stray write anywhere is caught)
 * or kept across calls (chain scenarios; result = hash of the WHOLE object after every call).
 * Pointer slots are compared NORMALISED (in-object -> offset, harness buffer -> (region id, offset));
 * raw addresses are never compared across the two processes.
 *
 * The callees (V34EchoFilter/Adapt/EstimateDelayLineEnergy, V34HilbertFilter, V34TimingHPFilter,
 * V34TimingFiltersInit, the LOCAL V34demodulate) are the REAL ones on both sides (the blob's own /
 * the already verified ports), so the blob and port run identical data through identical code and
 * any difference is in the eight functions under test. The fake object carries valid echo
 * cancellers (headers from the verified V34InitializeImplementationSpecific), valid tx-history and
 * RX ring pointers and read/write indices (incl. wrap edges), a valid rotation table for
 * V34demodulate and valid scratch memory behind the coefLo pointer fields the FIR path reuses.
 *
 * sysdep_memset (V34EchoHistoryBackwardClean) and dsplibs_debug_printf live in this file: the
 * memset stub hashes every call (normalised dst, value, length) so the ORDER, TARGETS and LENGTHS
 * are compared, and performs it only when it lies inside the fake object; the printer can lower the
 * debug level after the k-th print of a call (to prove the level is re-read at every print).
 *
 * INPUT ORACLES / HAZARDS (documented in src/v34/v34_echo_rx_timing.c):
 *   - updateAlpha hangs for x == 0x80000000 and divides by zero for x in [0xffff8000, 0xffffffff];
 *     the energies fed to it come from V34EchoEstimateDelayLineEnergy on the live state; a dry run
 *     on a snapshot rejects (and re-rolls) such states.
 *   - V34EchoFilter's tap index (writePtr + d + N - 1), the RX/TX ring pointers, the 600/300-entry
 *     rings and rxtiming's S[] array are unchecked: the harness keeps them inside the object.
 * Every scenario keeps COVERAGE COUNTERS (from the INPUTS / independent predicates) and exits 2 if a
 * branch class was never reached; exit 3 = harness assumption violated.
 *
 * Scenarios: 0 updateAlpha direct, 1 rxreadqueue/txwritequeue, 2 BackwardClean (all n classes, all
 * write-pointer positions), 3 adaptecho random, 4 adaptecho chain, 5 modem_serrint random,
 * 6 modem_serrint chain (counter through 0..18100), 7 rxtiming random + chain, 8 rxtiminginit,
 * 9 debug prints / level flips (updateAlpha, adaptecho, modem_serrint), 10 BackwardClean typical
 * (the caller's n = 3k, cap = 0 shape), 11 / 12 / 13 = 2 / 5 / 7 with in-array inputs (T07).
 */

