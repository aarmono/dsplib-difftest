typedef struct {
  int d;
  int32_t c0; /* counter BEFORE the call */
  int fmode;  /* 0 plain {x,0} (0x8000), 1 FIR (0x800), 2 Hilbert */
  int place;  /* FIR scratch: 0 in-object coefLo, 1 external, 2 aliases the flags word */
  int calias; /* FIR coefficient pointer aliases the scratch */
  int hz, echo, frozen;
  int i2aa6, j2aa4;
} ms_par_t;

typedef struct {
  long calls, frozen, plain, fir, hilbert, fir_in, fir_ext, fir_ext_odd, fir_alias, fir_alias_flag_cleared, fir_alias_flag_kept,
      fir_calias, echo_on, echo_off, hz_on_echo, hz_on_noecho, hz_off, d_neg, c1_zero, c1_90, sh_90, sh_90_hz, sh_90_nohz, b13, b13_gt2000_c1,
      b13_sh_gt2000, b13_c1_gt_not_sh, b13_sh_wrapneg, b13_not, c_small, c_17999, c_18000, c_gt18000, c_699, c_700, c_701, c_gt700, i_wrap,
      i_big, i_neg, i_alias, j_wrap, j_neg, j_m1, j_big, c1_neg, c_intmax, ring_wr_wrap, ring_rd_wrap, alpha_neg;
} ms_cov_t;

static int32_t pick_c0(void) {
  switch (lcg_mod(20)) {
    case 0: return -1;
    case 1: return -1;
    case 2: return 0x8f;
    case 3: return 0x8f;
    case 4: return 843 + 65536 * rr(-1, 1);
    case 5: return 843;
    case 6: return 45 * rr(1, 700) - 1;
    case 7: return 45 * rr(1, 700) - 1;
    case 8: {
      /* 920205 / 2034315: c1 % 45 == 0 with sh == 2001 / 1999 (sh is c1 - 700 truncated to 16 bits) */
      static const int32_t s[] = {2700 - 1, 2745 - 1, 2025 - 1, 1980 - 1, 33480 - 1, 33435 - 1, 33525 - 1, 2655 - 1, 2699 - 1, 2701 - 1, 65536 + 2745 - 1,
                                  920205 - 1, 2034315 - 1, 920205 - 1, 2034315 - 1};
      return s[lcg_mod(sizeof s / sizeof s[0])];
    }
    case 9: return 698 + rr(0, 3);
    case 10: return 17997 + rr(0, 4);
    case 11: return 17999;
    case 12: return -rr(2, 300);
    case 13: {
      static const int32_t s[] = {0x7fffffff, (int32_t)0x80000000u, 0x7ffffffe, -0x7fffffff, 100000, 60000};
      return s[lcg_mod(sizeof s / sizeof s[0])];
    }
    case 14: return 18001 + rr(0, 30);
    case 15: return 700 + rr(-1, 2);
    default: return rr(0, 19000);
  }
}

/* configure one modem_serrint call; `p` is filled, `o` prepared. */
static void ms_setup(unsigned char *o, ms_par_t *p, int fixed_c0, int32_t c0_value) {
  int amp = (int)lcg_mod(10);
  uint16_t fl;
  amp = amp < 4 ? 0 : (amp < 6 ? 1 : (amp < 8 ? 2 : 3));
  seed_obj(o, amp);
  junk_word(o, 0x394);
  junk_word(o, 0x418);
  switch (lcg_mod(6)) {
    case 0: p->d = -rr(1, 60); break;
    case 1: p->d = 0; break;
    default: p->d = rr(0, 1500); break;
  }
  set_delay(o, p->d);
  p->frozen = lcg_mod(7) == 0;
  p->echo = lcg_mod(10) < 7;
  {
    uint16_t w = U16(o, 0x25c2);
    w = p->echo ? (uint16_t)(w | 0x200) : (uint16_t)(w & ~0x200);
    w = p->frozen ? (uint16_t)(w | 4) : (uint16_t)(w & ~4);
    U16(o, 0x25c2) = w;
  }
  switch (lcg_mod(6)) {
    case 0: p->hz = 0; break;
    case 1: p->hz = 1; break;
    case 2: p->hz = 0x100; break;
    case 3: p->hz = 0xffff; break;
    default: p->hz = 1; break;
  }
  U16(o, 0xa23c) = (uint16_t)p->hz;
  p->c0 = fixed_c0 ? c0_value : pick_c0();
  I32(o, 0x354c) = p->c0;
  /* RX flags word obj+0x386 */
  switch (lcg_mod(10)) {
    case 0: case 1: case 2: p->fmode = 0; break;
    case 3: case 4: case 5: p->fmode = 1; break;
    default: p->fmode = 2; break;
  }
  fl = rnd16();
  if (p->fmode == 0) fl |= 0x8000u;
  else if (p->fmode == 1) fl = (uint16_t)((fl & ~0x8000u) | 0x800u);
  else fl = (uint16_t)(fl & ~0x8800u);
  U16(o, 0x386) = fl;
  /* FIR scratch / coefficients */
  p->place = 0;
  p->calias = 0;
  if (p->fmode == 1) {
    int r = (int)lcg_mod(12);
    if (r < 5) p->place = 0;
    else if (r < 9) p->place = 1;
    else p->place = g_t07 ? 1 : 2;
    if (lcg_mod(9) == 0) p->calias = 1;
  }
  fill_random(g_scrbuf, sizeof g_scrbuf);
  if (p->place == 1) {
    PTRS(o, 0x9144) = G_SCR + ((lcg_mod(3) == 0) ? 2 : 0);
  } else if (p->place == 2) {
    int k = rr(0, 60);
    PTRS(o, 0x9144) = OB(o, 0x386 - 2 * k);
    /* the FIR loop (and the far V34EchoAdapt, which uses the same pointer as coefLo) move / add the words in
     * obj+0x30e..0x4a6: those must not contain addresses (they differ between the two processes) */
    U32(o, 0x394) = 0x0d000000u | (lcg_next() & 0xffffffu);
    U32(o, 0x418) = 0x0d000000u | (lcg_next() & 0xffffffu);
  }
  if (p->calias) PTRS(o, 0x508) = PTRS(o, 0x9144);
  /* index words */
  switch (lcg_mod(8)) {
    case 0: p->i2aa6 = 599; break;
    case 1: p->i2aa6 = 598; break;
    case 2: p->i2aa6 = rr(600, 700); break;
    case 3: p->i2aa6 = -rr(1, 200); break;
    case 4: p->i2aa6 = -598; break;
    default: p->i2aa6 = rr(0, 597); break;
  }
  S16(o, 0x2aa6) = (int16_t)p->i2aa6;
  switch (lcg_mod(8)) {
    case 0: p->j2aa4 = 299; break;
    case 1: p->j2aa4 = 298; break;
    case 2: p->j2aa4 = rr(300, 400); break;
    case 3: p->j2aa4 = -rr(2, 30); break;
    case 4: p->j2aa4 = -1; break;
    default: p->j2aa4 = rr(0, 297); break;
  }
  S16(o, 0x2aa4) = (int16_t)p->j2aa4;
  /* RX ring write pointer near the end half of the time */
  if (lcg_mod(2)) PTRS(o, 0x26c) = OB(o, 0x270 + 4 * (62 + (int)lcg_mod(2)) + odd_off());
  if (lcg_mod(2)) PTRS(o, 0x2220) = OB(o, TXR_BASE + 4 * (TXR_N - 1 - (int)lcg_mod(2)) + odd_off());
  S16(o, 0x3550) = (lcg_mod(8) == 0) ? (int16_t)(lcg_mod(2) ? 32767 : -32768) : rshort();
  S16(o, 0x3552) = (lcg_mod(8) == 0) ? (int16_t)(lcg_mod(2) ? 32767 : -32768) : rshort();
  if (lcg_mod(6) == 0) S16(o, 0xa240) = (int16_t)(lcg_mod(2) ? 32767 : -32768);
  if (p->echo && lcg_mod(8) == 0) {
    steer_echo(o, p->d, (uint16_t)p->hz ? (int)lcg_mod(2) : 0);
    ms_steered++;
  } else if (p->echo && lcg_mod(7) == 0) {
    steer_echo2(o, p->d);
    ms_steered++;
  }
  if (p->fmode == 1 && p->place != 2 && !p->calias && lcg_mod(5) == 0) {
    /* designed FIR: one tap 0x4000 against a scratch word == 2 (mod 4): the sum is exactly at the rounding boundary */
    int k = rr(0, 58);
    short *sp = (short *)PTRS(o, 0x9144);
    int i;
    for (i = 0; i < 64 + 16; i++) g_cdes[i] = 0;
    g_cdes[k] = 0x4000;
    PTRS(o, 0x508) = g_cdes;
    sp[59 - k] = (short)(4 * rr(-3000, 3000) + 2);
    ms_fir_designed++;
  }
  if (p->fmode == 2 && lcg_mod(6) == 0) {
    /* designed Hilbert: echo off, x == 0, a single non-zero tap pair: buf[28] = v2 sets h2 = -1561*v2 and (with buf[30] = v1)
     * h1 = 12857*v1 - 2920*v2, both solved to sit at the rounding boundary of (h + 0x2000) >> 14 */
    uint32_t t1 = lcg_mod(2) ? 0x1fffu : 0x2000u, t2 = lcg_mod(2) ? 0x1fffu : 0x2000u;
    int v1 = 0, v2 = 0, ok2 = 0, ok1 = 0, i;
    unsigned int st = lcg_next() & 0xffffu;
    for (i = 0; i < 65536 && !ok2; i++) {
      int v = (int16_t)(st + (unsigned)i);
      if ((((uint32_t)(-1561 * v)) & 0x3fffu) == t2) {
        v2 = v;
        ok2 = 1;
      }
    }
    for (i = 0; i < 65536 && ok2 && !ok1; i++) {
      int v = (int16_t)(st * 7u + (unsigned)i);
      if ((((uint32_t)(12857 * v - 2920 * v2)) & 0x3fffu) == t1) {
        v1 = v;
        ok1 = 1;
      }
    }
    if (ok1 && ok2) {
      p->echo = 0;
      U16(o, 0x25c2) = (uint16_t)(U16(o, 0x25c2) & ~0x200);
      U16(o, 0x260) = 0;
      U16(o, 0xa23e) = 0;
      memset(OB(o, 0xa1b8), 0, 0x80);
      S16(o, 0xa1b8 + 2 * 28) = (int16_t)v2;
      S16(o, 0xa1b8 + 2 * 30) = (int16_t)v1;
      ms_hilbert_designed++;
    }
  } else if ((p->fmode == 0 || p->fmode == 2) && lcg_mod(5) == 0) {
    /* designed an / af: echo off so that x == (short)(F + a23e) is known; alpha chosen so that alpha*x*2 == 0x2000 (mod 0x4000)
     * (the rounding boundary of the `+ 0x2000 >> 14`); only when no alpha update can happen in this call */
    int32_t c1 = (int32_t)((uint32_t)p->c0 + 1u);
    int sh = (int16_t)((uint32_t)p->c0 - 699u);
    if (c1 != 0 && c1 != 0x90 && sh != 0x90 && (c1 % 45) != 0) {
      int Fv = rshort(), a23 = rshort();
      int x = (int16_t)(Fv + a23), i;
      unsigned int st = lcg_next() & 0xffffu;
      p->echo = 0;
      U16(o, 0x25c2) = (uint16_t)(U16(o, 0x25c2) & ~0x200);
      U16(o, 0x260) = (uint16_t)Fv;
      U16(o, 0xa23e) = (uint16_t)a23;
      for (i = 0; i < 65536; i++) {
        int a = (int16_t)(st + (unsigned)i);
        if ((((uint32_t)a * (uint32_t)x * 2u) & 0x3fffu) == 0x2000u) {
          S16(o, 0x3550) = (int16_t)a;
          ms_an_designed++;
          break;
        }
      }
      st = lcg_next() & 0xffffu;
      for (i = 0; i < 65536; i++) {
        int a = (int16_t)(st + (unsigned)i);
        if ((((uint32_t)a * (uint32_t)x * 2u) & 0x3fffu) == 0x2000u) {
          S16(o, 0x3552) = (int16_t)a;
          break;
        }
      }
    }
  }
  /* energy guard for the calls that estimate an energy */
  if (!p->frozen) {
    int32_t c1 = (int32_t)((uint32_t)p->c0 + 1u);
    int sh = (int16_t)((uint32_t)p->c0 - 699u);
    int near = (c1 == 0x90);
    int far = (c1 != 0 && sh == 0x90 && (uint16_t)p->hz != 0);
    if (near || far) guard_energy(o, p->d, p->echo, p->echo && (uint16_t)p->hz, near, far);
  }
}

static void ms_classify(const unsigned char *o, const ms_par_t *p, ms_cov_t *c) {
  int32_t c1;
  int sh, rem0;
  c->calls++;
  if (p->d < 0) c->d_neg++;
  if (p->echo) {
    c->echo_on++;
    if ((uint16_t)p->hz) c->hz_on_echo++;
  } else {
    c->echo_off++;
    if ((uint16_t)p->hz) c->hz_on_noecho++;
  }
  if (!(uint16_t)p->hz) c->hz_off++;
  if (S16(o, 0x3550) < 0) c->alpha_neg++;
  {
    /* RX ring write pointer */
    unsigned int wr = (unsigned int)((unsigned char *)PTRS(o, 0x26c) - o);
    if (wr + 4 >= 0x370) c->ring_wr_wrap++;
    if ((unsigned int)((unsigned char *)PTRS(o, 0x2220) - o) + 4 >= TXR_END) c->ring_rd_wrap++;
  }
  if (p->fmode == 0) c->plain++;
  else if (p->fmode == 2) c->hilbert++;
  else {
    c->fir++;
    if (p->place == 0) c->fir_in++;
    if (p->place == 1) {
      c->fir_ext++;
      if ((unsigned char *)PTRS(o, 0x9144) - G_SCR) c->fir_ext_odd++;
    }
    if (p->place == 2) c->fir_alias++;
    if (p->calias) c->fir_calias++;
  }
  if (p->i2aa6 >= 599) c->i_wrap++;
  if (p->i2aa6 > 599) c->i_big++;
  if (p->i2aa6 < 0) c->i_neg++;
  if (p->i2aa6 == -598) c->i_alias++;
  if (p->j2aa4 >= 299) c->j_wrap++;
  if (p->j2aa4 > 299) c->j_big++;
  if (p->j2aa4 < 0) c->j_neg++;
  if (p->j2aa4 == -1) c->j_m1++;
  if (p->frozen) {
    c->frozen++;
    return;
  }
  c1 = (int32_t)((uint32_t)p->c0 + 1u);
  sh = (int16_t)((uint32_t)p->c0 - 699u);
  rem0 = (c1 % 45) == 0;
  if (c1 == 0) {
    c->c1_zero++;
  } else {
    if (c1 == 0x90) c->c1_90++;
    if (sh == 0x90) {
      c->sh_90++;
      if ((uint16_t)p->hz) c->sh_90_hz++; else c->sh_90_nohz++;
    }
    if (rem0) {
      c->b13++;
      if (c1 > 2000) c->b13_gt2000_c1++;
      if (sh > 2000) c->b13_sh_gt2000++;
      if (c1 > 2000 && !(sh > 2000)) c->b13_c1_gt_not_sh++;
      if (c1 > 2000 && sh < 0) c->b13_sh_wrapneg++;
    } else {
      c->b13_not++;
    }
  }
  if (c1 < 0) c->c1_neg++;
  if (p->c0 == 0x7fffffff) c->c_intmax++;
  if (p->d >= 0) {
    if (c1 <= 17999) c->c_small++;
    if (c1 == 17999) c->c_17999++;
    if (c1 == 18000) c->c_18000++;
    if (c1 > 18000) c->c_gt18000++;
    if ((uint16_t)p->hz) {
      if (c1 == 699) c->c_699++;
      if (c1 == 700) c->c_700++;
      if (c1 == 701) c->c_701++;
      if (c1 > 700) c->c_gt700++;
    }
  }
}

