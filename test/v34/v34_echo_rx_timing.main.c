typedef struct {
  int cnt;
  unsigned pos, step, lim;
} rt_par_t;

typedef struct {
  long calls, cnt_le0, cnt1, cnt4, cnt_gt4, iters, nowrap, onewrap, twowrap, lim_neg, lim_zero, sum_overflow16, step_zero, pos_ge_lim,
      s2_eq_lim, s_eq_lim, sat_hp, a_neg, chain_calls, demod_calls, ring_wrap, dneg, cnt_big;
} rt_cov_t;

/* AGC / rotation / ring configuration of the RX front end b = obj+0x264 (same recipe as the tier-2 demodulate test) */
static void rt_demod_config(unsigned char *o) {
  unsigned char *b = OB(o, 0x264);
  unsigned int regime = lcg_mod(6);
  unsigned int shift = lcg_mod(16);
  unsigned int mod = 4 + lcg_mod(197);
  int i;
  U16(b, 0) = rnd16();
  for (i = 0; i < 128; i++)
    S16(b, 0x0c + 2 * i) = (int16_t)(rshort() >> (regime == 0 ? 0 : (regime == 1 ? 12 : shift)));
  PTRS(b, 4) = OB(b, 0x0c + 4 * ((lcg_mod(3) == 0) ? 63 - lcg_mod(3) : lcg_mod(64)));
  for (i = 0; i < 36; i++) {
    unsigned int m = lcg_mod(8);
    S16(b, 0x13c + 2 * i) = (m == 0) ? 0 : (m == 1) ? (int16_t)(rshort() >> 14) : (int16_t)(rshort() >> (regime == 2 ? 0 : shift));
  }
  S16(b, 0x19c) = (int16_t)lcg_mod(36);
  switch (lcg_mod(6)) {
    case 0: S16(b, 0x136) = (int16_t)(0x10 + lcg_mod(0x300)); break;
    case 1: S16(b, 0x136) = (int16_t)(0x300 + lcg_mod(0x300)); break;
    case 2: S16(b, 0x136) = (int16_t)(0x6000 + lcg_mod(0x2000)); break;
    case 3: S16(b, 0x136) = (int16_t)(0x7000 + lcg_mod(0xfff)); break;
    case 4: S16(b, 0x136) = rshort(); break;
    default: S16(b, 0x136) = (int16_t)(0x100 + lcg_mod(0x7000)); break;
  }
  switch (lcg_mod(4)) {
    case 0: S16(b, 0x134) = (int16_t)(4000 + (int)lcg_mod(6001) - 3000); break;
    case 1: S16(b, 0x134) = (int16_t)(4000 + (int)lcg_mod(1000) - 500); break;
    case 2: S16(b, 0x134) = rshort(); break;
    default: S16(b, 0x134) = (int16_t)(0x7000 + lcg_mod(0xf00)); break;
  }
  S16(b, 0x138) = (lcg_mod(2) ? (int16_t)((int)lcg_mod(1200) - 600) : rshort());
  S16(b, 0x13a) = (lcg_mod(3) ? (int16_t)lcg_mod(0x7fff) : rshort());
  U16(b, 0x122) = rnd16();
  if (lcg_mod(5) == 0) U16(b, 0x122) |= 0x200; else U16(b, 0x122) &= (uint16_t)~0x200;
  S16(b, 0x12a) = (int16_t)(lcg_mod(6) - 1);
  U32(b, 0x12c) = (lcg_mod(3) == 0) ? lcg_next() : (lcg_next() >> lcg_mod(32));
  PTRS(b, 0x1b4) = G_TAB;
  /* the sink pointer is set by rxtiming/rxtiminginit themselves: start it somewhere else so a missing store is visible */
  if (lcg_mod(4) != 0) PTRS(b, 0x130) = OB(o, 0x300 + 2 * (int)lcg_mod(20));
  U16(b, 0x1ba) = (uint16_t)mod;
  U16(b, 0x1b8) = (uint16_t)lcg_mod(mod + 1); /* step <= mod keeps idx in [0,mod) */
  S16(b, 0x1bc) = (int16_t)lcg_mod(mod);
}

static int rt_model(const rt_par_t *p, unsigned *pos_out, rt_cov_t *c);
#define RT_MAXCALLS 13 /* rxtiming's sink pointer is obj+0x370 = b+0x10c: call k stores at b+0x10c+2k; call 14 would hit b+0x128 (cnt) */
static void rt_timing_config(unsigned char *o, rt_par_t *p) {
  unsigned char *b = OB(o, 0x264);
  unsigned lim;
  switch (lcg_mod(12)) {
    case 0: case 1: case 2: case 3: case 4: p->cnt = 4; break;
    case 5: p->cnt = 1; break;
    case 6: p->cnt = 2; break;
    case 7: p->cnt = 3 + (int)lcg_mod(3); break;
    case 8: p->cnt = 8 + (int)lcg_mod(10); break;
    case 9: p->cnt = (int)lcg_mod(2) ? 0 : -(int)lcg_mod(3) - 1; break;
    case 10:
      p->cnt = (lcg_mod(4) == 0) ? -32768 : (lcg_mod(3) == 0 ? 128 + (int)lcg_mod(173) : 25 + (int)lcg_mod(30));
      break;
    default: p->cnt = 4; break;
  }
  if (g_t07 && p->cnt > 21) p->cnt = 8 + (int)lcg_mod(14);
  switch (lcg_mod(8)) {
    case 0: { /* small window, mostly no wrap */
      lim = 40 + lcg_mod(200);
      p->lim = lim;
      p->step = lcg_mod(lim / 3 + 1);
      p->pos = lcg_mod(lim);
      break;
    }
    case 1: { /* wraps once */
      lim = 10 + lcg_mod(100);
      p->lim = lim;
      p->step = lim / 2 + lcg_mod(lim / 2 + 1);
      p->pos = lim / 2 + lcg_mod(lim / 2);
      break;
    }
    case 2: { /* wraps twice */
      lim = 3 + lcg_mod(60);
      p->lim = lim;
      p->step = lim + lcg_mod(2 * lim + 1);
      p->pos = lcg_mod(lim);
      break;
    }
    case 3: { /* negative lim as a short */
      p->lim = 0x8000u + lcg_mod(0x8000);
      p->step = lcg_mod(0x10000);
      p->pos = lcg_mod(0x10000);
      break;
    }
    case 4: { /* boundaries around lim */
      lim = 5 + lcg_mod(50);
      p->lim = lim;
      p->pos = lcg_mod(lim);
      p->step = (lcg_mod(2) ? lim - p->pos : 2 * lim - p->pos) + (lcg_mod(3)) - 1; /* s == lim -1/0/+1, s2 == lim -1/0/+1 */
      break;
    }
    case 5: { /* 16-bit overflow of pos+step */
      p->lim = 0x7000u + lcg_mod(0x1000);
      p->pos = 0xf000u + lcg_mod(0x1000);
      p->step = 0x1000u + lcg_mod(0x8000);
      break;
    }
    case 6: p->lim = lcg_mod(3); p->pos = lcg_mod(0x10000); p->step = lcg_mod(0x10000); break;
    default: {
      p->lim = lcg_mod(0x10000);
      p->pos = lcg_mod(0x10000);
      p->step = lcg_mod(0x10000);
      if (lcg_mod(2)) p->lim &= 0x7fff;
      break;
    }
  }
  if (p->cnt >= 25) { /* long runs only make sense without wraps (each demodulate call stores one sample) */
    p->lim = 200 + lcg_mod(2000);
    p->step = lcg_mod(3);
    p->pos = lcg_mod(50);
  }
  p->pos &= 0xffffu;
  p->step &= 0xffffu;
  p->lim &= 0xffffu;
  for (;;) {
    unsigned pe;
    if (p->cnt <= 1 || rt_model(p, &pe, NULL) <= RT_MAXCALLS) break;
    p->cnt--;
  }
  S16(b, 0x128) = (int16_t)p->cnt;
  U16(b, 0x1ac) = (uint16_t)p->pos;
  U16(b, 0x1ae) = (uint16_t)p->step;
  U16(b, 0x1b0) = (uint16_t)p->lim;
  /* interpolation pairs / resonator state */
  switch (lcg_mod(4)) {
    case 0: {
      int i;
      for (i = 0; i < 4; i++) S16(b, 0x240 + 2 * i) = (int16_t)(rshort() >> 10);
      break;
    }
    case 1: {
      int i;
      for (i = 0; i < 4; i++) S16(b, 0x240 + 2 * i) = (lcg_mod(2)) ? 32767 : -32768;
      break;
    }
    default: break; /* random from seed_obj */
  }
  if (lcg_mod(3) == 0) {
    int i;
    for (i = 0; i < 4; i++) S16(b, 0x208 + 2 * i) = (int16_t)(rshort() >> lcg_mod(12));
  }
}

/* independent model of rxtiming's control flow: returns the number of V34demodulate calls; final pos */
static int rt_model(const rt_par_t *p, unsigned *pos_out, rt_cov_t *c) {
  unsigned pos = p->pos, step = p->step, lim = p->lim;
  int lims = (int16_t)lim, i = 0, calls = 0;
  if ((int16_t)p->cnt <= 0) {
    if (c) c->cnt_le0++;
    *pos_out = pos;
    return 0;
  }
  do {
    unsigned sum = pos + step;
    unsigned s = sum & 0xffffu;
    if (c) {
      c->iters++;
      if (lims < 0) c->lim_neg++;
      if (lim == 0) c->lim_zero++;
      if (sum > 0xffffu) c->sum_overflow16++;
      if (step == 0) c->step_zero++;
      if (pos >= lim) c->pos_ge_lim++;
      if ((int)s == lims) c->s_eq_lim++;
    }
    if ((int)s < lims) {
      pos = s;
      if (c) c->nowrap++;
    } else {
      unsigned t = sum - lim;
      if (c && (int)(t & 0xffffu) == lims) c->s2_eq_lim++;
      if ((int)(t & 0xffffu) < lims) {
        pos = t & 0xffffu;
        calls += 1;
        if (c) c->onewrap++;
      } else {
        pos = (t - lim) & 0xffffu;
        calls += 2;
        if (c) c->twowrap++;
      }
    }
    i = (int16_t)(i + 1);
  } while ((int16_t)p->cnt > i);
  *pos_out = pos;
  return calls;
}

static void rt_report(const rt_cov_t *c, int chain) {
  need("rxtiming calls", c->calls);
  need("rxtiming iterations", c->iters);
  need("rxtiming no-wrap iterations", c->nowrap);
  need("rxtiming one-wrap iterations", c->onewrap);
  need("rxtiming two-wrap iterations", c->twowrap);
  need("rxtiming demodulate calls", c->demod_calls);
  if (chain) return;
  need("rxtiming cnt <= 0 (returns at once)", c->cnt_le0);
  need("rxtiming cnt == 1", c->cnt1);
  need("rxtiming cnt == 4", c->cnt4);
  need("rxtiming cnt > 4", c->cnt_gt4);
  if (!g_t07) need("rxtiming cnt >= 25", c->cnt_big);
  need("rxtiming lim negative as a short", c->lim_neg);
  need("rxtiming lim == 0", c->lim_zero);
  need("rxtiming pos+step overflows 16 bits", c->sum_overflow16);
  need("rxtiming step == 0", c->step_zero);
  need("rxtiming pos >= lim", c->pos_ge_lim);
  need("rxtiming s == (short)lim", c->s_eq_lim);
  need("rxtiming s2 == (short)lim", c->s2_eq_lim);
  need("rxtiming interpolation input negative", c->a_neg);
}

static void scen_rxtiming(void) {
  logger_t lg = {"rxtiming", FNV0, 0, 499};
  rt_cov_t cv;
  unsigned char *o = G_OBJ;
  long c;
  slot_off(0x508);
  slot_off(0x620);
  slot_off(0x624);
  memset(&cv, 0, sizeof cv);
  for (c = 0; c < 40000; c++) {
    rt_par_t p;
    unsigned pos_exp, h;
    int calls;
    uint16_t b0;
    seed_obj(o, 0);
    junk_word(o, 0x508);
    rt_demod_config(o);
    rt_timing_config(o, &p);
    calls = rt_model(&p, &pos_exp, &cv);
    cv.calls++;
    if (p.cnt == 1) cv.cnt1++;
    if (p.cnt == 4) cv.cnt4++;
    if (p.cnt > 4) cv.cnt_gt4++;
    if (p.cnt >= 25) cv.cnt_big++;
    if (S16(o, 0x264 + 0x240) < 0) cv.a_neg++;
    cv.demod_calls += calls;
    b0 = U16(o, 0x264);
    memcpy(G_SNAP, o, OBJSZ);
    rxtiming(o);
    if (U16(o, 0x264 + 0x1ac) != (uint16_t)pos_exp) die("rxtiming: final position differs from the independent model");
    if ((uint16_t)(b0 - U16(o, 0x264)) != (uint16_t)calls) {
      fprintf(stderr, "call %ld cnt=%d pos=%u step=%u lim=%u: b0 %u -> %u, model calls %d\n", c, p.cnt, p.pos, p.step, p.lim, b0, U16(o, 0x264), calls);
      die("rxtiming: number of V34demodulate calls differs from the model");
    }
    h = diff_obj(o, G_SNAP);
    log_call(&lg, h, (long)p.cnt, (long)calls);
  }
  log_done(&lg);
  rt_report(&cv, 0);
}

/* chain: the object persists; the timing window is re-drawn every 40 calls */
static void scen_rxtiming_chain(void) {
  logger_t lg = {"rxtiming-chain", FNV0, 0, 499};
  rt_cov_t cv;
  unsigned char *o = G_OBJ;
  long c;
  rt_par_t p;
  slot_off(0x508);
  slot_off(0x620);
  slot_off(0x624);
  memset(&cv, 0, sizeof cv);
  seed_obj(o, 0);
  junk_word(o, 0x508);
  rt_demod_config(o);
  rt_timing_config(o, &p);
  for (c = 0; c < 30000; c++) {
    unsigned pos_exp, h;
    int calls;
    uint16_t b0;
    if (c % 40 == 39) {
      unsigned char *b = OB(o, 0x264);
      rt_par_t q;
      rt_timing_config(o, &q);
      /* keep the running position half of the time */
      if (lcg_mod(2)) {
        q.pos = p.pos;
        U16(b, 0x1ac) = (uint16_t)q.pos;
      }
      p = q;
    }
    if (c % 7 == 6) {
      unsigned char *b = OB(o, 0x264);
      int i;
      /* fresh input samples, valid ring pointer */
      for (i = 0; i < 128; i++) S16(b, 0x0c + 2 * i) = (int16_t)(rshort() >> (int)(lcg_mod(3) * 4));
      PTRS(b, 4) = OB(b, 0x0c + 4 * lcg_mod(64));
    }
    p.pos = U16(o, 0x264 + 0x1ac);
    p.cnt = S16(o, 0x264 + 0x128);
    p.step = U16(o, 0x264 + 0x1ae);
    p.lim = U16(o, 0x264 + 0x1b0);
    while (p.cnt > 1 && rt_model(&p, &pos_exp, NULL) > RT_MAXCALLS) { /* the position evolves: re-bound the call count */
      p.cnt--;
      S16(o, 0x264 + 0x128) = (int16_t)p.cnt;
    }
    calls = rt_model(&p, &pos_exp, &cv);
    cv.calls++;
    cv.demod_calls += calls;
    b0 = U16(o, 0x264);
    rxtiming(o);
    if (U16(o, 0x264 + 0x1ac) != (uint16_t)pos_exp) die("rxtiming chain: final position differs from the model");
    if ((uint16_t)(b0 - U16(o, 0x264)) != (uint16_t)calls) die("rxtiming chain: demodulate call count differs from the model");
    h = hash_obj(o);
    log_call(&lg, h, (long)p.cnt, (long)calls);
  }
  log_done(&lg);
  rt_report(&cv, 1);
}

static void scen_rxtiminginit(void) {
  logger_t lg = {"rxtiminginit", FNV0, 0, 199};
  unsigned char *o = G_OBJ;
  long c, seq = 0;
  for (c = 0; c < 6000; c++) {
    unsigned h;
    seed_obj(o, 0);
    PTRS(o, 0x394) = OB(o, 0x300 + 2 * (int)lcg_mod(20)); /* the sink pointer rxtiminginit stores must be visible */
    memcpy(G_SNAP, o, OBJSZ);
    rxtiminginit(o);
    h = diff_obj(o, G_SNAP);
    if (U16(o, 0x264 + 0x1d2) != 0x960 || U16(o, 0x264 + 0x1c0) != 0xffff || U32(o, 0x264 + 0x1c8) != 1) die("rxtiminginit: constants not stored");
    log_call(&lg, h, 0, 0);
  }
  /* rxtiminginit followed by rxtiming (integration: same object, valid demodulate configuration) */
  for (c = 0; c < 1500; c++) {
    rt_par_t p;
    unsigned h, pos_exp;
    int calls;
    seed_obj(o, 0);
    rt_demod_config(o);
    rt_timing_config(o, &p);
    rxtiminginit(o);
    S16(o, 0x264 + 0x128) = 4;
    p.cnt = 4;
    calls = rt_model(&p, &pos_exp, NULL);
    (void)calls;
    rxtiming(o);
    h = hash_obj(o);
    seq++;
    log_call(&lg, h, 1, 0);
  }
  log_done(&lg);
  need("rxtiminginit calls", lg.calls);
  need("rxtiminginit + rxtiming sequences", seq);
}

