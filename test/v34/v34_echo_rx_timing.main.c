/* Expected effect of the tail loop, computed independently: entry (word offset in the object) of the k-th zeroed slot */
static void bc_tail_slots(const bc_par_t *p, unsigned int slot[3]) {
  int k, top = 4;
  int wp = (int)(TXR_BASE + 4 * p->ringk + p->ringoff);
  for (k = 0; k < 3; k++) {
    int cur = wp - 4 * (k + 1);
    if (cur >= (int)TXR_BASE) {
      slot[k] = (unsigned)cur;
    } else {
      slot[k] = TXR_END - (unsigned)top;
      top += 4;
    }
  }
}

/* build an object + parameters for one call; `real` selects the caller's shape (cap = 0 ...) */
static void bc_setup(unsigned char *o, bc_par_t *p, int real, bc_cov_t *cv, long callno) {
  int mode, mcls;
  uint32_t m;
  int32_t lenN, lenF;
  seed_obj(o, 0);
  memset(p, 0, sizeof *p);
  /* echo delay-line lengths / write pointers (shorts) */
  switch (lcg_mod(6)) {
    case 0: lenN = 1 + (int)lcg_mod(3); break;
    case 1: lenN = 4 + (int)lcg_mod(12); break;
    case 2: lenN = 33; break;
    default: lenN = 0x678; break;
  }
  lenF = (lcg_mod(3) == 0) ? 1 + (int)lcg_mod(40) : (lcg_mod(2) ? lenN : 0x678);
  p->lenN = lenN;
  p->lenF = lenF;
  I32(o, 0x80d0) = lenN;
  I32(o, 0x9150) = lenF;
  switch (lcg_mod(5)) {
    case 0: p->wN = 0; break;
    case 1: p->wN = 1 % lenN; break;
    case 2: p->wN = lenN - 1; break;
    default: p->wN = (int)lcg_mod((unsigned)lenN); break;
  }
  switch (lcg_mod(5)) {
    case 0: p->wF = 0; break;
    case 1: p->wF = 1 % lenF; break;
    case 2: p->wF = lenF - 1; break;
    default: p->wF = (int)lcg_mod((unsigned)lenF); break;
  }
  PTRS(o, 0x80b8) = OB(o, 0x81f8 + 2 * p->wN);
  PTRS(o, 0x9138) = OB(o, 0x9278 + 2 * p->wF);
  /* tx ring write pointer: exhaustive sweep of all 230 positions first, then random with a bias to the low end */
  if (callno < 230 * 6)
    p->ringk = (int)(callno % 230);
  else if (lcg_mod(3) == 0)
    p->ringk = (int)lcg_mod(6);
  else
    p->ringk = (int)lcg_mod(TXR_N);
  p->ringoff = (lcg_mod(8) == 0) ? rr(1, 3) : 0;
  PTRS(o, 0x2224) = OB(o, TXR_BASE + 4 * p->ringk + p->ringoff);

  if (real) {
    /* the caller's shape: cap = 0, idx = 0, threshold = 0, n = 3k with k > 0x30 */
    p->cap = 0;
    p->idx = 0;
    p->u60 = 0;
    p->n = 3u * (uint32_t)rr(0x31, (lcg_mod(4) == 0) ? 2500 : 300);
    U32(o, 0x20d4) = 0;
    S16(o, 0x20d0) = 0;
    U32(o, 0x20d8) = 0;
    cv->real_shape++;
    m = p->n; /* t = 0: every echo clear runs n shorts */
    goto tail;
  }

  /* ---- PreFilter part: choose (cap, idx, n) by mode ---- */
  mode = (int)lcg_mod(10);
  if (mode < 2) { /* all fields zero / cap == 0: n >= cap always -> memset(.., 0) */
    p->cap = 0;
    p->idx = (lcg_mod(2) ? 0 : rr(-3, 9));
    p->n = (lcg_mod(3) == 0) ? (uint32_t)rr(0, 5) : (lcg_mod(2) ? (uint32_t)rr(147, 3000) : lcg_next());
    if (p->n == 0 && lcg_mod(2)) p->n = 0xffffffffu;
  } else if (mode < 4) { /* memset mode with small cap (memset covers the threshold word for cap >= 50) */
    p->cap = (uint32_t)((lcg_mod(2)) ? rr(50, 62) : rr(1, 49));
    p->idx = rr(-3, (int)p->cap + 3);
    switch (lcg_mod(4)) {
      case 0: p->n = p->cap; break;
      case 1: p->n = p->cap + (uint32_t)rr(1, 500); break;
      case 2: p->n = 0xffffffffu - lcg_mod(50); break;
      default: p->n = 0x80000000u + lcg_mod(50); break;
    }
  } else if (mode < 6) { /* loop mode, small cap, idx inside: wraps; n up to 6000 */
    p->cap = (uint32_t)rr(2, 60);
    p->idx = (lcg_mod(3) == 0) ? (int)p->cap - 1 : rr(0, (int)p->cap - 1);
    p->n = (lcg_mod(4) == 0) ? p->cap - 1 : (uint32_t)rr(1, (int)p->cap - 1);
    if (p->cap > 1 && lcg_mod(2)) p->n = p->cap - 1;
    if (p->n == 0) p->n = 1;
  } else if (mode < 7) { /* loop mode, idx outside [0,cap): no wrap in the loop, n + idx small */
    p->cap = (uint32_t)rr(1, 20);
    p->idx = (lcg_mod(2)) ? (int)p->cap + rr(0, 20) : -rr(1, 3);
    p->n = (uint32_t)rr(1, (int)p->cap > 1 ? (int)p->cap : 1);
    if (p->n >= p->cap) p->n = p->cap > 1 ? p->cap - 1 : 0;
    if (p->n == 0) p->n = 1; /* n == cap == 1 -> memset instead; fine */
  } else if (mode < 8) { /* huge cap: n < cap, small n; or n == cap with the 32-bit wrap of cap*2 */
    static const uint32_t hc[] = {0x80000000u, 0x80000001u, 0x7fffffffu, 0xffffffffu, 0x40000010u, 0x80000010u, 0xfffffff0u, 0x10000u};
    p->cap = hc[lcg_mod(8)];
    p->idx = rr(-3, 40);
    switch (lcg_mod(3)) {
      case 0: p->n = (uint32_t)rr(1, 150); break;
      case 1: p->n = p->cap; break;
      default: p->n = (lcg_mod(2)) ? 0u : 0x80000000u; break;
    }
    if (p->n == p->cap && p->cap == 0x10000u) p->n = 5;
    if (p->n < p->cap && (int32_t)p->n > 0 && p->n + (uint32_t)(p->idx > 0 ? p->idx : 0) > 200u) p->n = 150;
  } else { /* skip mode: n <= 0 (signed) while n < cap (unsigned) */
    if (lcg_mod(2)) {
      p->cap = (uint32_t)rr(1, 60);
      p->n = 0;
    } else {
      p->cap = 0x80000001u + lcg_mod(0x7fffffffu);
      p->n = 0x80000000u + lcg_mod(p->cap - 0x80000000u);
    }
    p->idx = rr(-3, 9);
  }
  if (g_t07) {
    if (p->cap > 42) p->cap = 1u + p->cap % 42u;
    if (p->cap == 0) p->idx = 0;
    else if (p->idx < 0 || (uint32_t)p->idx >= p->cap) p->idx = (int)((uint32_t)(p->idx < 0 ? -p->idx : p->idx) % p->cap);
    if (p->n > 20) p->n %= 21u;
  }
  /* keep the memset target away from the tx ring write pointer (obj+0x2224 = pf+0x1ac): real memset only for cap*2 < 0x1ac
   * or when the stub skips it (length > the object) */
  if (p->n >= p->cap) {
    uint32_t len = p->cap * 2u;
    if (len >= 0x1a0u && len <= OBJSZ) p->cap = 0x50;
  }
  U32(o, 0x20d4) = p->cap;
  S16(o, 0x20d0) = (int16_t)p->idx;

  /* ---- echo-clear part: threshold word, so that m = n - t is small / len-related ---- */
  mcls = (int)lcg_mod(9);
  switch (mcls) {
    case 0: m = 0; break;                                    /* n <= t: no clear */
    case 1: m = 1; break;
    case 2: m = (uint32_t)lenN; break;
    case 3: m = (uint32_t)lenN - 1u + (uint32_t)lcg_mod(3); break;
    case 4: m = (uint32_t)lenN * 2u + 3u; break;
    case 5: m = (uint32_t)lenF + (uint32_t)lcg_mod(3); break;
    case 6: m = 1 + lcg_mod(40); break;
    case 7: m = 1 + lcg_mod(3000); break;
    default: m = (uint32_t)lenN + (uint32_t)lenF + 1u; break;
  }
  if ((int32_t)p->n <= 0 || m > 0x7fffffffu) m = 0; /* only a positive n can exceed the threshold */
  if (m > 0 && m > p->n) m = p->n;
  if (m > 0) {
    uint32_t t = p->n - m;
    p->u60 = 2u * t + (lcg_mod(2) ? 1u : 0u);
  } else {
    /* (int)n <= (int)t: t >= n (or n negative) */
    uint32_t t = ((int32_t)p->n > 0) ? p->n + lcg_mod(5) : lcg_mod(50);
    if (t > 0x7fffffffu) t = 0x7fffffffu; /* 2*t must not wrap: a wrapped threshold would make m ~ 2^31 (hang) */
    if (lcg_mod(6) == 0) t = 0x7fffffffu;
    p->u60 = 2u * t + (lcg_mod(2) ? 1u : 0u);
    if (lcg_mod(4) == 0 && (int32_t)p->n <= 0) p->u60 = 0;
  }
  U32(o, 0x20d8) = p->u60;
  /* the loop's writes must not reach the ring pointers (obj+0x2220/0x2224 = pf+0x1a8/0x1ac) */
tail:
  if (real) {
    U32(o, 0x20d8) = 0;
  }
  (void)callno;
}

/* independent classification of what the call will do (coverage + the tail self-check) */
static void bc_classify(const bc_par_t *p, bc_cov_t *cv) {
  uint32_t t = p->u60 >> 1;
  if (p->n >= p->cap && p->cap * 2u >= 0x64u && p->cap * 2u <= OBJSZ) t = 0; /* the memset zeroed the threshold word */
  if (p->n >= p->cap) {
    uint32_t len = p->cap * 2u;
    if (p->cap == 0) cv->memset_cap0++;
    else cv->memset_cap_small++;
    if (p->cap >= 0x80000000u && len < p->cap) cv->memset_cap_wrap32++;
    if (len > OBJSZ) cv->memset_cap_skipped++;
    if (len >= 0x64) cv->memset_covers_u60++;
    if (p->n == p->cap) cv->n_ge_cap_exact++;
    if (p->cap == p->n + 1) cv->n_lt_cap_by1++;
  } else if ((int32_t)p->n > 0) {
    cv->loop_run++;
    if (p->n == p->cap - 1) cv->n_lt_cap_by1++;
    if (p->idx >= 0 && (uint32_t)p->idx < p->cap && p->cap <= 100) {
      uint32_t left = p->cap - (uint32_t)p->idx;
      if (p->n > left) cv->loop_wrap++;
    }
    if (p->idx >= 0 && (uint32_t)p->idx >= p->cap) cv->loop_idx_ge_cap++;
    if (p->idx < 0) cv->loop_idx_neg++;
  } else {
    cv->skip_zero += (p->n == 0);
    cv->skip_negative += ((int32_t)p->n < 0);
  }
  if ((int32_t)p->n > (int32_t)t) {
    uint32_t m = p->n - t;
    int sN = (p->wN == 0) ? (int)p->lenN - 1 : p->wN - 1;
    int sF = (p->wF == 0) ? (int)p->lenF - 1 : p->wF - 1;
    cv->clear_run++;
    if (p->wN == 0) cv->clear_wp_base_near++;
    if (p->wF == 0) cv->clear_wp_base_far++;
    if (m > (uint32_t)sN + 1u) cv->clear_near_wrap++;
    if (m > (uint32_t)sF + 1u) cv->clear_far_wrap++;
    if (m > (uint32_t)p->lenN * 2u + 1u) cv->clear_multi_wrap++;
    if (m == (uint32_t)p->lenN) cv->clear_m_eq_len++;
  } else {
    cv->clear_none_t_ge_n++;
  }
  if (p->u60 & 1u) cv->u60_odd++;
  if (p->u60 > 0xfffffff0u) cv->u60_huge++;
  if (p->lenN < 20 || p->lenF < 20) cv->len_small++;
  {
    unsigned sl[3];
    int k, w = 0;
    bc_tail_slots(p, sl);
    for (k = 0; k < 3; k++)
      if ((int)(TXR_BASE + 4 * p->ringk + p->ringoff) - 4 * (k + 1) < (int)TXR_BASE) w++;
    (void)sl;
    cv->tail_wrap[w]++;
    if (p->ringoff) cv->tail_skew++;
  }
}

