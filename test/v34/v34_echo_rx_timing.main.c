static void scen_backwardclean(int typical) {
  logger_t lg = {typical ? "BackwardClean-typical" : "BackwardClean", FNV0, 0, typical ? 311 : 397};
  bc_cov_t cv;
  unsigned char *o = G_OBJ;
  long c, total = typical ? 12000 : 60000;
  memset(&cv, 0, sizeof cv);
  for (c = 0; c < total; c++) {
    bc_par_t p;
    unsigned int h, slot_idx;
    unsigned int slots[3];
    int i;
    bc_setup(o, &p, typical, &cv, c);
    if (p.ringk >= 0) {
      bc_tail_slots(&p, slots);
      /* make the three target samples non-zero so the model check below means something */
      for (i = 0; i < 3; i++) U16(o, slots[i]) = (uint16_t)(1u + lcg_mod(0xfffe));
    }
    bc_classify(&p, &cv);
    memcpy(G_SNAP, o, OBJSZ);
    g_ms_h = FNV0;
    g_ms_calls = 0;
    V34EchoHistoryBackwardClean(o, p.n);
    /* self-check of the resolved tail semantics against the independent model (both binaries) */
    for (i = 0; i < 3; i++) {
      slot_idx = slots[i];
      if (U16(o, slot_idx) != 0) die("BackwardClean tail: the modelled ring slot was not zeroed");
    }
    if (g_ms_calls < 2) die("BackwardClean: fewer than the two fixed memsets");
    h = diff_obj(o, G_SNAP);
    h = fnv32(h, g_ms_h);
    h = fnv32(h, (uint32_t)g_ms_calls);
    log_call(&lg, h, (long)p.n, (long)p.cap);
  }
  log_done(&lg);
  bc_report(&cv, typical);
  printf("  memset stub: %ld calls, %ld performed, %ld skipped (longer than the object)\n", g_ms_calls, g_ms_real, g_ms_skipped);
}

