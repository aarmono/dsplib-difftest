/* dry-run energy guard: the value V34EchoEstimateDelayLineEnergy returns must not be one of the
 * inputs updateAlpha hangs / traps on. The estimate is taken on the state AFTER the filters the call
 * itself runs first (V34EchoFilter shifts the history). The live object is restored from a snapshot. */
static int energy_bad(uint32_t e) { return e == 0x80000000u || e >= 0xffff8000u; }
static void guard_energy(unsigned char *o, int d, int filt_near, int filt_far, int need_near, int need_far) {
  int tries;
  for (tries = 0; tries < 400; tries++) {
    uint32_t en = 0, ef = 0;
    memcpy(G_SNAP, o, OBJSZ);
    if (filt_near) V34EchoFilter(OB(o, 0x80b8), (short)d);
    if (filt_far) V34EchoFilter(OB(o, 0x9138), (short)d);
    if (need_near) en = (uint32_t)V34EchoEstimateDelayLineEnergy(OB(o, 0x80b8));
    if (need_far) ef = (uint32_t)V34EchoEstimateDelayLineEnergy(OB(o, 0x9138));
    memcpy(o, G_SNAP, OBJSZ);
    if (!(need_near && energy_bad(en)) && !(need_far && energy_bad(ef))) return;
    S16(o, 0x8ee8 + 2 * 60) = rshort();
    S16(o, 0x9f68 + 2 * 60) = rshort();
  }
  die("could not find a safe echo energy");
}

/* rounding-boundary steering of the echo canceller outputs: all high-half coefficients zero except the last tap
 * (0x2000), whose history sample is the delay-line word V34EchoFilter shifts in. The filter output is r = 0x2000*v, so
 * r*4 + 0x8000 has a zero low half when v is odd (the boundary of the `>> 16`). far_mode: 0 far output 0, 1 far output
 * 0x2000*v2 with v2 even (the sum keeps the boundary). */
static void steer_echo(unsigned char *o, int d, int far_mode) {
  int i;
  short *tap, *wp, *base;
  int len;
  for (i = 0; i < 0x90; i++) {
    S16(o, 0x9018 + 2 * i) = 0;
    S16(o, 0xa098 + 2 * i) = 0;
  }
  S16(o, 0x9018 + 2 * 0x8f) = 0x2000;
  wp = (short *)PTRS(o, 0x80b8);
  base = (short *)PTRS(o, 0x80bc);
  len = I32(o, 0x80d0);
  tap = wp + (d + 0x90 - 1);
  if (base + len <= tap) tap -= len;
  *tap = (short)(rshort() | 1);
  if (far_mode) {
    S16(o, 0xa098 + 2 * 0x8f) = 0x2000;
    wp = (short *)PTRS(o, 0x9138);
    base = (short *)PTRS(o, 0x913c);
    len = I32(o, 0x9150);
    tap = wp + (d + 0x90 - 1);
    if (base + len <= tap) tap -= len;
    *tap = (short)(rshort() & ~1);
  }
}

/* second steering mode: the filter output is r = v with v == 0x1fff (mod 0x4000), i.e. r*4 + 0x8000 has the low half 0xfffc, one
 * "+4" short of the rounding boundary (kills mutants that add a stray +1 to the far output when the far canceller is off). */
static void steer_echo2(unsigned char *o, int d) {
  int i;
  short *tap, *wp, *base;
  int len;
  static const short vs[4] = {0x1fff, 0x5fff, (short)0xdfff, (short)0x9fff};
  for (i = 0; i < 0x90; i++) {
    S16(o, 0x9018 + 2 * i) = 0;
    S16(o, 0xa098 + 2 * i) = 0;
  }
  S16(o, 0x9018 + 2 * 0x8f) = 1;
  wp = (short *)PTRS(o, 0x80b8);
  base = (short *)PTRS(o, 0x80bc);
  len = I32(o, 0x80d0);
  tap = wp + (d + 0x90 - 1);
  if (base + len <= tap) tap -= len;
  *tap = vs[lcg_mod(4)];
}

/* set d = (short)(tgt - cnt) by choosing cnt at random */
static void set_delay(unsigned char *o, int d) {
  uint16_t cnt = (lcg_mod(6) == 0) ? (uint16_t)lcg_mod(4) : rnd16();
  U16(o, 0x221c) = cnt;
  U16(o, 0x25c) = (uint16_t)(cnt + d);
}

