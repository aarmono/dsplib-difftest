/* ================================================================== scenario 6/7: demapFrame */
/* mode 0: independent calls from random states; mode 1: sequential chains */
static void scen_demap(int mode) {
  logger_t lg = {mode == 0 ? "demapFrame(single)" : "demapFrame(chain)", FNV0, 0, mode == 0 ? 3000 : 4000};
  unsigned char *pre = xalloc(OBJSZ), *w = xalloc(OBJSZ), *live = xalloc(OBJSZ);
  long iter, total = mode == 0 ? 60000 : 120000;
  long c_even = 0, c_odd = 0, c_u9[8] = {0}, c_tail_e4c0 = 0, c_tail_e4c1 = 0, c_tail_gt40 = 0, c_tail_le40 = 0,
       c_e4c_set = 0, c_a3c_lt = 0, c_a3c_ge = 0, c_a3e_lt = 0, c_a3e_ge = 0, c_kkinv = 0, c_kknorm = 0, c_negidx = 0,
       c_tail_e4c_noset = 0, c_zero_n = 0, c_neg_n = 0, c_shell_calls = 0, c_junk_idx = 0, c_wild_odd = 0;
  long c_fn[3] = {0, 0, 0}, c_gi[16] = {0};
  int idx = 0, i, remain = 0;

  fill_random(live, OBJSZ);
  for (iter = 0; iter < total; iter++) {
    uint32_t sym;
    short o2[2];
    unsigned int h;
    int tries = 0, idx32, r;

    if (mode == 0 || remain <= 0) { /* new episode */
      g_fnmode = mode == 0 ? rr(0, 2) : (int)(iter / 20000 % 3);
      gen_region(live, (int)(iter & 1));
      if (mode == 1) tame_frame_params(live);
      U16(live, 0xa00) = pick_a00();
      U16(live, 0xe4c) = pick_e4c();
      if (rr(0, 9) == 0) U16(live, 0xa3e) = 0xffff; /* (a3e+1) == 0 -> gInvertPat[0] */
      remain = rr(60, 400);
      idx = mode == 0 ? (int)(int16_t)rnd16() : rr(-6, 40);
      if (mode == 1 && rr(0, 3) == 0) idx = rr(-200, 200);
    }
    remain--;
    if (mode == 1 && rr(0, 30) == 0) idx += rr(-3, 9); /* occasional discontinuity */
    sym = pick_sym_pair(S16(live, 0xa42));
    if (mode == 0 && (idx & 1) && rr(0, 3) == 0) {
      /* WILD odd call: full-range 16-bit received points (current stage record and *sym). An odd call never runs
       * decodeDepth, so the grid is not involved; this reaches int32-overflowing squared distances (|diff| > 46340),
       * 16-bit wrap of the candidate points and unsigned-16-bit metric sums >= 0x8000. */
      int st = S16(live, 0x144c) & 0x1f;
      int q;
      for (q = 0; q < 4; q++) S16(live, 0x12d0 + 12 * st + 2 * q) = (int16_t)(rr(0, 2) == 0 ? (int16_t)rnd16() : (rr(0, 1) ? 32767 : -32768));
      sym = rnd32();
      c_wild_odd++;
    }
    /* oracle: repair the state until every table read is in range */
    while (!orc_ok_demap(live, &sym, idx)) {
      if (++tries > 40) {
        fprintf(stderr, "harness: cannot find an in-range demapFrame state\n");
        exit(3);
      }
      repair(live, tries < 8 ? 1 : (tries < 16 ? 2 : 3));
      if (tries % 5 == 0) sym = pick_sym_pair(S16(live, 0xa42));
    }
    orc_commit();
    memcpy(pre, live, OBJSZ);

    /* independent predicates on the pre-state */
    {
      int u9 = idx & 7, n = S16(pre, 0xa42);
      if (n == 0) c_zero_n++;
      if (n < 0) c_neg_n++;
      if (idx < 0) c_negidx++;
      c_u9[u9]++;
      if (idx & 1) {
        c_odd++;
        if (S16(pre, 0xa3a) == 0) c_kknorm++; else c_kkinv++;
        {
          int16_t c = (int16_t)(U16(pre, 0xa3c) + 1);
          if ((int)c < (int)U16(pre, 0xa02)) c_a3c_lt++;
          else {
            c_a3c_ge++;
            if ((int16_t)(U16(pre, 0xa3e) + 1) < S16(pre, 0xa40)) {
              c_a3e_lt++;
              c_gi[(int16_t)(U16(pre, 0xa3e) + 1)]++;
            } else
              c_a3e_ge++;
          }
        }
        if (u9 == 7) {
          if (S16(pre, 0xe4c) == 0) {
            c_tail_e4c0++;
            if (idx > 0x40) {
              c_tail_gt40++;
              if (idx >= (int)U16(pre, 0xa00) * 8 + 0x40) c_e4c_set++; else c_tail_e4c_noset++;
            } else
              c_tail_le40++;
          } else
            c_tail_e4c1++;
        }
      } else
        c_even++;
    }

    fill_random(o2, sizeof o2);
    idx32 = (idx & 0xffff) | (int)(lcg_next() & 0xffff0000u); /* garbage above bit 15: must be ignored */
    if (idx32 != (idx & 0xffff)) c_junk_idx++;
    memcpy(w, live, OBJSZ);
    if (g_fnmode == 0) {
      g_rec_h = FNV0;
      g_rec_n = 0;
      g_rec_obj = w;
      g_rec_on = 1;
    }
    r = demapFrame(w, &sym, o2, idx32);
    g_rec_on = 0;
    h = mode == 0 ? hash_diff(w, pre) : hash_obj(w);
    h = fnv32(h, (uint32_t)r);
    h = fnv(h, o2, 4);
    if (g_fnmode == 0) {
      h = fnv32(fnv32(h, g_rec_h), (uint32_t)g_rec_n);
      c_shell_calls += g_rec_n;
    }
    c_fn[g_fnmode]++;
    log_call(&lg, h, r, idx);
    if (r != (idx & 1)) {
      printf("demapFrame return value %d for idx %d\n", r, idx);
      g_fail = 1;
    }
    if (mode == 1) {
      memcpy(live, w, OBJSZ);
      idx++;
    }
  }
  log_done(&lg);
  {
    int n = 0;
    for (i = 0; i < 529; i++) n += g_ghit[i];
    printf("  oracle runs %ld, rejected %ld, grid indices hit %d\n", g_orc_runs, g_orc_reject, n);
  }
  need("even idx (decodeDepth path)", c_even);
  need("odd idx (ACS path)", c_odd);
  for (i = 0; i < 8; i++) {
    char nm[32];
    snprintf(nm, sizeof nm, "idx&7 == %d", i);
    need(nm, c_u9[i]);
  }
  need("odd, kkNormal (a3a == 0)", c_kknorm);
  need("odd, kkInvert (a3a != 0)", c_kkinv);
  need("odd, (a3c+1) < a02", c_a3c_lt);
  need("odd, (a3c+1) >= a02", c_a3c_ge);
  need("odd, (a3e+1) < a40 (gInvertPat read)", c_a3e_lt);
  need("odd, (a3e+1) >= a40", c_a3e_ge);
  for (i = 0; i < 4; i++) {
    char nm[48];
    snprintf(nm, sizeof nm, "gInvertPat index %d read", i);
    need(nm, c_gi[i]);
  }
  need("tail: e4c == 0", c_tail_e4c0);
  need("tail: e4c != 0", c_tail_e4c1);
  need("tail: e4c == 0, idx > 0x40", c_tail_gt40);
  need("tail: e4c == 0, idx <= 0x40", c_tail_le40);
  need("tail: e4c set to 1", c_e4c_set);
  need("tail: threshold not reached", c_tail_e4c_noset);
  need("n < 0", c_neg_n);
  need("n == 0 (forced 1)", c_zero_n);
  need("negative idx", c_negidx);
  need("garbage in the upper half of idx", c_junk_idx);
  if (mode == 0) need("wild odd calls (full-range received points)", c_wild_odd);
  need("recorder used", c_fn[0]);
  need("real descrambleGPC used", c_fn[1]);
  need("real descrambleGPA used", c_fn[2]);
  need("descrambler calls recorded (shell/put path)", c_shell_calls);
  free(pre);
  free(w);
  free(live);
}

/* ================================================================== scenario 7: decoderv34 slicer path */
static void scen_slicer(void) {
  logger_t lg = {"decoderv34(slicer)", FNV0, 0, 5000};
  unsigned char *tmpl = xalloc(OBJSZ), *w = xalloc(OBJSZ);
  long iter, total = 200000;
  long c_best[4] = {0}, c_tie = 0, c_neg = 0, c_f4 = 0, c_nf4 = 0, c_d[4] = {0}, c_47[3] = {0, 0, 0}, c_bits[4] = {0},
       c_flag98_1 = 0, c_neg7 = 0, c_all_ge = 0, c_aa_neg = 0, c_ord_eq = 0;

  g_fnmode = 0;
  fill_random(tmpl, OBJSZ);
  for (iter = 0; iter < total; iter++) {
    unsigned int h;
    int I, Q, dm = rr(0, 9);
    fill_random(tmpl + 0x380, 0x20);
    fill_random(tmpl + 0x400, 0x20);
    fill_random(tmpl + 0x470, 0x20);
    U16(tmpl, 0xaa96) = rnd16();
    /* flags: never both 0x98 bits */
    {
      uint16_t f = rnd16();
      switch (rr(0, 7)) {
        case 0: f &= (uint16_t)~0x98u; break;
        case 1: f = (uint16_t)((f & ~0x98u) | 0x80); break;
        case 2: f = (uint16_t)((f & ~0x98u) | 0x10); break;
        case 3: f = (uint16_t)((f & ~0x98u) | 0x08); break;
        case 4: f = (uint16_t)((f & ~0x98u) | 0x90); break; /* two of the three frame-mode bits */
        case 5: f = (uint16_t)((f & ~0x98u) | 0x88); break;
        case 6: f = (uint16_t)((f & ~0x98u) | 0x18); break;
        default: f = (uint16_t)(f & ~0x98u); break;
      }
      if (lcg_bool()) f |= 4; else f &= (uint16_t)~4u;
      U16(tmpl, 0x386) = f;
    }
    /* rxvect4 points (read from the harness's own view of the table through the decoder's outputs) */
    switch (dm) {
      case 0: I = 0; Q = 0; break; /* exact tie among all four */
      case 1: I = 0; Q = rr(-3, 3); break;
      case 2: I = rr(-3, 3); Q = 0; break;
      case 3: I = (int16_t)rnd16(); Q = (int16_t)rnd16(); break;
      case 4: I = rr(-5000, 5000); Q = rr(-5000, 5000); break;
      case 5: I = rr(-32768, 32767); Q = (int16_t)rnd16(); break;
      case 6: I = (lcg_bool() ? 1 : -1) * 2289 + rr(-2, 2); Q = (lcg_bool() ? 1 : -1) * 2289 + rr(-2, 2); break;
      case 7: I = rr(-32768, -30000); Q = rr(30000, 32767); break; /* huge distances: 16-bit wrap of the metric */
      case 8: I = (lcg_bool() ? 32767 : -32768); Q = (lcg_bool() ? 32767 : -32768); break;
      default: I = rr(-3000, 3000); Q = rr(-3000, 3000); break;
    }
    S16(tmpl, 0x474) = (int16_t)I;
    S16(tmpl, 0x476) = (int16_t)Q;
    if (rr(0, 3) == 0) U32(tmpl, 0x408) = (uint32_t)(lcg_next() & 0x0000ffff);
    {
      /* 0x388 vs 0xaa96 relations */
      uint16_t a = U16(tmpl, 0xaa96);
      switch (rr(0, 4)) {
        case 0: U16(tmpl, 0x388) = (uint16_t)((int16_t)a >> 1); break;
        case 1: U16(tmpl, 0x388) = a; break;
        case 2: U16(tmpl, 0x388) = (uint16_t)(a >> 1); break; /* logical shift: differs from sar when negative */
        default: break;
      }
      if (rr(0, 9) == 0) { U16(tmpl, 0xaa96) = 0; U16(tmpl, 0x388) = 0; }
      if (rr(0, 9) == 0) { U16(tmpl, 0xaa96) = 1; U16(tmpl, 0x388) = (uint16_t)rr(0, 1); }
    }
    U16(tmpl, 0x47c) = rnd16();
    U16(tmpl, 0x40e) = (uint16_t)(lcg_bool() ? rr(0, 3) : (int)rnd16());
    /* predicates: independent re-derivation of the slicer choice from the extracted table view */
    {
      const int16_t *rp = (const int16_t *)(const void *)rxvect4;
      int best = 0, i, bestv = 0x7fff, ties = 0;
      uint16_t Iu = (uint16_t)I, Qu = (uint16_t)Q;
      for (i = 0; i < 4; i++) {
        int a = (int16_t)(Iu - (uint16_t)rp[2 * i]);
        int b = (int16_t)(Qu - (uint16_t)rp[2 * i + 1]);
        int16_t val = (int16_t)(((uint32_t)(a * a) + (uint32_t)(b * b)) >> 14);
        if (val < bestv) { best = i; bestv = val; ties = 0; }
        else if (val == bestv) ties++;
        if (val < 0) c_neg++;
      }
      c_best[best]++;
      if (ties) c_tie++;
      if (bestv == 0x7fff) c_all_ge++;
      if (bestv < 0) c_neg7++;
      c_d[(best - U16(tmpl, 0x40e)) & 3]++;
    }
    if (U16(tmpl, 0x386) & 4) c_f4++; else c_nf4++;
    if ((U16(tmpl, 0x386) & 0x98) == 0x98) c_flag98_1++;
    if (S16(tmpl, 0xaa96) < 0) c_aa_neg++;
    if (U16(tmpl, 0x388) == (uint16_t)((int16_t)U16(tmpl, 0xaa96) >> 1) && U16(tmpl, 0x388) == U16(tmpl, 0xaa96)) c_ord_eq++;
    PTRS(tmpl, SLOT_FN) = fn_addr(0);
    PTRS(tmpl, SLOT_COEF) = g_coef;

    memcpy(w, tmpl, OBJSZ);
    decoderv34(w);
    h = hash_diff(w, tmpl);
    {
      uint16_t v = U16(w, 0x47c);
      if (v == 0x4000) c_47[1]++;
      else if (v == 0x2000) c_47[2]++;
      else c_47[0]++;
      c_bits[U16(w, 0x38a) & 3]++;
    }
    log_call(&lg, h, (long)S16(w, 0x40e), (long)U16(w, 0x38a));
  }
  log_done(&lg);
  need("slicer point 0 chosen", c_best[0]);
  need("slicer point 1 chosen", c_best[1]);
  need("slicer point 2 chosen", c_best[2]);
  need("slicer point 3 chosen", c_best[3]);
  need("exact tie for the minimum (first wins)", c_tie);
  need("wrapped (negative short) distance metric", c_neg);
  need("winning metric negative", c_neg7);
  need("flags & 4 set (tap 0x12)", c_f4);
  need("flags & 4 clear (tap 5)", c_nf4);
  need("d == 0", c_d[0]);
  need("d == 1", c_d[1]);
  need("d == 2", c_d[2]);
  need("d == 3", c_d[3]);
  need("0x47c unchanged", c_47[0]);
  need("0x47c == 0x4000", c_47[1]);
  need("0x47c == 0x2000", c_47[2]);
  need("out bits == 0", c_bits[0]);
  need("out bits == 1", c_bits[1]);
  need("out bits == 2", c_bits[2]);
  need("out bits == 3", c_bits[3]);
  need("0xaa96 negative", c_aa_neg);
  need("a == a>>1 (both compares equal)", c_ord_eq);
  (void)c_flag98_1;
  (void)c_all_ge;
  free(tmpl);
  free(w);
}

/* ================================================================== scenario 9/10: decoderv34 frame mode */
/* dbg: 1 = level-2 debug output (compared as stdout) */
static void scen_frame(int dbg) {
  logger_t lg = {dbg ? "decoderv34(frame,debug)" : "decoderv34(frame)", FNV0, 0, dbg ? 1000000 : 4000};
  unsigned char *w = xalloc(OBJSZ), *live = xalloc(OBJSZ), *pre = xalloc(OBJSZ);
  long iter, total = dbg ? 4000 : 150000;
  long c_r0 = 0, c_r1 = 0, c_9fc[6] = {0}, c_print = 0, c_fn[3] = {0, 0, 0}, c_f100_set = 0, c_f100_clr = 0,
       c_4ca_wrap = 0, c_e4c = 0, c_calls = 0, c_shells = 0;
  int remain = 0, tries;

  fill_random(live, OBJSZ);
    for (iter = 0; iter < total; iter++) {
    unsigned int h;
    if (remain <= 0) {
      g_fnmode = (int)((iter / 1000) % 3);
      gen_region(live, (int)(iter & 1));
      tame_frame_params(live);
      fill_random(live + 0x380, 0x20);
      fill_random(live + 0x400, 0x20);
      fill_random(live + 0x470, 0x60);
      U16(live, 0xa00) = pick_a00();
      U16(live, 0xe4c) = pick_e4c();
      U16(live, 0x4ca) = (uint16_t)(rr(0, 5) == 0 ? rr(0x7fe0, 0x7fff) : rr(-5, 80));
      remain = rr(40, 200);
    }
    remain--;
    if (remain % 7 == 0 || iter == 0) {
      int16_t v;
      switch (rr(0, 6)) {
        case 0: v = -0x40; break;
        case 1: v = -0x41; break;
        case 2: v = -0x45; break;
        case 3: v = -0x46; break;
        case 4: v = -0x47; break;
        case 5: v = (int16_t)rnd16(); break;
        default: v = (int16_t)rr(-0x50, 0); break;
      }
      S16(live, 0x9fc) = v;
    }
    {
      uint32_t s = pick_sym_pair(S16(live, 0xa42)); /* new I/Q every call */
      memcpy(live + 0x474, &s, 4);
    }
    /* frame-mode bits stay set; the other flag bits (incl. 0x100, 0x4) are randomised every call */
    U16(live, 0x386) = (uint16_t)((rnd16() & ~0x98u) | 0x98u);
    U16(live, 0x47c) = rnd16();
    tries = 0;
    while (!orc_ok_decoder(live)) {
      if (++tries > 40) {
        fprintf(stderr, "harness: cannot find an in-range decoderv34 state\n");
        exit(3);
      }
      repair(live, tries < 8 ? 1 : (tries < 16 ? 2 : 3));
      if (tries % 5 == 0) {
        uint32_t s = pick_sym_pair(S16(live, 0xa42));
        memcpy(live + 0x474, &s, 4);
      }
    }
    orc_commit();
    memcpy(pre, live, OBJSZ);
    memcpy(w, live, OBJSZ);
    if (dbg) {
      /* the guard is UNSIGNED `1 < level`: levels 0, 1 quiet; 2, 3, 0x80000000, 0xffffffff print */
      static const unsigned int lv[6] = {2u, 0u, 1u, 0x80000000u, 3u, 0xffffffffu};
      dsplibs_debug_level = lv[iter % 6];
    }
    if (g_fnmode == 0) {
      g_rec_h = FNV0;
      g_rec_n = 0;
      g_rec_obj = w;
      g_rec_on = 1;
    }
    {
      int v = S16(pre, 0x9fc);
      if (v < -0x40) {
        if (v > -0x46) { c_9fc[5]++; c_print++; } else c_9fc[4]++;
      } else
        c_9fc[v == -0x40 ? 3 : 0]++;
      if (S16(pre, 0x4ca) == 0x7fff) c_4ca_wrap++;
      if (S16(pre, 0xe4c)) c_e4c++;
    }
    decoderv34(w);
    g_rec_on = 0;
    h = hash_obj(w);
    if (g_fnmode == 0) {
      h = fnv32(fnv32(h, g_rec_h), (uint32_t)g_rec_n);
      c_calls += g_rec_n;
      if (g_rec_n) c_shells++;
    }
    c_fn[g_fnmode]++;
    if (U16(w, 0x386) & 0x100) c_f100_set++; else c_f100_clr++;
    if (S16(w, 0x144c) == S16(pre, 0x144c)) c_r0++; else c_r1++; /* even path leaves the stage alone */
    log_call(&lg, h, (long)S16(w, 0x4ca), (long)U16(w, 0x386));
    memcpy(live, w, OBJSZ);
  }
  if (dbg) dsplibs_debug_level = 0;
  log_done(&lg);
  printf("  oracle runs %ld, rejected %ld\n", g_orc_runs, g_orc_reject);
  need("demapFrame even path (stage unchanged)", c_r0);
  need("demapFrame odd path (stage advanced)", c_r1);
  need("0x9fc < -0x46 (flag only)", c_9fc[4]);
  need("-0x46 < 0x9fc < -0x40 (flag + print if level>1)", c_9fc[5]);
  need("0x9fc == -0x40 (no flag)", c_9fc[3]);
  need("0x9fc > -0x40", c_9fc[0]);
  need("flags & 0x100 set after", c_f100_set);
  need("flags & 0x100 clear after", c_f100_clr);
  need("descrambler recorder", c_fn[0]);
  need("real GPC", c_fn[1]);
  need("real GPA", c_fn[2]);
  need("descrambler calls recorded", c_calls);
  need("calls that ran the shell/put tail", c_shells);
  need("e4c != 0 at call", c_e4c);
  need("0x4ca == 0x7fff (16-bit counter wrap)", c_4ca_wrap);
  if (dbg) need("V34RENEG print zone", c_print);
  free(w);
  free(live);
  free(pre);
}

int main(int argc, char **argv) {
  V34I_REG(g_orc, OBJSZ);
  int s = argc > 1 ? atoi(argv[1]) : -1;
  const char *v = getenv("V34T4_VERBOSE");
  if (v) g_verbose = atoi(v);
  tables_check();
  switch (s) {
    case 0: scen_putframe(0); break;
    case 1: scen_putframe(1); scen_putframe(2); break;
    case 2: scen_shell(0); break;
    case 3: scen_shell(1); break;
    case 4: scen_decodeDepth(0); break;
    case 5: scen_decodeDepth(1); break;
    case 6: scen_demap(0); break;
    case 7: scen_demap(1); break;
    case 8: scen_slicer(); break;
    case 9: scen_frame(0); break;
    case 10: scen_frame(1); break;
    case 11: scen_shell(2); break;
    default: fprintf(stderr, "usage: %s <scenario 0-11>\n", argv[0]); return 1;
  }
  fflush(stdout);
  return g_fail ? 2 : 0;
}
