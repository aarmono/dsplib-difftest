/* ---- deterministic LCG with bijective finaliser (raw low bytes are period-256) ---- */
static unsigned int g_lcg = 0x5ca1ab1eu;
static unsigned int lcg_next(void) {
  unsigned int x;
  g_lcg = g_lcg * 1103515245u + 12345u;
  x = g_lcg;
  x ^= x >> 16;
  x *= 0x7feb352du;
  x ^= x >> 15;
  x *= 0x846ca68bu;
  x ^= x >> 16;
  return x;
}
static unsigned int lcg_mod(unsigned int m) { return (lcg_next() >> 8) % m; }
static int rr(int lo, int hi) { return lo + (int)lcg_mod((unsigned int)(hi - lo + 1)); }
static int lcg_bool(void) { return (int)(lcg_next() >> 31); }
static uint16_t rnd16(void) { return (uint16_t)(lcg_next() >> 16); }
static uint32_t rnd32(void) { return lcg_next(); }


static unsigned int fnv(unsigned int h, const void *p, size_t n) {
  const unsigned char *b = (const unsigned char *)p;
  size_t i;
  for (i = 0; i < n; i++) {
    h ^= b[i];
    h *= 16777619u;
  }
  return h;
}
static unsigned int fnv32(unsigned int h, uint32_t w) {
  h ^= w;
  h *= 16777619u;
  h ^= h >> 15;
  return h;
}
#define FNV0 2166136261u

static void fill_random(void *p, size_t n) {
  unsigned char *b = (unsigned char *)p;
  size_t i;
  for (i = 0; i + 4 <= n; i += 4) {
    uint32_t v = lcg_next();
    memcpy(b + i, &v, 4);
  }
  for (; i < n; i++) b[i] = (unsigned char)(lcg_next() >> 16);
}

