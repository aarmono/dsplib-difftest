typedef struct {
  const char *name;
  unsigned int all;
  long calls;
  long every;
} logger_t;
static void log_call(logger_t *l, unsigned int h, long a, long b) {
  l->all = fnv(l->all, &h, 4);
  if (g_verbose || l->calls % l->every == 0) printf("%s c=%ld a=%ld b=%ld hash=%08x\n", l->name, l->calls, L32(a), L32(b), h);
  l->calls++;
}
