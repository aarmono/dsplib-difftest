/*
 * Differential test harness for the V.34 "tier 4a" RX frame-decode chain
 * (src/v34/v34_frame_decoder.c): putFrame, shellDemapper, decodeDepth, demapFrame,
 * decoderv34. All five are GLOBAL in dsplibs.o (no thunks needed).
 *
 * One source, two binaries (same convention as test/v34_tier3{ab,c,d}_diff_main.c):
 *   v34_tier4a_test_blob - linked against the real dsplibs.o (-DTEST_BLOB)
 *   v34_tier4a_test_port - linked against src/v34/v34_frame_decoder.c + tables + the ported
 *                          descramblers (src/v34/v34_init.c and its deps)
 * Each scenario runs in its OWN process (argv[1]); its stdout is diffed.
 *
 * Fake object: tagV34Object is not a struct; the harness keeps a random fake
 * object of OBJSZ bytes and pokes byte offsets. Functions are called on the
 * object (or a fresh copy of a template; the hash is then of the DIFF, so a
 * stray write anywhere is caught). The two pointer slots the chain reads
 * (obj+0xe48 descrambler function pointer, obj+0xa24 coefficient-row pointer)
 * are set by the harness, excluded from the hashes and checked unchanged (a
 * function clobbering them changes the hash), so raw addresses are never
 * compared across the two processes. The function pointer is either a harness
 * RECORDER (hashes every (word, nbits) argument pair as full 32-bit values) or
 * the real descrambleGPC/descrambleGPA of the respective side.
 *
 * TABLE-INDEX ORACLE (important, read this): decodeDepth indexes grid[529] with
 * `(v+0x408)>>2` and demapFrame indexes gInvertPat[16] with a signed 16-bit
 * value that was only tested `< a40` - neither has a bounds check in the blob,
 * and out-of-range reads read whatever follows the table in each binary's own
 * image (not comparable). So EVERY generated input is first run through an
 * ORACLE: a private copy of src/v34/v34_frame_decoder.c compiled into this harness under
 * oracle_* names with PORT_TRACE_INDEX defined (its two table reads report the
 * index). An input whose oracle run leaves either table is REJECTED and
 * repaired/regenerated (deterministically, identically in both processes: the
 * oracle uses the blob's tables in the blob process and the port's in the port
 * process, and the two are byte-identical - re-proved at start-up). The oracle
 * source is the pristine src/v34/v34_frame_decoder.c (PORT_T4A_ORACLE_SRC), so a mutant
 * of the port under test cannot change the input stream.
 *
 * Every scenario keeps COVERAGE COUNTERS (from inputs / outputs / tiny
 * independent predicates) and exits 2 if a branch class was never reached.
 * Env V34T4_VERBOSE=1 prints a line per call.
 */

