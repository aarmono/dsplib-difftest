static volatile sig_atomic_t g_alarm;
static void on_alarm(int s) {
  (void)s;
  g_alarm = 1;
}
/* the recursion hazard: a restart that needs a restart again never ends.  The BLOB must die (stack overflow);
 * the port recurses the same way (an optimising compiler may turn it into a loop: a hang, killed by the alarm). */
static void scen_getbit_probe(void) {
  int pid, status;
  struct sigaction sa;
  fill_random(g_rb, RBSZ);
  memset(&sa, 0, sizeof sa);
  sa.sa_handler = on_alarm;
  sigaction(SIGALRM, &sa, NULL);
  fflush(stdout);
  pid = fork();
  if (pid == 0) {
    struct rlimit rl;
    unsigned char *R = RB_R;
    rl.rlim_cur = rl.rlim_max = 256 * 1024;
    setrlimit(RLIMIT_STACK, &rl);
    alarm(10);
    R16(R, 0x28) = 0;
    R16(R, 0x18) = 0; /* total 0, pos 0 -> d == 0 without crcOn: restart forever */
    R16(R, 0x1a) = 0;
    R16(R, 0x16) = 0;
    R16(R, 0x20) = 1;
    R16(R, 0x2a) = 0;
    (void)call_getbit(R);
    _exit(0);
  }
  waitpid(pid, &status, 0);
  if (WIFSIGNALED(status)) {
    int sg = WTERMSIG(status);
    fprintf(stderr, "probe: child killed by signal %d\n", sg);
#ifdef TEST_BLOB
    if (sg != SIGSEGV) die("blob getbit: the infinite recursion did not end in SIGSEGV");
#endif
    printf("getbit infinite-recursion hazard: the call did not return (killed)\n");
  } else {
    printf("getbit infinite-recursion hazard: the call RETURNED (unexpected)\n");
    fprintf(stderr, "probe: child exited normally\n");
    g_fail = 1;
  }
}

