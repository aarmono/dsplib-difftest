static unsigned int sfr_call(unsigned char *o, const unsigned char *snap, int record) {
  int txc, rxc;
  long bad;
  memcpy(G_EXP, o, g_sz);
  sfr_model(G_EXP, &txc, &rxc);
  if (record) sfr_cover(o, txc, rxc);
  g_junk1 = rint32();
  setfinalrate(o);
  bad = obj_vs_model(o, G_EXP);
  if (bad >= 0) {
    fprintf(stderr, "setfinalrate model mismatch at obj+0x%lx\n", bad);
    die("setfinalrate disagrees with the independent model");
  }
  return snap ? diff_obj(o, snap) : hash_obj(o);
}

/* pointer slots: valid table pointers, or garbage (scrubbed): a store that does not replace the whole 32-bit slot must show */
static void sfr_poke_sane(unsigned char *o) {
  scrub_slots(o);
  if (lcg_mod(2)) PTRS_SET(o, 0xaa90, (void *)scale_tbl((int)lcg_mod(5)));
  if (lcg_mod(2)) PTRS_SET(o, 0xaaac, (void *)scale_tbl((int)lcg_mod(5)));
  if (lcg_mod(2)) PTRS_SET(o, 0xaab0, (void *)c_tbl((int)lcg_mod(8)));
}

static void scen_sfr(void) {
  logger_t lg = {"setfinalrate", FNV0, 0, 4001};
  long i;
  int tx, rx, tf, rf, pe;
  g_sz = 0xb400;
  tables_init();
  dsplibs_debug_level = 0;
  fill_random(G_BASE, g_sz);
  /* exhaustive over the raw INFO fields */
  for (tx = 0; tx < 8; tx++)
    for (rx = 0; rx < 8; rx++)
      for (tf = 0; tf < 2; tf++)
        for (rf = 0; rf < 16; rf++)
          for (pe = 0; pe < 16; pe++) {
            unsigned int h;
            unsigned w0, w1, w2;
            if (lg.calls % 512 == 0) fill_random(G_BASE, g_sz);
            memcpy(G_OBJ, G_BASE, g_sz);
            sfr_poke_sane(G_OBJ);
            w0 = (unsigned)rnd16() & ~7u & 0xffffu;
            w1 = (unsigned)rnd16() & ~0xc3u & 0xffffu;
            w2 = (unsigned)rnd16() & ~0xf0u & 0xffffu;
            /* raw tx field p = bits 4..6 of w2 (the model reverses it); raw rx field: w1 bits 0..1 -> rx bits 1..2, w2 bit 7 -> rx bit 0 */
            w2 |= (unsigned)tx << 4;
            w2 |= (unsigned)(rx & 1) << 7;
            w1 |= (unsigned)((rx >> 1) & 3);
            w0 |= (unsigned)(pe >> 2) & 3u;
            w0 |= (unsigned)tf << 2;
            w1 |= (unsigned)(pe & 3) << 6;
            U16(G_OBJ, 0xa9de) = (uint16_t)w0;
            U16(G_OBJ, 0xa9e0) = (uint16_t)w1;
            U16(G_OBJ, 0xa9e2) = (uint16_t)w2;
            U8(G_OBJ, 0xa9ae) = (uint8_t)((U8(G_OBJ, 0xa9ae) & ~4u) | ((rf & 1) << 2));
            U8(G_OBJ, 0xa9b2) = (uint8_t)((U8(G_OBJ, 0xa9b2) & ~1u) | ((rf >> 1) & 1));
            U8(G_OBJ, 0xa9b6) = (uint8_t)((U8(G_OBJ, 0xa9b6) & ~0x80u) | (((rf >> 2) & 1) << 7));
            U8(G_OBJ, 0xa9b8) = (uint8_t)((U8(G_OBJ, 0xa9b8) & ~0x40u) | (((rf >> 3) & 1) << 6));
            memcpy(G_SNAP, G_OBJ, g_sz);
            h = sfr_call(G_OBJ, G_SNAP, 1);
            log_call(&lg, h, tx * 8 + rx, tf * 256 + rf * 16 + pe);
          }
  for (i = 0; i < 80000; i++) {
    unsigned int h;
    if (i % 300 == 0) fill_random(G_BASE, g_sz);
    memcpy(G_OBJ, G_BASE, g_sz);
    sfr_poke_sane(G_OBJ);
    /* the INFO words: fully random (garbage in all the unused bits) */
    U16(G_OBJ, 0xa9de) = rnd16();
    U16(G_OBJ, 0xa9e0) = rnd16();
    U16(G_OBJ, 0xa9e2) = rnd16();
    memcpy(G_SNAP, G_OBJ, g_sz);
    h = sfr_call(G_OBJ, G_SNAP, 1);
    log_call(&lg, h, i, 0);
  }
  log_done(&lg);
  sfr_need_all();
}

