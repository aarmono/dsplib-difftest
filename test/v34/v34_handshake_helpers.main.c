static unsigned int diff_obj(const unsigned char *obj, const unsigned char *snap) {
  unsigned int h = FNV0;
  size_t i;
  for (i = 0; i < g_sz / 4; i++) {
    uint32_t a, b;
    memcpy(&a, obj + 4 * i, 4);
    memcpy(&b, snap + 4 * i, 4);
    if (g_isslot[i]) {
      a = norm_val(a);
      b = norm_val(b);
    }
    if (a != b) {
      uint32_t idx = (uint32_t)i;
      h = fnv(h, &idx, 4);
      h = fnv(h, &a, 4);
      if (g_verbose > 1) printf("   diffword off=%05x new=%08x\n", (unsigned int)(4 * i), a);
    }
  }
  return h;
}
static unsigned int hash_obj(const unsigned char *obj) {
  unsigned int h = FNV0;
  size_t i;
  for (i = 0; i < g_sz / 4; i++) {
    uint32_t a;
    memcpy(&a, obj + 4 * i, 4);
    if (g_isslot[i]) a = norm_val(a);
    h = fnv(h, &a, 4);
  }
  return h;
}
/* is the object equal to the model's expected object (pointer slots normalised)? returns the first differing word or -1 */
static long obj_vs_model(const unsigned char *obj, const unsigned char *exp) {
  size_t i;
  for (i = 0; i < g_sz / 4; i++) {
    uint32_t a, b;
    memcpy(&a, obj + 4 * i, 4);
    memcpy(&b, exp + 4 * i, 4);
    if (g_isslot[i]) {
      a = norm_val(a);
      b = norm_val(b);
    }
    if (a != b) return (long)(4 * i);
  }
  return -1;
}

