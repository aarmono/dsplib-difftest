/* ---- named coverage counters ---- */
#define MAXCOV 200
static const char *g_covname[MAXCOV];
static long g_covn[MAXCOV];
static int g_ncov;
static void cov(const char *name) {
  int i;
  for (i = 0; i < g_ncov; i++)
    if (g_covname[i] == name || !strcmp(g_covname[i], name)) {
      g_covn[i]++;
      return;
    }
  if (g_ncov >= MAXCOV) die("too many coverage counters");
  g_covname[g_ncov] = name;
  g_covn[g_ncov] = 1;
  g_ncov++;
}
static long cov_get(const char *name) {
  int i;
  for (i = 0; i < g_ncov; i++)
    if (!strcmp(g_covname[i], name)) return g_covn[i];
  return 0;
}
static void need_min(const char *name, long lo);
static void need(const char *name) {
  long v = cov_get(name);
  printf("  coverage %s = %ld\n", name, v);
  if (v <= 0) {
    fprintf(stderr, "COVERAGE FAILURE: %s never reached\n", name);
    g_fail = 1;
  }
}
static void need_min(const char *name, long lo) {
  long v = cov_get(name);
  printf("  coverage %s = %ld (min %ld)\n", name, v, lo);
  if (v < lo) {
    fprintf(stderr, "COVERAGE FAILURE: %s reached %ld < %ld times\n", name, v, lo);
    g_fail = 1;
  }
}

