typedef struct {
  int ok;
  int m65, clampT, clampR, minpath, minpath_neg, trimT, trimR, wrapT, wrapR, errbr, err_ok, bit13;
  int Tn, Rn, hi, hiRx, idx1, idx2, s1, s2, zerodiv;
  int nof, tnzero, ac16zero, ac_flags0;
  int w8, wa;
  int ac04, ac08, ac16;
  int tblT, tblR;
} idm_t;

static int sc_read(const void *p, int i) {
  if (i < 0 || i > 27) return 0;
  return ((const int16_t *)p)[i];
}
static int tbl_id(const void *p) {
  int i;
  for (i = 0; i < 5; i++)
    if (p == (const void *)scale_tbl(i)) return i;
  return -1;
}
static int trim_model(int idx, unsigned bm, int *iters, int *wrap) {
  unsigned sh = ((unsigned)idx - 1u) & 31u;
  uint32_t m0 = (sh < 16) ? (1u << sh) : 0u;
  int cur = idx, j = 0;
  *iters = 0;
  *wrap = 0;
  if (idx == 0) return 0;
  if (bm & m0) return idx;
  for (;;) {
    int prev = cur;
    cur = (int16_t)(cur - 1);
    j++;
    (*iters)++;
    if (prev == -0x8000) *wrap = 1;
    if (cur == 0) return 0;
    if (j < 32 && (bm & (m0 >> j))) return cur;
  }
}

static int id_model(const unsigned char *o, idm_t *m) {
  unsigned x = U16(o, 0xaa0c), y = U16(o, 0xaa3c), bm = U16(o, 0xaa0e);
  int tn0, b, c, a, Tn, Rn, it1, it2, w1, w2;
  const unsigned char *R = o + 0xaa84;
  memset(m, 0, sizeof *m);
  m->m65 = (S16(o, 0x359c) == 0x65);
  if (m->m65) {
    tn0 = (int)((x >> 2) & 0xf);
    b = (int)((x >> 6) & 0xf);
    c = (int)((y >> 10) & 0xf);
  } else {
    tn0 = (int)((x >> 6) & 0xf);
    b = (int)((x >> 2) & 0xf);
    c = (int)((y >> 6) & 0xf);
  }
  Tn = tn0;
  a = brev(c, 4);
  if (Tn > a) {
    Tn = a;
    m->clampT = 1;
  }
  Rn = (int16_t)U16(R, 0x14);
  if (Rn > b) {
    Rn = b;
    m->clampR = 1;
  }
  m->minpath = ((int16_t)bm >= 0) || !(U8(o, 0xaa3e) & 1);
  m->minpath_neg = ((int16_t)bm < 0);
  if (m->minpath) {
    int mn = Tn <= Rn ? Tn : Rn;
    Tn = Rn = mn;
  }
  Tn = trim_model(Tn, bm, &it1, &w1);
  Rn = trim_model(Rn, bm, &it2, &w2);
  m->trimT = it1;
  m->trimR = it2;
  m->wrapT = w1;
  m->wrapR = w2;
  if (Tn == 0) {
    if (U16(R, 0x12) != 0x960) {
      m->errbr = 1;
      Tn = Rn = 2;
    } else {
      m->err_ok = 1;
    }
  }
  m->tnzero = (Tn == 0);
  m->w8 = (int)((x >> 11) & 3);
  m->wa = (int)((x >> 14) & 1);
  m->bit13 = (U8(o, 0xaa0d) & 0x20) != 0;
  m->hi = m->wa;
  m->Tn = Tn;
  m->Rn = Rn;
  m->idx1 = Tn + 14 * m->hi - 1;
  m->hiRx = S16(R, 0x22);
  m->idx2 = Rn + 14 * m->hiRx - 1;
  if (m->idx1 < -1 || m->idx1 > 28 || m->idx2 < -1 || m->idx2 > 28) return 0;
  if (tbl_id(PTRS_GET(o, 0xaa90)) < 0 || tbl_id(PTRS_GET(o, 0xaaac)) < 0) return 0;
  m->tblT = tbl_id(PTRS_GET(o, 0xaa90));
  m->tblR = tbl_id(PTRS_GET(o, 0xaaac));
  m->s1 = sc_read(PTRS_GET(o, 0xaa90), m->idx1);
  m->s2 = sc_read(PTRS_GET(o, 0xaaac), m->idx2) >> 1;
  m->nof = Tn ? ((int)((uint32_t)Tn * (uint32_t)I32(o, 8)) >> 6) + 6 : 0;
  if (m->s2 == 0) {
    m->zerodiv = 1;
    m->s2 = 1;
  }
  m->ac16zero = (U8(o, 0xac16) == 0);
  m->ac_flags0 = (I32(o, 0x24c) == 0 && I32(o, 0x250) == 0);
  m->ac16 = U8(o, 0xac16);
  m->ac04 = I32(o, 0xac04);
  m->ac08 = I32(o, 0xac08);
  if (m->ac16zero) {
    m->ac04 = Tn * 0x960;
    if (m->ac_flags0) {
      m->ac16 = 1;
      m->ac08 = Rn * 0x960;
    }
  }
  m->ok = 1;
  return 1;
}

static void id_check(const unsigned char *o, const idm_t *m) {
  const unsigned char *R = o + 0xaa84;
  uint16_t w25 = U16(o, 0x25c2);
  const char *bad = NULL;
  if (S16(R, 4) != m->Tn) bad = "R+4 (Tn)";
  else if (S16(R, 0x14) != m->Rn) bad = "R+0x14 (Rn)";
  else if (S16(R, 8) != m->w8) bad = "R+8";
  else if (S16(R, 0xa) != m->wa) bad = "R+0xa (hi)";
  else if (I32(o, 0x10) != m->nof) bad = "nofTxBits";
  else if (I32(o, 0xac04) != m->ac04) bad = "0xac04";
  else if (I32(o, 0xac08) != m->ac08) bad = "0xac08";
  else if (U8(o, 0xac16) != m->ac16) bad = "0xac16";
  else if (((w25 & 0x4000) != 0) != m->bit13) bad = "0x25c2 bit 0x4000";
  else if (U16(o, 0x25e0 + 0x42) != (uint16_t)m->s1) bad = "initV34 p7 of block A (s1)";
  else if (U16(o, 0xa00 + 0x42) != (uint16_t)m->s2) bad = "initV34 p7 of block B (s2)";
  if (bad) {
    fprintf(stderr, "initdigital model mismatch: %s\n", bad);
    die("initdigital disagrees with the independent model");
  }
}

