static void gb_cover(unsigned cls, int res) {
  size_t i;
  for (i = 0; i < sizeof k_gbcov / sizeof k_gbcov[0]; i++)
    if (cls & k_gbcov[i].bit) cov(k_gbcov[i].name);
  if (res == 0) cov("getbit result 0");
  if (res == 1) cov("getbit result 1");
  if (res == -1) cov("getbit result -1");
}
static void gb_need_all(void) {
  size_t i;
  for (i = 0; i < sizeof k_gbcov / sizeof k_gbcov[0]; i++) need(k_gbcov[i].name);
  need("getbit result 0");
  need("getbit result 1");
  need("getbit result -1");
}

/* runs one call: model on the snapshot, blob/port on the live buffer; returns the per-call hash */
static unsigned int gb_step(int record, long *resp, unsigned *clsp) {
  unsigned cls = 0;
  int mres, res;
  unsigned char *R = RB_R;
  unsigned int h = FNV0;
  size_t i;
  memcpy(g_rbsnap, g_rb, RBSZ);
  memcpy(g_rbmodel, g_rb, RBSZ);
  mres = gb_model(g_rbmodel + RB_OFF, &cls, 0);
  if (cls & GB_HAZARD) die("getbit infinite-recursion state reached the call (oracle failure)");
  g_junk1 = rint32();
  g_junk2 = rint32();
  res = call_getbit(R);
  if (res != mres) {
    fprintf(stderr, "getbit result %d, model %d (cls %x)\n", res, mres, cls);
    die("getbit disagrees with the independent model (result)");
  }
  if (memcmp(g_rb, g_rbmodel, RBSZ) != 0) {
    for (i = 0; i < RBSZ; i++)
      if (g_rb[i] != g_rbmodel[i]) break;
    fprintf(stderr, "getbit state differs from the model at reader%+ld (cls %x)\n", (long)i - RB_OFF, cls);
    die("getbit disagrees with the independent model (state)");
  }
  if (record) gb_cover(cls, res);
  h = fnv32(h, (uint32_t)res);
  for (i = RB_OFF - REG_HALF; i < RB_OFF + REG_HALF; i++)
    if (g_rb[i] != g_rbsnap[i]) {
      uint32_t x = (uint32_t)(i - (RB_OFF - REG_HALF));
      h = fnv32(fnv32(h, x), g_rb[i]);
    }
  /* nothing outside the region may change */
  if (memcmp(g_rb, g_rbsnap, RB_OFF - REG_HALF) != 0 || memcmp(g_rb + RB_OFF + REG_HALF, g_rbsnap + RB_OFF + REG_HALF, RBSZ - RB_OFF - REG_HALF) != 0)
    die("getbit wrote outside the reader region");
  *resp = res;
  *clsp = cls;
  return h;
}

