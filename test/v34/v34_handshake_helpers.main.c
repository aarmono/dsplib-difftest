int dsplibs_debug_printf(const char *fmt, ...) {
  va_list ap;
  int ret;
  va_start(ap, fmt);
  ret = vprintf(fmt, ap);
  va_end(ap);
  g_total_prints++;
  if (strstr(fmt, "preliminary")) cov("print preliminary");
  else if (strstr(fmt, "2400bps")) cov("print 2400bps");
  else if (strstr(fmt, "finally")) cov("print finally");
  else if (strstr(fmt, "setting nofTxBits")) cov("print nofTxBits");
  else if (strstr(fmt, "ZERODIV")) cov("print ZERODIV");
  else if (strstr(fmt, "setfinalrate")) cov("print setfinalrate");
  else if (strstr(fmt, "first estimation")) cov("print first estimation");
  else if (strstr(fmt, "RTD")) cov("print RTD");
  else if (strstr(fmt, "Modifying")) cov("print Modifying");
  else if (strstr(fmt, "bulk delay estimation")) cov("print final estimation");
  if (g_flip_after >= 0 && g_nprint == g_flip_after) dsplibs_debug_level = g_flip_to;
  g_nprint++;
  return ret;
}
static void print_begin(int flip_after, unsigned int flip_to) {
  g_flip_after = flip_after;
  g_flip_to = flip_to;
  g_nprint = 0;
}
static void print_end(void) {
  if (g_nprint < 16) g_print_hist[g_nprint]++;
}

