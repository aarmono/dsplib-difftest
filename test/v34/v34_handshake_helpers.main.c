/* ============================================================================
 * getbit
 * ========================================================================== */
#define RBSZ 0x20100
static unsigned char g_rb[RBSZ];
static unsigned char g_rbsnap[RBSZ];
static unsigned char g_rbmodel[RBSZ];
#define RB_OFF 0x10080
#define RB_R (g_rb + RB_OFF)
#define REG_HALF 0x200

#define R16(R, o) (*(uint16_t *)((R) + (o)))
#define R32(R, o) (*(uint32_t *)((R) + (o)))
/* classes reported by the model (bit mask) */
enum {
  GB_FAST = 1 << 0,
  GB_FULL = 1 << 1,
  GB_FULLEQ = 1 << 2,
  GB_PARTIAL = 1 << 3,
  GB_CHUNK_LE0 = 1 << 4,
  GB_CHUNK_GT16 = 1 << 5,
  GB_CRC_LOOP = 1 << 6,
  GB_CRC_N0 = 1 << 7,
  GB_CRC_EMIT = 1 << 8,
  GB_TAIL = 1 << 9,
  GB_END = 1 << 10,
  GB_RESTART = 1 << 11,
  GB_RS_NB = 1 << 12,
  GB_RS_POS = 1 << 13,
  GB_RS_CRC = 1 << 14,
  GB_RS_TAIL = 1 << 15,
  GB_OVERLAP = 1 << 16,
  GB_NEGW = 1 << 17,
  GB_D_NEG_OTHER = 1 << 18,
  GB_D_ZERO_NOCRC = 1 << 19,
  GB_HAZARD = 1 << 20,
  GB_CRC_FB = 1 << 21, /* the CRC feedback fired at least once */
  GB_CRC_NOFB = 1 << 22,
  GB_NB_BIG = 1 << 23, /* nbits > 16 on the fast path */
  GB_CRC_WRAP = 1 << 24 /* the CRC loop's 16-bit counter wrapped (negative n) */
};

/* independent model: works on a full copy of the buffer (m) with the reader at R = m + RB_OFF */
static int gb_model(unsigned char *R, unsigned *cls, int depth) {
  uint16_t nb = R16(R, 0x28);
  uint32_t acc;
  int nbits;
  if (depth > 1) {
    *cls |= GB_HAZARD;
    return -99;
  }
  if (nb != 0) {
    *cls |= GB_FAST;
    if (nb > 16) *cls |= GB_NB_BIG;
    acc = R32(R, 0x24);
    nbits = nb;
  } else {
    int16_t total = (int16_t)R16(R, 0x18);
    uint16_t pos = R16(R, 0x1a);
    int16_t d = (int16_t)(total - pos);
    (void)total;
    if (d <= 0) {
      if (d == 0 && R16(R, 0x16) != 0) {
        *cls |= GB_CRC_EMIT | (depth ? GB_RS_CRC : 0);
        acc = R16(R, 0x14);
        R16(R, 0x28) = 16;
        R16(R, 0x1a) = (uint16_t)(pos + 16);
        R32(R, 0x24) = acc;
        nbits = 16;
      } else if (d == -16) {
        *cls |= GB_TAIL | (depth ? GB_RS_TAIL : 0);
        R32(R, 0x24) = 0xf;
        R16(R, 0x28) = 4;
        R16(R, 0x1a) = (uint16_t)(pos + 4);
        acc = 0xf;
        nbits = 4;
      } else {
        if (d == 0) *cls |= GB_D_ZERO_NOCRC;
        else *cls |= GB_D_NEG_OTHER;
        if (R16(R, 0x20) == 0) {
          *cls |= GB_END;
          return -1;
        }
        *cls |= GB_RESTART;
        R16(R, 0x14) = 0xffff;
        R16(R, 0x1a) = 0;
        R16(R, 0x22) = (uint16_t)(R16(R, 0x22) + 1);
        R16(R, 0x1e) = 0;
        R32(R, 0x24) = R32(R, 0x2c);
        R16(R, 0x28) = R16(R, 0x2a);
        if (R16(R, 0x2a) != 0) *cls |= GB_RS_NB;
        else if ((int16_t)R16(R, 0x18) > 0) *cls |= GB_RS_POS;
        return (int16_t)gb_model(R, cls, depth + 1);
      }
    } else {
      int16_t chunk = (int16_t)R16(R, 0x1c);
      int16_t widx = (int16_t)R16(R, 0x1e);
      int n;
      uint32_t dat;
      uint32_t oldacc = R32(R, 0x24);
      if (chunk <= 0) *cls |= GB_CHUNK_LE0;
      if (chunk > 16) *cls |= GB_CHUNK_GT16;
      if (widx < 0) *cls |= GB_NEGW;
      if (widx >= 0 && widx * 2 < 0x30) *cls |= GB_OVERLAP;
      if (chunk <= d) {
        *cls |= GB_FULL;
        if (chunk == d) *cls |= GB_FULLEQ;
        n = chunk;
        R16(R, 0x28) = (uint16_t)chunk;
        dat = *(uint16_t *)(R + 2 * (int)widx);
        acc = (oldacc << (chunk & 31)) | dat;
        R16(R, 0x1e) = (uint16_t)(widx + 1);
        R16(R, 0x1a) = (uint16_t)(pos + (uint16_t)chunk);
        nbits = (uint16_t)chunk;
      } else {
        *cls |= GB_PARTIAL;
        n = d;
        R16(R, 0x28) = (uint16_t)d;
        dat = *(uint16_t *)(R + 2 * (int)widx);
        acc = (oldacc << (d & 31)) | dat;
        R16(R, 0x1a) = (uint16_t)(pos + d);
        nbits = (uint16_t)d;
      }
      R32(R, 0x24) = acc;
      if (R16(R, 0x16) != 0) {
        if (n == 0) {
          *cls |= GB_CRC_N0;
        } else {
          int k = (int16_t)(n - 1);
          int cnt = 0;
          *cls |= GB_CRC_LOOP;
          if (n < 0) *cls |= GB_CRC_WRAP;
          for (;;) {
            uint16_t c = R16(R, 0x14);
            int bit = (int)((acc >> (k & 31)) & 1);
            int fb = ((c >> 15) & 1) ^ bit;
            R16(R, 0x14) = (uint16_t)((c << 1) ^ (fb ? 0x1021 : 0));
            *cls |= fb ? GB_CRC_FB : GB_CRC_NOFB;
            cnt++;
            if (k == 0) break;
            k = (int16_t)(k - 1);
          }
        }
      }
    }
  }
  {
    int16_t sh = (int16_t)(nbits - 1);
    R16(R, 0x28) = (uint16_t)sh;
    return (int)((acc >> (sh & 31)) & 1);
  }
}

static int16_t pick_chunk(void) {
  static const uint16_t edge[] = {0x8000, 0x7fff, 0x8001, 0xffff, 0x7ffe, 0xfff0, 17, 15};
  switch (lcg_mod(12)) {
  case 10:
  case 11: return (int16_t)edge[lcg_mod(8)];
  case 0: return 0;
  case 1: return (int16_t)-rr(1, 0x7fff);
  case 2: return (int16_t)rr(17, 0x7fff);
  case 3: return (int16_t)(0x8000 | (int)lcg_mod(0x8000));
  case 4: return 16;
  case 5: return 8;
  default: return (int16_t)rr(1, 16);
  }
}

/* fills the reader region with random bytes and pokes a structured state; mode 0 wild, 1 nominal stream start */
static void gb_gen(unsigned char *R) {
  unsigned int pos, d;
  int dclass;
  fill_random(R - REG_HALF, 2 * REG_HALF);
  /* nbits */
  switch (lcg_mod(10)) {
  case 0: R16(R, 0x28) = (uint16_t)rr(1, 16); break;
  case 1: R16(R, 0x28) = (uint16_t)(lcg_next() | 1u); break;
  case 2: R16(R, 0x28) = (uint16_t)(lcg_mod(2) ? 0x8000 : 0xffff); break;
  case 3: R16(R, 0x28) = 1; break;
  default: R16(R, 0x28) = 0; break;
  }
  pos = rnd16();
  dclass = (int)lcg_mod(12);
  switch (dclass) {
  case 0: d = 0; break;
  case 1: d = 0xfff0; break; /* -16 */
  case 2: d = (unsigned)(-rr(1, 40)) & 0xffff; break;
  case 3: d = 0x8000; break;
  case 4: d = (unsigned)rr(1, 40); break;
  case 5: d = (unsigned)rr(1, 0x7fff); break;
  case 6: d = 16; break;
  case 7: d = (unsigned)rr(1, 17); break;
  case 8: d = 0xfff1; break;
  case 9: d = 0xffef; break;
  default: d = (unsigned)rr(1, 40); break;
  }
  R16(R, 0x1a) = (uint16_t)pos;
  R16(R, 0x18) = (uint16_t)(pos + d);
  /* totals that make the RESTARTED state (pos == 0) end in each way: 0 (with/without crcOn), -16, -1, small positive */
  switch (lcg_mod(14)) {
  case 0: R16(R, 0x18) = 0; break;
  case 1: R16(R, 0x18) = 0xfff0; break;
  case 2: R16(R, 0x18) = 0xffff; break;
  case 3: R16(R, 0x18) = (uint16_t)rr(1, 40); break;
  default: break;
  }
  {
    int16_t ch = pick_chunk();
    /* boundary chunk == d, d+1, d-1 */
    if ((int16_t)d > 0 && lcg_mod(4) == 0) ch = (int16_t)((int)(int16_t)d + rr(-1, 1));
    R16(R, 0x1c) = (uint16_t)ch;
  }
  switch (lcg_mod(6)) {
  case 0:
  case 1: R16(R, 0x16) = 0; break;
  case 2: R16(R, 0x16) = 1; break;
  case 3: R16(R, 0x16) = 0x100; break; /* non-zero word with a zero low byte */
  case 4: R16(R, 0x16) = 0x8000; break;
  default: R16(R, 0x16) = (uint16_t)(rnd16() | 1u); break;
  }
  switch (lcg_mod(7)) {
  case 0:
  case 1: R16(R, 0x20) = 0; break;
  case 2: R16(R, 0x20) = 1; break;
  case 3: R16(R, 0x20) = 0x100; break; /* non-zero word with a zero low byte */
  case 4: R16(R, 0x20) = 0x8000; break;
  default: R16(R, 0x20) = (uint16_t)(rnd16() | 1u); break;
  }
  /* widx */
  switch (lcg_mod(10)) {
  case 0:
  case 1:
  case 2:
  case 3: R16(R, 0x1e) = (uint16_t)rr(0, 9); break;
  case 4:
  case 5: R16(R, 0x1e) = (uint16_t)rr(10, 0x18); break;
  case 6: R16(R, 0x1e) = (uint16_t)-rr(1, 16); break;
  default: R16(R, 0x1e) = rnd16(); break;
  }
  switch (lcg_mod(6)) {
  case 0:
  case 1:
  case 2: R16(R, 0x2a) = 0; break;
  case 3: R16(R, 0x2a) = (uint16_t)rr(1, 16); break;
  case 4: R16(R, 0x2a) = (uint16_t)(0x100u | (unsigned)rr(1, 16)); break; /* the low byte alone would look like a small count */
  default: R16(R, 0x2a) = (uint16_t)(rnd16() | 1u); break;
  }
}

static void gb_check_hazard(unsigned char *R, int *patched) {
  unsigned cls = 0;
  int r;
  memcpy(g_rbmodel, g_rb, RBSZ);
  r = gb_model(g_rbmodel + RB_OFF, &cls, 0);
  (void)r;
  if (cls & GB_HAZARD) {
    R16(R, 0x2a) = (uint16_t)(lcg_mod(2) ? (unsigned)rr(1, 16) : (unsigned)(rnd16() | 1u));
    (*patched)++;
  }
}

