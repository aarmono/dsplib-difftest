static const int k_bauds[] = {0x960, 0xaf0, 0xbb8, 0xc80, 0xd65, 0xab7, 0x708, 0};

static void id_gen(unsigned char *o, int biased) {
  scrub_slots(o);
  switch (lcg_mod(8)) {
  case 0:
  case 1:
  case 2:
  case 3: U16(o, 0x359c) = 0x65; break;
  case 4: U16(o, 0x359c) = 0x64; break;
  case 5: U16(o, 0x359c) = 0x66; break;
  case 6: U16(o, 0x359c) = lcg_mod(2) ? 0x0165 : 0x8065; break;
  default: U16(o, 0x359c) = rnd16(); break;
  }
  U16(o, 0xaa0c) = rnd16();
  U16(o, 0xaa3c) = rnd16();
  switch (lcg_mod(8)) {
  case 0: U16(o, 0xaa0e) = 0xffff; break;
  case 1: U16(o, 0xaa0e) = 0; break;
  case 2: U16(o, 0xaa0e) = (uint16_t)(0x8000u | rnd16()); break;
  case 3: U16(o, 0xaa0e) = (uint16_t)(rnd16() & 0x7fffu); break;
  case 4: U16(o, 0xaa0e) = (uint16_t)(1u << rr(0, 15)); break;
  case 5: U16(o, 0xaa0e) = (uint16_t)((1u << rr(0, 16)) - 1u); break;
  case 6: U16(o, 0xaa0e) = rnd16(); break;
  default: U16(o, 0xaa0e) = 0x8000; break;
  }
  if (biased && lcg_mod(2)) U16(o, 0xaa0e) = 0;
  U16(o, 0xaa3e) = rnd16();
  U16(o, 0xaa84) = (uint16_t)(lcg_mod(4) ? k_bauds[lcg_mod(8)] : rnd16());
  U16(o, 0xaa96) = (uint16_t)(lcg_mod(2) ? 0x960 : (lcg_mod(4) ? k_bauds[lcg_mod(8)] : rnd16()));
  if (biased && lcg_mod(3)) U16(o, 0xaa96) = (uint16_t)k_bauds[1 + lcg_mod(7)];
  U16(o, 0xaa98) = (uint16_t)(lcg_mod(4) ? rr(0, 15) : rnd16());
  U16(o, 0xaa88) = rnd16();
  switch (lcg_mod(5)) {
  case 0:
  case 1:
  case 2: U16(o, 0xaaa6) = (uint16_t)lcg_mod(2); break;
  case 3: U16(o, 0xaaa6) = (uint16_t)rr(-3, 3); break;
  default: U16(o, 0xaaa6) = rnd16(); break;
  }
  if (biased && lcg_mod(3) == 0) {
    U16(o, 0xaa98) = 0;
    U16(o, 0xaaa6) = 0;
  }
  PTRS_SET(o, 0xaa90, (void *)scale_tbl((int)lcg_mod(5)));
  PTRS_SET(o, 0xaaac, (void *)scale_tbl((int)lcg_mod(5)));
  switch (lcg_mod(3)) {
  case 0: I32(o, 8) = rr(-1000, 1000); break;
  case 1: I32(o, 8) = rr(0, 0x400); break;
  default: I32(o, 8) = rint32(); break;
  }
  I32(o, 0x24c) = lcg_mod(2) ? 0 : nz32();
  I32(o, 0x250) = lcg_mod(2) ? 0 : nz32();
  U8(o, 0xac16) = (uint8_t)(lcg_mod(2) ? 0 : (lcg_next() | 1u));
}

/* generate until the scale-index oracle accepts */
static void id_gen_ok(unsigned char *o, int biased, idm_t *m, long *rerolls) {
  int tries;
  for (tries = 0; tries < 1000; tries++) {
    id_gen(o, biased);
    if (id_model(o, m)) return;
    (*rerolls)++;
  }
  die("initdigital: no acceptable state found");
}

static unsigned int id_call(unsigned char *o, const unsigned char *snap, const idm_t *m) {
  g_junk1 = rint32();
  initdigital(o);
  id_check(o, m);
  return snap ? diff_obj(o, snap) : hash_obj(o);
}

