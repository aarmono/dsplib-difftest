/* independent model on the expected object; returns the number of prints as a bitmask of classes */
typedef struct {
  int first1, first2, rtd, modify, final_print, cond, small, far_set, far_clr, clamp_w, nfinal;
  uint32_t len;
} abd_cls_t;
static void abd_model(unsigned char *o, int arg, abd_cls_t *c) {
  int n = (int16_t)arg;
  uint32_t nn;
  uint32_t len = U32(o, 0x35b4);
  memset(c, 0, sizeof *c);
  c->len = len;
  if (n <= 0) {
    c->first1 = 1;
    n = 0x90;
  }
  nn = (uint32_t)n;
  if (nn >= len) {
    c->first2 = 1;
    nn = 0;
  }
  c->nfinal = (int)nn;
  U32(o, 0x35ac) = nn;
  U32(o, 0x35a8) = 0;
  memset(o + 0x35b8, 0, 2 * (size_t)nn);
  if (I32(o, 0x24c) == 0 && I32(o, 0x250) == 0 && S16(o, 0xa23c) != 0) {
    c->cond = 1;
    if ((int)nn <= 0x1d) {
      int w = (int)nn + 0xf;
      c->small = 1;
      if (w > 0x1e) {
        w = 0x1e;
        c->clamp_w = 1;
      }
      U16(o, 0xa23c) = 0;
      U16(o, 0x25c) = (uint16_t)(U16(o, 0x25c) - w);
      c->far_clr = 1;
    } else {
      U16(o, 0xa23c) = 1;
      c->far_set = 1;
    }
  } else {
    U16(o, 0xa23c) = 0;
    c->far_clr = 1;
  }
}

/* a non-zero dword, incl. ones whose low half (or low byte) is zero: the machine code tests 32-bit flags as dwords */
static int32_t nz32(void) {
  switch (lcg_mod(5)) {
  case 0: return (int32_t)((uint32_t)(rnd16() | 1u) << 16); /* low half zero */
  case 1: return (int32_t)(0x100u * (1u + lcg_mod(255)));    /* low byte zero */
  case 2: return (int32_t)((1u + lcg_mod(255)) << 24);       /* only the top byte set */
  default: return (int32_t)(lcg_next() | 1u);
  }
}
static void abd_gen(unsigned char *o, int *argp, int biased) {
  uint32_t len;
  int n;
  switch (lcg_mod(12)) {
  case 0: len = 0; break;
  case 1: len = 1; break;
  case 2: len = 0x90; break;
  case 3: len = 0x91; break;
  case 4: len = 0x1e; break;
  case 5: len = (uint32_t)rr(2, 0x40); break;
  case 6: len = 0x2580; break;
  case 7: len = (uint32_t)rr(0x91, 0x7fff); break;
  case 8: len = (uint32_t)rr(0x8000, 0x7fffffff); break;
  case 9: len = 0x80000000u | lcg_next(); break;
  case 10: len = 0xffffffffu; break;
  default: len = (uint32_t)rr(1, 0x300); break;
  }
  if (biased && lcg_mod(2)) len = 0x2580;
  U32(o, 0x35b4) = len;
  switch (lcg_mod(15)) {
  case 0: n = 0; break;
  case 1: n = -rr(1, 0x7fff); break;
  case 2: n = -0x8000; break;
  case 3: n = rr(1, 0x1d); break;
  case 4: n = 0x1e + (int)lcg_mod(2); break;
  case 5: n = 0x0f + (int)lcg_mod(2); break;
  case 6: n = 0x1d; break;
  case 7: n = rr(0x20, 0x300); break;
  case 8: n = 0x90; break;
  case 9: n = 0x7fff; break;
  case 10: n = rr(1, 0x7fff); break;
  case 11: n = (int)(len - 1u) & 0xffff; break;
  case 12: n = (int)len & 0xffff; break;
  case 13: n = (int)(len + 1u) & 0xffff; break;
  default: n = rr(1, 0x40); break;
  }
  *argp = (int)(((uint32_t)rnd16() << 16) | (uint16_t)n);
  I32(o, 0x24c) = (lcg_mod(2) || biased) ? 0 : nz32();
  I32(o, 0x250) = (lcg_mod(4) || biased) ? 0 : nz32();
  {
    uint32_t low;
    switch (lcg_mod(5)) { /* the flag is a WORD: zero (with garbage above), 1, odd, or non-zero with a zero low byte */
    case 0: low = biased ? 1u : 0u; break;
    case 1: low = 1u; break;
    case 2: low = 0x100u * (1u + lcg_mod(255)); break;
    default: low = (uint32_t)(rnd16() | 1u); break;
    }
    if (lcg_mod(6) == 0 && !biased) low = 0u;
    U32(o, 0xa23c) = ((uint32_t)rnd16() << 16) | low;
  }
  U16(o, 0x25c) = rnd16();
}

static void abd_cover(const abd_cls_t *c, int arg) {
  int n = (int16_t)arg;
  if (n == 0) cov("abd arg n == 0");
  if (n < 0) cov("abd arg n < 0");
  if (n > 0) cov("abd arg n > 0");
  if (n == -0x8000) cov("abd arg n == INT16_MIN");
  if (c->first1) cov("abd first-estimation (n<=0 -> 0x90)");
  if (c->first2) cov("abd first-estimation (n>=len -> 0)");
  if (c->first2 && c->len == 0) cov("abd len == 0");
  if (c->first2 && c->len != 0) cov("abd len != 0 clamp");
  if (!c->first1 && !c->first2) cov("abd n unchanged");
  if (c->first1 && c->first2) cov("abd both clamps");
  if (c->len >= 0x80000000u) cov("abd len >= 2^31");
  if (c->cond) cov("abd far-EC condition (flags 0, a23c != 0)");
  if (c->cond && c->small) cov("abd small n (RTD branch)");
  if (c->cond && c->small && c->clamp_w) cov("abd RTD w clamped to 0x1e");
  if (c->cond && c->small && !c->clamp_w) cov("abd RTD w not clamped");
  if (c->cond && c->far_set) cov("abd far EC set (n >= 0x1e)");
  if (!c->cond) cov("abd far EC cleared (condition false)");
  if (c->nfinal == 0x1d) cov("abd final n == 0x1d");
  if (c->nfinal == 0x1e) cov("abd final n == 0x1e");
  if (c->nfinal == 0x0f) cov("abd final n == 0x0f");
  if (c->nfinal == 0x10) cov("abd final n == 0x10");
  if (c->nfinal == 0) cov("abd final n == 0");
  if (c->nfinal > 0x1e) cov("abd final n > 0x1e");
}

static void abd_check_model(const unsigned char *o, const unsigned char *exp, int arg) {
  long bad = obj_vs_model(o, exp);
  if (bad >= 0) {
    fprintf(stderr, "ApplyBulkDelay model mismatch at obj+0x%lx (arg %d)\n", bad, arg);
    die("ApplyBulkDelay disagrees with the independent model");
  }
}

