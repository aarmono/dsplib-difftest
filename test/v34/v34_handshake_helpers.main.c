/* nominal streams: reader set up the way a producer would; the emitted bit sequence is checked against a
 * straightforward bit-level model of the stream (data bits, CRC, 4-bit tail, restart) */
static void scen_getbit_streams(void) {
  logger_t lg = {"getbit_stream", FNV0, 0, 251};
  long s, res;
  unsigned cls;
  long bits_checked = 0, restarts_seen = 0, passes = 0;
  g_sz = OBJSZ;
  fill_random(g_rb, RBSZ);
  for (s = 0; s < 6000; s++) {
    unsigned char *R = RB_R;
    int chunk = rr(1, 16);
    int loop = (int)lcg_mod(2);
    /* a restart resets widx to 0, so a looping stream keeps its data in words 0..9 (below the crc field at +0x14);
     * a one-shot stream may place long data beyond the 0x30-byte header */
    int total = loop ? rr(1, 10 * chunk) : rr(1, 200);
    int crcOn = (int)lcg_mod(2);
    int nb2a = lcg_mod(2) ? 0 : rr(1, 16);
    uint32_t acc2c = lcg_next();
    int nwords = (total + chunk - 1) / chunk;
    int w, k, i;
    uint8_t exp[4096];
    int nexp = 0;
    unsigned int h = FNV0;
    uint16_t crc = 0xffff;
    int limit;
    int pass;
    fill_random(R - REG_HALF, 2 * REG_HALF);
    /* the data words live at r+0.. : words 0..nwords-1 must not overlap the reader fields (0x14..0x2f) */
    if (nwords > 10) {
      /* long streams place the data far away by using a non-zero starting widx */
    }
    {
      int base_w = (nwords <= 10) ? 0 : 0x18; /* first data word index; words 0x18.. are beyond the 0x30-byte header */
      for (w = 0; w < nwords; w++) {
        uint16_t v = rnd16();
        if (lcg_mod(2)) v &= (uint16_t)((1u << chunk) - 1u); /* half the streams have clean words, half garbage above the chunk */
        R16(R, 2 * (base_w + w)) = v;
      }
      R16(R, 0x1e) = (uint16_t)base_w;
      R16(R, 0x14) = 0xffff;
      R16(R, 0x16) = (uint16_t)crcOn;
      R16(R, 0x18) = (uint16_t)total;
      R16(R, 0x1a) = 0;
      R16(R, 0x1c) = (uint16_t)chunk;
      R16(R, 0x20) = (uint16_t)loop;
      R16(R, 0x22) = 0;
      R32(R, 0x24) = lcg_next();
      R16(R, 0x28) = 0;
      R16(R, 0x2a) = (uint16_t)nb2a;
      R32(R, 0x2c) = acc2c;
      /* expected sequence for ONE pass, then (loop) the restart values and the same pass again */
      pass = 0;
      for (;;) {
        int wi = base_w;
        int left = total;
        crc = 0xffff;
        /* restart prefix: the nb2a low bits of acc2c, MSB first (only on a restart, i.e. pass > 0) */
        if (pass > 0)
          for (k = nb2a - 1; k >= 0; k--) exp[nexp++] = (uint8_t)((acc2c >> k) & 1);
        while (left > 0) {
          int n = left < chunk ? left : chunk;
          uint16_t v = R16(R, 2 * wi);
          for (k = n - 1; k >= 0; k--) {
            int bit = (v >> k) & 1;
            int fb = ((crc >> 15) & 1) ^ bit;
            crc = (uint16_t)((crc << 1) ^ (fb ? 0x1021 : 0));
            exp[nexp++] = (uint8_t)bit;
          }
          if (left >= chunk) wi++; /* the partial last chunk does not advance widx (irrelevant to the sequence) */
          left -= n;
        }
        if (crcOn) {
          for (k = 15; k >= 0; k--) exp[nexp++] = (uint8_t)((crc >> k) & 1);
          for (k = 0; k < 4; k++) exp[nexp++] = 1;
        }
        pass++;
        if (!loop || pass >= 2 || nexp > 3000) break;
      }
      limit = nexp + (loop ? 0 : 6);
    }
    for (i = 0; i < limit; i++) {
      int want = (i < nexp) ? exp[i] : -1;
      unsigned int hh;
      hh = gb_step(1, &res, &cls);
      h = fnv32(h, hh);
      if (res != want) {
        fprintf(stderr, "stream %ld bit %d: got %ld, sequence model %d (total %d chunk %d crc %d loop %d nb2a %d)\n", s, i, res, want, total,
                chunk, crcOn, loop, nb2a);
        die("getbit stream disagrees with the bit-level model");
      }
      bits_checked++;
      if (cls & GB_RESTART) restarts_seen++;
      if (cls & GB_END) cov("getbit stream end reached");
    }
    if (pass >= 2) passes++;
    log_call(&lg, h, total, chunk);
  }
  log_done(&lg);
  printf("  stream bits verified against the sequence model = %ld, restarts seen = %ld, two-pass streams = %ld\n", bits_checked, restarts_seen, passes);
  need("getbit stream end reached");
  need("getbit CRC emitted (d == 0, crcOn)");
  need("getbit 4-bit tail (d == -16)");
  need("getbit restart (recursion)");
  need("getbit restart, nbits != 0 after restart");
  need("getbit partial chunk (chunk > d)");
  need("getbit full chunk (chunk <= d)");
  need("getbit CRC feedback taken");
  need("getbit d == 0 without crcOn");
  if (restarts_seen == 0) g_fail = 1;
}

