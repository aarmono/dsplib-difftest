static int brev(int x, int n) {
  int r = 0, i;
  for (i = 0; i < n; i++)
    if (x & (1 << i)) r |= 1 << (n - 1 - i);
  return r;
}

/* independent model on the expected object: table-driven */
static const struct {
  int baud, tbl, carClr, carSet;
} k_tx[6] = {{0x960, 0, 0x640, 0x708}, {0, 0, 0, 0}, {0xaf0, 1, 0x690, 0x74b}, {3000, 2, 0x708, 2000}, {0xc80, 3, 0x725, 0x780}, {0xd65, 4, 0x7a7, 0x7a7}};
static const struct {
  int baud, tbl, off, mask, carClr, tblClr, carSet, tblSet;
} k_rx[6] = {{0x960, 0, 0xa9ae, 0x04, 0x640, 0, 0x708, 2},   /* c1600 / c1800_ */
             {0, 0, 0, 0, 0, 0, 0, 0},
             {0xaf0, 1, 0xa9b2, 0x01, 0x690, 1, 0x74b, 4},   /* c1680 / c1867 */
             {3000, 2, 0xa9b6, 0x80, 0x708, 2, 2000, 7},     /* c1800_ / c2000 */
             {0xc80, 3, 0xa9b8, 0x40, 0x725, 3, 0x780, 5},   /* c1829 / c1920 */
             {0xd65, 4, 0, 0, 0x7a7, 6, 0x7a7, 6}};          /* c1959 */
static void sfr_model(unsigned char *e, int *txc, int *rxc) {
  unsigned w0 = U16(e, 0xa9de), w1 = U16(e, 0xa9e0), w2 = U16(e, 0xa9e2);
  int s, b;
  U16(e, 0xaa8a) = (uint16_t)brev((int)(((w0 & 3u) << 2) | ((w1 & 0xc0u) >> 6)), 4);
  s = brev((int)((w2 >> 4) & 7u), 3);
  b = brev((int)(((w1 * 2u) & 7u) | ((w2 >> 7) & 1u)), 3);
  *txc = s;
  *rxc = b;
  if (s >= 0 && s <= 5 && s != 1) {
    U16(e, 0xaa84) = (uint16_t)k_tx[s].baud;
    PTRS_SET(e, 0xaa90, (void *)scale_tbl(k_tx[s].tbl));
    U16(e, 0xaa94) = (uint16_t)((U8(e, 0xa9de) & 4) ? k_tx[s].carSet : k_tx[s].carClr);
    if (s == 5) U16(e, 0xaa94) = 0x7a7;
  }
  if (b >= 0 && b <= 5 && b != 1) {
    int set = k_rx[b].mask ? ((U8(e, k_rx[b].off) & k_rx[b].mask) != 0) : 0;
    U16(e, 0xaa96) = (uint16_t)k_rx[b].baud;
    PTRS_SET(e, 0xaaac, (void *)scale_tbl(k_rx[b].tbl));
    U16(e, 0xaaa8) = (uint16_t)(set ? k_rx[b].carSet : k_rx[b].carClr);
    PTRS_SET(e, 0xaab0, (void *)c_tbl(set ? k_rx[b].tblSet : k_rx[b].tblClr));
    if (b == 5) {
      U16(e, 0xaaa8) = 0x7a7;
      PTRS_SET(e, 0xaab0, (void *)c_tbl(6));
    }
  }
}
