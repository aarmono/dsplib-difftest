/*
 * Differential test harness for V.34 "tier 5d" (src/v34/v34_handshake_helpers.c): the handshake helpers
 *   ApplyBulkDelay (LOCAL regparm3), getbit (LOCAL regparm3, self-recursive), setfinalrate, initdigital
 *
 * One source, two binaries (same convention as test/v34/v34_tx_symbol.main.c):
 *   v34_tier5d_test_blob - linked against the real dsplibs.o (-DTEST_BLOB)
 *   v34_tier5d_test_port - linked against src/v34/v34_handshake_helpers.c + the already verified ports
 * Each scenario runs in its OWN process (argv[1]).
 *
 * Reaching the blob's LOCAL functions (both by address arithmetic from a GLOBAL neighbour in the
 * one contiguous .text piece of dsplibs.o; the first 20 prologue bytes are verified at run time,
 * exit 3 on mismatch) and calling them through regparm(3) function pointers:
 *   ApplyBulkDelay  ELF .text 0x5dd10 = &txwritequeue (0x5dc40) + 0xd0     (EAX = obj, EDX = n, ECX unused:
 *                   the harness passes garbage in ECX and in the upper half of EDX)
 *   getbit          ELF .text 0x5eaf0 = &setfinalrate (0x5ecb0) - 0x1c0     (EAX = reader; EDX/ECX garbage)
 *
 * Objects: tagV34Object is not a struct.  A random fake object (OBJSZ bytes, static) is restored from
 * a random base per call (single-call scenarios; result = hash of the DIFF: word index + new value of
 * every changed word, so a stray write anywhere is caught) or kept across calls (chain scenarios;
 * result = hash of the WHOLE object after every call).  Pointer slots (obj+0xaa90/0xaaac/0xaab0 table
 * pointers stored by setfinalrate; initV34's stores at blk+0x24/+0x28 of the two PreInitBlocks) are
 * compared NORMALISED (in-object -> offset, table -> (id, offset)); raw addresses are never compared
 * across the two processes.  Every function under test also has an INDEPENDENT MODEL in this file
 * (written from the disassembly, not from the port); each call's result is asserted against the model
 * (exit 3 on a disagreement of blob or port with it), and the model's predicates drive the coverage
 * counters (exit 2 if any required branch class was never reached).
 *
 * The callees are the REAL ones on both sides (bitreverse, initV34: the verified ports / the blob's own).
 * sysdep_memset (ApplyBulkDelay) and dsplibs_debug_printf live in this file: the memset stub hashes every
 * call (normalised dst, value, length) and performs it inside the object; the printer can lower the
 * debug level after the k-th print of a call (proves every level guard is re-read / snapshotted exactly
 * where the machine code does).
 *
 * INPUT ORACLES / HAZARDS (documented in src/v34/v34_handshake_helpers.c):
 *   - getbit: a restart that needs a restart again recurses without end (blob: stack overflow); the
 *     harness patches such states ([+0x2a] != 0); scenario 6 confirms the blob's crash in a child.
 *   - initdigital: the scale index Tn+14*hi-1 (and the RX twin) is reproduced for [-1, 28] only (both
 *     ends read 0 - alignment padding in the blob, verified at start-up); states leading outside are
 *     re-rolled and never claimed covered.
 * Scenarios: 0 ApplyBulkDelay random, 1 ApplyBulkDelay debug/level flips, 2 ApplyBulkDelay chain,
 * 3 getbit random single calls, 4 getbit streams (nominal readers vs a bit-sequence model), 5 getbit
 * chains on wild state, 6 getbit recursion-hazard probe, 7 setfinalrate exhaustive + random,
 * 8 setfinalrate debug, 9 initdigital random, 10 initdigital grid, 11 setfinalrate+initdigital chain,
 * 12 initdigital debug/level flips.
 */

