/* test/v34/v34_img.h - T04: the 32-bit IMAGE <-> native V34Obj marshalling layer of the x86-64 V.34 tier harnesses.
 *
 * The tier harnesses (test/v34_tier*_diff_main.c) model the V.34 module object as a flat byte buffer in the i386 layout ("image"): random templates,
 * raw-offset pokes, word-index diffs hashed into the recorded goldens (test/golden/*_blob32.out.gz).  On x86-64 the port works on a REAL V34Obj
 * (src/v34/v34_object_view.h: pointer members are 8 bytes, so every later member moves).  This header keeps the harness model in the image and converts around each call
 * of a function under test (the shims generated by `tools/tier_rewrite.py shims`):
 *     v34i_enter(); f(v34i_in(img_ptr), ...); v34i_leave();
 * v34i_in() translates a pointer that points INTO a registered image to the same place in that image's native shadow (marshalling image -> shadow
 * member by member through test/v34/v34objmap.h the first time the image is touched during the call); v34i_leave() marshals the shadows back
 * (native -> image).  Pointer members hold, in the image, a 32-bit value: the (zero-extended) address when the target lives below 4 GB (the harness
 * keeps everything it points to in low memory: static data, brk heap with M_MMAP_MAX=0, MAP_32BIT) or, for a pointer into a registered image,
 * the address inside the IMAGE (decoded to the shadow on entry, encoded back on exit).
 * Everything here is x86-64 only: at -m32 the macros expand to nothing, so the 32-bit harness object code is untouched (tools/ident32.sh). */
