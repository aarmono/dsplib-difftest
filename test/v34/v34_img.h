/* The harnesses compare hashes of images that hold addresses (heap objects, tables): make the run deterministic, as the 32-bit runs of the goldens were, by
 * re-executing once without address-space randomisation (a random 32-bit garbage word that happens to fall into a registered buffer would otherwise
 * make a rare scenario flaky). Failure of personality() is ignored. */
extern char **environ;
static void __attribute__((constructor)) v34i_noaslr(int argc, char **argv, char **envp) {
  int pers = personality(0xffffffffu);
  (void)argc;
  if (pers == -1 || (pers & ADDR_NO_RANDOMIZE)) return;
  if (personality((unsigned long)pers | ADDR_NO_RANDOMIZE) == -1) return;
  execve("/proc/self/exe", argv, envp);
}

#define V34I_MAXIMG 24
#define V34I_TAIL 0x40000u /* zero slack after a shadow (the harnesses deliberately read past tables; the values read there are layout dependent, but must not fault) */
#define V34I_FRONT 0x20000u /* ... and before it */
/* T05: a marshalled CLASS (the V34 object, the ctx VPcmFloModem, the cfg V90Parameters): its offset map and the two lookup tables */
typedef struct {
  const V34MapEnt *map;
  size_t nmap, size32, natsz;
  int32_t *d;   /* image offset -> native offset delta (below size32) */
  int32_t *inv; /* native offset -> image offset (or -1 inside pointer padding) */
} v34c_t;
typedef struct {
  v34c_t *cls;
  unsigned char *img, *nat;
  size_t sz;
  unsigned char *map;
  size_t maplen;
  size_t base32; /* the object offset (i386 layout) of img[0]: 0 for a whole object image, e.g. 0xa00 for a standalone "block B" buffer (a WINDOW of the object) */
  int active;
} v34i_t;
static v34i_t v34i_tab[V34I_MAXIMG];
static int v34i_n, v34i_depth;
static v34c_t v34c_obj = {V34OBJ_MAP, V34OBJ_NMAP, V34OBJ_SIZE32, V34OBJ_NATSZ, 0, 0};
static v34c_t v34c_ctx = {V34CTX_MAP, V34CTX_NMAP, V34CTX_SIZE32, V34CTX_NATSZ, 0, 0};
static v34c_t v34c_cfg = {V34CFG_MAP, V34CFG_NMAP, V34CFG_SIZE32, V34CFG_NATSZ, 0, 0};
static v34c_t v34c_e90 = {V34E90_MAP, V34E90_NMAP, V34E90_SIZE32, V34E90_NATSZ, 0, 0};
static v34c_t v34c_e92 = {V34E92_MAP, V34E92_NMAP, V34E92_SIZE32, V34E92_NATSZ, 0, 0};
static v34c_t v34c_ers = {V34ERS_MAP, V34ERS_NMAP, V34ERS_SIZE32, V34ERS_NATSZ, 0, 0};
static v34c_t v34c_erc90 = {V34ERC90_MAP, V34ERC90_NMAP, V34ERC90_SIZE32, V34ERC90_NATSZ, 0, 0};   /* RS1 / M3: V90Mapper (was one `erc`) */
static v34c_t v34c_erc92 = {V34ERC92_MAP, V34ERC92_NMAP, V34ERC92_SIZE32, V34ERC92_NATSZ, 0, 0};   /* RS1 / M3: V92Transmitter */
static v34c_t v34c_edm = {V34EDM_MAP, V34EDM_NMAP, V34EDM_SIZE32, V34EDM_NATSZ, 0, 0};
static v34c_t v34c_emg = {V34EMG_MAP, V34EMG_NMAP, V34EMG_SIZE32, V34EMG_NATSZ, 0, 0};

static void v34c_init(v34c_t *c) {
  size_t i, k;
  if (c->d) return;
  c->d = (int32_t *)calloc(c->size32 + 4, sizeof(int32_t));
  c->inv = (int32_t *)malloc((c->natsz + 8) * sizeof(int32_t));
  for (i = 0; i < c->natsz + 8; i++) c->inv[i] = -1;
  for (i = 0; i < c->nmap; i++) {
    const V34MapEnt *e = &c->map[i];
    for (k = 0; k < e->s32; k++) {
      size_t nk = e->isptr ? (k / 4) * (e->s64 / (e->s32 / 4)) + (k % 4) : k;
      c->d[e->o32 + k] = (int32_t)(e->o64 + nk) - (int32_t)(e->o32 + k);
      c->inv[e->o64 + nk] = (int32_t)(e->o32 + k);
    }
  }
}
static void v34i_init_maps(void) {
  static int done;
  if (done) return;
  done = 1;
  mallopt(M_MMAP_MAX, 0); /* the harness' pointers must stay below 4 GB (non-PIE brk heap) */
  v34c_init(&v34c_obj);
  v34c_init(&v34c_ctx);
  v34c_init(&v34c_cfg);
  v34c_init(&v34c_e90);
  v34c_init(&v34c_e92);
  v34c_init(&v34c_ers);
  v34c_init(&v34c_erc90);
  v34c_init(&v34c_erc92);
  v34c_init(&v34c_edm);
  v34c_init(&v34c_emg);
}
/* image offset -> native offset (offsets beyond the object keep their distance from its end) */
static size_t v34c_n32(const v34c_t *c, size_t off) { return off < c->size32 ? (size_t)((int64_t)off + c->d[off]) : off - c->size32 + c->natsz; }
static size_t v34c_ni(const v34c_t *c, size_t noff) {
  if (noff < c->natsz) return c->inv[noff] < 0 ? (size_t)0 : (size_t)c->inv[noff];
  return noff - c->natsz + c->size32;
}
static size_t v34i_n32(size_t off) { return v34c_n32(&v34c_obj, off); }
#define V34N(off) v34i_n32(off)

static void v34i_unreg(void *img);
#define MAP_FAILED_PTR ((unsigned char *)0)
static void *v34i_hint; /* the next shadow is mapped at exactly this address (V34I_PLACE) */
static void v34i_reg_cls(void *img, size_t sz, size_t base32, v34c_t *cls) {
  int i;
  v34i_init_maps();
  for (i = 0; i < v34i_n; i++)
    if (v34i_tab[i].img == (unsigned char *)img) { v34i_tab[i].sz = sz; v34i_tab[i].base32 = base32; v34i_tab[i].cls = cls; return; }
  if (v34i_n >= V34I_MAXIMG) { fprintf(stderr, "v34_img: too many images\n"); exit(4); }
  v34i_tab[v34i_n].img = (unsigned char *)img;
  v34i_tab[v34i_n].cls = cls;
  v34i_tab[v34i_n].sz = sz;
  v34i_tab[v34i_n].base32 = base32;
  /* the shadow lives in an anonymous mapping (an address above 4 GB, far from the small integers that some functions return disguised as pointers, and from the
     low heap of the harness' own buffers) */
  {
    size_t want = V34I_FRONT + sz + cls->natsz + V34I_TAIL;
    uintptr_t at = (uintptr_t)v34i_hint, page = (at - V34I_FRONT) & ~(uintptr_t)0xfff;
    size_t len = at ? ((at - page) + want + 0xfff) & ~(size_t)0xfff : want;
    unsigned char *m = MAP_FAILED_PTR;
    if (!at) {
      /* T06: shadows are mapped at INCREASING addresses in registration order.  The harnesses compare pointers into different image buffers (v34_tier7a: the RX ring
         pointer of the template object `o` is compared with a member address of the called object `w`, allocated later, so w > o in the 32-bit heap): the order of the
         shadows has to follow the order of the images (mmap's own top-down placement reversed it) */
      static uintptr_t mono = (uintptr_t)0x100000000000ull;
      len = (len + 0xfff) & ~(size_t)0xfff;
      m = (unsigned char *)mmap((void *)mono, len, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS | MAP_FIXED_NOREPLACE, -1, 0);
      if (m != (unsigned char *)MAP_FAILED && m == (unsigned char *)mono) mono += len + 0x10000;
      else m = MAP_FAILED_PTR;
    }
    if (m == MAP_FAILED_PTR)
      m = (unsigned char *)mmap(at ? (void *)page : NULL, len, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANONYMOUS | (at ? MAP_FIXED_NOREPLACE : 0), -1, 0);
    if (m == (unsigned char *)MAP_FAILED || (at && m != (unsigned char *)page)) { fprintf(stderr, "v34_img: mmap failed\n"); exit(4); }
    v34i_tab[v34i_n].map = m;
    v34i_tab[v34i_n].maplen = len;
    v34i_tab[v34i_n].nat = at ? (unsigned char *)at : m + V34I_FRONT;
    v34i_hint = NULL;
  }
  v34i_tab[v34i_n].active = 0;
  v34i_n++;
}
static void v34i_reg_win(void *img, size_t sz, size_t base32) { v34i_reg_cls(img, sz, base32, &v34c_obj); }
static void v34i_reg(void *img, size_t sz) { v34i_reg_win(img, sz, 0); }
/* register a whole-object image whose SHADOW is placed so that the shadow address of object offset `anchor_off` is exactly `anchor_addr` (the harness places its
   object so that 0x80000000 falls inside a ring; the port then sees the same straddle in its own memory) */
static void v34i_place(void *img, size_t sz, size_t anchor_off, uintptr_t anchor_addr) {
  v34i_init_maps();
  v34i_unreg(img);
  v34i_hint = (void *)(anchor_addr - v34i_n32(anchor_off));
  v34i_reg_cls(img, sz, 0, &v34c_obj);
}
static void v34i_unreg(void *img) {
  int i;
  for (i = 0; i < v34i_n; i++)
    if (v34i_tab[i].img == (unsigned char *)img) { munmap(v34i_tab[i].map, v34i_tab[i].maplen); v34i_tab[i] = v34i_tab[--v34i_n]; return; }
}

static void v34i_to_nat(v34i_t *t);
static int v34i_noact; /* set while an image is marshalled BACK (leave): a pointer compared there must not activate (and leave active) another image */
static void *v34i_decode(uint32_t w) {
  int i;
  uintptr_t a = (uintptr_t)w;
  for (i = 0; i < v34i_n; i++)
    if (a >= (uintptr_t)v34i_tab[i].img && a < (uintptr_t)v34i_tab[i].img + v34i_tab[i].sz) {
      v34i_t *t = &v34i_tab[i];
      if (!t->active && !v34i_noact) { t->active = 1; v34i_to_nat(t); } /* T05: a pointer to a registered ctx / cfg image (obj -> ctx -> cfg) marshals that image too; T06: and a pointer to another registered V34 object image (v34_tier7a: the RX ring pointer of the template object `o` stored in the called object `w`) */
      return t->nat + v34c_n32(t->cls, t->base32 + (a - (uintptr_t)t->img));
    }
  return (void *)a;
}
static uint32_t v34i_encode(void *p) {
  int i;
  uintptr_t a = (uintptr_t)p;
  for (i = 0; i < v34i_n; i++)
    if (a >= (uintptr_t)v34i_tab[i].nat && a < (uintptr_t)v34i_tab[i].nat + v34i_tab[i].sz + v34i_tab[i].cls->natsz) {
      size_t o = v34c_ni(v34i_tab[i].cls, a - (uintptr_t)v34i_tab[i].nat);
      if (o >= v34i_tab[i].base32 && o < v34i_tab[i].base32 + v34i_tab[i].sz) return (uint32_t)((uintptr_t)v34i_tab[i].img + (o - v34i_tab[i].base32));
    }
  return (uint32_t)a;
}

/* image -> shadow (a window marshals only the members that lie inside it; an unknown-region crossing the edge is cut) */
static int v34i_clip(const v34i_t *t, const V34MapEnt *e, size_t *lo, size_t *hi) {
  size_t a = e->o32, b = e->o32 + e->s32;
  if (b <= t->base32 || a >= t->base32 + t->sz) return 0;
  *lo = a < t->base32 ? t->base32 - a : 0;
  *hi = b > t->base32 + t->sz ? t->base32 + t->sz - a : e->s32;
  return 1;
}
static void v34i_to_nat(v34i_t *t) {
  size_t i, k, lo, hi;
  for (i = 0; i < t->cls->nmap; i++) {
    const V34MapEnt *e = &t->cls->map[i];
    if (!v34i_clip(t, e, &lo, &hi)) continue;
    if (!e->isptr) {
      memcpy(t->nat + e->o64 + lo, t->img + e->o32 - t->base32 + lo, hi - lo);
    } else {
      size_t cnt = e->s32 / 4, st = e->s64 / cnt;
      if (lo != 0 || hi != e->s32) { if (hi - lo < 4) continue; }
      for (k = lo / 4; k < hi / 4; k++) {
        uint32_t w;
        void *p;
        memcpy(&w, t->img + e->o32 - t->base32 + 4 * k, 4);
        p = w ? v34i_decode(w) : NULL;
        memset(t->nat + e->o64 + st * k, 0, st);
        memcpy(t->nat + e->o64 + st * k, &p, sizeof p);
      }
    }
  }
  if (t->base32 == 0 && t->sz > t->cls->size32) memcpy(t->nat + t->cls->natsz, t->img + t->cls->size32, t->sz - t->cls->size32);
}
/* shadow -> image */
static void v34i_to_img(v34i_t *t) {
  size_t i, k, lo, hi;
  v34i_noact++;
  for (i = 0; i < t->cls->nmap; i++) {
    const V34MapEnt *e = &t->cls->map[i];
    if (!v34i_clip(t, e, &lo, &hi)) continue;
    if (!e->isptr) {
      memcpy(t->img + e->o32 - t->base32 + lo, t->nat + e->o64 + lo, hi - lo);
    } else {
      size_t cnt = e->s32 / 4, st = e->s64 / cnt;
      for (k = lo / 4; k < hi / 4; k++) {
        void *p;
        uint32_t w, wold;
        memcpy(&p, t->nat + e->o64 + st * k, sizeof p);
        memcpy(&wold, t->img + e->o32 - t->base32 + 4 * k, 4);
        /* a slot the port did not change keeps its image word bit for bit (random garbage in a slot could otherwise be mistaken for an address inside a shadow) */
        if (p == (wold ? v34i_decode(wold) : NULL)) continue;
        w = p ? v34i_encode(p) : 0;
        memcpy(t->img + e->o32 - t->base32 + 4 * k, &w, 4);
      }
    }
  }
  if (t->base32 == 0 && t->sz > t->cls->size32) memcpy(t->img + t->cls->size32, t->nat + t->cls->natsz, t->sz - t->cls->size32);
  v34i_noact--;
}

static void v34i_enter(void) { v34i_depth++; }
/* translate an argument pointer; marshals the image it points into (once per outermost call) */
static void *v34i_in(void *p) {
  int i;
  uintptr_t a = (uintptr_t)p;
  for (i = 0; i < v34i_n; i++) {
    v34i_t *t = &v34i_tab[i];
    if (a >= (uintptr_t)t->img && a < (uintptr_t)t->img + t->sz) {
      if (!t->active) { v34i_to_nat(t); t->active = 1; }
      return t->nat + v34c_n32(t->cls, t->base32 + (a - (uintptr_t)t->img));
    }
  }
  return p;
}
static void v34i_leave(void) {
  int i;
  if (--v34i_depth > 0) return;
  for (i = 0; i < v34i_n; i++)
    if (v34i_tab[i].active) { v34i_to_img(&v34i_tab[i]); v34i_tab[i].active = 0; }
}
/* translate a returned / callback pointer that points into a shadow back into the image */
static void *v34i_outp(void *p) {
  int i;
  uintptr_t a = (uintptr_t)p;
  for (i = 0; i < v34i_n; i++) {
    v34i_t *t = &v34i_tab[i];
    if (a >= (uintptr_t)t->nat && a < (uintptr_t)t->nat + t->sz + t->cls->natsz) {
      size_t o = v34c_ni(t->cls, a - (uintptr_t)t->nat);
      if (o >= t->base32 && o < t->base32 + t->sz) return t->img + (o - t->base32);
    }
  }
  return p;
}
/* callbacks (recorders called by the port while it works on a shadow): bring the images up to date / push harness changes of an image into its shadow */
static void v34i_sync_img(void) {
  int i;
  for (i = 0; i < v34i_n; i++)
    if (v34i_tab[i].active) v34i_to_img(&v34i_tab[i]);
}
static void v34i_sync_nat(void) {
  int i;
  for (i = 0; i < v34i_n; i++)
    if (v34i_tab[i].active) v34i_to_nat(&v34i_tab[i]);
}

/* a heap object image: calloc / malloc of exactly V34I_OBJSZ bytes registers it, free() unregisters it (the harness callocs its fake objects per scenario) */
#define V34I_OBJSZ 0xb400u
static void *v34i_calloc(size_t n, size_t sz) {
  void *p = calloc(n, sz);
  if (p && n * sz == V34I_OBJSZ) v34i_reg(p, V34I_OBJSZ);
  return p;
}
static void *v34i_malloc(size_t n) {
  void *p = malloc(n);
  if (p && n == V34I_OBJSZ) v34i_reg(p, V34I_OBJSZ);
  return p;
}
static void v34i_free(void *p) {
  v34i_unreg(p);
  free(p);
}
