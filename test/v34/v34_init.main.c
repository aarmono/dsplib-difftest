/* ===================== scenario 10: setInitialPhase ===================== */

/* tiny independent predicate: which i does the sign scan end on (5 = error/reset) */
static int ref_i(unsigned char *o, int *is_err) {
  int i = 1;
  *is_err = 0;
  if ((int)SMP(o, 1) * (int)SMP(o, 2) < 0) {
    do { i++; } while (i <= 4 && (int)SMP(o, i) * (int)SMP(o, i + 1) < 0);
    if (i == 5) { *is_err = 1; i = 1; }
  }
  return i;
}

/*
 * Set S[0..7] so the sign scan stops at index j: S1*S2 < 0 and pairs (1,2)..(j-1,j) have opposite signs,
 * pair (j,j+1) has the same sign (j in 2..4); j == 5 alternates all the way (scan runs off the end -> i==5).
 * All of S[1..6] are nonzero. magnitude regime: 0 wide, 1 small, 2 extremes.
 */
static short sip_mag(int regime) {
  switch (regime) {
    case 0: return (short)lcg_range(1, 32767);
    case 1: return (short)lcg_range(1, 40);
    default: return (short)(lcg_mod(2) ? 32767 : 32767 - (int)lcg_mod(3));
  }
}

static void sip_alt_pattern(unsigned char *o, int j, int mag_regime) {
  int k, sign = lcg_mod(2) ? 1 : -1;
  SMP(o, 0) = lcg_short();
  SMP(o, 7) = lcg_short();
  for (k = 1; k <= 6; k++) {
    if (k >= 2) {
      if (k <= j) sign = -sign;               /* pair (k-1,k) opposite */
      else if (k == j + 1) { /* pair (j,j+1) same sign */ }
      else sign = lcg_mod(2) ? 1 : -1;
    }
    SMP(o, k) = (short)(sign * sip_mag(mag_regime));
  }
}

static void seed_sip(unsigned char *o, int regime) {
  int k;
  obj_seed(o);
  S16(BB(o), 0x1ac) = (short)(lcg_mod(3) ? lcg_range(0, 40000) : (int)lcg_next());
  switch (lcg_mod(4)) {
    case 0: S16(BB(o), 0x1b0) = (short)lcg_range(1000, 32000); break;
    case 1: S16(BB(o), 0x1b0) = (short)lcg_range(-32768, -1); break;
    case 2: S16(BB(o), 0x1b0) = (short)lcg_range(0, 200); break;
    default: S16(BB(o), 0x1b0) = lcg_short(); break;
  }
  switch (regime) {
    case 0: for (k = 0; k < 8; k++) SMP(o, k) = lcg_short(); break;
    case 1: for (k = 0; k < 8; k++) SMP(o, k) = (short)lcg_range(1, 32767); break;
    case 2: sip_alt_pattern(o, 5, (int)lcg_mod(3)); break;
    case 3: sip_alt_pattern(o, 2, (int)lcg_mod(3)); break;
    case 4: sip_alt_pattern(o, 3, (int)lcg_mod(3)); break;
    case 5: sip_alt_pattern(o, 4, (int)lcg_mod(3)); break;
    case 6: /* zero samples at the scanned pair: product 0 -> i==1, sum == 0 (or a==0) */
      for (k = 0; k < 8; k++) SMP(o, k) = lcg_short();
      SMP(o, 1) = 0;
      if (lcg_mod(2)) SMP(o, 2) = 0;
      break;
    case 7: /* extremes (i==1 path, S1*S2 >= 0) */
      for (k = 0; k < 8; k++) SMP(o, k) = (short)(lcg_mod(2) ? 32767 : -32768);
      SMP(o, 2) = SMP(o, 1);
      break;
    case 8: { /* reset path with c close to -a: sum tiny or 0 (q0 = 0 or huge) */
      int a = lcg_range(1, 32767), d = (int)lcg_mod(4) == 0 ? 0 : lcg_range(-3, 3);
      sip_alt_pattern(o, 5, 0);
      SMP(o, 1) = (short)(lcg_mod(2) ? a : -a);
      SMP(o, 2) = (short)(-(int)SMP(o, 1) + ((int)SMP(o, 1) > 0 ? -d : d));
      if (SMP(o, 1) > 0 && SMP(o, 2) >= 0) SMP(o, 2) = -1;
      if (SMP(o, 1) < 0 && SMP(o, 2) <= 0) SMP(o, 2) = 1;
      break; }
    default: /* small values */
      for (k = 0; k < 8; k++) SMP(o, k) = (short)lcg_range(-50, 50);
      break;
  }
}

static void scen_setInitialPhase(void) {
  unsigned char *o = (unsigned char *)calloc(1, OBJSZ);
  int c;
  long n_i[6] = {0, 0, 0, 0, 0, 0};
  long n_neg_a = 0, n_sum0 = 0, n_stored = 0, n_limclip = 0, n_bk_seen[20], n_bigq0 = 0, n_wrapv = 0;
  long calls = 6000, distinct = 0;
  unsigned int all = FNV0;
  int k;
  memset(n_bk_seen, 0, sizeof n_bk_seen);
  for (c = 0; c < calls; c++) {
    int regime = c % 10;
    int is_err, i, a, cc, bk, found;
    unsigned int h;
    unsigned short old1ac, nv, limw;
    short lim;
    seed_sip(o, regime);
    i = ref_i(o, &is_err);
    n_i[is_err ? 5 : i]++;
    a = SMP(o, i);
    cc = SMP(o, i + 1);
    if (a < 0) { n_neg_a++; a = (short)-a; cc = (short)-cc; }
    if (a + cc == 0) n_sum0++;
    else {
      long q0 = ((a + cc) >> 1) + (long)(cc - a) * 0x2000;
      q0 /= (a + cc);
      if (q0 > 100000 || q0 < -100000) n_bigq0++;
    }
    old1ac = U16(BB(o), 0x1ac);
    limw = U16(BB(o), 0x1b0);
    lim = (short)limw;
    setInitialPhase(o);
    nv = U16(BB(o), 0x1ac);
    /* recover bestk from the observable result: branch A stores v = (ushort)(old + (10-bk)*0x230) when v < lim */
    found = -1;
    for (bk = 0; bk < 20; bk++) {
      unsigned short v = (unsigned short)(old1ac + (10 - bk) * 0x230);
      if ((int)v < (int)lim && v == nv) { found = bk; break; }
    }
    if (found >= 0) { n_stored++; n_bk_seen[found]++; }
    else {
      if (nv != (unsigned short)(limw - 1)) { fprintf(stderr, "harness: setInitialPhase result matches neither branch\n"); g_fail = 1; }
      n_limclip++;
    }
    if ((int)old1ac + 5600 > 65535 || (int)old1ac - 5040 < 0) n_wrapv++;
    h = hash_plain(o);
    all = fnv(all, &h, 4);
    if (c % 25 == 0) printf("setInitialPhase c=%d regime=%d i=%d err=%d e1ec=%d e1ee=%d bestk=%d p1ac=%d hash=%08x\n", c, regime, i, is_err, S16(BB(o), 0x1ec), S16(BB(o), 0x1ee), found, (int)S16(BB(o), 0x1ac), h);
  }
  printf("setInitialPhase calls=%ld all=%08x\n", calls, all);
  /* dedicated extra stress on the reset + tiny-sum regime (32-bit wrapping scores) */
  {
    unsigned int all2 = FNV0;
    for (c = 0; c < 40000; c++) {
      unsigned int h2;
      seed_sip(o, 8);
      setInitialPhase(o);
      h2 = hash_plain(o);
      all2 = fnv(all2, &h2, 4);
      if (c % 4000 == 0) printf("setInitialPhase stress c=%d p1ac=%d hash=%08x\n", c, (int)S16(BB(o), 0x1ac), h2);
    }
    printf("setInitialPhase stress calls=40000 all=%08x\n", all2);
  }
  for (k = 0; k < 20; k++) if (n_bk_seen[k]) distinct++;
  printf("  distinct best-k values observed = %ld\n", distinct);
  need("setInitialPhase i==1 (no scan / S1*S2>=0)", n_i[1]);
  need("setInitialPhase i==2", n_i[2]);
  need("setInitialPhase i==3", n_i[3]);
  need("setInitialPhase i==4", n_i[4]);
  need("setInitialPhase i==5 (error print path, reset to 1)", n_i[5]);
  need("setInitialPhase S[i]<0 (16-bit negation)", n_neg_a);
  need("setInitialPhase sum==0 (q0=0 path)", n_sum0);
  need("setInitialPhase |q0| > 100000 (score wraps 32-bit)", n_bigq0);
  need("setInitialPhase phase store branch (v < limit)", n_stored);
  need("setInitialPhase limit-1 branch (v >= limit)", n_limclip);
  need("setInitialPhase 16-bit wrap of the phase sum possible", n_wrapv);
  if (distinct < 12) { fprintf(stderr, "COVERAGE FAILURE: only %ld distinct best-k values\n", distinct); g_fail = 1; }
  free(o);
}

/* ===================== scenario 11: TimingV34 ===================== */

/* T07: scenario 13 = scenario 11 with the sample indices inside S[] (0..19; S[] is 22 shorts), so the result does not depend on the members behind S[] (i386 vs x86-64 layout) */
static int g_t07;

static void seed_tv34(unsigned char *o) {
  int k, reg = (int)lcg_mod(9);
  obj_seed(o);
  /* mode */
  switch (lcg_mod(10)) {
    case 0: U16(BB(o), 0x1c0) = 0xffff; break;
    case 1: U16(BB(o), 0x1c0) = 0; break;
    case 2: case 3: U16(BB(o), 0x1c0) = 1; break;
    case 4: U16(BB(o), 0x1c0) = 0xfffe; break;
    case 5: U16(BB(o), 0x1c0) = (uint16_t)lcg_range(9, 40); break;
    default: U16(BB(o), 0x1c0) = (uint16_t)lcg_range(2, 8); break;
  }
  I32(BB(o), 0x1c8) = (int)lcg_mod(3);
  if (lcg_mod(4) == 0) I32(BB(o), 0x1c8) = (int)(((unsigned)(lcg_mod(2) ? 1 : 0)) | (lcg_next() & 0xffff0000u) | 0x10000u); /* low half 0/1, high half nonzero: a 32-bit compare != 1 */
  /* window counter / limit */
  switch (lcg_mod(6)) {
    case 0: U16(BB(o), 0x232) = 0xffff; break;
    case 1: U16(BB(o), 0x232) = (uint16_t)lcg_range(0xfff0, 0xfffe); break; /* negative, never matches */
    case 2: U16(BB(o), 0x232) = 0; break;
    default: U16(BB(o), 0x232) = (uint16_t)lcg_range(1, 30); break;
  }
  if (lcg_mod(2)) U16(BB(o), 0x230) = (uint16_t)((S16(BB(o), 0x232) > 0 ? S16(BB(o), 0x232) : 3) - 1); /* next call hits the limit */
  else if (S16(BB(o), 0x232) < -1 && lcg_mod(2)) U16(BB(o), 0x230) = (uint16_t)(U16(BB(o), 0x232) - 1); /* cnt+1 == zero-extended (negative) lim: must NOT match */
  else U16(BB(o), 0x230) = (uint16_t)lcg_range(0, 40);
  S16(BB(o), 0x234) = (lcg_mod(3) ? (short)lcg_range(0, 15000) : lcg_short()); /* Kp */
  S16(BB(o), 0x236) = (lcg_mod(3) ? (short)lcg_range(0, 300) : lcg_short());   /* Ki */
  /* selected sample indices */
  if (lcg_mod(3)) { S16(BB(o), 0x1ec) = 1; S16(BB(o), 0x1ee) = 2; }
  else if (lcg_mod(2)) { S16(BB(o), 0x1ec) = 2; S16(BB(o), 0x1ee) = 1; }
  else { S16(BB(o), 0x1ec) = (short)(g_t07 ? lcg_range(0, 19) : lcg_range(-200, 2000)); S16(BB(o), 0x1ee) = (short)(g_t07 ? lcg_range(0, 19) : lcg_range(-200, 2000)); }
  /* samples (the S[] array and everything around it is random already) */
  for (k = 0; k < 12; k++) {
    switch (reg) {
      case 0: SMP(o, k) = lcg_short(); break;
      case 1: SMP(o, k) = (short)(lcg_short() >> 8); break;
      case 2: SMP(o, k) = (short)(lcg_mod(2) ? -32768 : 32767); break; /* E overflows to negative */
      case 3: SMP(o, k) = (short)(lcg_short() >> 12); break;
      case 4: SMP(o, k) = 0; break;
      case 5: SMP(o, k) = (short)(lcg_range(0, 3) * 11000); break;
      case 6: SMP(o, k) = (short)(lcg_short() >> 1); break;
      case 7: SMP(o, k) = (short)(lcg_mod(4) ? lcg_range(-10, 10) : lcg_range(-30000, 30000)); break;
      default: SMP(o, k) = (short)(lcg_short() >> lcg_mod(15)); break;
    }
  }
  U32(BB(o), 0x1e0) = lcg_mod(3) ? (uint32_t)lcg_range(-100000, 100000) : lcg_next();   /* integrator */
  U32(BB(o), 0x1d8) = lcg_mod(3) ? (uint32_t)lcg_range(-40000, 40000) : lcg_next();     /* frac accumulator */
  /* m==0 leaves v == I, so F+I can be steered onto the r-rounding boundary (F2 = 0x4000 mod 0x8000) */
  if (U16(BB(o), 0x1c0) == 0 && lcg_mod(3) == 0)
    U32(BB(o), 0x1d8) = (uint32_t)(0x4000u - U32(BB(o), 0x1e0) + ((lcg_next() & 0xffu) << 15));
  /* symbol constant T: nonzero (unguarded idiv) */
  switch (lcg_mod(5)) {
    case 0: U16(BB(o), 0x1be) = (uint16_t)lcg_range(1, 40); break;
    case 1: U16(BB(o), 0x1be) = (uint16_t)lcg_range(0x8000, 0xffff); break; /* negative as short */
    default: U16(BB(o), 0x1be) = (uint16_t)lcg_range(100, 700); break;
  }
  if (lcg_mod(4) == 0) U16(BB(o), 0x1be) = (uint16_t)(0x10000 - lcg_range(1, 40)); /* small negative T, odd and even */
  if (U16(BB(o), 0x1be) == 0) U16(BB(o), 0x1be) = 1;
  S16(BB(o), 0x1cc) = (lcg_mod(3) ? (short)lcg_range(-3000, 3000) : lcg_short());
  /* ppm-window counter/limit; count never 0xffff (n == 0 would be an unguarded #DE) */
  U16(BB(o), 0x1ce) = (uint16_t)(lcg_mod(4) ? lcg_range(0, 60) : lcg_range(0, 0x7ffe));
  S16(BB(o), 0x1d2) = (short)(lcg_mod(3) ? lcg_range(1, 50) : lcg_range(-5, 32767));
  if (lcg_mod(3) == 0) S16(BB(o), 0x1d2) = (short)lcg_range(-3, (int)(short)(uint16_t)(U16(BB(o), 0x1ce) + 1)); /* window <= n: division path */
}

static void scen_timingv34(void) {
  unsigned char *o = (unsigned char *)calloc(1, OBJSZ);
  long calls = 6000, c;
  long n_ret_ff = 0, n_m1_a = 0, n_m1_b = 0, n_limmatch = 0, n_limcount = 0, n_m0 = 0, n_norm = 0, n_ovf = 0, n_ab0 = 0, n_early = 0, n_div = 0;
  long n_negT = 0, n_bigE = 0, n_ppmneg = 0, n_chain = 0, n_modes[10];
  unsigned int all = FNV0;
  int need_reseed = 1;
  memset(n_modes, 0, sizeof n_modes);
  for (c = 0; c < calls; c++) {
    unsigned int h;
    unsigned short m, lim;
    unsigned int ea, eb;
    int m_eff;
    if (need_reseed || lcg_mod(3) == 0) {
      seed_tv34(o);
      need_reseed = 0;
    } else {
      /* keep evolving state, only feed fresh samples */
      int k;
      for (k = 0; k < 12; k++) SMP(o, k) = (short)(lcg_short() >> lcg_mod(9));
      n_chain++;
    }
    /* ---- pre-state classification (independent of the code under test) ---- */
    m = U16(BB(o), 0x1c0);
    lim = U16(BB(o), 0x232);
    m_eff = m;
    if (m == 0xffff) n_ret_ff++;
    else {
      if (m == 1) {
        /* setInitialPhase and setTimingStateParameters will run; mode becomes 2 or 6 */
        if (I32(BB(o), 0x1c8) == 1) n_m1_a++; else n_m1_b++;
        m_eff = (I32(BB(o), 0x1c8) == 1) ? 2 : 6;
      }
      if (m != 1 && lim != 0xffff && m != 0) {
        unsigned short cn = (unsigned short)(U16(BB(o), 0x230) + 1);
        if ((int)cn == (int)(short)lim) n_limmatch++; else n_limcount++;
      }
      if (m != 1 && m < 10) n_modes[m]++;
    }
    /* stay clear of the unguarded divisions */
    if ((short)(unsigned short)(U16(BB(o), 0x1ce) + 1) == 0 || U16(BB(o), 0x1be) == 0) { fprintf(stderr, "harness bug: zero divisor\n"); exit(4); }
    {
      /* energies (before the call: setInitialPhase only rewrites 1ec/1ee which then are 1/2 or 2/1) */
      int ia = S16(BB(o), 0x1ec), ib = S16(BB(o), 0x1ee);
      if (m == 1) { ia = 1; ib = 2; }
      if (m != 0xffff) {
        ea = (unsigned int)((int)SMP(o, ia) * (int)SMP(o, ia)) + (unsigned int)((int)SMP(o, ia + 2) * (int)SMP(o, ia + 2));
        eb = (unsigned int)((int)SMP(o, ib) * (int)SMP(o, ib)) + (unsigned int)((int)SMP(o, ib + 2) * (int)SMP(o, ib + 2));
        if (m_eff == 0) n_m0++;
        else {
          n_norm++;
          if ((int)ea < 0 || (int)eb < 0) { n_ovf++; }
          if (ea == 0 && eb == 0) n_ab0++;
          if (ea >= 0x40000000u || eb >= 0x40000000u) n_bigE++;
        }
      }
    }
    if (U16(BB(o), 0x1be) >= 0x8000) n_negT++;
    {
      short win = S16(BB(o), 0x1d2);
      short nn = (short)(unsigned short)(U16(BB(o), 0x1ce) + 1);
      if (m != 0xffff) {
        /* whether the division path is reached is fully determined by the pre-state except when the
         * limit/m==1 logic runs first (which does not touch 1ce/1d2) */
        if (nn < win) n_early++;
        else n_div++;
      }
    }
    TimingV34(o);
    if (m != 0xffff && S16(BB(o), 0x1d0) < 0) n_ppmneg++;
    h = hash_plain(o);
    all = fnv(all, &h, 4);
    if (c % 40 == 0) printf("TimingV34 c=%ld m=%u mode_after=%u lim=%u cnt=%u I=%d F=%d p1ae=%d p1d0=%d p1cc=%d p1ce=%d hash=%08x\n", c, m, U16(BB(o), 0x1c0), U16(BB(o), 0x232), U16(BB(o), 0x230), I32(BB(o), 0x1e0), I32(BB(o), 0x1d8), S16(BB(o), 0x1ae), S16(BB(o), 0x1d0), S16(BB(o), 0x1cc), S16(BB(o), 0x1ce), h);
  }
  printf("TimingV34 calls=%ld all=%08x\n", calls, all);
  need("TimingV34 m==0xffff early return", n_ret_ff);
  need("TimingV34 m==1 with [b+0x1c8]==1 (-> mode 2)", n_m1_a);
  need("TimingV34 m==1 with [b+0x1c8]!=1 (-> mode 6)", n_m1_b);
  need("TimingV34 window limit reached (cnt+1 == lim)", n_limmatch);
  need("TimingV34 window counter incremented", n_limcount);
  need("TimingV34 m==0 (integrator held)", n_m0);
  need("TimingV34 normalise path", n_norm);
  need("TimingV34 energy overflow to negative (loop skipped)", n_ovf);
  need("TimingV34 both energies zero (A|B==0)", n_ab0);
  need("TimingV34 large energy (>= 2^30)", n_bigE);
  need("TimingV34 early return (n < window)", n_early);
  need("TimingV34 ppm division path (n >= window)", n_div);
  need("TimingV34 negative-as-short T", n_negT);
  need("TimingV34 negative ppm", n_ppmneg);
  need("TimingV34 chained (non-reseeded) calls", n_chain);
  {
    int md;
    for (md = 0; md < 10; md++) {
      char nm[64];
      if (md == 1) continue;
      snprintf(nm, sizeof nm, "TimingV34 mode %d (m!=1)", md);
      need(nm, n_modes[md]);
    }
  }
  free(o);
}

/* ===================== scenario 12: debug level 2 output ===================== */
static void scen_debug(void) {
  unsigned char *o = (unsigned char *)calloc(1, OBJSZ);
  int c;
  dsplibs_debug_level = 2;
  /* setInitialPhase: i==5 print, sum==0 print */
  for (c = 0; c < 6; c++) {
    obj_seed(o);
    S16(BB(o), 0x1b0) = 1000;
    S16(BB(o), 0x1ac) = 100;
    if (c < 2) sip_alt_pattern(o, 5, 0);
    else if (c < 4) { int k; for (k = 0; k < 8; k++) SMP(o, k) = 0; }
    else { sip_alt_pattern(o, 5, 1); SMP(o, 1) = (short)(c == 4 ? 40 : -40); SMP(o, 2) = (short)(c == 4 ? -40 : 40); } /* i==5 reset AND sum==0 */
    printf("-- setInitialPhase debug c=%d\n", c);
    setInitialPhase(o);
    printf("state hash %08x\n", hash_plain(o));
  }
  /* TimingV34: ppm print */
  for (c = 0; c < 8; c++) {
    seed_tv34(o);
    U16(BB(o), 0x1c0) = (uint16_t)(c < 4 ? 2 + c : 1);
    S16(BB(o), 0x1d2) = (short)(c & 1 ? 1 : -2);
    U16(BB(o), 0x1ce) = 0;
    printf("-- TimingV34 debug c=%d\n", c);
    TimingV34(o);
    printf("state hash %08x ppm=%d\n", hash_plain(o), S16(BB(o), 0x1d0));
  }
  /* txinit: the two V34EchoCleanUp debug strings */
  for (c = 0; c < 2; c++) {
    seed_echo_obj(o);
    printf("-- txinit debug c=%d\n", c);
    txinit(o);
    printf("state hash %08x\n", hash_obj(o));
  }
  dsplibs_debug_level = 0;
  free(o);
}

