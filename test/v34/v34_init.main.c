/*
 * Differential test harness for V.34 "tier 3" groups A and B
 * (src/v34/v34_init.c):
 *   A: txrxdmainit, detectorinit, scrambleGPC, scrambleGPA, descrambleGPA,
 *      descrambleGPC, preinitV34, preinitdigital, txinit, rxinit,
 *      VPcmV34LogTimingOffset
 *   B: setInitialPhase, setTimingStateParameters, TimingV34
 * All 14 symbols are GLOBAL in dsplibs.o (no LOCAL thunks needed; the
 * function pointers stored by preinit* are GLOBAL functions too, so identity
 * is compared through `&scrambleGPC` etc. resolved in each process).
 *
 * One source, two binaries (same convention as test/v34/v34_agc_demod.main.c):
 *   v34_tier3ab_test_blob - linked against the real dsplibs.o (-DTEST_BLOB)
 *   v34_tier3ab_test_port - linked against src/v34/v34_init.c + src/v34/v34_agc_demod.c
 *                           + src/v34/v34_dsp_primitives.c + tables
 * Each scenario runs in its OWN process (argv[1]).
 *
 * tagV34Object is not a struct: the harness builds a fake object of OBJSZ
 * bytes, deterministically random-filled (so stray writes and unwritten-field
 * bugs show up in the whole-object hash), and pokes byte offsets through the
 * accessor macros. Pointer-bearing slots the functions write are hashed
 * NORMALISED: in-object pointers become offsets, addresses of the blob's/port's
 * own scramblers or Convolve16 become small ids (identity-mapping - raw
 * pointer values are never compared across the two processes).
 *
 * Every scenario keeps COVERAGE COUNTERS derived from the pre/post state
 * (or from tiny independent predicates on the pre-state), prints them, and
 * exits 2 if a branch class the scenario should reach was never reached.
 *
 * Safety of the real blob: TimingV34 has unguarded idivs (divisor
 * (short)([b+0x1ce]+1), and (short)[b+0x1be]); the harness keeps both
 * nonzero by construction (asserted before each call).
 */

