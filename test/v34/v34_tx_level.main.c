/*
 * Differential test harness for V.34 "tier 3" group D (src/v34/v34_tx_level.c):
 *   edprintf, GetVPcmMinimalTxPowerReduction, settxlevel
 * All three (and bitreverse) are GLOBAL in dsplibs.o.
 *
 * One source, two binaries (same convention as test/v34/v34_init_tables.main.c):
 *   v34_tier3d_test_blob - linked against the real dsplibs.o (-DTEST_BLOB)
 *   v34_tier3d_test_port - linked against src/v34/v34_tx_level.c (+ v34_agc_demod.c for
 *                          bitreverse, + tables incl. offsetarr)
 * Each scenario runs in its OWN process (argv[1]), so the blob's and the port's
 * static edprintf state (temp / encoded buffer / iEncodeOffset) start out
 * identical (zero .bss) on both sides.
 *
 * The sysdep_vsnprintf / strlen / strcpy / strcat stubs are DEFINED HERE (real
 * libc behaviour, plus logging, plus optional "chaos" behaviour), so what both
 * implementations send to them - call order, call count, which buffer, the
 * strings - is compared as an event hash and (for small scenarios) as printed
 * text. The stubs learn the address of edprintf's scratch buffer from the first
 * vsnprintf call; the encoded buffer must be at +0x100 and iEncodeOffset at
 * +0x210 from it on BOTH sides (the blob's .bss layout 0x900/0xa00/0xb10; the
 * port keeps the same layout in one struct) - this is asserted at run time
 * (exit 3) and re-checked semantically: after a non-"too long" call
 * iEncodeOffset must equal (2*len) mod 10. After EVERY edprintf call the harness
 * hashes the whole static state: temp[256], enc[272], iEncodeOffset.
 *
 * edprintf is called with REAL C varargs (ints, unsigned, long long, doubles,
 * strings, chars) - the same call on both sides - so the va_list the port builds
 * is checked against the blob's `lea ebx,[esp+0x24]` construction by the
 * formatted output the stub's vsnprintf produces from it.
 *
 * settxlevel / GetVPcmMinimalTxPowerReduction run on fake obj / ctx (obj+0x3548)
 * / cfg (*(ctx+0x610c)) / P (obj+0xac3c) buffers (recipe from
 * test/v34/v34_init_tables.main.c); the whole of each buffer is compared (diff vs
 * the pre-call template), so a stray write anywhere is caught. Their edprintf
 * output flows through the same stubs (hashed even at debug level 0).
 *
 * Every scenario keeps COVERAGE COUNTERS and exits 2 if a branch class was never
 * reached. Env V34D_TRACE=1|2 forces the event trace on (2 also prints strlen).
 */

