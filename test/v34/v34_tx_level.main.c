/* T04: the 32-bit harness computes `int * double` on the x87 stack (extended product, rounded once more when it is passed as a double); the x86-64 build reproduces that rounding */
#if defined(__x86_64__)
#define XM(a, b) ((double)((long double)(a) * (long double)(b)))
#define XD(a, b) ((double)((long double)(a) / (long double)(b)))
#else
#define XM(a, b) ((a) * (b))
#define XD(a, b) ((a) / (b))
#endif

/* ---- deterministic LCG with a bijective finaliser ---- */
static unsigned int g_lcg = 0x3d5c0de1u;
static unsigned int lcg_next(void) {
  unsigned int x;
  g_lcg = g_lcg * 1103515245u + 12345u;
  x = g_lcg;
  x ^= x >> 16;
  x *= 0x7feb352du;
  x ^= x >> 15;
  x *= 0x846ca68bu;
  x ^= x >> 16;
  return x;
}
static unsigned int lcg_mod(unsigned int m) { return (lcg_next() >> 8) % m; }
static int lcg_range(int lo, int hi) { return lo + (int)lcg_mod((unsigned int)(hi - lo + 1)); }

static unsigned int fnv(unsigned int h, const void *p, size_t n) {
  const unsigned char *b = (const unsigned char *)p;
  size_t i;
  for (i = 0; i < n; i++) {
    h ^= b[i];
    h *= 16777619u;
  }
  return h;
}
#define FNV0 2166136261u

static void fill_random(void *p, size_t n) {
  unsigned char *b = (unsigned char *)p;
  size_t i;
  for (i = 0; i + 4 <= n; i += 4) {
    uint32_t v = lcg_next();
    memcpy(b + i, &v, 4);
  }
  for (; i < n; i++) b[i] = (unsigned char)(lcg_next() >> 16);
}

static int g_fail = 0;
static void need(const char *name, long v) {
  printf("  coverage %s = %ld\n", name, v);
  if (v <= 0) {
    fprintf(stderr, "COVERAGE FAILURE: %s never reached\n", name);
    g_fail = 1;
  }
}
static void die(const char *msg) {
  fflush(stdout);
  fprintf(stderr, "HARNESS ERROR: %s\n", msg);
  exit(3);
}

