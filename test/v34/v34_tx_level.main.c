#define OBJSZ 0xb400u
#define CTXSZ 0x6200u
#define CFGSZ 0x600u
#define PSZ 0x80u
#define OB(o, off) ((unsigned char *)(o) + (off))
#define S16(o, off) (*(int16_t *)OB(o, off))
#define U16(o, off) (*(uint16_t *)OB(o, off))
#define I32(o, off) (*(int32_t *)OB(o, off))
#define U32(o, off) (*(uint32_t *)OB(o, off))
#if defined(__x86_64__)
#define PTRW(o, off) (*(uint32_t *)OB(o, off)) /* x86-64: a pointer slot of the V34 object IMAGE is 32 bits (marshalled to a real pointer, test/v34/v34_img.h) */
#else
#define PTRW(o, off) (*(void **)OB(o, off))
#endif
#define PTRX(o, off) (*(void **)OB(o, off)) /* a pointer slot of the fake ctx (raw 32-bit offset, pointer-sized: the port reads it with PTR(ctx, off)) */
#if defined(__x86_64__) /* T05: the ctx is an IMAGE too (i386 layout, marshalled by test/v34/v34_img.h): its pointer slots are 32-bit words */
#define PTRX_SET(o, off, v) (*(uint32_t *)OB(o, off) = (uint32_t)(uintptr_t)(v))
#else
#define PTRX_SET(o, off, v) (PTRX(o, off) = (v))
#endif

static unsigned char *xalloc(size_t n) {
  unsigned char *p = (unsigned char *)calloc(1, n);
  if (!p) exit(4);
  if (n == OBJSZ) V34I_REG(p, n);
  else if (n == CTXSZ) V34I_REGC(p, n, ctx);
  else if (n == CFGSZ) V34I_REGC(p, n, cfg);
  return p;
}

typedef struct {
  unsigned char *obj, *ctx, *cfg, *P;         /* templates (pre-call state) */
  unsigned char *wobj, *wctx, *wcfg, *wP;     /* work copies */
  unsigned char *ext_info;                     /* external 2-byte info word (+ slack) */
} env_t;

static env_t g_env;

static void env_init(void) {
  g_env.obj = xalloc(OBJSZ);
  g_env.ctx = xalloc(CTXSZ);
  g_env.cfg = xalloc(CFGSZ);
  g_env.P = xalloc(PSZ);
  g_env.wobj = xalloc(OBJSZ);
  g_env.wctx = xalloc(CTXSZ);
  g_env.wcfg = xalloc(CFGSZ);
  g_env.wP = xalloc(PSZ);
  g_env.ext_info = xalloc(16);
  fill_random(g_env.obj, OBJSZ);
  fill_random(g_env.ctx, CTXSZ);
  fill_random(g_env.cfg, CFGSZ);
  fill_random(g_env.P, PSZ);
}

static unsigned int diff_words(const unsigned char *a, const unsigned char *b, size_t sz, unsigned int h) {
  size_t i;
  if (!memcmp(a, b, sz)) return fnv(h, "=", 1);
  for (i = 0; i + 4 <= sz; i += 4)
    if (memcmp(a + i, b + i, 4)) {
      uint32_t idx = (uint32_t)i, v;
      memcpy(&v, a + i, 4);
      h = fnv(h, &idx, 4);
      h = fnv(h, &v, 4);
    }
  return h;
}

typedef struct {
  int32_t f6120, f24c, f250, f4f8, p54;
  int16_t p44, scale, stale;
  uint16_t info;
  int use_ext_info;
} in_t;

/* garbage-heavy flag values: low 16 bits often zero, high bit set, etc. */
static int32_t rflag(int nz) {
  static const int32_t nzv[] = {1, 0x10000, (int32_t)0x80000000u, 0x100, (int32_t)0xfffe0000u, -1, 0x7fffffff, 0x10001};
  unsigned int r = lcg_mod(10);
  if (!nz) return 0;
  return r < 8 ? nzv[r] : (int32_t)(lcg_next() | 0x10000u);
}

static in_t rand_in(void) {
  static const int32_t p54v[] = {4, 4, 3, 5, 0, -4, 0x10004, (int32_t)0x80000004u, 0x20000004, 1};
  in_t in;
  in.f6120 = rflag((int)(lcg_next() & 1));
  in.f24c = rflag((int)(lcg_next() & 1));
  in.f250 = rflag((int)(lcg_next() & 1));
  in.f4f8 = rflag((int)(lcg_next() & 1));
  in.p54 = lcg_mod(3) ? p54v[lcg_mod(10)] : (int32_t)lcg_next();
  in.p44 = (int16_t)(lcg_mod(3) ? lcg_range(-14, 11) : (int)(lcg_next() >> 16));
  {
    static const int16_t sv[] = {0, 1, -1, 32767, -32768, 16384, -16384, 4096, 1000, -1000};
    in.scale = lcg_mod(3) ? (int16_t)(lcg_next() >> 16) : sv[lcg_mod(10)];
  }
  in.stale = (int16_t)(lcg_next() >> 16);
  in.info = (uint16_t)(lcg_next() >> 16);
  in.use_ext_info = (lcg_mod(8) == 0);
  return in;
}

static long g_c_calls;
static struct {
  long r_neg, r_zero, r_pos, red_neg, red_zero, red_pos, red_max, red_min, path_B, path_C_p54_4, path_C_p54_other, Ck_250z, Ck_250nz,
      clamp_lo, clamp_hi, clamp_none, min_neg, min_pos, raise_by_min, scale_wrapped;
  long f24c_z, f24c_nz, f6120_z, f6120_nz, f4f8_z, f4f8_nz, f250_z, f250_nz, ext_info, in_info;
  long redseen[64];
} cv;

/* mode 0: GetVPcm only; mode 1: settxlevel. Returns the call hash. */
static unsigned int env_call(const in_t *in, int mode, unsigned int *ret_out) {
  env_t *e = &g_env;
  unsigned int h = FNV0, eh;
  int ret = 0;
  const unsigned short *info;

  /* inputs go into the TEMPLATE, then it is copied to the work buffers */
  PTRW(e->obj, 0x3548) = e->ctx;
  PTRX_SET(e->ctx, 0x610c, e->cfg);
  PTRW(e->obj, 0xac3c) = e->P;
  I32(e->ctx, 0x6120) = in->f6120;
  I32(e->obj, 0x24c) = in->f24c;
  I32(e->obj, 0x250) = in->f250;
  I32(e->cfg, 0x4f8) = in->f4f8;
  I32(e->P, 0x54) = in->p54;
  S16(e->P, 0x44) = in->p44;
  S16(e->obj, 0x25d4) = in->scale;
  S16(e->obj, 0x25dc) = in->stale;
  /* with an external info word, the in-object word at +0xa9dc is DIFFERENT (bits 2..7 flipped) so reading the wrong one is caught */
  U16(e->obj, 0xa9dc) = in->use_ext_info ? (uint16_t)(in->info ^ 0x00fcu) : in->info;
  memcpy(e->ext_info, &in->info, 2);
  memcpy(e->wobj, e->obj, OBJSZ);
  memcpy(e->wctx, e->ctx, CTXSZ);
  memcpy(e->wcfg, e->cfg, CFGSZ);
  memcpy(e->wP, e->P, PSZ);
  info = in->use_ext_info ? (const unsigned short *)e->ext_info : (const unsigned short *)OB(e->wobj, 0xa9dc);

  /* the work object points at the WORK ctx/cfg/P (so writes land there) */
  PTRW(e->wobj, 0x3548) = e->wctx;
  PTRX_SET(e->wctx, 0x610c, e->wcfg);
  PTRW(e->wobj, 0xac3c) = e->wP;

  if (mode == 0)
    ret = GetVPcmMinimalTxPowerReduction(e->wobj);
  else
    settxlevel(e->wobj, info);

  /* restore the three pointer words so the diff against the template sees only real changes */
  PTRW(e->wobj, 0x3548) = e->ctx;
  PTRX_SET(e->wctx, 0x610c, e->cfg);
  PTRW(e->wobj, 0xac3c) = e->P;

  h = diff_words(e->wobj, e->obj, OBJSZ, h);
  h = diff_words(e->wctx, e->ctx, CTXSZ, h);
  h = diff_words(e->wcfg, e->cfg, CFGSZ, h);
  h = diff_words(e->wP, e->P, PSZ, h);
  h = fnv(h, &ret, 4);
  eh = ed_after(1);
  h = fnv(h, &eh, 4);
  if (ret_out) *ret_out = (unsigned int)ret;

  /* coverage from OBSERVED outputs / inputs */
  g_c_calls++;
  {
    int32_t f3558 = I32(e->wobj, 0x3558), f355c = I32(e->wobj, 0x355c);
    int16_t red = S16(e->wobj, 0x25dc);
    if (f3558 == 0x7fdf) cv.path_B++;
    else if (f355c == 4) cv.path_C_p54_4++;
    else if (f355c == 6) cv.path_C_p54_other++;
    if (in->f6120 == 0) cv.f6120_z++; else cv.f6120_nz++;
    if (in->f24c == 0) cv.f24c_z++; else cv.f24c_nz++;
    if (in->f250 == 0) cv.f250_z++; else cv.f250_nz++;
    if (in->f4f8 == 0) cv.f4f8_z++; else cv.f4f8_nz++;
    if (in->p44 < -10) cv.clamp_lo++; else if (in->p44 > 7) cv.clamp_hi++; else cv.clamp_none++;
    if (in->p44 < 0) cv.min_neg++; else cv.min_pos++;
    if (mode == 0) {
      if (ret < 0) cv.r_neg++; else if (ret == 0) cv.r_zero++; else cv.r_pos++;
    } else {
      int ri = red + 32;
      if (red < 0) cv.red_neg++; else if (red == 0) cv.red_zero++; else cv.red_pos++;
      if (ri >= 0 && ri < 64) cv.redseen[ri]++;
      if (in->use_ext_info) cv.ext_info++; else cv.in_info++;
      if (in->f24c && in->f6120 && in->f4f8 == 0) { /* min-power path may apply */ }
    }
  }
  return h;
}

