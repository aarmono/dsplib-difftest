/* block A + bit reader configuration.  keep_state != 0: only re-draw the "programme" fields
 * (used by chains).  The index oracle keeps W and t2 inside [0,31]. */
static int pick_n(void) {
  switch (lcg_mod(10)) {
    case 0: return rr(17, 40);
    case 1: return 32; /* n & 15 == 0 */
    case 2: return 0x7fff;
    case 3: return 17;
    case 4: return 16;
    case 5: return 1;
    case 6: return rr(1, 16);
    case 7: return -rr(0, 3);
    case 8: return rr(-3, 31);
    default: return (int)(lcg_next() % 0x8000u);
  }
}
static int pick_count(void) {
  switch (lcg_mod(10)) {
    case 0: return rr(-40, -1);
    case 1: return 15;
    case 2: return 16;
    case 3: return rr(16, 70);
    case 4: return rr(16, 200);
    case 5: return rr(-32768, -1);
    default: return rr(0, 15);
  }
}
static int pick_W(void) {
  switch (lcg_mod(8)) {
    case 0: return 0;
    case 1: return 16;
    case 2: return rr(17, 31);
    case 3: return 1;
    default: return rr(0, 16);
  }
}
static void gf_config_program(unsigned char *o) {
  unsigned int N, a6, a8;
  int n_lo, n_hi, t1, a4;
  /* N vs (a8+a6) with boundary steering */
  N = (lcg_mod(3) == 0) ? (unsigned int)rr(1, 40) : (unsigned int)rr(1, 0xffff);
  a6 = (lcg_mod(3) == 0) ? (unsigned int)rr(0, 40) : rnd16();
  switch (lcg_mod(6)) {
    case 0: a8 = (N - a6) & 0xffffu; break;      /* low word of the sum == N: the "not greater" boundary */
    case 1: a8 = (N - 1u - a6) & 0xffffu; break; /* low word of the sum == N-1: greater by one */
    case 2:                                      /* 32-bit sum above 0xffff, low word N or N-1 */
      N = (unsigned int)rr(1, 0x7fff);
      a6 = 0x8000u + lcg_mod(0x7fff);
      a8 = (N - a6 - (lcg_mod(2) ? 1u : 0u)) & 0xffffu;
      break;
    default: a8 = rnd16(); break;
  }
  U16(o, 0x25e0) = (uint16_t)N;
  U16(o, 0x25e6) = (uint16_t)a6;
  U16(o, 0x25e8) = (uint16_t)a8;
  switch (lcg_mod(6)) {
    case 0: a4 = 8; break;
    case 1: a4 = 9; break;
    case 2: a4 = 0; break;
    case 3: a4 = 0xffff; break;
    default: a4 = rr(0, 20); break;
  }
  U16(o, 0x25e4) = (uint16_t)a4;
  t1 = a4 < 9 ? 1 : 2;
  n_lo = pick_n();
  n_hi = pick_n();
  /* index oracle: n <= 0 needs t1 + n >= 0 (lsbMask[t2], t2 = (short)(t1 + n)) */
  if (n_lo <= 0 && t1 + n_lo < 0) n_lo = -t1;
  if (n_hi <= 0 && t1 + n_hi < 0) n_hi = -t1;
  S16(o, 0x25ee) = (int16_t)n_lo;
  S16(o, 0x25f0) = (int16_t)n_hi;
  S16(o, 0x25f4) = (int16_t)pick_W();
}

