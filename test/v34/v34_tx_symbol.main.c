/*
 * Differential test harness for V.34 "tier 5a" (src/v34/v34_tx_symbol.c): the tx symbol path
 *   getFrame, txmit, txmitdibit, txmitquadbit
 *
 * One source, two binaries (same convention as test/v34/v34_frame_decoder.main.c):
 *   v34_tier5a_test_blob - linked against the real dsplibs.o (-DTEST_BLOB)
 *   v34_tier5a_test_port - linked against src/v34/v34_tx_symbol.c + the ported callees + tables
 * Each scenario runs in its OWN process (argv[1]).
 *
 * Objects: tagV34Object is not a struct. A random fake object (OBJSZ = 0xb400 bytes) is
 * refreshed per call (single-call scenarios; result = hash of the DIFF: word index + new
 * value of every changed word, so a stray write anywhere is caught) or kept across calls
 * (chain scenarios; result = hash of the WHOLE object after every call). Pointer slots
 * are compared NORMALISED (in-object -> offset, harness buffer -> (region id, offset),
 * function -> id); raw addresses are never compared across the two processes.
 *
 * Callees that txmit reaches (V34ModulatorProcess, V34EchoPreFilter,
 * V34EchoUpdateDelayLine) are the REAL ones on both sides (blob's own / the already
 * verified ports). Their state is configured with valid in-object / harness-buffer
 * pointers and bounded indices (see setup_tx).
 *
 * INPUT ORACLES (the two unchecked table reads, port header notes (1) and (2)):
 *   - lsbMask[i] in getFrame is unchecked: the harness keeps W = [obj+0x25f4] and
 *     t2 = t1 + n inside [0,31] (0..16 table, 17..31 the blob's zero padding, checked
 *     at start-up in the blob build). Anything outside is undefined in the blob and is
 *     NOT claimed covered.
 *   - txmitquadbit's vect16 index is (sh2>>29) + 4k with bit 31 of sh2 always clear (the
 *     parity bit is OR-ed in BEFORE the logical shift), so it is always 0..15: the
 *     over-read the archaeology pass feared (16..19 = rxvect4[0..3]) is UNREACHABLE. The
 *     harness's independent model asserts idx <= 15 on every call (exit 3 otherwise); the
 *     blob build additionally verifies at start-up that the blob's vect16[16..19] is
 *     rxvect4[0..3] (so the claim is recorded as true, and would be reproducible).
 *
 * Scenarios: 0 getFrame(recorder) single, 1 getFrame(real scrambleGPC/GPA) single + chain,
 * 2 txmit single, 3 tx chain (txmit / txmitdibit / txmitquadbit), 4 txmitdibit single,
 * 5 txmitquadbit single, 6 txmitquadbit grid (all bits x tap x k x top-3 bits),
 * 7 txmit ring/bulk-delay wrap-edge grid.
 * Every scenario keeps COVERAGE COUNTERS (from the INPUTS / independent predicates) and exits
 * 2 if a branch class was never reached; exit 3 = harness assumption violated.
 */

