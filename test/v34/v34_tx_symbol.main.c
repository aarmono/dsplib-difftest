/* ---- independent scrambler model (coverage + expectation check for dibit/quadbit) ---- */
static uint32_t model_step(uint32_t sh, int bit, uint32_t tap) {
  int b = bit ^ ((sh & tap) ? 1 : 0) ^ (int)((sh >> 8) & 1u);
  if (b) sh |= 0x80000000u; /* the parity bit is OR-ed into bit 31 BEFORE the logical shift: it lands in bit 30 */
  sh >>= 1;
  return sh;
}
typedef struct {
  uint32_t sh_out, k, point;
  int idx; /* vect16 index (quad) or vect4 index (dibit) */
} sm_t;
static void model_dibit(const unsigned char *o, int bits, sm_t *r) {
  uint32_t tap = (U16(o, 0x25c2) & 1u) ? 0x4000000u : 0x2000u;
  uint32_t sh = U32(o, 0x25cc);
  sh = model_step(sh, bits & 1, tap);
  sh = model_step(sh, (bits >> 1) & 1, tap);
  r->sh_out = sh;
  r->k = ((sh >> 29) + U16(o, 0x25c6)) & 3u;
  r->idx = (int)r->k;
  r->point = (uint32_t)vect4[r->k];
}
static void model_quad(const unsigned char *o, int bits, sm_t *r) {
  uint32_t tap = (U16(o, 0x25c2) & 1u) ? 0x4000000u : 0x2000u;
  uint32_t sh = U32(o, 0x25cc);
  uint32_t k;
  int idx;
  sh = model_step(sh, bits & 1, tap);
  sh = model_step(sh, (bits >> 1) & 1, tap);
  k = ((sh >> 29) + U16(o, 0x25c6)) & 3u;
  sh = model_step(sh, (bits >> 2) & 1, tap);
  sh = model_step(sh, (bits >> 3) & 1, tap);
  idx = (int)((sh >> 29) + 4u * k);
  r->sh_out = sh;
  r->k = k;
  r->idx = idx;
  if (idx > 15) die("model: vect16 index above 15 (the over-read the archaeology pass feared is reachable after all)");
  r->point = (uint32_t)vect16[idx];
}

static void check_sym(const unsigned char *o, const sm_t *e, const char *what) {
  if (U32(o, 0x25cc) != e->sh_out || U16(o, 0x25c8) != (uint16_t)e->k || U16(o, 0x25c6) != (uint16_t)e->k ||
      U32(o, 0x25d0) != e->point) {
    fprintf(stderr, "%s: result differs from the harness's scrambler model (sh=%08x/%08x k=%u/%u pt=%08x/%08x)\n", what,
            U32(o, 0x25cc), e->sh_out, U16(o, 0x25c8), e->k, U32(o, 0x25d0), e->point);
    exit(3);
  }
}

static void pick_scrambler_regs(unsigned char *o, int steer_top) {
  U32(o, 0x25cc) = lcg_next();
  if (steer_top) U32(o, 0x25cc) = (U32(o, 0x25cc) & 0x1fffffffu) | ((uint32_t)steer_top - 1u) << 29;
  U16(o, 0x25c6) = rnd16();
  U16(o, 0x25c8) = rnd16();
}

static void scen_dibit(void) {
  logger_t lg = {"txmitdibit", FNV0, 0, 211};
  txcov_t cov;
  long c, tap13 = 0, tap26 = 0, kk[4] = {0, 0, 0, 0}, bitv[4] = {0, 0, 0, 0}, garb = 0, shb8 = 0, shtap = 0;
  unsigned char *o = G_OBJ;
  memset(&cov, 0, sizeof cov);
  for (c = 0; c < 40000; c++) {
    txm_t m;
    sm_t e;
    unsigned int h;
    int bits = (int)lcg_next();
    tx_prepare(o, &m);
    pick_scrambler_regs(o, 0);
    memcpy(G_SNAP, o, OBJSZ);
    txcov_add(&cov, &m);
    model_dibit(o, bits, &e);
    if ((bits >> 16) != 0 && (bits >> 16) != -1) garb++;
    txmitdibit(o, bits);
    check_sym(o, &e, "txmitdibit");
    h = diff_obj(o, G_SNAP);
    h = fnv32(h, hash_ext());
    log_call(&lg, h, bits & 3, (long)e.k);
    if (U16(G_SNAP, 0x25c2) & 1) tap26++; else tap13++;
    kk[e.k]++;
    bitv[bits & 3]++;
    if (U32(G_SNAP, 0x25cc) & 0x100) shb8++;
    if (U32(G_SNAP, 0x25cc) & ((U16(G_SNAP, 0x25c2) & 1) ? 0x4000000u : 0x2000u)) shtap++;
  }
  log_done(&lg);
  txcov_report(&cov);
  need("txmitdibit tap 0x2000 (bit 0 of 0x25c2 clear)", tap13);
  need("txmitdibit tap 0x4000000 (bit 0 of 0x25c2 set)", tap26);
  need("txmitdibit k == 0", kk[0]);
  need("txmitdibit k == 1", kk[1]);
  need("txmitdibit k == 2", kk[2]);
  need("txmitdibit k == 3", kk[3]);
  need("txmitdibit bits == 0", bitv[0]);
  need("txmitdibit bits == 1", bitv[1]);
  need("txmitdibit bits == 2", bitv[2]);
  need("txmitdibit bits == 3", bitv[3]);
  need("txmitdibit garbage in the upper 16 bits of the argument", garb);
  need("txmitdibit scrambler bit 8 set", shb8);
  need("txmitdibit scrambler tap bit set", shtap);
}

