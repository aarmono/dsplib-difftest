/* ---- table-address normalisation of the two slots ---- */
typedef struct {
  const void *p;
  size_t len;
  uint32_t id;
} tab_t;
static tab_t g_tabs[10];
static void tabs_init(void) {
  g_tabs[0] = (tab_t){hsine1600, 24, 0x7e010000u};
  g_tabs[1] = (tab_t){hsine1680, 160, 0x7e020000u};
  g_tabs[2] = (tab_t){hsine1800, 64, 0x7e030000u};
  g_tabs[3] = (tab_t){hsine1829, 84, 0x7e040000u};
  g_tabs[4] = (tab_t){hsine1867, 144, 0x7e050000u};
  g_tabs[5] = (tab_t){hsine1920, 20, 0x7e060000u};
  g_tabs[6] = (tab_t){hsine1959, 196, 0x7e070000u};
  g_tabs[7] = (tab_t){hsine2000, 96, 0x7e080000u};
  g_tabs[8] = (tab_t){bpv22high, 120, 0x7e090000u};
  g_tabs[9] = (tab_t){bpv22low, 120, 0x7e0a0000u};
}
static uint32_t norm_val(uint32_t v) {
  size_t i;
  uintptr_t a = (uintptr_t)v;
  if (a >= (uintptr_t)g_obj && a < (uintptr_t)g_obj + OBJSZ) return 0x80000000u | (uint32_t)(a - (uintptr_t)g_obj);
  for (i = 0; i < 10; i++)
    if (a >= (uintptr_t)g_tabs[i].p && a < (uintptr_t)g_tabs[i].p + g_tabs[i].len) return g_tabs[i].id | (uint32_t)(a - (uintptr_t)g_tabs[i].p);
  return v;
}
static const unsigned int k_slots[] = {0x418, 0x508};
#define NSLOTS (sizeof k_slots / sizeof k_slots[0])
static unsigned char g_isslot[OBJSZ / 4];
static void slots_init(void) {
  size_t i;
  for (i = 0; i < NSLOTS; i++) g_isslot[k_slots[i] / 4] = 1;
}

/* hash of the DIFF (word index + new value) against the snapshot, table slots normalised */
static unsigned int diff_obj(void) {
  unsigned int h = FNV0;
  size_t i, j;
  V34I_SYNC_IMG(); /* x86-64: the print hook and the recorders call this while the port works on a SHADOW: bring the image up to date first (no-op outside a call) */
  for (i = 0; i < OBJSZ / 4; i += 16) {
    if (!memcmp(g_obj + 4 * i, g_snap + 4 * i, 64)) continue;
    for (j = i; j < i + 16; j++) {
      uint32_t a, b;
      memcpy(&a, g_obj + 4 * j, 4);
      memcpy(&b, g_snap + 4 * j, 4);
      if (g_isslot[j]) {
        a = norm_val(a);
        b = norm_val(b);
      }
      if (a != b) {
        uint32_t idx = (uint32_t)j;
        h = fnv(h, &idx, 4);
        h = fnv(h, &a, 4);
      }
    }
  }
  return h;
}

typedef struct {
  const char *name;
  unsigned int all;
  long calls;
  long every;
} logger_t;
static void log_call(logger_t *l, unsigned int h, long a, long b) {
  l->all = fnv(l->all, &h, 4);
  l->all = fnv(l->all, &a, 4);
  if (l->calls % l->every == 0) printf("%s c=%ld a=%ld b=%ld hash=%08x\n", l->name, l->calls, L32(a), L32(b), h);
  l->calls++;
}
static void log_done(logger_t *l) { printf("%s calls=%ld all=%08x\n", l->name, l->calls, l->all); }

/* ---- prints (state at each print) and the level hook ---- */
#define MAXL 16
typedef struct {
  char line[MAXL][200];
  unsigned int ph[MAXL];
  int nl;
} plog_t;
static plog_t g_pl;
static int g_hook_k = -1;
static unsigned int g_hook_lvl;
int dsplibs_debug_printf(const char *fmt, ...) {
  va_list ap;
  int len;
  if (g_pl.nl >= MAXL) die("too many prints in one call");
  va_start(ap, fmt);
  len = vsnprintf(g_pl.line[g_pl.nl], sizeof g_pl.line[0], fmt, ap);
  va_end(ap);
  g_pl.ph[g_pl.nl] = diff_obj();
  if (g_hook_k >= 0 && g_pl.nl == g_hook_k) dsplibs_debug_level = g_hook_lvl;
  g_pl.nl++;
  return len;
}
static unsigned int hash_plog(void) {
  unsigned int h = FNV0;
  int i;
  for (i = 0; i < g_pl.nl; i++) {
    h = fnv(h, g_pl.line[i], strlen(g_pl.line[i]) + 1);
    h = fnv(h, &g_pl.ph[i], 4);
  }
  return fnv(h, &g_pl.nl, 4);
}

