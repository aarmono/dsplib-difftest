static int g_ntr;
static int g_scr_baud, g_scr_car; /* the baud / carrier the rxinit recorder scribbled */
static int32_t g_cnt4;            /* [0xa24c] after the dftupdate recorder */
static int g_have_mid;
static uint64_t xs_next(uint64_t *s) {
  uint64_t x = *s;
  x ^= x << 13;
  x ^= x >> 7;
  x ^= x << 17;
  *s = x;
  return x;
}
static const int k_bauds[] = {0x960, 0xab7, 0xaf0, 0xbb8, 0xc80, 0xd65};
static const int k_cars[] = {0x640, 0x690, 0x708, 0x725, 0x74b, 0x780, 0x7a7, 0x7d0};
static void scribble(int id, unsigned char *obj, uint64_t s) {
  unsigned int r;
  if (id == 1) { /* rxinit: setupreceiver reads baud / carrier / gain / flags / 0xaab0 AFTER the call */
    r = (unsigned int)(xs_next(&s) >> 20) % 100;
    g_scr_baud = (r < 80) ? k_bauds[(r >> 2) % 6] : (r < 90) ? (int)(int16_t)(xs_next(&s) >> 30) : 0x960 + (int)((r & 1) ? 1 : -1);
    r = (unsigned int)(xs_next(&s) >> 20) % 100;
    g_scr_car = (r < 80) ? k_cars[(r >> 2) % 8] : (r < 90) ? (int)(int16_t)(xs_next(&s) >> 30) : 0x708 + (int)((r & 1) ? 1 : -1);
    U16T(obj, 0xaa96) = (uint16_t)g_scr_baud;
    U16T(obj, 0xaaa8) = (uint16_t)g_scr_car;
    U16T(obj, 0x4c6) = (uint16_t)(xs_next(&s) >> 30);
    U16T(obj, 0x386) = (uint16_t)(xs_next(&s) >> 30);
    U32T(obj, 0xaab0) = (uint32_t)(xs_next(&s) >> 30);
  } else if (id == 2 || id == 3) { /* detectorinit / V34SetupModulator: [0x386] and [0x4c6] are read after */
    U16T(obj, 0x386) = (uint16_t)(xs_next(&s) >> 30);
    U16T(obj, 0x4c6) = (uint16_t)(xs_next(&s) >> 30);
  } else if (id == 4) { /* dftupdate: detectRetrainReq reads the counter [0xa24c] after */
    r = (unsigned int)(xs_next(&s) >> 20) % 100;
    S32T(obj, 0xa24c) = (r < 55) ? 0x7c : (r < 65) ? 0x78 : (r < 75) ? 0x80 : (int32_t)(xs_next(&s) >> 30);
    g_cnt4 = S32T(obj, 0xa24c);
  } else if (id == 5) { /* dftenergy: the detector state machine reads the bin energies / counters after */
    static const int16_t ev[] = {0, 1, 2, 100, 500, 0x7fff, -1, -100, (int16_t)0x8000, 300, 20000};
    unsigned char *bins = OB(obj, 0xa81c);
    unsigned int k;
    for (k = 0; k < 6; k++) {
      static const unsigned short off[] = {0xc, 0x38, 0x64, 0x28, 0x54, 0x80};
      r = (unsigned int)(xs_next(&s) >> 20);
      /* u16 energies at 0xc / 0x38 / 0x64, thresholds s16 at 0x28 / 0x54 / 0x80: make them close to each other */
      U16(bins, off[k]) = (uint16_t)ev[(r >> 4) % 11];
      if (k >= 3 && (r % 4) != 0) U16(bins, off[k]) = (uint16_t)(U16(bins, off[k - 3]) + (int)((r >> 9) % 3) - 1);
    }
    U16(bins, 0x56) = (uint16_t)ev[(xs_next(&s) >> 20) % 11];
    if (xs_next(&s) & 1) U16(bins, 0x56) = (uint16_t)(U16(bins, 0x38) + (int)((xs_next(&s) >> 20) % 3) - 1);
    r = (unsigned int)(xs_next(&s) >> 20) % 100;
    U16T(obj, 0xa24a) = (r < 40) ? 1 : (r < 80) ? 2 : (uint16_t)(xs_next(&s) >> 30);
    r = (unsigned int)(xs_next(&s) >> 20) % 100;
    U16T(obj, 0xa252) = (r < 60) ? 3 : (uint16_t)(xs_next(&s) >> 30);
    U16T(obj, 0xa254) = (r % 3 == 0) ? 9 : (uint16_t)(xs_next(&s) >> 30);
    r = (unsigned int)(xs_next(&s) >> 20) % 100;
    U16T(obj, 0xa250) = (r < 30) ? (U16T(obj, 0xa254)) : (r < 55) ? (uint16_t)(U16T(obj, 0xa254) - 1) : (r < 70) ? (uint16_t)(U16T(obj, 0xa252) - 1)
                       : (r < 80) ? U16T(obj, 0xa252) : (uint16_t)(xs_next(&s) >> 30);
    memcpy(g_mid, obj, OBJSZ);
    g_have_mid = 1;
  }
}
static void rec(int id, void *a0, uint32_t a1, uint32_t a2, uint32_t a3, uint32_t a4, uint32_t a5, uint32_t a6) {
  tr_t *t;
  V34I_SYNC_IMG(); /* x86-64: the port works on a SHADOW; bring the image up to date before it is hashed, and push the scribbled fields back at the end */
  a0 = V34I_IMGP(a0);
  uint64_t s = (((uint64_t)(g_cseed + 0x9e3779b9u * (unsigned int)(g_occ[id]++)) << 32) | 0x5bd1e995u) ^
               (0x9e3779b97f4a7c15ull * (uint64_t)(id + 1));
  int i;
  if (g_ntr >= 8) die("too many callee calls");
  t = &g_tr[g_ntr++];
  t->id = id;
  t->a[0] = norm_val((uint32_t)(uintptr_t)a0);
  t->a[1] = a1;
  t->a[2] = a2;
  t->a[3] = a3;
  t->a[4] = a4;
  t->a[5] = a5;
  t->a[6] = a6;
  t->dh = diff_obj();
  if (!s) s = 1;
  for (i = 0; i < 4; i++) xs_next(&s);
  scribble(id, g_obj, s);
  V34I_SYNC_NAT();
}
