typedef struct {
  int16_t g134, g136, g138;
  int branch;
} agc_t;
static void model_agc(const unsigned char *b, agc_t *o) {
  int64_t g = (int16_t)U16((unsigned char *)b, 0x134);
  uint32_t add = U16((unsigned char *)b, 0x12e);
  int64_t sh = (g * 0x6ccd) >> 15; /* arithmetic (floor) */
  uint32_t sum = (uint32_t)((uint64_t)(sh + (int64_t)add));
  uint32_t hi = sum >> 15;
  int64_t d, t, s, sd, u;
  o->g134 = (hi == 0 || hi == 0x1ffff) ? (int16_t)sum : 0x7f00;
  o->g136 = (int16_t)U16((unsigned char *)b, 0x136);
  o->g138 = (int16_t)U16((unsigned char *)b, 0x138);
  o->branch = 0;
  if (U8((unsigned char *)b, 0x123) & 2) { o->branch = 1; return; }
  d = (int16_t)(uint16_t)((uint32_t)(uint16_t)o->g134 - 4000u);
  t = (d < 0 ? -d : d) - 0x4b0;
  if ((int16_t)t <= 0) { o->branch = 2; return; }
  s = ((int64_t)(int16_t)U16((unsigned char *)b, 0x13a) * d) >> 16;
  s = (int64_t)(uint32_t)((uint64_t)(s + (int64_t)U16((unsigned char *)b, 0x138)));
  sd = (int16_t)(uint16_t)s;
  u = (sd < 0 ? -sd : sd) - 500;
  if ((int16_t)u <= 0) { o->g138 = (int16_t)s; o->branch = 3; return; }
  o->g138 = 0;
  if (sd > 0) { o->g136 = (int16_t)(((int64_t)o->g136 * 0x390a) >> 14); o->branch = 4; return; }
  if (o->g136 > 0x6a00) { o->branch = 5; return; }
  o->g136 = (int16_t)(((int64_t)o->g136 * 0x47cf) >> 14);
  o->branch = 6;
}
