/*
 * Differential test harness for V.34 "tier 10b" (src/v34/v34_unused.c): the 16 DEAD plain-C DSP-chain functions
 *   setScramble scaleVector initG248 decision agcadapt dpskDetectInfo1Init dftfreqinit dftnlinitSignalBins
 *   dftnlinitNoiseBins detectRetrainReq dftRetrainDetInit setupreceiver dpskinit polyValue preempindex cosread
 * (no caller anywhere in dsplibs.o; all GLOBAL, so reached directly).
 *
 * One source, two binaries (convention of test/vpcm/v34_api.main.c):
 *   v34_tier10b_test_blob - real dsplibs.o (-DTEST_BLOB) in which the five CALLEES (rxinit, detectorinit, V34SetupModulator,
 *                           dftupdate, dftenergy) are WEAK (objcopy --weaken-symbol)
 *   v34_tier10b_test_port - src/v34/v34_unused.c + the extracted tables only
 * The callees are RECORDERS defined here in BOTH binaries: they log their arguments (pointers normalised) and the state DIFF
 * at entry (so store-vs-call ORDER is compared), then SCRIBBLE deterministic, branch-steering values over the fields the
 * caller reads after the call (baud / carrier / flags / detector counters ...).
 *
 * State: a random fake object (OBJSZ 0xb400 B) re-filled before every call; the call's effect is hashed as the DIFF of the
 * object against a pre-call snapshot.  Two 4-byte slots hold table ADDRESSES (obj+0x418 = &hsineNNNN, obj+0x508 = &bpv22*):
 * they are normalised to table ids (the harness references the SAME symbol names in both builds: the blob's own tables in the
 * blob binary, the port's in the port binary).
 *
 * INDEPENDENT MODELS (written from the disassembly facts, 64-bit arithmetic where the blob uses 32): agcadapt,
 * preempindex, detectRetrainReq (applied to the object state the recorders produced), initG248 (rebuilt from `xyz`),
 * polyValue / scaleVector.  Mismatch with the model: exit 3.
 *
 * Scenarios: 0 trivial setters / initialisers / polyValue / cosread (exhaustive), 1 initG248, 2 decision, 3 agcadapt,
 * 4 preempindex, 5 detectRetrainReq, 6 setupreceiver, 7 dpskinit, 8 detectRetrainReq with n <= 6 (T07).  Each keeps coverage counters (from the models / inputs)
 * and exits 2 if a required class was never reached.
 */

