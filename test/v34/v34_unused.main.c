/* ============================================================================
 * scenario 2: decision
 * ========================================================================== */
static void scen2(void) {
  logger_t L = {"decision", FNV0, 0, 997};
  long n_le0 = 0, n_ties = 0, n_first = 0, n_last = 0, n_wrap = 0, n_unreach = 0, n_edge = 0, n_win1 = 0;
  int i;
  for (i = 0; i < 60000; i++) {
    unsigned int h;
    int n, ret;
    unsigned char *b = OB(g_obj, 0x264);
    short *pts = (short *)(void *)OB(g_obj, 0x4000);
    int k;
    fresh();
    dsplibs_debug_level = 0;
    {
      unsigned int c = lcg_mod(10);
      n = (c < 1) ? lcg_range(-3, 0) : (c < 7) ? lcg_range(1, 40) : (c < 8) ? 1 : lcg_range(1, 200);
    }
    if (lcg_pct(40)) { /* small-range points around the target: exercises the >> 14 metric with ties */
      int ti = (int)(int16_t)(lcg_next() >> 8), tq = (int)(int16_t)(lcg_next() >> 8);
      for (k = 0; k < n * 2 + 2; k += 2) {
        pts[k] = (short)(ti + lcg_range(-300, 300));
        pts[k + 1] = (short)(tq + lcg_range(-300, 300));
      }
      U16(b, 0x210) = (uint16_t)ti;
      U16(b, 0x212) = (uint16_t)tq;
    }
    if (lcg_pct(15) && n >= 2) { /* exact tie between two points: the FIRST wins (strict <) */
      int a = lcg_range(0, n - 2);
      int d = lcg_range(a + 1, n - 1);
      pts[2 * d] = pts[2 * a];
      pts[2 * d + 1] = pts[2 * a + 1];
    }
    if (lcg_pct(10)) { U16(b, 0x210) = 0x8000; U16(b, 0x212) = 0x7fff; } /* extreme target: 16-bit wrap of the differences */
    if (lcg_pct(12) && n >= 2) {
      /* the initial best (0x7fff): point 0 has metric EXACTLY 0x7fff (never < best), point 1 a metric of 0x7ffe or 0x7ffd, which
       * the original selects (strict < against 0x7fff) and a mutated initial best of 0x7ffe / 0x7ffd would not */
      int ti = (int)(int16_t)(lcg_next() >> 8), tq = (int)(int16_t)(lcg_next() >> 8);
      U16(b, 0x210) = (uint16_t)ti;
      U16(b, 0x212) = (uint16_t)tq;
      pts[0] = (short)(ti - 23170);
      pts[1] = (short)(tq - 76);                                  /* 23170^2 + 76^2 >> 14 = 0x7fff */
      if (lcg_pct(50)) { pts[2] = (short)(ti - 23170); pts[3] = (short)tq; }       /* >> 14 = 0x7ffe */
      else { pts[2] = (short)(ti - 23169); pts[3] = (short)(tq - 150); }          /* >> 14 = 0x7ffd */
      n_edge++;
    }
    call_begin();
    ret = decision(b, pts, (lcg_pct(50)) ? garb16(n) : n);
    {
      /* model: 64-bit metric with the 16-bit wrap rules */
      int best = 0x7fff, bi = 0, idx;
      for (idx = 0; idx < n; idx++) {
        int32_t di = (int16_t)(uint16_t)((uint32_t)U16(b, 0x210) - (uint16_t)pts[2 * idx]);
        int32_t dq = (int16_t)(uint16_t)((uint32_t)U16(b, 0x212) - (uint16_t)pts[2 * idx + 1]);
        uint64_t sq = (uint64_t)(uint32_t)(di * di) + (uint64_t)(uint32_t)(dq * dq);
        int m = (int)(int16_t)(uint16_t)((uint32_t)sq >> 14);
        if (m < best) { best = m; bi = idx; }
        if (m == best && idx != bi) n_ties++;
      }
      if (n <= 0) { bi = 0; n_le0++; }
      if (ret != bi) die("decision: index differs from the model");
      if (S16(b, 0x126) != (int16_t)bi) die("decision: [b+0x126] differs from the model");
      if (U32(b, 0x20c) != *(uint32_t *)(void *)&pts[2 * bi]) die("decision: [b+0x20c] differs from the model");
      if (bi == 1 && best >= 0x7ffd && best < 0x7fff) n_win1++;
      if (bi == 0 && n > 0) n_first++;
      if (bi == n - 1 && n > 1) n_last++;
      if (best == 0x7fff) n_unreach++;
      if ((uint32_t)(U16(b, 0x210)) < 0x100u || U16(b, 0x210) >= 0xff00u) n_wrap++;
    }
    h = call_end();
    log_call(&L, h, ret, n);
  }
  log_done(&L);
  need("decision n <= 0 (index 0, loop skipped)", n_le0);
  need("decision exact tie (first wins)", n_ties);
  need("decision winner is the first point", n_first);
  need("decision winner is the last point", n_last);
  need("decision all metrics >= 0x7fff (initial best kept)", n_unreach);
  need("decision target near the 16-bit wrap", n_wrap);
  need("decision metric 0x7ffe / 0x7ffd below the initial best (point 1 wins)", n_win1);
  need("decision edge case steered", n_edge);
}

