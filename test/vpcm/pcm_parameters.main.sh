#!/bin/sh
# Builds the differential test of port chunks P08 + P07 (V90Parameters incl. the 295-call loadParams, V92Parameters; src/vpcm/pcm_parameters_load.cpp + src/vpcm/pcm_parameters.cpp, REAL C++
# compiled with -fno-exceptions -fno-rtti) and runs every scenario in its OWN process:
#   blob      test/vpcm/pcm_parameters.main.main.c + a copy of dsplibs.o in which Vparser_read_int / Vparser_read_float / edprintf are WEAK (the harness' recorders win)   (gcc -m32 -no-pie)
#   port -O0  test/vpcm/pcm_parameters.main.main.c + g++ -m32 -O0 port objects (LINKED WITH gcc: no libstdc++)
#   port -O2  same at -O2
#   port -m64 (NO64=1 skips) the same harness and the port compiled for x86-64; its output is diffed against the 32-bit BLOB's output (the golden dump)
# The ONE harness source has no #ifdef around the code under test: the functions are reached through __asm__ labels with the mangled names.  A scenario exits 2 if its own coverage
# counters fail, 3 if a harness assumption / independent model is violated; either fails this script.
# Also checked here: the blob function symbols of V90Parameters / V92Parameters (name + binding) are defined by the port objects; the harness mirror structs (generated by
# tools/layout_gen.py from test/vpcm/pcm_parameters.layout) equal the port header's real class layouts (layout probe, every binary); every byte offset P05 / P06 still use for the parameter
# blocks is the offset of a named member (test/vpcm/pcm_parameters.offsets.cpp, i386).
# "MATCH" is only printed if every scenario matched AND reached its branches.
#
# Env: PORT_P07 / PORT_P08 (port sources under test, mutation testing; MUT_P08=1 when mutating pcm_parameters_load.cpp, see below), SCENARIOS, NOO2=1, NO64=1, TPREFIX (output prefix, parallel mutation runs), P07_SEED (alternative input stream),
# GOLDEN_UPDATE=1 (rewrite test/golden/vpcm/pcm_parameters.main.blob32.out from this blob run), FP64_FLAGS (extra flags of the x86-64 port build).
#
# Usage: sh test/vpcm/pcm_parameters.main.sh   (run from slmodemd/dsplibs-port/)

set -e
cd "$(dirname "$0")/../.."
. test/blob.sh   # BLOB_O: the blob oracle (dsplibs.o), see test/blob.sh

PORT_P07="${PORT_P07:-src/vpcm/pcm_parameters.cpp}"
PORT_P08="${PORT_P08:-src/vpcm/pcm_parameters_load.cpp}"
T="${TPREFIX:-test/.build/vpcm/pcm_parameters.main}"
mkdir -p "$(dirname "$T")"
# the 32-bit -O2 object of the port source under mutation is named *_port_o2.o (tools/mutate.py picks that compile): MUT_P08=1 swaps the names so that pcm_parameters_load.cpp is the mutated one
if [ -n "$MUT_P08" ]; then O2_P07=${T}_p07_o2.o; O2_P08=${T}_port_o2.o; else O2_P07=${T}_port_o2.o; O2_P08=${T}_p08_o2.o; fi
CF="-m32 -Wall -Wextra -Wno-unused-function -O0 -g"
HCF="-m32 -Wall -Wextra -Wno-unused-function -O2 -g"
CXXF="-Wall -Wextra -fno-exceptions -fno-rtti -Isrc"
LD32="-no-pie"
SCENARIOS="${SCENARIOS:-0 1 2 3 4 5}"
ALLSC="0 1 2 3 4 5"
case "$T" in /*) R="";; *) R="./";; esac   # absolute TPREFIX (mutation / coverage tools) needs no "./"

SRENAME="-Dsysdep_malloc=stub_env_unused_malloc -Dsysdep_free=stub_env_unused_free -Ddsplibs_debug_printf=stub_env_unused_dbgprintf"
gcc $CF $SRENAME -c test/stub_env.c -o ${T}_stub_env.o
g++ -m32 $CXXF -O2 -c test/vpcm/pcm_parameters_layout_probe.cpp -o ${T}_probe.o
gcc $HCF -c test/harness/harness.c -o ${T}_harness.o     # the shared harness library (test/harness/, plain C)
objcopy --weaken-symbol=edprintf --weaken-symbol=Vparser_read_int --weaken-symbol=Vparser_read_float $BLOB_O ${T}_dsplibs_weak.o

gcc $HCF $LD32 -o ${T}_test_blob test/vpcm/pcm_parameters.main.main.c ${T}_harness.o ${T}_stub_env.o ${T}_probe.o ${T}_dsplibs_weak.o

g++ -m32 $CXXF -O0 -g -c $PORT_P07 -o ${T}_port_o0.o
g++ -m32 $CXXF -O0 -g -c $PORT_P08 -o ${T}_p08_o0.o
gcc $HCF $LD32 -o ${T}_test_port test/vpcm/pcm_parameters.main.main.c ${T}_harness.o ${T}_stub_env.o ${T}_probe.o ${T}_port_o0.o ${T}_p08_o0.o
if [ -z "$NOO2" ]; then
  g++ -m32 $CXXF -O2 -g -c $PORT_P07 -o $O2_P07
  g++ -m32 $CXXF -O2 -g -c $PORT_P08 -o $O2_P08
  gcc $HCF $LD32 -o ${T}_test_port_o2 test/vpcm/pcm_parameters.main.main.c ${T}_harness.o ${T}_stub_env.o ${T}_probe.o $O2_P07 $O2_P08
fi

# the P05 / P06 byte offsets of the parameter blocks are named members (compile-time asserts, i386)
g++ -m32 $CXXF -O2 -c test/vpcm/pcm_parameters.offsets.cpp -o ${T}_offsets.o
echo "OFFSETS: every V90Parameters / V92Parameters byte offset still used by P05 / P06 is the offset of a named member (test/vpcm/pcm_parameters.offsets.cpp)"
python3 test/vpcm/pcm_parameters.offsets_check.py

# symbol check: every function symbol of the two classes exists, with the same name and binding, in the port objects
DEFAULT_SYMRE='_Z(N|NK)(13V90Parameters|13V92Parameters)'
SYMRE="${P07_SYMRE:-$DEFAULT_SYMRE}"
BLOBSYMS=$(nm --defined-only $BLOB_O | awk -v re="^($SYMRE)" '$3 ~ re {print $2" "$3}' | sort)
PORTSYMS=$( (nm --defined-only $O2_P07 $O2_P08 2>/dev/null || nm --defined-only ${T}_port_o0.o ${T}_p08_o0.o) | grep -v ':$')
MISSING=$(echo "$BLOBSYMS" | while read b s; do echo "$PORTSYMS" | grep -q " $b $s\$" || echo "$b $s"; done)
NBLOB=$(echo "$BLOBSYMS" | wc -l)
if [ -n "$MISSING" ]; then echo "SYMBOL MISMATCH (blob symbol missing / different binding in the port object):"; echo "$MISSING"; exit 1; fi
echo "SYMBOLS: all $NBLOB blob symbols (name + binding) are defined by the port objects"

if [ -z "$NO64" ]; then
  g++ -m64 $CXXF -O2 $FP64_FLAGS -c $PORT_P07 -o ${T}_port64.o
  g++ -m64 $CXXF -O2 $FP64_FLAGS -c $PORT_P08 -o ${T}_p08_64.o
  g++ -m64 $CXXF -O2 -c test/vpcm/pcm_parameters_layout_probe.cpp -o ${T}_probe64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 $SRENAME -c test/stub_env.c -o ${T}_stub_env64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 -c test/harness/harness.c -o ${T}_harness64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 -no-pie -o ${T}_test_port64 test/vpcm/pcm_parameters.main.main.c ${T}_harness64.o ${T}_stub_env64.o ${T}_probe64.o ${T}_port64.o ${T}_p08_64.o
fi

# scenarios are independent processes: run them concurrently in groups, then concatenate in order
rm -f ${T}_s*.out
rc=0
pids=""
njobs=0
for i in $SCENARIOS; do
  ( ${R}${T}_test_blob "$i" > ${T}_s$i.blob.out ) & pids="$pids $!"
  ( ${R}${T}_test_port "$i" > ${T}_s$i.port.out ) & pids="$pids $!"
  if [ -z "$NOO2" ]; then ( ${R}${T}_test_port_o2 "$i" > ${T}_s$i.o2.out ) & pids="$pids $!"; fi
  if [ -z "$NO64" ]; then ( ${R}${T}_test_port64 "$i" > ${T}_s$i.p64.out ) & pids="$pids $!"; fi
  njobs=$((njobs + 1))
  if [ $njobs -ge 2 ]; then for p in $pids; do wait $p || rc=1; done; pids=""; njobs=0; fi
done
for p in $pids; do wait $p || rc=1; done
: > ${T}_blob.out; : > ${T}_port.out; : > ${T}_port_o2.out; : > ${T}_port64.out
for i in $SCENARIOS; do
  cat ${T}_s$i.blob.out >> ${T}_blob.out
  cat ${T}_s$i.port.out >> ${T}_port.out
  if [ -z "$NOO2" ]; then cat ${T}_s$i.o2.out >> ${T}_port_o2.out; fi
  if [ -z "$NO64" ]; then cat ${T}_s$i.p64.out >> ${T}_port64.out; fi
done
rm -f ${T}_s*.out
if [ $rc -ne 0 ]; then echo "SCENARIO FAILURE (non-zero exit: coverage, harness assertion / model violation or crash)"; exit 1; fi

diff -u ${T}_blob.out ${T}_port.out
if [ -z "$NOO2" ]; then diff -u ${T}_blob.out ${T}_port_o2.out; fi
if [ -z "$NO64" ]; then diff -u ${T}_blob.out ${T}_port64.out; fi
if [ -n "$GOLDEN_UPDATE" ]; then mkdir -p test/golden; cp ${T}_blob.out test/golden/vpcm/pcm_parameters.main.blob32.out; echo "golden updated"; fi
if [ -z "$TPREFIX" ] && [ "$SCENARIOS" = "$ALLSC" ] && [ -f test/golden/vpcm/pcm_parameters.main.blob32.out ] && [ -z "$P07_SEED" ]; then
  if diff -u test/golden/vpcm/pcm_parameters.main.blob32.out ${T}_blob.out; then echo "GOLDEN: the 32-bit blob run equals test/golden/vpcm/pcm_parameters.main.blob32.out"
  else echo "STALE GOLDEN: the blob output differs from test/golden/vpcm/pcm_parameters.main.blob32.out (GOLDEN_UPDATE=1 rewrites it)"; exit 1; fi
fi
echo "MATCH: P07 / P08 C++ port ($([ -z "$NOO2" ] && echo '-O0 and -O2' || echo '-O0')$([ -z "$NO64" ] && echo " + x86-64 [$FP64_FLAGS] vs the 32-bit blob output")) is behaviorally identical to dsplibs.o for this test"
