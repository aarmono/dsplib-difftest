static void need_common(void) {
  static const int k_all[] = {C_MODE0, C_MODE1, C_MODE2, C_MODE3, C_MODE4, C_MODE_GT4};
  size_t i;
  for (i = 0; i < sizeof k_all / sizeof k_all[0]; i++) need(k_cnames[k_all[i]], g_cov[k_all[i]]);
}
static void need_list(const int *l, size_t n) {
  size_t i;
  for (i = 0; i < n; i++) need(k_cnames[l[i]], g_cov[l[i]]);
}

static void scen_random(const char *name, long n, int use_levels, int level_mask) {
  logger_t lg = {name, FNV0, 0, 2500};
  long i;
  for (i = 0; i < n; i++) {
    unsigned int mode = pick_mode();
    unsigned int level = use_levels ? k_levels[lcg_mod(6)] : (lcg_pct(70) ? 0 : 1);
    if (use_levels && lcg_pct(60)) level = 2;
    (void)level_mask;
    gen_obj(g_obj, 0);
    log_call(&lg, run_hsi(mode, level, 0, -1, 0, 0, -1), (long)mode, (long)level, 0);
  }
  log_done(&lg);
}

int main(int argc, char **argv) {
  int sc = argc > 1 ? atoi(argv[1]) : 0;
  long i, n;
  logger_t lg;
  slots_init();
  g_obj = xalloc(OBJSZ);
  g_snap = xalloc(OBJSZ);
  g_mobj = xalloc(OBJSZ);
  V34I_REG(g_obj, OBJSZ);
#ifdef TEST_BLOB
  if (memcmp(c1200_, port_c1200_, 16) || memcmp(c2400_, port_c2400_, 16)) die("blob c1200_/c2400_ != port copy");
#endif
  g_lcg ^= (unsigned int)sc * 0x9e3779b1u;
  if (getenv("T9A_SEED")) g_lcg ^= (unsigned int)strtoul(getenv("T9A_SEED"), NULL, 0) * 0x85ebca6bu;
  printf("scenario %d\n", sc);

  switch (sc) {
    case 0:
      scen_random("rand-lvl0", 80000, 0, 0);
      break;
    case 1:
      scen_random("rand-lvls", 60000, 1, 0);
      break;
    case 8: /* T07: scenario 2 with the reader pointer poked away from the pointer slots p9138_..p9148_ (obj+0x9100..0x9157), so the 12-word
             * store through it hits the same data on i386 and x86-64 (see NOTES.md); the original scenario 2 is unchanged */
    case 2: { /* hook: level flip / pointer poke after the k-th print */
      lg = (logger_t){"hook", FNV0, 0, 2000};
      n = 50000;
      for (i = 0; i < n; i++) {
        unsigned int mode = lcg_pct(45) ? 4u : pick_mode();
        unsigned int level = lcg_pct(70) ? 2u : k_levels[lcg_mod(6)];
        int k = lcg_range(0, 6);
        int setlvl = lcg_pct(60);
        unsigned int hl = k_levels[lcg_mod(6)];
        int poke = lcg_pct(50) ? 0x9000 + 4 * (int)lcg_mod(0x300) : -1;
        if (sc == 8 && poke >= 0x9100 && poke < 0x9158) poke += 0x58;
        gen_obj(g_obj, 0);
        log_call(&lg, run_hsi(mode, level, 0, k, setlvl, hl, poke), (long)mode, (long)k, (long)poke);
      }
      log_done(&lg);
      {
        static const int l[] = {C_HOOK_FIRED, C_HOOK_LEVEL, C_HOOK_POKE, C_POKE_EFFECT};
        need_list(l, 4);
      }
      break;
    }
    case 3: { /* SetMoh direct */
      lg = (logger_t){"moh", FNV0, 0, 2500};
      n = 60000;
      for (i = 0; i < n; i++) {
        unsigned int level = lcg_pct(50) ? 2u : k_levels[lcg_mod(6)];
        int outoff = 0xa94c;
        unsigned int r = lcg_mod(100);
        gen_obj(g_obj, 0);
        if (r < 12) outoff = 0xabe0; /* aliases the 0xabe0 input word */
        else if (r < 24) outoff = 0xabfa; /* aliases the 0xabfa byte test */
        else if (r < 30) outoff = 0xabf0; /* aliases the index dword */
        log_call(&lg, run_moh(level, NULL, NULL, outoff), (long)U32(g_snap, 0xabf0), (long)level, (long)outoff);
      }
      log_done(&lg);
      {
        static const int l[] = {C_M_0, C_M_1, C_M_2, C_M_3, C_M_4, C_M_5, C_M_GT5, C_M_2_AB0, C_M_2_AB1, C_M_2_OTH, C_M_2_AB_WORDNZ,
                                C_M_4_WRAP, C_M_ALIAS_E0, C_M_ALIAS_FA, C_M_PRINT, C_M_NOPRINT, C_M_4_HIGHBITS, C_M_6_BIG};
        need_list(l, sizeof l / sizeof l[0]);
      }
      break;
    }
    case 4: { /* wild state words, level <= 1 */
      lg = (logger_t){"wild", FNV0, 0, 2000};
      n = 40000;
      for (i = 0; i < n; i++) {
        unsigned int mode = pick_mode();
        gen_obj(g_obj, 1);
        log_call(&lg, run_hsi(mode, lcg_pct(50) ? 0u : 1u, 1, -1, 0, 0, -1), (long)mode, 0, 0);
      }
      log_done(&lg);
      need(k_cnames[C_NOPRINT_CHG], g_cov[C_NOPRINT_CHG]);
      break;
    }
    case 5: { /* timer block boundary sweep */
      static const uint32_t k_a[] = {1u, 2u, 0x100u, 96000u, 0x7fffffffu, 0x80000000u, 0x80000001u, 0xfffffffeu, 0xffffffffu, 0u};
      static const uint32_t k_d[] = {0u, 1u, 0x176feu, 0x176ffu, 0x17700u, 0x17701u, 95999u, 96000u, 0x7fffffffu, 0x80000000u, 0xffffffffu, 0xfffffffeu, 0x69780u, 0x8000u};
      lg = (logger_t){"timer", FNV0, 0, 500};
      for (i = 0; i < (long)(sizeof k_a / sizeof k_a[0]); i++) {
        long j;
        for (j = 0; j < (long)(sizeof k_d / sizeof k_d[0]); j++) {
          int r;
          for (r = 0; r < 12; r++) {
            unsigned int mode = (r < 6) ? (unsigned int)r : (unsigned int)(r % 5);
            gen_obj(g_obj, 0);
            U32(g_obj, 0x248) = k_a[i];
            U32(g_obj, 0x238) = k_a[i] + k_d[j];
            log_call(&lg, run_hsi(mode, (unsigned int)(r & 1), 0, -1, 0, 0, -1), (long)k_a[i], (long)k_d[j], (long)mode);
          }
        }
      }
      /* plus random timer words */
      for (i = 0; i < 30000; i++) {
        gen_obj(g_obj, 0);
        if (lcg_pct(50)) U32(g_obj, 0x248) = (uint32_t)lcg_range(-3, 5);
        U32(g_obj, 0x238) = lcg_pct(50) ? U32(g_obj, 0x248) + k_d[lcg_mod(sizeof k_d / sizeof k_d[0])] : lcg_next();
        log_call(&lg, run_hsi(lcg_pct(30) ? 0u : (unsigned int)lcg_mod(5), 0, 0, -1, 0, 0, -1), 0, 0, 0);
      }
      log_done(&lg);
      {
        static const int l[] = {C_T_POS_OK, C_T_POS_OVER, C_T_NONPOS, C_T_SIGNNEG, C_T_EQ, C_T_EQP1, C_T_EQM1, C_T_OVER_WRAP};
        need_list(l, sizeof l / sizeof l[0]);
      }
      break;
    }
    case 6: { /* arm-1 flag grid (+ arm 0 / arm 4 selector words) */
      static const uint8_t k_b386[] = {0x00, 0x40, 0x41, 0x80, 0xc0, 0xbf, 0xff, 0x3f};
      static const uint8_t k_ac17[] = {0x00, 0x01, 0x80, 0xff, 0x7f};
      lg = (logger_t){"flags", FNV0, 0, 500};
      for (i = 0; i < 30000; i++) {
        unsigned int mode = lcg_pct(60) ? 1u : (lcg_pct(50) ? 0u : 4u);
        gen_obj(g_obj, 0);
        U8(g_obj, 0x386) = k_b386[lcg_mod(sizeof k_b386)];
        U8(g_obj, 0x387) = (uint8_t)lcg_next();
        U8(g_obj, 0xac17) = k_ac17[lcg_mod(sizeof k_ac17)];
        if (lcg_pct(50)) { U8(g_obj, 0xac16) = 0; U8(g_obj, 0xac18) = 0; }
        if (lcg_pct(20)) U16(g_obj, 0xac14) = (uint16_t)(0xfffeu + lcg_mod(2));
        if (lcg_pct(20)) U16(g_obj, 0xac12) = (uint16_t)(0xfffeu + lcg_mod(2));
        if (lcg_pct(40)) {
          static const uint32_t k_z[] = {0x65u, 0x66u, 0x10065u, 0x20066u, 0xffff0065u, 0x64u, 0x67u, 0x165u, 0x166u, 0x8065u};
          U32(g_obj, 0x359c) = k_z[lcg_mod(sizeof k_z / sizeof k_z[0])];
        }
        log_call(&lg, run_hsi(mode, lcg_pct(40) ? 2u : 0u, 0, -1, 0, 0, -1), (long)mode, 0, 0);
      }
      log_done(&lg);
      {
        static const int l[] = {C_A1_B386, C_A1_AC17_ONLY, C_A1_CLEAR, C_A1_AC12_WRAP, C_A1_AC14_WRAP, C_A1_AC17_BYTEONLY, C_A0_66,
                                C_A0_NOT66, C_A0_66_UPPERNZ, C_A4_65, C_A4_OTHER, C_A4_65_UPPERNZ};
        need_list(l, sizeof l / sizeof l[0]);
      }
      break;
    }
    case 7: { /* persistent objects: state carries between calls */
      lg = (logger_t){"persist", FNV0, 0, 2000};
      for (i = 0; i < 4000; i++) {
        int k;
        gen_obj(g_obj, 0);
        for (k = 0; k < 8; k++) {
          unsigned int mode = lcg_pct(30) ? 4u : pick_mode();
          unsigned int level = lcg_pct(50) ? 2u : (lcg_pct(50) ? 0u : k_levels[lcg_mod(6)]);
          if (k && lcg_pct(25)) { /* keep the state words legal, vary a few fields */
            U32(g_obj, 0x248) = lcg_next() & 0xffffu;
            U16(g_obj, 0x359c) = (uint16_t)(lcg_pct(50) ? 0x66u : 0x65u);
          }
          log_call(&lg, run_hsi(mode, level, 0, -1, 0, 0, -1), (long)mode, (long)k, 0);
        }
      }
      log_done(&lg);
      break;
    }
    default:
      die("unknown scenario");
  }

  /* coverage of the shared classes for the random scenarios */
  if (sc == 0 || sc == 1 || sc == 7 || sc == 2 || sc == 8) {
    need_common();
    need(k_cnames[C_MODE_GT4_LOWOK], g_cov[C_MODE_GT4_LOWOK]);
    need(k_cnames[C_MODE_HUGE], g_cov[C_MODE_HUGE]);
    need(k_cnames[C_A23_NORNEG], g_cov[C_A23_NORNEG]);
    need(k_cnames[C_A4_NOMOH], g_cov[C_A4_NOMOH]);
    need(k_cnames[C_A0_66], g_cov[C_A0_66]);
    need(k_cnames[C_A1_CLEAR], g_cov[C_A1_CLEAR]);
  }
  if (sc == 1 || sc == 2 || sc == 7 || sc == 8) {
    static const int l[] = {C_P_TX_36, C_P_TX_4A, C_P_TX_12, C_P_RX_2B, C_P_RX_23, C_P_RX_4, C_P_MS_29, C_P_MS_4F,
                            C_S_TX_36, C_S_TX_4A, C_S_TX_12, C_S_RX_2B, C_S_RX_23, C_S_RX_4, C_S_MS_29, C_S_MS_4F,
                            C_A23_RNEG, C_A4_MOH};
    need_list(l, sizeof l / sizeof l[0]);
    need(k_cnames[C_M_4], g_cov[C_M_4]);
  }
  if (sc == 0 || sc == 5 || sc == 6) need(k_cnames[C_NOPRINT_CHG], g_cov[C_NOPRINT_CHG]);
  if (sc == 0) {
    static const int l[] = {C_T_POS_OK, C_T_POS_OVER, C_T_NONPOS, C_T_SIGNNEG, C_A1_B386, C_A1_AC17_ONLY, C_A0_NOT66, C_A4_65, C_A4_OTHER};
    need_list(l, sizeof l / sizeof l[0]);
  }
  fflush(stdout);
  return g_fail ? 2 : 0;
}
