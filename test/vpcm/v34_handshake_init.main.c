/* ---- pointer normalisation: real object, model object, the two tables ---- */
static unsigned char *g_obj, *g_snap, *g_mobj;
static uint32_t norm_val(uint32_t v) {
  uintptr_t a = (uintptr_t)v;
  if (a >= (uintptr_t)g_obj && a < (uintptr_t)g_obj + OBJSZ) return 0x80000000u | (uint32_t)(a - (uintptr_t)g_obj);
  if (a >= (uintptr_t)g_mobj && a < (uintptr_t)g_mobj + OBJSZ) return 0x80000000u | (uint32_t)(a - (uintptr_t)g_mobj);
  if (a >= (uintptr_t)c1200_ && a < (uintptr_t)c1200_ + 16) return 0x7e010000u | (uint32_t)(a - (uintptr_t)c1200_);
  if (a >= (uintptr_t)c2400_ && a < (uintptr_t)c2400_ + 16) return 0x7e020000u | (uint32_t)(a - (uintptr_t)c2400_);
  return v;
}

static const unsigned int k_slots[] = {0xaa6c, 0xaa70};
#define NSLOTS (sizeof k_slots / sizeof k_slots[0])
static unsigned char g_isslot[OBJSZ / 4];
static void slots_init(void) {
  size_t i;
  for (i = 0; i < NSLOTS; i++) g_isslot[k_slots[i] / 4] = 1;
}
static void scrub_slots(unsigned char *o) {
  size_t i;
  for (i = 0; i < NSLOTS; i++) U32(o, k_slots[i]) = 0x0d000000u | (lcg_next() & 0xffffffu);
}

/* hash of the DIFF (word index + new value) of `obj` against the pre-call snapshot, slots normalised */
static unsigned int diff_obj(const unsigned char *obj, const unsigned char *snap) {
  unsigned int h = FNV0;
  size_t i, j;
  for (i = 0; i < OBJSZ / 4; i += 16) {
    if (!memcmp(obj + 4 * i, snap + 4 * i, 64)) continue;
    for (j = i; j < i + 16; j++) {
      uint32_t a, b;
      memcpy(&a, obj + 4 * j, 4);
      memcpy(&b, snap + 4 * j, 4);
      if (g_isslot[j]) {
        a = norm_val(a);
        b = norm_val(b);
      }
      if (a != b) {
        uint32_t idx = (uint32_t)j;
        h = fnv(h, &idx, 4);
        h = fnv(h, &a, 4);
      }
    }
  }
  return h;
}

/* whole-object equality real vs model (slots normalised); on mismatch die with the first offset */
static void cmp_obj(const unsigned char *real, const unsigned char *model, const char *what) {
  size_t i;
  for (i = 0; i < OBJSZ / 4; i++) {
    uint32_t a, b;
    memcpy(&a, real + 4 * i, 4);
    memcpy(&b, model + 4 * i, 4);
    if (g_isslot[i]) {
      a = norm_val(a);
      b = norm_val(b);
    }
    if (a != b) {
      char m[200];
      snprintf(m, sizeof m, "%s: model/real object mismatch at +0x%zx real %08x model %08x", what, 4 * i, a, b);
      die(m);
    }
  }
}

/* ---- per-scenario rolling log ---- */
typedef struct {
  const char *name;
  unsigned int all;
  long calls;
  long every;
} logger_t;
static void log_call(logger_t *l, unsigned int h, long a, long b, long c) {
  l->all = fnv(l->all, &h, 4);
  if (l->calls % l->every == 0) printf("%s c=%ld a=%ld b=%ld c2=%ld hash=%08x\n", l->name, l->calls, L32(a), L32(b), L32(c), h);
  l->calls++;
}
static void log_done(logger_t *l) { printf("%s calls=%ld all=%08x\n", l->name, l->calls, l->all); }

