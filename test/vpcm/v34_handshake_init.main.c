static int g_wild;            /* scribbles may produce arbitrary 16-bit state words */
static int g_echo;

int dsplibs_debug_printf(const char *fmt, ...) {
  va_list ap;
  int len;
  if (g_rp.nl >= MAXL) die("too many prints in one call");
  va_start(ap, fmt);
  len = vsnprintf(g_rp.line[g_rp.nl], sizeof g_rp.line[0], fmt, ap);
  va_end(ap);
  V34I_SYNC_IMG(); /* callback: the port works on a shadow object */
  g_rp.ph[g_rp.nl] = diff_obj(g_obj, g_snap);
  if (g_echo) fputs(g_rp.line[g_rp.nl], stdout);
  if (g_hook_k >= 0 && g_rp.nl == g_hook_k) {
    if (g_hook_setlvl) dsplibs_debug_level = g_hook_lvl;
    if (g_hook_poke >= 0) PTR(g_obj, 0xaa6c) = g_obj + g_hook_poke;
  }
  V34I_SYNC_NAT();
  g_rp.nl++;
  return len;
}

/* ---- the scribble: deterministic, shared by the recorders and the model ---- */
static const int k_state_targets[] = {0x36, 0x2b, 0x29, 0x4a, 0x23, 0x12, 4, 0x4f};
static uint64_t xs_next(uint64_t *s) {
  uint64_t x = *s;
  x ^= x << 13;
  x ^= x >> 7;
  x ^= x << 17;
  *s = x;
  return x;
}
static void scribble(unsigned char *o, int id, unsigned int seed, int wild) {
  uint64_t s = (((uint64_t)seed << 32) | (seed ^ 0x5bd1e995u)) ^ (0x9e3779b97f4a7c15ull * (uint64_t)(id + 1));
  static const unsigned short k_so[3] = {0x3596, 0x3594, 0x3592};
  int i;
  if (id > 3) return;
  if (!s) s = 1;
  for (i = 0; i < 4; i++) xs_next(&s);
  for (i = 0; i < 3; i++) {
    unsigned int r = (unsigned int)(xs_next(&s) >> 20);
    if (r % 100 < 40) continue;
    if (r % 100 < 75) U16(o, k_so[i]) = (uint16_t)k_state_targets[(r >> 8) % 8];
    else if (wild) U16(o, k_so[i]) = (uint16_t)(xs_next(&s) >> 30);
    else U16(o, k_so[i]) = (uint16_t)((xs_next(&s) >> 30) % 87);
  }
  if (xs_next(&s) & 1) U16(o, 0x2aa2) = (uint16_t)(xs_next(&s) >> 30);
  if (xs_next(&s) & 1) U16(o, 0xaa78) = (uint16_t)(xs_next(&s) >> 30);
  if (xs_next(&s) & 1) U16(o, 0x4c6) = (uint16_t)(xs_next(&s) >> 30);
  {
    unsigned int r = (unsigned int)(xs_next(&s) >> 20) % 100;
    if (r < 25) U16(o, 0x359c) = 0x65;
    else if (r < 50) U16(o, 0x359c) = 0x66;
    else if (r < 60) U16(o, 0x359c) = (uint16_t)(xs_next(&s) >> 30);
  }
  if (xs_next(&s) & 1) U16(o, 0x386) = (uint16_t)(xs_next(&s) >> 30);
  if (xs_next(&s) & 1) U16(o, 0x25c2) = (uint16_t)(xs_next(&s) >> 30);
}

/* ---- recorders (the callees of v34handshakinit) ---- */
static int g_occ[8];
static void rec(int id, const void *a0, uint32_t a1, uint32_t a2, uint32_t a3, uint32_t a4, uint32_t a5, uint32_t a6) {
  tr_t *t;
  if (g_rt.n >= 16) die("too many callee calls");
  t = &g_rt.t[g_rt.n++];
  t->id = id;
  V34I_SYNC_IMG();
  t->a[0] = norm_val((uint32_t)(uintptr_t)V34I_IMGP(a0));
  t->a[1] = norm_val(a1);
  t->a[2] = a2;
  t->a[3] = a3;
  t->a[4] = a4;
  t->a[5] = a5;
  t->a[6] = a6;
  t->dh = diff_obj(g_obj, g_snap);
  scribble(g_obj, id, g_cseed + 0x9e3779b9u * (unsigned int)(g_occ[id]++), g_wild);
  V34I_SYNC_NAT();
}
