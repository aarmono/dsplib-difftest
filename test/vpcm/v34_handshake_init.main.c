/*
 * Differential test harness for V.34 "tier 9a" (src/vpcm/v34_handshake_init.c):
 *   v34handshakinit (2,629 B), VPcmV34SetMohMessageBits (350 B)
 *
 * One source, two binaries (same convention as test/v34/v34_probe_select.main.c):
 *   v34_tier9a_test_blob - linked against the real dsplibs.o (-DTEST_BLOB)
 *   v34_tier9a_test_port - linked against src/vpcm/v34_handshake_init.c only (+ the tier-3/4 tables)
 * Each scenario runs in its OWN process (argv[1]).
 *
 * CALLEES ARE INTERPOSED.  v34handshakinit calls five already-verified functions (v34modeminit, rxtiminginit,
 * preinitdigital, detectorinit, V34SetINFO0dBits).  In BOTH binaries those five are RECORDERS defined in this file
 * (the blob binary links a copy of dsplibs.o whose five definitions were made WEAK by objcopy, so the strong
 * recorders here win for every reference - relocations are symbol-relative).  A recorder (1) logs its arguments
 * (pointers normalised), (2) hashes the DIFF of the whole object against the pre-call snapshot (so the store-vs-call
 * ORDER of every field is compared) and (3) "scribbles" deterministic pseudo-random values over the fields the
 * caller reads AFTER the call (state words, counters, flags) - worst-case callee behaviour, which exposes any
 * cached-instead-of-re-read value.  The real callees are exercised together with the real v34handshakinit in the
 * INTEGRATED scenario (see the build script).  VPcmV34SetMohMessageBits is NOT interposed (it is part of this
 * chunk): it is the blob's own / the port's own and is also tested directly (scenario 3).
 *
 * INDEPENDENT MODEL: model_hsi()/model_moh() re-implement both functions from the disassembly facts in
 * porting/decompiled/dp/v34_handshakinit.c (byte-offset reads/writes on their own object copy, names from the extracted
 * StateName table).  After every call the model's post-state of the WHOLE object, its list of formatted debug lines,
 * the object-diff hash AT each print, and the callee trace (ids, normalised args, object-diff hash at each entry)
 * are compared with the real ones (exit 3 on any disagreement); the coverage counters come from the model.
 *
 * Objects: tagV34Object is not a struct.  A random fake object (OBJSZ = 0xb400 bytes) per call; the two pointer slots
 * the function writes (obj+0xaa6c, obj+0xaa70) are normalised to object offsets.  ORACLE: the state words obj+0x3592/
 * 0x3594/0x3596 index the 87-entry StateName table unchecked in the blob, so whenever a print can fire they are kept
 * in 0..86 (scribbles included); scenario 4 uses arbitrary 16-bit state words at levels <= 1 (no print, no table read).
 *
 * Scenarios: 0 random single calls (level 0/1), 1 random at debug levels (prints), 2 hook (level flip / reader-pointer
 * poke after the k-th print), 3 VPcmV34SetMohMessageBits direct (incl. aliased out pointer), 4 wild state words at
 * level <= 1, 5 timer field (obj+0x238/0x248) boundary sweep, 6 arm-1 flag grid, 7 persistent objects, 8 = scenario 2 with the pokes
 * outside obj+0x9100..0x9157 (T07).
 * Every scenario keeps COVERAGE COUNTERS (from the model) and exits 2 if a required class was never reached.
 */

