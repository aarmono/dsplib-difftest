/* which: 0 tx (0x3596), 1 rx (0x3594), 2 microstate (0x3592) */
static void m_state(M *m, int which, int k) {
  static const unsigned short off[3] = {0x3596, 0x3594, 0x3592};
  static const int cix[3][8] = {{0}};
  int cur = (int16_t)U16(m->o, off[which]);
  int tix = -1, i;
  (void)cix;
  for (i = 0; i < 8; i++)
    if (k_state_targets[i] == k) tix = i;
  /* covered (which,k) pairs: tx 0x36 0x4a 0x12, rx 0x2b 0x23 4, ms 0x29 0x4f */
  if (cur != k) {
    if (m->lvl > 1) {
      int c0 = -1;
      if (which == 0) c0 = (k == 0x36) ? C_P_TX_36 : (k == 0x4a) ? C_P_TX_4A : C_P_TX_12;
      if (which == 1) c0 = (k == 0x2b) ? C_P_RX_2B : (k == 0x23) ? C_P_RX_23 : C_P_RX_4;
      if (which == 2) c0 = (k == 0x29) ? C_P_MS_29 : C_P_MS_4F;
      COV(c0);
      if (which == 0)
        m_print(m, "V34HSHAKE: txstate %s=>%s(rx %s, mst %s, [1]%ld, [2]%ld)\n", mname(cur), mname(k),
                mname((int16_t)U16(m->o, 0x3594)), mname((int16_t)U16(m->o, 0x3592)), (long)(int16_t)U16(m->o, 0x2aa2),
                (long)(int16_t)U16(m->o, 0xaa78));
      else if (which == 1)
        m_print(m, "V34HSHAKE: rxstate %s=>%s(tx %s, mst %s, [1]%ld, [2]%ld)\n", mname(cur), mname(k),
                mname((int16_t)U16(m->o, 0x3596)), mname((int16_t)U16(m->o, 0x3592)), (long)(int16_t)U16(m->o, 0x2aa2),
                (long)(int16_t)U16(m->o, 0xaa78));
      else
        m_print(m, "V34HSHAKE: microstate %s=>%s(tx %s, rx %s, [1]%ld, [2]%ld)\n", mname(cur), mname(k),
                mname((int16_t)U16(m->o, 0x3596)), mname((int16_t)U16(m->o, 0x3594)), (long)(int16_t)U16(m->o, 0x2aa2),
                (long)(int16_t)U16(m->o, 0xaa78));
    } else {
      COV(C_NOPRINT_CHG);
    }
    U16(m->o, off[which]) = (uint16_t)k;
  } else if (m->lvl > 1) {
    int c0 = -1;
    if (which == 0) c0 = (k == 0x36) ? C_S_TX_36 : (k == 0x4a) ? C_S_TX_4A : C_S_TX_12;
    if (which == 1) c0 = (k == 0x2b) ? C_S_RX_2B : (k == 0x23) ? C_S_RX_23 : C_S_RX_4;
    if (which == 2) c0 = (k == 0x29) ? C_S_MS_29 : C_S_MS_4F;
    COV(c0);
  }
  (void)tix;
}

static void model_moh(M *m, unsigned char *out) {
  unsigned int idx = U32(m->o, 0xabf0);
  unsigned int hold;
  if (idx > 5) {
    COV(C_M_GT5);
    if ((idx & 7) <= 5) COV(C_M_6_BIG);
    return;
  }
  if (m->lvl > 1) COV(C_M_PRINT);
  else COV(C_M_NOPRINT);
  if (out == m->o + 0xabe0) COV(C_M_ALIAS_E0);
  if (out == m->o + 0xabfa) COV(C_M_ALIAS_FA);
  switch (idx) {
    case 0:
      COV(C_M_0);
      if (m->lvl > 1) m_print(m, "VPcmV34SetMohMessageBits: Building MHreq message...\r\n");
      U16(out, 0) = 0x33;
      break;
    case 1:
      COV(C_M_1);
      if (m->lvl > 1) m_print(m, "VPcmV34SetMohMessageBits: Building MHfrr message...\r\n");
      U16(out, 0) = 0xdd;
      break;
    case 2:
      COV(C_M_2);
      if (m->lvl > 1) m_print(m, "VPcmV34SetMohMessageBits: Building MHclrd message...\r\n");
      U16(out, 0) = 0x90;
      hold = U8(m->o, 0xabfa);
      if (hold == 0) {
        COV(C_M_2_AB0);
        if (U16(m->o, 0xabfa) != 0) COV(C_M_2_AB_WORDNZ);
        U16(out, 0) = 0x95;
      } else if (hold == 1) {
        COV(C_M_2_AB1);
        U16(out, 0) = 0x96;
      } else {
        COV(C_M_2_OTH);
        U16(out, 0) = 0x9a;
      }
      break;
    case 3:
      COV(C_M_3);
      if (m->lvl > 1) m_print(m, "VPcmV34SetMohMessageBits: Building MHcda message...\r\n");
      U16(out, 0) = 0xbb;
      break;
    case 4: {
      unsigned int sum;
      COV(C_M_4);
      if (m->lvl > 1) m_print(m, "VPcmV34SetMohMessageBits: Building MHack message...\r\n");
      U16(out, 0) = 0x50;
      sum = (unsigned int)U16(m->o, 0xabe0) + 0x50u;
      if (sum > 0xffffu) COV(C_M_4_WRAP);
      if (U16(m->o, 0xabe0) > 0x7fff) COV(C_M_4_HIGHBITS);
      U16(out, 0) = (uint16_t)sum;
      break;
    }
    default:
      COV(C_M_5);
      if (m->lvl > 1) m_print(m, "VPcmV34SetMohMessageBits: Building MHnack message...\r\n");
      U16(out, 0) = 0x77;
      break;
  }
}

static int model_hsi(M *m, unsigned int mode) {
  unsigned char *o = m->o;
  int32_t t248 = (int32_t)U32(o, 0x248);
  U32(o, 0x2218) = 0;
  if (t248 > 0) {
    uint32_t d = U32(o, 0x238) - U32(o, 0x248);
    if (d == 0x176ffu) COV(C_T_EQ);
    if (d == 0x17700u) COV(C_T_EQP1);
    if (d == 0x176feu) COV(C_T_EQM1);
    if (d >= 0x80000000u) COV(C_T_OVER_WRAP);
    if (d < 96000u) {
      COV(C_T_POS_OK);
      U32(o, 0x238) = d;
      U32(o, 0x248) = 0;
    } else {
      COV(C_T_POS_OVER);
      U32(o, 0x238) = 0;
      U32(o, 0x248) = 0xfff15a00u;
    }
  } else {
    COV(C_T_NONPOS);
    if (t248 < 0) COV(C_T_SIGNNEG);
  }
  U16(o, 0xabe6) = 0;
  U32(o, 0x244) = U32(o, 0x238);
  U32(o, 0x23c) = U32(o, 0x238) + 0x69780u;
  U8(o, 0xabe8) = 0;
  U8(o, 0xabf8) = 0;
  U16(o, 0xabe4) = 0;
  U8(o, 0xabfe) = 0;
  U8(o, 0xabff) = 0;
  U16(o, 0x25c2) &= 0x7fff;

  if (mode > 4u) {
    COV(C_MODE_GT4);
    if ((mode & 0xffu) <= 4u) COV(C_MODE_GT4_LOWOK);
    if (mode >= 0x80000000u) COV(C_MODE_HUGE);
  } else if (mode == 0) {
    COV(C_MODE0);
    m_call(m, 1, 0, 0, 0, 0, 0, 0, 0);
    m_call(m, 2, 0, 0, 0, 0, 0, 0, 0);
    m_state(m, 0, 0x36);
    m_state(m, 1, 0x2b);
    m_state(m, 2, 0x29);
    {
      uint16_t f = (uint16_t)(U16(o, 0x386) | 0x1000);
      PTR(o, 0xaa70) = o + 0xa97c;
      U16(o, 0x386) = f;
    }
    U16(o, 0xa994) = 0x11;
    U16(o, 0x25dc) = 0;
    if (U16(o, 0x359c) == 0x66) {
      COV(C_A0_66);
      if (U32(o, 0x359c) != 0x66u) COV(C_A0_66_UPPERNZ);
      m_call(m, 5, 0x80000000u | 0xa97c, 0, 0, 0, 0, 0, 0);
    } else {
      COV(C_A0_NOT66);
    }
  } else if (mode == 1) {
    COV(C_MODE1);
    if ((U8(o, 0x386) & 0x40) != 0 || U8(o, 0xac17) != 0) {
      if (U8(o, 0x386) & 0x40) COV(C_A1_B386);
      else COV(C_A1_AC17_ONLY);
      if (U8(o, 0xac17) != 0 && U8(o, 0xac16) == 0 && U8(o, 0xac18) == 0) COV(C_A1_AC17_BYTEONLY);
      if (U16(o, 0xac14) == 0xffff) COV(C_A1_AC14_WRAP);
      U8(o, 0xac17) = 0;
      U16(o, 0xac14) = (uint16_t)(U16(o, 0xac14) + 1);
    } else {
      COV(C_A1_CLEAR);
      if (U16(o, 0xac12) == 0xffff) COV(C_A1_AC12_WRAP);
      U16(o, 0xac12) = (uint16_t)(U16(o, 0xac12) + 1);
    }
    m_call(m, 1, 0, 0, 0, 0, 0, 0, 0);
    m_state(m, 0, 0x4a);
    m_state(m, 1, 0x23);
    U16(o, 0x386) = (uint16_t)(U16(o, 0x386) | 0x1000);
    U16(o, 0x39a) = U16(o, 0x4c6);
    U16(o, 0x358a) = 2;
    U16(o, 0x3588) = 2;
  } else if (mode == 2 || mode == 3) {
    COV(mode == 2 ? C_MODE2 : C_MODE3);
    m_state(m, 0, 0x12);
    m_state(m, 1, 4);
    m_state(m, 2, 0x29);
    U16(o, 0xaa20) = 0xffff;
    U16(o, 0xaa26) = 0;
    U16(o, 0xaa2a) = 0;
    U16(o, 0xaa2e) = 0;
    U16(o, 0xaa24) = 0;
    U16(o, 0xaa28) = 0;
    U16(o, 0xaa22) = 0;
    U16(o, 0xaa34) = 0;
    U16(o, 0xaa36) = 0;
    U16(o, 0xaa2c) = 0;
    U32(o, 0xaa30) = 0;
    U32(o, 0xaa38) = 0;
    U16(o, 0x25c0) = 0;
    U16(o, 0x25c6) = 0;
    U16(o, 0x25c2) = (uint16_t)((U16(o, 0x25c2) & 0xbfe7u) | 0x2000u);
    U32(o, 0x25cc) = 0;
    U16(o, 0x388) = 0x21e;
    U16(o, 0x382) = 0x8990;
    U16(o, 0x386) = (uint16_t)((U16(o, 0x386) & 0xfe27u) | 0x18u);
    U16(o, 0x2aa2) = 0;
    U16(o, 0xaa78) = 0;
    m_call(m, 3, 0, 0, 0, 0, 0, 0, 0);
    U16(o, 0x47c) = 0x400;
    U16(o, 0x386) = (uint16_t)(U16(o, 0x386) & 0xdfffu);
    if (m->lvl > 1) {
      COV(C_A23_RNEG);
      m_print(m, "V34RNEG, initialize RNEG, tx->txflags= 0x%x,rx->rxflgs= 0x%x\n", (int)(int16_t)U16(o, 0x25c2),
              (unsigned int)U16(o, 0x386));
    } else {
      COV(C_A23_NORNEG);
    }
  } else { /* mode 4 */
    unsigned char *rd;
    int lv;
    COV(C_MODE4);
    U8(o, 0xabe8) = 1;
    m_call(m, 1, 0, 0, 0, 0, 0, 0, 0);
    U16(o, 0x39a) = U16(o, 0x4c6);
    m_state(m, 0, 0x4a);
    m_state(m, 1, 0x23);
    m_state(m, 2, 0x4f);
    PTR(o, 0xaa70) = o + 0xa97c;
    U16(o, 0xa994) = 8;
    PTR(o, 0xaa6c) = o + 0xa94c;
    model_moh(m, o + 0xa94c);
    lv = m->lvl > 1;
    rd = (unsigned char *)PTR(o, 0xaa6c);
    if (rd != o + 0xa94c) COV(C_POKE_EFFECT);
    U16(rd, 0x14) = 0xffff;
    U16(rd, 0x1a) = 0;
    U16(rd, 0x1e) = 0;
    U16(rd, 0x22) = 0;
    U16(rd, 0x18) = 8;
    U16(rd, 0x1c) = 8;
    U16(rd, 0x16) = 1;
    U16(rd, 0x28) = 0xc;
    U16(rd, 0x2a) = 0xc;
    U16(rd, 0x20) = 0;
    U32(rd, 0x24) = 0xf72;
    U32(rd, 0x2c) = 0xf72;
    U16(o, 0x358c) = 0;
    if (lv) {
      COV(C_A4_MOH);
      m_print(m, "v34handshakinit: initiating MOH negotiation\n");
    } else {
      COV(C_A4_NOMOH);
    }
    {
      int is65 = U16(o, 0x359c) == 0x65;
      if (is65) {
        COV(C_A4_65);
        if (U32(o, 0x359c) != 0x65u) COV(C_A4_65_UPPERNZ);
      } else {
        COV(C_A4_OTHER);
      }
      m_call(m, 4, (uint32_t)(is65 ? 0x7e020000u : 0x7e010000u), 0, 100, 0x32, 0x800, 0, 0x3564);
    }
    U16(o, 0x356a) = 1;
    U16(o, 0x358a) = 0;
  }
  U16(o, 0xaa3c) = 0;
  U16(o, 0x2aa0) = 0x10;
  return 0;
}

/* ============================================================================
 * object generation and the driver
 * ========================================================================== */
static void gen_obj(unsigned char *o, int wild) {
  int i;
  static const unsigned short k_so[3] = {0x3596, 0x3594, 0x3592};
  fill_random(o, OBJSZ);
  scrub_slots(o);
  for (i = 0; i < 3; i++) {
    unsigned int r = lcg_mod(100);
    if (r < 45) U16(o, k_so[i]) = (uint16_t)k_state_targets[lcg_mod(8)];
    else if (wild) U16(o, k_so[i]) = (uint16_t)lcg_next();
    else U16(o, k_so[i]) = (uint16_t)lcg_mod(87);
  }
  /* timer block */
  {
    unsigned int c = lcg_mod(12);
    uint32_t a248;
    uint32_t T;
    static const uint32_t k_t[] = {0x176feu, 0x176ffu, 0x17700u, 0x17701u, 0u, 1u, 95999u, 96000u, 0xffffffffu, 0x80000000u, 0x7fffffffu, 0x69780u};
    if (c < 4) a248 = 0;
    else if (c < 6) a248 = 0x80000000u | lcg_next();
    else if (c < 7) a248 = 0x80000000u;
    else a248 = 1u + lcg_mod(0x20000);
    U32(o, 0x248) = a248;
    if (lcg_pct(60)) {
      T = k_t[lcg_mod(sizeof k_t / sizeof k_t[0])];
      U32(o, 0x238) = a248 + T;
    }
  }
  /* arm-1 flags */
  switch (lcg_mod(4)) {
    case 0: U8(o, 0xac17) = 0; break;
    case 1: U8(o, 0xac17) = 0; U8(o, 0xac16) = 0; U8(o, 0xac18) = 0; break;
    case 2: U8(o, 0xac17) = (uint8_t)(1u + lcg_mod(255)); U8(o, 0xac16) = 0; U8(o, 0xac18) = 0; break;
    default: break;
  }
  if (lcg_pct(30)) U8(o, 0x386) = (uint8_t)(U8(o, 0x386) & ~0x40u);
  if (lcg_pct(15)) U16(o, 0xac12) = 0xffff;
  if (lcg_pct(15)) U16(o, 0xac14) = 0xffff;
  /* 0x359c */
  switch (lcg_mod(6)) {
    case 0: U16(o, 0x359c) = 0x65; break;
    case 1: U16(o, 0x359c) = 0x66; break;
    case 2: U16(o, 0x359c) = 0x64; break;
    case 3: U16(o, 0x359c) = 0x67; break;
    default: break;
  }
  if (lcg_pct(25)) U16(o, 0x359e) = 0;
  /* moh inputs */
  {
    static const uint32_t k_i[] = {0, 1, 2, 3, 4, 5, 6, 7, 0x100, 0x80000000u, 0xffffffffu, 0x10002u, 0x103u};
    U32(o, 0xabf0) = lcg_pct(75) ? (uint32_t)lcg_mod(6) : k_i[lcg_mod(sizeof k_i / sizeof k_i[0])];
    switch (lcg_mod(6)) {
      case 0: U8(o, 0xabfa) = 0; break;
      case 1: U8(o, 0xabfa) = 1; break;
      case 2: U8(o, 0xabfa) = 0; U8(o, 0xabfb) = (uint8_t)(1u + lcg_mod(255)); break;
      case 3: U8(o, 0xabfa) = 1; U8(o, 0xabfb) = (uint8_t)(1u + lcg_mod(255)); break;
      default: break;
    }
    if (lcg_pct(25)) U16(o, 0xabe0) = (uint16_t)(0xffffu - lcg_mod(0x60));
  }
}

static const unsigned int k_levels[] = {0, 1, 2, 3, 0x80000000u, 0xffffffffu};
static const unsigned int k_mode_misc[] = {5, 6, 7, 0x100, 0x101, 0x102, 0x103, 0x104, 0x10004u, 0x80000000u, 0xffffffffu, 0xfffffffcu, 0x80000004u, 0xffffffffu};

static unsigned int pick_mode(void) {
  unsigned int r = lcg_mod(100);
  if (r < 14) return 0;
  if (r < 28) return 1;
  if (r < 42) return 2;
  if (r < 56) return 3;
  if (r < 72) return 4;
  if (r < 85) return k_mode_misc[lcg_mod(sizeof k_mode_misc / sizeof k_mode_misc[0])];
  return lcg_next();
}

/* one call: real vs model.  Returns the call hash. */
static unsigned int run_hsi(unsigned int mode, unsigned int level, int wild, int hook_k, int setlvl, unsigned int hook_lvl, int poke) {
  unsigned int h = FNV0, rc, i;
  M m;
  memcpy(g_snap, g_obj, OBJSZ);
  memcpy(g_mobj, g_obj, OBJSZ);
  g_cseed = lcg_next();
  g_wild = wild;
  g_hook_k = hook_k;
  g_hook_setlvl = setlvl;
  g_hook_lvl = hook_lvl;
  g_hook_poke = poke;
  /* model */
  memset(g_occ, 0, sizeof g_occ);
  g_mp.nl = 0;
  g_mt.n = 0;
  m.o = g_mobj;
  m.lvl = level;
  m.hooked = 0;
  (void)model_hsi(&m, mode);
  /* real */
  memset(g_occ, 0, sizeof g_occ);
  g_rp.nl = 0;
  g_rt.n = 0;
  dsplibs_debug_level = level;
  rc = (unsigned int)v34handshakinit(g_obj, mode);
  dsplibs_debug_level = 0;
  g_hook_k = -1;
  if (rc != 0) die("v34handshakinit returned non-zero");
  /* compare */
  if (g_rp.nl != g_mp.nl) die("print count differs from the model");
  for (i = 0; i < (unsigned)g_rp.nl; i++) {
    if (strcmp(g_rp.line[i], g_mp.line[i])) {
      fprintf(stderr, "real : %smodel: %s", g_rp.line[i], g_mp.line[i]);
      die("print line differs from the model");
    }
    if (g_rp.ph[i] != g_mp.ph[i]) die("object state at a print differs from the model");
  }
  if (g_rt.n != g_mt.n) die("callee count differs from the model");
  for (i = 0; i < (unsigned)g_rt.n; i++)
    if (memcmp(&g_rt.t[i], &g_mt.t[i], sizeof(tr_t))) {
      fprintf(stderr, "callee %d: id real %d model %d\n", (int)i, g_rt.t[i].id, g_mt.t[i].id);
      die("callee trace differs from the model");
    }
  cmp_obj(g_obj, g_mobj, "v34handshakinit");
  /* the call hash */
  h = fnv(h, &rc, 4);
  h = fnv(h, &(unsigned int){diff_obj(g_obj, g_snap)}, 4);
  for (i = 0; i < (unsigned)g_rp.nl; i++) {
    h = fnv(h, g_rp.line[i], strlen(g_rp.line[i]));
    h = fnv(h, &g_rp.ph[i], 4);
  }
  for (i = 0; i < (unsigned)g_rt.n; i++) h = fnv(h, &g_rt.t[i], sizeof(tr_t));
  return h;
}

static unsigned int run_moh(unsigned int level, unsigned char *outoff_real, unsigned char *outoff_model, int outoff) {
  unsigned int h = FNV0, i;
  M m;
  (void)outoff_real;
  (void)outoff_model;
  memcpy(g_snap, g_obj, OBJSZ);
  memcpy(g_mobj, g_obj, OBJSZ);
  g_hook_k = -1;
  m.o = g_mobj;
  m.lvl = level;
  g_mp.nl = 0;
  model_moh(&m, g_mobj + outoff);
  g_rp.nl = 0;
  dsplibs_debug_level = level;
  VPcmV34SetMohMessageBits(g_obj, g_obj + outoff);
  dsplibs_debug_level = 0;
  if (g_rp.nl != g_mp.nl) die("moh: print count differs from the model");
  for (i = 0; i < (unsigned)g_rp.nl; i++) {
    if (strcmp(g_rp.line[i], g_mp.line[i])) die("moh: print line differs from the model");
    if (g_rp.ph[i] != g_mp.ph[i]) die("moh: object state at a print differs from the model");
  }
  cmp_obj(g_obj, g_mobj, "VPcmV34SetMohMessageBits");
  h = fnv(h, &(unsigned int){diff_obj(g_obj, g_snap)}, 4);
  for (i = 0; i < (unsigned)g_rp.nl; i++) h = fnv(h, g_rp.line[i], strlen(g_rp.line[i]));
  return h;
}

