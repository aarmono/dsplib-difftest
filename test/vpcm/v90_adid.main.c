/* float values: quiet patterns only */
static uint32_t rf_bits(void) {
  uint32_t r = h_rmod(100), sign = (h_rnd() & 1u) << 31;
  float f;
  uint32_t b;
  if (r < 50) { f = (float)((int)h_rrange(-4000, 4000)) / 128.0f; memcpy(&b, &f, 4); return b; }
  if (r < 68) { f = (float)((int)h_rrange(-3000, 3000)); memcpy(&b, &f, 4); return b; }
  if (r < 80) { f = (float)((int)h_rrange(-100000, 100000)) / 4096.0f; memcpy(&b, &f, 4); return b; }
  if (r < 84) return sign | 0x7f800000u;
  if (r < 88) return sign | 0x7fc00000u | (h_rnd() & 0x3fffffu);
  if (r < 91) return sign;
  return sign | ((uint32_t)(100 + h_rmod(60)) << 23) | (h_rnd() & 0x7fffffu);
}
static uint32_t quiet_bits(uint32_t b) { return ((b & 0x7f800000u) == 0x7f800000u && (b & 0x007fffffu)) ? (b | 0x00400000u) : b; }
static uint32_t ff(int v) { float f = (float)v; uint32_t b; memcpy(&b, &f, 4); return b; }   /* an integer as float bits (exact for |v| < 2^24) */
