/* ------------------------------------------------------------------------------------------------ scenario 1: accumulation and per-bin statistics */
/* independent model of one bin: mean / variance by DIVISION in extended precision (the blob multiplies by the extended reciprocal: the results agree to ~2^-63 relative, so the
 * variance is compared with a tolerance that covers the cancellation of sumsq / n - mean^2 and the linear value away from rounding boundaries) */
static int model_bin_check(const char *what, unsigned n, float sum, float sumsq, uint16_t lin, float var) {
  LD mean, mm, q, v, tol, got;
  long long fl;
  if (n == 0) return 0;
  mean = (LD)sum / (LD)n;
  mm = mean * mean;
  q = (LD)sumsq / (LD)n;
  v = q - mm;
  got = (LD)var;
  tol = (q < 0 ? -q : q) * 1e-17L + (v < 0 ? -v : v) * 6.5e-8L + 1e-30L;
  if (!(got == got) || !(v == v)) { if ((got == got) != (v == v)) { if (sum == sum && sumsq == sumsq && (LD)sum - (LD)sum == 0) h_die3("%s: variance NaN-ness differs", what); } }
  else if (got - v > tol || v - got > tol) h_die3("%s: variance %Lg, model %Lg (n %u sum %g sumsq %g)", what, got, v, n, (double)sum, (double)sumsq);
  /* the linear value: truncation of mean + 0.5; checked away from the boundary (and for finite, in-range means) */
  if (mean > -30000.0L && mean < 30000.0L) {
    LD t = mean + 0.5L;
    LD fr = t - (LD)(long long)t;
    if (fr < 0) fr = -fr;
    if (!(fr < 1e-9L || fr > 1.0L - 1e-9L)) {
      fl = (long long)t;
      if ((int16_t)lin != (int16_t)fl) h_die3("%s: linear value %d, model %lld (mean %Lg)", what, (int)(int16_t)lin, fl, mean);
    }
  }
  return 1;
}

