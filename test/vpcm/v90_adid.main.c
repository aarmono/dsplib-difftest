/* ---- scenario 12: porcessSecondStudy ---- */
static void dbg_lin(const char *tag, const AdidObj *o) {
  int i;
  fprintf(stderr, "== %s unsusp=%d susp=%d%d%d%d%d%d alt=%d%d%d%d%d%d\n", tag, (int)(int16_t)o->unsuspectedPhase_, o->suspectedPhase_[0] != 0, o->suspectedPhase_[1] != 0, o->suspectedPhase_[2] != 0, o->suspectedPhase_[3] != 0,
          o->suspectedPhase_[4] != 0, o->suspectedPhase_[5] != 0, o->altRbsPhase_[0] != 0, o->altRbsPhase_[1] != 0, o->altRbsPhase_[2] != 0, o->altRbsPhase_[3] != 0, o->altRbsPhase_[4] != 0, o->altRbsPhase_[5] != 0);
  for (i = 0; i < 768; i++) fprintf(stderr, "%d%s", (int)(int16_t)o->linearMapping_[i], (i % 16 == 15) ? "\n" : " ");
}
static void sc_pss(void) {
  unsigned trial;
  h_cov_define(C18_PSS, "porcessSecondStudy"); h_cov_define(C18_PSS_UNS0, "porcessSecondStudy: unsuspected phase 0"); h_cov_define(C18_PSS_UNSN, "porcessSecondStudy: unsuspected phase > 0"); h_cov_define(C18_PSS_ACCEPT, "porcessSecondStudy: a value replaced");
  h_cov_define(C18_PSS_LV2, "porcessSecondStudy at level > 1");
  h_scenario_begin(1);
  relax_reserved();
  log_snap_mode(61);
  for (trial = 0; trial < 1500; trial++) {
    V90ParObj *p = par_new();
    AdidObj *o = ad_new_raw(p, 0), pre;
    unsigned lvl = pick_level(), hookk = 0, hooklvl = 0;
    int ph, u, mode = (int)h_rmod(4);
    gen_dil_state(o, 0);
    for (ph = 0; ph < 6; ph++) {
      o->suspectedPhase_[ph] = (uint8_t)(h_rpct(55) ? 1 + h_rmod(3) : 0);
      if (mode == 0) o->suspectedPhase_[ph] = (uint8_t)(h_rpct(30) ? 1 : 0);
    }
    if (h_rpct(8)) for (ph = 0; ph < 6; ph++) o->suspectedPhase_[ph] = 1;      /* all suspected: the unsuspected phase is 5 */
    /* linear values: the unsuspected phase has a ladder, the others are near it (a clear nearest candidate) or ambiguous */
    {
      int us = 0, k;
      for (k = 0; k < 6; k++) if (o->suspectedPhase_[0] && o->suspectedPhase_[k] == 0) { us = k; break; }
      for (u = 0; u < 128; u++) {
        int ladder = (u < 16) ? u * 8 : 128 + (u - 16) * 60, step = ladder < 100 ? 8 : 60;
        o->linearMapping_[us * 128 + u] = (uint16_t)ladder;
        for (ph = 0; ph < 6; ph++) {
          int r2 = (int)h_rmod(100);
          if (ph == us) continue;
          if (r2 < 40) o->linearMapping_[ph * 128 + u] = (uint16_t)(ladder + (int)h_rrange(-step / 4, step / 4));
          else if (r2 < 55) o->linearMapping_[ph * 128 + u] = (uint16_t)ladder;
          else if (r2 < 75) o->linearMapping_[ph * 128 + u] = (uint16_t)(ladder + step / 2 + (int)h_rrange(-1, 1));
          else if (r2 < 85) o->linearMapping_[ph * 128 + u] = (uint16_t)(h_rpct(50) ? ladder - 2 * step : ladder + 2 * step);
          else o->linearMapping_[ph * 128 + u] = (uint16_t)h_rrange(-32768, 32767);
        }
      }
    }
    if (lvl < 2u && h_rpct(50)) lvl = 2u;
    if (h_rpct(10)) { hookk = h_rpct(70) ? 1 + h_rmod(3) : 1 + h_rmod(40); hooklvl = h_rpct(60) ? 0u : 1u; }
    memcpy(&pre, o, sizeof pre);
    g_snap_o = o;
    log_begin();
    dsplibs_debug_level = lvl;
    g_hook_k = hookk; g_hook_level = hooklvl;
    if (getenv("ADID_TRIAL") && (unsigned)atoi(getenv("ADID_TRIAL")) == trial) dbg_lin("pre", o);
    ad_secondStudy(o);
    if (getenv("ADID_TRIAL") && (unsigned)atoi(getenv("ADID_TRIAL")) == trial) dbg_lin("post", o);
    g_hook_k = 0;
    h_cov_hit(C18_PSS);
    if (o->unsuspectedPhase_ == 0) h_cov_hit(C18_PSS_UNS0); else h_cov_hit(C18_PSS_UNSN);
    if (lvl > 1u && !hookk) h_cov_hit(C18_PSS_LV2);
    { int changed = 0; for (u = 0; u < 768; u++) if (pre.linearMapping_[u] != o->linearMapping_[u]) changed = 1; if (changed) h_cov_hit(C18_PSS_ACCEPT); }
    { char ex[200], buf[200]; snprintf(buf, sizeof buf, "V90AutoDigitalImpDetector: unSuspectedPhase = %d\r\n", (int)(int16_t)o->unsuspectedPhase_); ex[0] = 0; esc_cat(ex, sizeof ex, buf);
      if (g_nlog < 1 || strcmp(g_log[0].text, ex)) h_die3("porcessSecondStudy first print '%s'", g_nlog ? g_log[0].text : "(none)"); }
    h_emit(0, "pss nlog %u", g_nlog);
    ad_dump_s("pss", o);
    snap_clear();
    h_trial_end("pss");
  }
  log_snap_mode(1);
}

