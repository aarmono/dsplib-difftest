/* an expectation list for the prints of one call */
typedef struct { char kind; char text[400]; } ExpEnt;
static ExpEnt g_ex[64];
static unsigned g_nex;
static void ex_begin(void) { g_nex = 0; }
static void ex_add(char kind, const char *fmt, ...) {
  va_list ap;
  char buf[500];
  va_start(ap, fmt);
  vsnprintf(buf, sizeof buf, fmt, ap);
  va_end(ap);
  if (g_nex < 64) { g_ex[g_nex].kind = kind; g_ex[g_nex].text[0] = 0; esc_cat(g_ex[g_nex].text, sizeof g_ex[g_nex].text, buf); }
  g_nex++;
}
static void ex_check(const char *what) {
  unsigned i;
  if (g_nlog != g_nex) h_die3("%s: %u prints, expected %u", what, g_nlog, g_nex);
  for (i = 0; i < g_nex && i < 64 && i < LOGMAX; i++)
    if (g_log[i].kind != g_ex[i].kind || strcmp(g_log[i].text, g_ex[i].text)) h_die3("%s: print %u is %c '%s', expected %c '%s'", what, i, g_log[i].kind, g_log[i].text, g_ex[i].kind, g_ex[i].text);
}
/* split of a float into the "%c%d.%0Nd" arguments, written with long long conversions (independent of the port's helper) */
static void model_split(LD v, LD scale, int *sign, int *ip, int *fp) {
  int t = to_i32(v), f;
  long long fl;
  LD av = v < 0 ? -v : v, frac = v - (LD)t, sc = frac * scale;
  if (v != v) av = v;
  *sign = (v > 0.0L || v != v) ? '+' : '-';
  *ip = to_i32(av);
  f = to_i32(sc);
  fl = f;
  if (fl < 0) fl = -fl;
  *fp = (int)fl;
  if (f == (int)0x80000000u) *fp = (int)0x80000000u;
}
static void ex_val(char kind, const char *fmt, LD v, LD scale) {
  int s, ip, fp;
  model_split(v, scale, &s, &ip, &fp);
  ex_add(kind, fmt, s, ip, fp);
}
static float fbits(uint32_t b) { float f; memcpy(&f, &b, 4); return f; }

