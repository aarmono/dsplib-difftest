static void esc_cat(char *out, size_t cap, const char *s) {
  size_t n = strlen(out);
  for (; *s && n + 6 < cap; s++) {
    if (*s == '\r') { out[n++] = '\\'; out[n++] = 'r'; }
    else if (*s == '\n') { out[n++] = '\\'; out[n++] = 'n'; }
    else out[n++] = *s;
  }
  out[n] = 0;
}
static void snapshot(void) {
  if (g_snap_o && g_snap_mod) {
    unsigned k = g_nlog - 1;   /* index of the print just recorded */
    if (g_snap_mod == 1 || k < 3 || k % g_snap_mod == 0) ad_dump(0, "snap", g_snap_o);
  }
}
static void record(char kind, const char *fmt, va_list ap) {
  char buf[800];
  if (strstr(fmt, "trn1Sigma = %d")) {   /* the blob passes a DOUBLE for the %d: print its bits (a %d would read garbage that differs between i386 and x86-64) */
    double dv = va_arg(ap, double);
    uint64_t bits;
    memcpy(&bits, &dv, 8);
    snprintf(buf, sizeof buf, "%s [double %016llx]", fmt, (unsigned long long)bits);
  } else vsnprintf(buf, sizeof buf, fmt, ap);
  if (g_nlog < LOGMAX) { g_log[g_nlog].kind = kind; g_log[g_nlog].text[0] = 0; esc_cat(g_log[g_nlog].text, sizeof g_log[g_nlog].text, buf); }
  h_emit(g_show, "%cprintf %s", kind, g_nlog < LOGMAX ? g_log[g_nlog].text : "(many)");
  g_nlog++;
  snapshot();
}
void edprintf(const char *fmt, ...) {
  va_list ap;
  va_start(ap, fmt);
  record('e', fmt, ap);
  va_end(ap);
  g_nlog_total_e++;
}
int dsplibs_debug_printf(const char *fmt, ...) {
  va_list ap;
  va_start(ap, fmt);
  record('d', fmt, ap);
  va_end(ap);
  g_nlog_total_d++;
  g_nd_in_call++;
  if (g_hook_k && g_nd_in_call == g_hook_k) dsplibs_debug_level = g_hook_level;
  return 0;
}
