  h_cov_define(C_UUNS, "uniteLinMappInfoOfUnsuspectedPhases"); h_cov_define(C_UUNS_G, "uniteLinMappInfoOfUnsuspectedPhases: phases united"); h_cov_define(C_UUNS_N0, "uniteLinMappInfoOfUnsuspectedPhases: count 0 (return)");
