/* ---- scenario 7: findPadGain ---- */
static void gen_fpg_state(AdidObj *o, int regime) {
  int ph, u, steered = 0;
  gen_arrays(o, 0);
  o->unsuspectedPhase_ = (uint16_t)h_rmod(6);
  /* maxUcode_ in 3 .. 7 makes the blob's minimum search loop forever (its lower bound becomes negative): excluded; 0 .. 2 wrap the 8-bit index to 253 .. 255 (tested) */
  o->maxUcode_ = (uint8_t)(h_rpct(85) ? 0x40 + h_rmod(0x30) : h_rpct(50) ? 8 + h_rmod(0x38) : h_rpct(30) ? h_rmod(3) : 0x60 + h_rmod(0x20));
  put_f(&o->minUcodeScale_, h_rpct(50) ? 0x3e800000u : h_rpct(50) ? 0x3eb33333u : quiet_bits(rf_bits() & 0x7fffffffu));
  /* linear values: a mu-law or A-law ladder scaled by a pad gain, so that the gain search finds structure */
  {
    int a = (int)h_rmod(2);
    for (ph = 0; ph < 6; ph++) for (u = 0; u < 128; u++) {
      int code = u, lin, mul = 1 + (int)h_rmod(4), noise = h_rpct(30) ? (int)h_rrange(-6, 6) : 0;
      lin = a ? alaw2linear((code & 0x7f) ^ 0xd5) : ulaw2linear((code & 0x7f) ^ 0xff);
      lin = (int)(((long long)lin * (long long)mul * 3) / 8) + noise;
      if (regime == 1) lin = plaus_lin(u);
      o->linearMapping_[ph * 128 + u] = (uint16_t)lin;
    }
  }
  for (ph = 0; ph < 6; ph++) for (u = 0; u < 128; u++) {
    uint32_t b;
    int r = (int)h_rmod(100);
    if (r < 70) b = ff(h_rrange(0, 6000)); else if (r < 80) b = ff(h_rrange(0, 30)); else if (r < 84) b = quiet_bits(rf_bits()); else if (r < 90) b = 0; else b = ff(h_rrange(0, 2000000));
    put_f(&o->variance_[ph * 128 + u], b);
  }
  if (h_rpct(10)) o->maxUcode_ = (uint8_t)(0x3d + h_rmod(5));            /* around the 0x3f limit of the projection loop */
  if (h_rpct(6)) for (ph = 0; ph < 6; ph++) for (u = 0; u < 128; u++) o->linearMapping_[ph * 128 + u] = (uint16_t)h_rnd();   /* huge errors: the candidate fall-backs */
  if (h_rpct(25)) {   /* steer the minimum ucode of the mu-law pass to the clamp boundary (0x26 .. 0x29): the base ucode is maxUcode_ - 3 (below), the scale is searched */
    int tgt = 0x53 + (int)h_rmod(0x10), k0 = 1 + (int)h_rmod(190), k;
    int base = tgt - 3;
    int codeMu = (~(base & 0x7f)) & 0xff, lin = ulaw2linear(codeMu);
    o->maxUcode_ = (uint8_t)tgt;
    for (k = 0; k < 200; k++) {
      int kk = 1 + (k0 + k) % 199;
      float sc = (float)((LD)kk / 100.0L);
      int t = (int)((LD)lin * (LD)sc), minU;
      if (t < 0) t = -t;
      minU = (int)(uint8_t)~(uint8_t)linear2ulaw(t);
      if (minU >= 0x26 && minU <= 0x29) { memcpy(&o->minUcodeScale_, &sc, 4); break; }
    }
    for (ph = 0; ph < 6; ph++) for (u = 0; u < 128; u++) put_f(&o->variance_[ph * 128 + u], ff(100 + (int)h_rmod(5000)));
    base = (int)(uint8_t)(o->maxUcode_ - 3u);
    if ((int)o->unsuspectedPhase_ * 128 + base < 768) put_f(&o->variance_[(int)o->unsuspectedPhase_ * 128 + base], ff(1));
    steered = 1;
  }
  /* a variance below 1e8 among the five scanned entries (otherwise the winning ucode is uninitialised in the blob) */
  if (!steered) {
    int base = (int)(uint8_t)(o->maxUcode_ - 3u), vv = (int)h_rrange(0, 5000);
    if ((int)o->unsuspectedPhase_ * 128 + base < 768) put_f(&o->variance_[(int)o->unsuspectedPhase_ * 128 + base], ff(vv));
  }
}
