/* every detector object lives inside a block with canary guards before and after it (an out-of-range index of a mutant or of a port bug writes there): checked at every dump */
#define GUARD 512
static uint8_t guard_byte(const uint8_t *p, int k) { (void)p; return (uint8_t)(0xa5u ^ (uint8_t)(k * 29) ^ (uint8_t)(k >> 5)); }   /* a function of k only: porcessSecondStudy reads the words before the object (ucodes 0 and 1) */
static AdidObj *ad_alloc(void) {
  uint8_t *blk = (uint8_t *)h_obj_new(sizeof(AdidObj) + 2 * GUARD + 32);
  AdidObj *o = (AdidObj *)(blk + GUARD);
  int k;
  for (k = 0; k < GUARD; k++) { blk[k] = guard_byte(blk, k); ((uint8_t *)o)[sizeof(AdidObj) + k] = guard_byte(blk, k + GUARD); }
  return o;
}
static void ad_check_guards(const AdidObj *o) {
  const uint8_t *blk = (const uint8_t *)o - GUARD;
  int k;
  for (k = 0; k < GUARD; k++) {
    if (blk[k] != guard_byte(blk, k)) h_die3("a write before the object (guard byte %d)", k - GUARD);
    if (((const uint8_t *)o)[sizeof(AdidObj) + k] != guard_byte(blk, k + GUARD)) h_die3("a write after the object (guard byte %d)", k);
  }
}
static void fill_bytes(uint8_t *b, size_t n) {
  size_t i = 0;
  for (; i + 4 <= n; i += 4) { uint32_t w = h_rnd(); memcpy(b + i, &w, 4); }
  for (; i < n; i++) b[i] = (uint8_t)h_rnd();
}
static void quiet_floats(float *a, size_t n) {
  size_t i;
  for (i = 0; i < n; i++) { uint32_t b; memcpy(&b, &a[i], 4); b = quiet_bits(b); memcpy(&a[i], &b, 4); }
}
/* the whole object: member-wise garbage (the stream of random words is the same on i386 and x86-64: two segments of fixed byte counts around params_) */
static void ad_garbage(AdidObj *o) {
  uint8_t *b = (uint8_t *)o;
  size_t s1 = offsetof(AdidObj, unk2812_) + sizeof o->unk2812_;
  size_t e = offsetof(AdidObj, params_) + sizeof(void *);
  fill_bytes(b, s1);
  fill_bytes(b + e, sizeof(AdidObj) - e);
  o->params_ = NULL;
  quiet_floats(o->cumSum_, 768); quiet_floats(o->cumSumSq_, 768); quiet_floats(o->variance_, 768); quiet_floats(o->altSum_, 6);
  quiet_floats(&o->padGain_, 1); quiet_floats(&o->studyParam_, 1); quiet_floats(&o->trn1Sigma_, 1); quiet_floats(&o->altVarFactor_, 1); quiet_floats(&o->altVarFactor974_, 1);
  quiet_floats(&o->minUcodeScale_, 1); quiet_floats(&o->varThreshFactor_, 1); quiet_floats(&o->altVarThreshMax_, 1);
}
static AdidObj *ad_new_raw(V90ParObj *p, int c2) {
  AdidObj *o = ad_alloc();
  ad_garbage(o);
  if (c2) ad_c2(o, p); else ad_c1(o, p);
  return o;
}

