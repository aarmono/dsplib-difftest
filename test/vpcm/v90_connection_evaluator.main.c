/* ------------------------------------------------------------------------------------------------ models: the float prints */
static int to_i32(LD v) {   /* fist / fistp with truncation: the integer indefinite for NaN and out-of-range values */
  if (!(v > -2147483649.0L && v < 2147483648.0L)) return (int)0x80000000u;
  return (int)(long long)v;
}
static void model_split(LD v, LD scale, int *sign, int *ip, int *fp) {
  int t = to_i32(v), f;
  long long fl;
  LD av = v < 0 ? -v : v, frac = v - (LD)t, sc = frac * scale;
  if (v != v) av = v;   /* NaN stays NaN */
  *sign = (v > 0.0L || v != v) ? '+' : '-';
  *ip = to_i32(av);
  f = to_i32(sc);
  fl = f;
  if (fl < 0) fl = -fl;
  *fp = (int)fl;       /* abs of INT_MIN is INT_MIN (cdq; xor; sub) */
  if (f == (int)0x80000000u) *fp = (int)0x80000000u;
}
static void model_fmt_ave(char *out, size_t cap, const char *fmt, LD v, LD scale, unsigned n, int has_n) {
  int s, ip, fp;
  model_split(v, scale, &s, &ip, &fp);
  if (has_n) snprintf(out, cap, fmt, n, s, ip, fp); else snprintf(out, cap, fmt, s, ip, fp);
}
static void esc_str(char *out, size_t cap, const char *s) { out[0] = 0; esc_cat(out, cap, s); }

