/* ------------------------------------------------------------------------------------------------ the evaluate scenarios */
enum { K_P3 = 0, K_P4, K_EC };

/* a counter value near `dur - w` (the boundary of "counter + w >= dur") */
static uint32_t cnt_near(uint32_t dur, uint32_t w) {
  uint32_t r = h_rmod(100), base = dur - w;
  if (r < 20) return base;
  if (r < 35) return base - 1u;
  if (r < 50) return base + 1u;
  if (r < 58) return 0u;
  if (r < 66) return dur;
  if (r < 80) return h_rmod(dur + 3u);
  return h_rmod(120);
}
static uint32_t ave_bits(void) {
  uint32_t r = h_rmod(100);
  float f;
  if (r < 70) { f = (float)((int)h_rrange(-80, 800)) / 16.0f; uint32_t b; memcpy(&b, &f, 4); return b; }
  if (r < 85) { f = (float)((int)h_rrange(-3, 40)); uint32_t b; memcpy(&b, &f, 4); return b; }
  return rf_bits();
}

/* random state of the evaluator and the parameter block for one call */
static void gen_state(EvObj *o, V90ParObj *p, int kind, int hl) {
  uint32_t w = h_rpct(4) ? 0u : (uint32_t)(1 + h_rmod(h_rpct(15) ? 400 : 40)), ab = ave_bits();
  uint32_t ec_;
  unsigned c;
  o->weight_ = w;
  memcpy(&o->avePdsnr_, &ab, 4);
  /* thresholds around the average */
  put_f(&o->threshUp_, thr_near(ab)); put_f(&o->threshDown_, thr_near(ab)); put_f(&o->threshRetrain_, thr_near(ab));
  put_f(&p->pdsnrThresholdInPhase3, thr_near(ab)); put_f(&p->pdsnrThresholdInPhase4, thr_near(ab)); put_f(&p->trn1dErrorForV34Fallback, thr_near(ab));
  put_f(&p->phase3ErrorForV34Fallback, thr_near(ab)); put_f(&o->pdsnrV34DropThreshPhase4_, thr_near(ab));
  put_f(&p->unk434, h_rpct(50) ? thr_near(ab) : rf_bits());
  put_f(&p->phase4MeanErrorBefToAftUpdateRatioThresh, thr_near(ab));
  put_f(&p->rrnSilenceMinEchoEnergyForKeepRate, h_rnd() & 0x7fffffffu);
  /* limits and durations (copies in the object) */
  p->maxNofV90Retrains = (int32_t)h_rmod(5);
  p->maxNofRemoteRetrains = (int32_t)h_rmod(5);
  p->maxNofRatesDiffBeforeRetrain = (int32_t)(h_rpct(60) ? h_rmod(10) : h_rnd());
  p->unk45c = (int32_t)h_rmod(6);
  p->highLevelTxActive = hl < 0 ? (int32_t)h_rpct(50) : hl;
  p->rrnSilenceRequested = (int32_t)(h_rpct(60) ? h_rmod(2) : h_rnd());
  o->params_ = p;
  o->rateUpDetectDuration_ = h_rmod(50); o->minDurationInDataBeforeRrnUp_ = h_rmod(80);
  o->rateDownDetectDuration_ = h_rpct(25) ? h_rmod(16) : h_rmod(90);
  o->minDurationInDataBeforeRrnDown_ = h_rpct(8) ? h_rmod(4) : h_rpct(30) ? h_rmod(40) : h_rmod(100);
  o->retrainDetectDuration_ = h_rmod(60);
  o->largeErrorDuration_ = h_rpct(20) ? 1600u : h_rmod(60);
  o->largeErrorDurationPhase4_ = h_rpct(20) ? 1600u : h_rmod(60);
  o->retrainCounterFadeCount_ = 1 + h_rmod(h_rpct(25) ? 3 : 50);
  o->remoteRrnCounterFadeCount_ = 1 + h_rmod(h_rpct(25) ? 3 : 50);
  o->nofRemoteRateRenegBeforeRetrain_ = 1 + h_rmod(5);
  o->debugPeriod_ = (int32_t)(h_rpct(8) ? h_rrange(-3, 3) : h_rrange(0, 40));
  /* counters near their boundaries */
  o->rateUpCounter_ = cnt_near(o->rateUpDetectDuration_, w);
  o->rateDownCounter_ = cnt_near(o->rateDownDetectDuration_, w);
  o->retrainCounter_ = cnt_near(o->retrainDetectDuration_, w);
  if (kind == K_P3) o->rateUpCounter_ = cnt_near(o->largeErrorDuration_, w);
  if (kind == K_P4) o->rateUpCounter_ = cnt_near(o->largeErrorDurationPhase4_, w);
  if (h_rpct(40)) { /* the echo-RRN thresholds d58 / 3 and d58 / 5 of the rate-down counter */
    uint32_t dd = o->rateDownDetectDuration_ / (h_rpct(50) ? 3u : 5u);
    o->rateDownCounter_ = dd - w + h_rmod(3) - 1u;
  }
  c = h_rmod(100);
  ec_ = c < 25 ? o->minDurationInDataBeforeRrnUp_ : c < 45 ? o->minDurationInDataBeforeRrnDown_ : c < 55 ? (o->minDurationInDataBeforeRrnDown_ * 23u / 10u) :
        c < 63 ? (o->minDurationInDataBeforeRrnDown_ * 13u / 10u) : c < 71 ? (o->minDurationInDataBeforeRrnDown_ * 6u / 10u) : h_rmod(150);
  if (h_rpct(40)) ec_ += h_rmod(3) - 1u;
  if (h_rpct(4)) ec_ = 0xffffff00u + h_rmod(0x100);   /* counters with the top bit set: signed / unsigned compares */
  o->evaluatorCounter_ = ec_;
  if (h_rpct(6)) { static const int32_t big[] = { -1, 0x7fffffff, (int32_t)0x80000000, -2 }; p->maxNofV90Retrains = big[h_rmod(4)]; }
  o->nofRetrainsSoFar_ = (uint32_t)((int)(unsigned)p->maxNofV90Retrains + (int)h_rrange(-2, 2));
  if (h_rpct(10)) o->nofRetrainsSoFar_ = (uint32_t)p->unk45c + h_rmod(3) - 1u;
  o->nofRateRenegSoFar_ = o->nofRemoteRateRenegBeforeRetrain_ + h_rmod(3) - 1u;
  if (h_rpct(10)) o->nofRateRenegSoFar_ = 0;
  if (h_rpct(4)) o->nofRateRenegSoFar_ = 0xfffffff0u + h_rmod(16);
  o->nofRemoteRetrainsSoFar_ = h_rpct(50) ? 0u : h_rmod(4);
  o->fadeCounter_ = (uint32_t)((int)(o->retrainCounterFadeCount_ * h_rmod(5)) - (int)h_rmod(w + 2));
  if (h_rpct(10)) o->fadeCounter_ = o->remoteRrnCounterFadeCount_ * h_rmod(5) - h_rmod(w + 2);
  /* flags */
  o->enableRrnUp_ = h_rpct(75); o->enableRrnDown_ = h_rpct(75); o->retrainInsteadOfRateDown_ = h_rpct(30);
  o->altRbsDetectedOnQc_ = (uint16_t)(h_rpct(25) ? (h_rpct(50) ? 1 : (int)h_rnd()) : 0);
  o->trn1dEvalActive_ = h_rpct(30) ? (h_rpct(70) ? 1 : (int32_t)h_rnd()) : 0;
  o->phase3EvalActive_ = h_rpct(60) ? 1 : 0;
  o->phase4RatioCheckEnabled_ = (uint16_t)(h_rpct(60) ? 1 : h_rpct(50) ? 0 : (int)h_rnd());
  o->delayedRetrainRequest_ = h_rpct(25) ? 1 : 0; o->delayedRetrainEnable_ = h_rpct(60) ? 1 : 0;
  o->altDebugState_ = (int32_t)(h_rpct(90) ? h_rmod(4) : h_rnd());
  o->debugAlternate_ = h_rpct(10); o->debugFallBack_ = h_rpct(8); o->debugRetrain_ = h_rpct(8); o->debugRateUp_ = h_rpct(8); o->debugRateDown_ = h_rpct(8);
  o->debugCounter_ = (int32_t)(h_rpct(50) ? (int)h_rmod(40) : (int)h_rnd());
  if (h_rpct(30)) o->debugCounter_ = (int32_t)((uint32_t)o->debugPeriod_ - w + h_rmod(3) - 1u);
  o->externalCommand_ = h_rpct(55) ? -1 : h_rpct(85) ? (int32_t)h_rmod(8) : (int32_t)(h_rpct(50) ? (int)h_rnd() : -(int)h_rmod(3));
  o->rrnSilence_ = (int32_t)h_rnd(); o->noRestrictionRrn_ = (int32_t)h_rnd();
  /* distances */
  o->initDmin_ = (uint16_t)(h_rpct(15) ? 0xffff : h_rpct(60) ? (int)h_rrange(-3, 40) : (int)h_rnd());
  o->curDmin_ = (uint16_t)(h_rpct(50) ? (int)((int16_t)o->initDmin_ * 2 + (int)h_rrange(-2, 2)) : (int)h_rrange(-3, 80));
  o->echoRrnState_ = (uint16_t)(h_rpct(75) ? (int)h_rmod(5) : h_rpct(50) ? (int)h_rnd() : 0xffff);
  put_f(&o->echoRrnFactor_, h_rpct(60) ? thr_near(0x3fc00000u) : rf_bits());
}

static unsigned run_eval(int kind, EvObj *o, V90ParObj *p, float arg, unsigned lvl, unsigned hookk, unsigned hooklvl) {
  unsigned res;
  dsplibs_debug_level = lvl;
  g_hook_k = hookk; g_hook_level = hooklvl;
  ev_hook(o, p);
  log_begin();
  if (kind == K_P3) res = ev_p3(o);
  else if (kind == K_P4) res = ev_p4(o, arg);
  else res = ev_ec(o);
  g_hook_k = 0;
  return res;
}

static void check_eval(int kind, const EvObj *pre, const EvObj *o, unsigned res, unsigned lvl) {
  unsigned i, nd = 0;
  if (pre->weight_ == 0) {
    EvObj ex;
    EXPECT_EQ("result with weight 0", res, 0);
    memcpy(&ex, pre, sizeof ex);
    if (kind == K_EC && ex.initDmin_ == 0xffff) ex.initDmin_ = ex.curDmin_;   /* evaluateConnection fixes the initial distance before it looks at the weight */
    if (g_nlog || memcmp(&ex, o, sizeof ex)) h_die3("an evaluate call with weight_ == 0 did something");
    return;
  }
  if (kind != K_EC && res != 0 && res != 4 && res != 5) h_die3("phase 3 / 4 answered %u", res);
  if (kind == K_EC && res > 5) h_die3("evaluateConnection answered %u", res);
  if (o->weight_ != 0 || bits_f(o->avePdsnr_) != 0) h_die3("the weight / average were not cleared (weight %u ave %08x)", o->weight_, bits_f(o->avePdsnr_));
  if (res == 5 && o->nofRetrainsSoFar_ != 0 && kind != K_EC) h_die3("fall back left a retrain count");
  for (i = 0; i < g_nlog && i < LOGMAX; i++) if (g_log[i].kind == 'd') nd++;
  if (nd && lvl <= 1u && !(g_hook_level)) h_die3("dsplibs_debug_printf at level %u", lvl);
  /* (the debug demands at the end of evaluateConnection may replace the answer: the message / answer rules hold without them) */
  /* (the answer of a fall-back message can be replaced later in the same call by phase 3's retrain test, phase 4's delayed retrain, evaluateConnection's remote-reneg retrain / debug demands) */
  if (kind == K_EC && !(pre->debugAlternate_ || pre->debugFallBack_ || pre->debugRetrain_ || pre->debugRateUp_ || pre->debugRateDown_) && log_has("initiating Retrain instead of One Rate Down") && res != 4)
    h_die3("retrain-instead message with the answer %u", res);
  msg_cover_log();
}

static void sc_eval(int kind, int hl, unsigned ntrials) {
  unsigned trial;
  msg_cov_define();
  h_scenario_begin(1);
  relax_reserved();
  if (kind == K_P3) msg_req(33, 38);
  else if (kind == K_P4) { msg_req(40, 45); msg_req(46, 46); msg_req(47, 48); }
  else if (hl == 0) { msg_req(4, 32); h_covreq[64 + 22] = h_covreq[64 + 32] = 0; }
  else { msg_req(22, 22); msg_req(32, 32); msg_req(59, 60); }
  for (trial = 0; trial < ntrials; trial++) {
    V90ParObj *p = par_new(0);
    EvObj *o = ev_new(p, 0), pre;
    unsigned res, lvl = pick_level(), hookk = 0, hooklvl = 0;
    float arg = 0.0f;
    gen_state(o, p, kind, hl);
    if (kind == K_P4) { uint32_t rb = thr_near(h_bits_of(p->phase4MeanErrorBefToAftUpdateRatioThresh)); memcpy(&arg, &rb, 4); if (h_rpct(20)) { rb = rf_bits(); memcpy(&arg, &rb, 4); } }
    if (h_rpct(8)) { hookk = 1 + h_rmod(2); hooklvl = h_rpct(50) ? 0u : 1u; }
    memcpy(&pre, o, sizeof pre);
    res = run_eval(kind, o, p, arg, lvl, hookk, hooklvl);
    check_eval(kind, &pre, o, res, hookk ? 2u : lvl);
    h_emit(0, "eval %d res %u", kind, res);
    ev_dump("eval", o, p);
    g_snap_o = NULL;
    h_trial_end("eval");
  }
}

/* chains: one object, realistic use (average updates and evaluations in sequence, thresholds updated, external demands) */
static void sc_chain(void) {
  unsigned trial;
  msg_cov_define();
  h_scenario_begin(1);
  relax_reserved();
  msg_req(0, 0);
  for (trial = 0; trial < 160; trial++) {
    V90ParObj *p = par_new(0);
    EvObj *o = ev_new(p, 0), pre;
    unsigned nops = 40 + h_rmod(120), op;
    int hl = (int)h_rpct(35);
    uint32_t lastave = ave_bits();
    dsplibs_debug_level = pick_level();
    gen_state(o, p, K_EC, hl);
    o->weight_ = 0;
    ev_hook(o, p);
    for (op = 0; op < nops; op++) {
      unsigned r = h_rmod(100), lvl = pick_level(), res;
      if (r < 40) { uint32_t xb = h_rpct(80) ? thr_near(lastave) : ave_bits(); float x; memcpy(&x, &xb, 4); log_begin(); dsplibs_debug_level = lvl; ev_upd(o, x, 1 + h_rmod(h_rpct(10) ? 100 : 12)); lastave = bits_f(o->avePdsnr_); }
      else if (r < 60) { memcpy(&pre, o, sizeof pre); res = run_eval(K_EC, o, p, 0.0f, lvl, 0, 0); check_eval(K_EC, &pre, o, res, lvl); h_emit(0, "chain ec %u", res); }
      else if (r < 68) { memcpy(&pre, o, sizeof pre); res = run_eval(K_P3, o, p, 0.0f, lvl, 0, 0); check_eval(K_P3, &pre, o, res, lvl); h_emit(0, "chain p3 %u", res); }
      else if (r < 76) { float a; uint32_t rb = thr_near(h_bits_of(p->phase4MeanErrorBefToAftUpdateRatioThresh)); memcpy(&a, &rb, 4); memcpy(&pre, o, sizeof pre); res = run_eval(K_P4, o, p, a, lvl, 0, 0); check_eval(K_P4, &pre, o, res, lvl); h_emit(0, "chain p4 %u", res); }
      else if (r < 84) { float u, d, rr; uint32_t ub = thr_near(lastave), db = thr_near(lastave), rb = thr_near(lastave); memcpy(&u, &ub, 4); memcpy(&d, &db, 4); memcpy(&rr, &rb, 4); log_begin(); dsplibs_debug_level = lvl; ev_ucd(o, (short)h_rrange(-3, 60), u, d, rr); }
      else if (r < 90) { o->externalCommand_ = (int32_t)h_rrange(-1, 7); }
      else if (r < 93) { log_begin(); dsplibs_debug_level = lvl; ev_irrr(o); }
      else if (r < 96) { log_begin(); dsplibs_debug_level = lvl; res = ev_ilr(o); h_emit(0, "chain ilr %u", res); }
      else if (r < 98) { log_begin(); dsplibs_debug_level = lvl; res = ev_irt(o); h_emit(0, "chain irt %u", res); }
      else { log_begin(); dsplibs_debug_level = lvl; ev_reset(o); }
      msg_cover_log();
      ev_dump("chain", o, p);
    }
    g_snap_o = NULL;
    h_trial_end("chain");
  }
}

int main(int argc, char **argv) {
  int sc = argc > 1 ? atoi(argv[1]) : 0;
  const char *seed = getenv("P17_SEED");
  if (seed) h_seed_xor((unsigned int)strtoul(seed, NULL, 0));
  if (getenv("P17_DBG")) g_show = 1;
  p07_layout_check();
  p17_layout_check();
  h_x87_check();
  h_arena_init();
  switch (sc) {
    case 0: msg_cov_define(); msg_req(0, 1); sc_ctor(); break;
    case 1: msg_cov_define(); msg_req(2, 3); msg_req(21, 21); msg_req(39, 39); msg_req(49, 58); sc_misc(); break;
    case 2: sc_eval(K_P3, -1, 6000); break;
    case 3: sc_eval(K_P4, -1, 6000); break;
    case 4: sc_eval(K_EC, 0, 12000); break;
    case 5: sc_eval(K_EC, 1, 12000); break;
    case 6: sc_chain(); break;
    default: fprintf(stderr, "unknown scenario %d\n", sc); return 2;
  }
  h_emit(1, "calls: malloc %lu free %lu edprintf %u dbgprintf %u", h_nmalloc, h_nfree, g_nlog_total_e, g_nlog_total_d);
  h_cov_finish();
  return 0;
}
