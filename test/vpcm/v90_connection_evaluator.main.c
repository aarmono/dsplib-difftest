static void expect_log(const char *what, unsigned idx, char kind, const char *text) {
  if (idx >= g_nlog) h_die3("%s: print %u missing (have %u)", what, idx, g_nlog);
  if (g_log[idx].kind != kind || strcmp(g_log[idx].text, text)) h_die3("%s: print %u is %c '%s', expected %c '%s'", what, idx, g_log[idx].kind, g_log[idx].text, kind, text);
}
static void model_upd(EvObj *e, uint32_t xb, unsigned w) {
  float x;
  memcpy(&x, &xb, 4);
  if (e->weight_ == 0) { memcpy(&e->avePdsnr_, &xb, 4); e->weight_ = w; return; }
  {
    unsigned n = e->weight_, cnt = n + w;
    float av = e->avePdsnr_;
    volatile float res;
    LD sum = (LD)w * (LD)x + (LD)n * (LD)av;   /* the same operand pair order as the blob's fmulp / faddp (commutative) */
    e->weight_ = cnt;
    res = (float)(sum / (LD)cnt);
    e->avePdsnr_ = res;
  }
}

