/* float values: quiet patterns only (finite regimes, zeros, infinities, quiet NaNs) */
static uint32_t rf_bits(void) {
  uint32_t r = h_rmod(100), sign = (h_rnd() & 1u) << 31;
  float f;
  if (r < 55) { f = (float)((int)h_rrange(-4000, 4000)) / 128.0f; uint32_t b; memcpy(&b, &f, 4); return b; }
  if (r < 70) { f = (float)((int)h_rrange(-100, 100)); uint32_t b; memcpy(&b, &f, 4); return b; }
  if (r < 80) { f = (float)((int)h_rrange(-100000, 100000)) / 4096.0f; uint32_t b; memcpy(&b, &f, 4); return b; }
  if (r < 86) return sign | 0x7f800000u;
  if (r < 92) return sign | 0x7fc00000u | (h_rnd() & 0x3fffffu);
  if (r < 96) return sign;
  return sign | ((uint32_t)(100 + h_rmod(60)) << 23) | (h_rnd() & 0x7fffffu);
}
/* a threshold relative to a reference value: equal, one ulp up / down, +- small steps, random */
static uint32_t thr_near(uint32_t ref) {
  uint32_t r = h_rmod(100);
  float x, y;
  memcpy(&x, &ref, 4);
  if (is_nan_f(ref) || (ref & 0x7f800000u) == 0x7f800000u) return rf_bits();
  if (r < 25) return ref;
  if (r < 35) return ref + 1u;
  if (r < 45) return ref - 1u;
  if (r < 60) { y = x + 0.5f; uint32_t b; memcpy(&b, &y, 4); return b; }
  if (r < 75) { y = x - 0.5f; uint32_t b; memcpy(&b, &y, 4); return b; }
  if (r < 80) { y = -x; uint32_t b; memcpy(&b, &y, 4); return b; }
  return rf_bits();
}

