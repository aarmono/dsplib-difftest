/*
 * Differential test harness for port chunk P21 (src/vpcm/v90_spectral_shaper.cpp): classes V90SpectralVerifier (14 functions) and V90SpectralShaper (10 functions) of dsplibs.o.
 *
 * ONE C source, no #ifdef, built by test/vpcm/v90_spectral_shaper.sh against the blob (dsplibs.o with `edprintf` WEAK so that the recorder below wins), against the port (-O0 / -O2: the
 * port file under test + the port files of P01 (differential encoders), P03 (Psd) and P06 (V90SpectralShapingFilter), cached objects) and for x86-64 (the 64-bit run is diffed against
 * the 32-bit BLOB's output = the golden test/golden/vpcm/v90_spectral_shaper.blob32.out; -mfpmath=387 variant in test/vpcm/v90_spectral_shaper.golden64.sh).  The functions are reached through __asm__ labels; the objects and
 * the V90Parameters block are the C mirrors generated by tools/layout_gen.py (v90_spectral_shaper.layout, pcm_parameters.layout, p03.layout, pcm_leaf_classes.layout); objects are filled MEMBER-WISE (sizes and offsets
 * differ on x86-64; the random stream must not depend on sizeof).
 *
 * What is compared: every return value, the whole object after every call (field-wise, floats as bit patterns, heap blocks followed), the heap Psd of the verifier, every
 * edprintf / dsplibs_debug_printf call (kind, text, and a SNAPSHOT of the verifier at the moment of the call: the store order between prints), the unsigned `level > 1` test of
 * the one dsplibs_debug_printf site, the malloc log (sizes, order, leaks), the store order of the constructors (malloc-time snapshot), the two tables (bytes of the blob's
 * `actionLookupTable` / `pow10Table` against an embedded copy).  INDEPENDENT MODELS (not copies of the port; written from the disassembly facts with long long conversions and
 * explicit extended arithmetic): the bin arithmetic, the float -> "%c%d.%02d" splitting of every print of printSpectrum / checkSpecialSpectralConditions with the text expected
 * for each (flag, message) pair, the accumulation state machine, the whole trellis (candidate enumeration over the table digits, an independent extended-precision model of the
 * V90SpectralShapingFilter recursion, the best-metric selection with float rounding, the committed sign action) and process() (differential encoders, sign decisions, delay line,
 * output, shift).
 *
 * Excluded because the BLOB itself is undefined there: spectrum bins outside the heap block beyond its red zone (and negative bin numbers: the i386 index wraps), a shaper with
 * spf_ == 0 or depth_ > 3 (loop counts of 2^32 / table reads beyond the 512 B), advanceTrellis without a candidate below 1e38 or with a leading code digit outside 1 .. 4 (a stack
 * slot the blob never writes), signalling-NaN floats (the blob's fst / fld quiet them, a word copy may not).
 */

