/* ------------------------------------------------------------------------------------------------ scenario 0: constructors, reset, start, bins, accessors */
static void sc_sv_basic(void) {
  unsigned trial;
  h_cov_define(C_TRIAL, "trials"); h_cov_define(C_C2, "C2 constructor"); h_cov_define(C_D2, "D2 destructor"); h_cov_define(C_DT_BUF, "dtor with buf_ NULL");
  h_cov_define(C_DT_SPEC, "dtor with spec_ NULL"); h_cov_define(C_DT_PSD, "dtor with psd_ NULL"); h_cov_define(C_START_ON, "startAccumulation enabled"); h_cov_define(C_START_OFF, "startAccumulation disabled");
  h_cov_define(C_START_ACC, "startAccumulation while accumulating"); h_cov_define(C_RESET, "reset"); h_cov_define(C_NEAREST, "freqToNearestBin"); h_cov_define(C_LEFT, "freqToLeftBin");
  h_cov_define(C_RIGHT, "freqToRightBin"); h_cov_define(C_GETBIN, "getSpectrumOfBin"); h_cov_define(C_GETNEAR, "getSpectrumOfNearestBin"); h_cov_define(C_NEAR_NAN, "bin of NaN / inf / huge (0)");
  h_cov_define(C_RES_NAN, "resolution NaN / inf (sample rate NaN / inf)");
  h_scenario_begin(1);
  relax_reserved();
  h_log_map_from = (unsigned)sizeof(PsdObj);
  h_log_map_to = 0x10;
  for (trial = 0; trial < 500; trial++) {
    Geo g;
    V90ParObj *p;
    SvObj *o, ex;
    unsigned k, i, lvl = pick_level();
    int c2 = h_rpct(25);
    h_cov_hit(C_TRIAL);
    geo_pick(&g);
    p = par_new_sv(&g, 0);
    if (h_rpct(6)) { static const uint32_t sfb[] = { 0x7fc00000u, 0x7f800000u, 0xff800000u, 0x00000000u, 0x80000000u, 0xffc00000u }; put_f(&p->spectralVerifierSampleFreq, sfb[h_rmod(6)]); h_cov_hit(C_RES_NAN); }
    dsplibs_debug_level = lvl;
    g_snap_o = NULL;
    log_begin();
    o = sv_make(p, c2);
    if (c2) h_cov_hit(C_C2);
    if (g_nlog != 0) h_die3("constructor printed");
    /* the model of the constructor */
    memset(&ex, 0, sizeof ex);
    EXPECT_EQ("params_", (uintptr_t)o->params_, (uintptr_t)p);
    EXPECT_EQ("fftLen_", o->fftLen_, g.fftLen);
    EXPECT_EQ("psdLen_", o->psdLen_, g.psdLen);
    EXPECT_EQ("sampleFreq_", bits_f(get_f(&o->sampleFreq_)), bits_f(get_f(&p->spectralVerifierSampleFreq)));
    { LD sf = (LD)get_f(&p->spectralVerifierSampleFreq);
      float want = rnd_f(sf / (LD)(unsigned long long)g.fftLen);
      EXPECT_EQ("resolution_", bits_f(get_f(&o->resolution_)), bits_f(want)); }
    EXPECT_EQ("flag_", o->flag_, 0);
    if (!o->buf_ || !o->spec_ || !o->psd_) h_die3("constructor left a NULL block");
    { HAl *a = h_find_al(o->buf_, 0); if (!a || a->size != g.psdLen * 4) h_die3("buf_ block size"); a = h_find_al(o->spec_, 0); if (!a || a->size != (g.fftLen >> 1) * 4) h_die3("spec_ block size"); }
    sv_dump("ctor", o);
    g_snap_o = o;
    /* reset: the banner and the three stores */
    if (h_rpct(60)) {
      o->fill_ = h_rnd(); o->state_ = h_rnd(); o->flag_ = h_rnd();
      log_begin(); sv_reset(o); h_cov_hit(C_RESET);
      expect_log("reset", 0, 'e', "V90SpectralVerifier: Reset\\r\\n");
      EXPECT_EQ("reset state", o->state_, 0); EXPECT_EQ("reset fill", o->fill_, 0); EXPECT_EQ("reset flag", o->flag_, 0);
      sv_dump("reset", o);
    }
    /* startAccumulation in every state, enabled / not */
    for (k = 0; k < 6; k++) {
      unsigned st = (unsigned)(h_rpct(70) ? h_rmod(3) : h_rnd());
      int en = (int)(h_rpct(60) ? 1 : (h_rpct(50) ? 0 : (int)h_rnd()));
      p->spectralVerifierEnable = en;
      o->state_ = st; o->fill_ = h_rnd();
      { unsigned fl0 = o->fill_;
        log_begin(); sv_start(o);
        if (st == 1) { EXPECT_EQ("start (accumulating)", g_nlog, 0); EXPECT_EQ("start fill kept", o->fill_, fl0); h_cov_hit(C_START_ACC); }
        else if (en == 0) { EXPECT_EQ("start (disabled)", g_nlog, 0); EXPECT_EQ("start state kept", o->state_, st); h_cov_hit(C_START_OFF); }
        else { expect_log("start", 0, 'e', "V90SpectralVerifier: start data accumulation\\r\\n"); EXPECT_EQ("start prints", g_nlog, 1); EXPECT_EQ("start state", o->state_, 1); EXPECT_EQ("start fill", o->fill_, 0); h_cov_hit(C_START_ON); }
      }
      sv_dump("start", o);
    }
    /* the bin functions against the model: exact bin multiples, halves, below / above, negatives (above -0.5 bins only), NaN / inf / huge (bin 0) */
    spec_fill_random(o, 0);
    for (k = 0; k < 40; k++) {
      uint32_t fb;
      float f;
      LD q;
      unsigned long n1, l1, r1, want;
      uint32_t r = h_rmod(100);
      if (r < 60) f = bin_freq(&g, (int)h_rmod(g.fftLen / 2 + 3), h_rrange(-4, 4));
      else if (r < 70) f = bin_freq(&g, 0, h_rrange(-3, 3));
      else if (r < 90) { static const uint32_t sp[] = { 0x7fc00000u, 0xffc00000u, 0x7f800000u, 0xff800000u, 0x5f000000u, 0xdf000000u, 0x7f7fffffu, 0xff7fffffu, 0x5e800000u }; fb = sp[h_rmod(9)]; memcpy(&f, &fb, 4); f = f_from(fb); h_cov_hit(C_NEAR_NAN); }
      else f = bin_freq(&g, (int)h_rmod(g.fftLen / 2 + 3), 0);
      q = (LD)f / (LD)get_f(&o->resolution_);
      want = lo32_i64(q + 0.5L);
      n1 = sv_nearest(o, f); EXPECT_EQ("nearest", n1, want); h_cov_hit(C_NEAREST);
      want = lo32_i64(q);
      l1 = sv_left(o, f); EXPECT_EQ("left", l1, want); h_cov_hit(C_LEFT);
      r1 = sv_right(o, f); EXPECT_EQ("right", r1, (uint32_t)(want + 1u)); h_cov_hit(C_RIGHT);
      h_emit(0, "bins %lx %lx %lx", n1, l1, r1);
      if (n1 <= g.fftLen / 2 + 10) { /* in the block or its red zone: the accessors */
        float a = sv_getnearest(o, f), b = sv_getbin(o, n1);
        uint32_t aw = bits_f(a), bw = bits_f(b);
        h_cov_hit(C_GETNEAR); h_cov_hit(C_GETBIN);
        if (n1 < g.fftLen / 2) { float *sp = o->spec_; EXPECT_EQ("getSpectrumOfNearestBin", aw, bits_f(get_f(&sp[n1]))); EXPECT_EQ("getSpectrumOfBin", bw, bits_f(get_f(&sp[n1]))); }
        h_emit(0, "specbits %08x %08x", aw, bw);
      }
      (void)i;
    }
    sv_dump("end", o);
    g_snap_o = NULL;
    sv_free(o);
    h_trial_end("sv_basic");
    h_log_map_from = (unsigned)sizeof(PsdObj);
  }
}

/* spectrum values: regimes (quiet patterns only) */
static uint32_t spec_val(int regime) {
  uint32_t r = h_rmod(100);
  float f;
  if (regime == 1 || r < 40) { f = (float)((int)h_rrange(-4000, 4000)) / 16.0f; uint32_t b; memcpy(&b, &f, 4); return b; }                /* exact sixteenths: ties */
  if (r < 65) { f = (float)((int)h_rrange(-120000, 30000)) / 1000.0f; uint32_t b; memcpy(&b, &f, 4); return b; }                      /* dB-like */
  if (r < 75) { f = (float)((int)h_rrange(-1000, 1000)); uint32_t b; memcpy(&b, &f, 4); return b; }
  if (r < 85) return (h_rnd() & 0x80000000u) | 0x3f800000u | (h_rnd() & 0x7fffffu);
  if (r < 90) return (h_rnd() & 0x80000000u) | 0x7f800000u;                                                                              /* inf */
  if (r < 94) return (h_rnd() & 0x80000000u) | 0x7fc00000u | (h_rnd() & 0x3fffffu);                                                       /* quiet NaN */
  if (r < 97) return (h_rnd() & 0x80000000u) | ((uint32_t)(100 + h_rmod(60)) << 23) | (h_rnd() & 0x7fffffu);                             /* huge / tiny */
  return h_rnd() & 0x80000000u;
}
static void spec_fill_random(SvObj *o, int regime) {
  unsigned i, n = o->fftLen_ >> 1;
  float *sp = o->spec_;
  for (i = 0; i < n; i++) put_f(&sp[i], spec_val(regime));
}

/* ------------------------------------------------------------------------------------------------ models: printSpectrum and checkSpecialSpectralConditions */
typedef struct { char kind; char text[160]; } ExpEnt;
typedef struct { ExpEnt e[LOGMAX]; unsigned n; } ExpList;
static void exp_add(ExpList *l, char kind, const char *fmt, ...) {
  char buf[400];
  va_list ap;
  va_start(ap, fmt);
  vsnprintf(buf, sizeof buf, fmt, ap);
  va_end(ap);
  if (l->n < LOGMAX) { l->e[l->n].kind = kind; l->e[l->n].text[0] = 0; esc_cat(l->e[l->n].text, sizeof l->e[l->n].text, buf); }
  l->n++;
}
static void exp_check(const char *what, const ExpList *l, unsigned base) {
  unsigned i;
  if (g_nlog != base + l->n) h_die3("%s: %u prints, expected %u", what, g_nlog - base, l->n);
  for (i = 0; i < l->n && i + base < LOGMAX; i++)
    if (g_log[base + i].kind != l->e[i].kind || strcmp(g_log[base + i].text, l->e[i].text)) h_die3("%s: print #%u is %c '%s', expected %c '%s'", what, i, g_log[base + i].kind, g_log[base + i].text, l->e[i].kind, l->e[i].text);
}
static const char *BAR = "--------------------------------------------------------\r\n";

static void model_print_spectrum(const SvObj *o, ExpList *l) {
  unsigned i, n = o->fftLen_ >> 1;
  LD res = (LD)get_f(&o->resolution_);
  exp_add(l, 'e', "%s", BAR);
  for (i = 0; i < n; i++) {
    LD v = (LD)get_f(&((float *)o->spec_)[i]);
    int s, ip, fp, fr = to_i32((LD)i * res + 0.5L);
    model_plain(v, &s, &ip, &fp);
    exp_add(l, 'e', "V90SpectralVerifier: Spectrum[%d] = %c%d.%02d\r\n", fr, s, ip, fp);
  }
  exp_add(l, 'e', "%s", BAR);
}
/* the expected prints and the final flag of checkSpecialSpectralConditions for the object's spectrum and the parameter block */
static void model_check(const SvObj *o, const V90ParObj *p, unsigned level, unsigned *flag, ExpList *l, int *cov) {
  LD r = 1.0L / (LD)get_f(&o->resolution_);
  const float *sp = o->spec_;
  unsigned fl = 0;
  int s, ip, fp;
#define PF(m) ((LD)get_f(&p->m))
  /* ISDN */
  { uint32_t il = lo32_i64(PF(spectralVerifierIsdnLeftPeakFreq) * r + 0.5L), in = lo32_i64(PF(spectralVerifierIsdnNullFreq) * r + 0.5L), ir = lo32_i64(0.5L + r * PF(spectralVerifierIsdnRightPeakFreq));
    float spN = get_f(&sp[in]);
    LD t8 = (LD)get_f(&sp[il]) - (LD)spN; float dL = rnd_f(t8);
    LD t1 = (LD)get_f(&sp[ir]) - (LD)spN; float dR = rnd_f(t1);
    model_left(t8, dL, &s, &ip, &fp);  exp_add(l, 'e', "V90SpectralVerifier: German ISDN NT1 box: left peak delta = %c%d.%02d\r\n", s, ip, fp);
    model_right(t1, dR, &s, &ip, &fp); exp_add(l, 'e', "V90SpectralVerifier: German ISDN NT1 box: right peak delta = %c%d.%02d\r\n", s, ip, fp);
    if ((LD)dL > PF(spectralVerifierIsdnLeftPeakDelta)) { if ((LD)dR > PF(spectralVerifierIsdnRightPeakDelta)) { fl = 1; exp_add(l, 'e', "V90SpectralVerifier: German ISDN NT1 box conditions detected!\r\n"); cov[0] = 1; } else cov[3] = 1; }
    if ((LD)dL > 1e30L || (LD)dL != (LD)dL) cov[7] = 1;
    if (to_i32(t8) != to_i32((LD)dL) || to_i32(t1) != to_i32((LD)dR)) cov[8] = 1;   /* the unrounded and the rounded value truncate differently */
    if ((LD)dL == PF(spectralVerifierIsdnLeftPeakDelta) || (LD)dR == PF(spectralVerifierIsdnRightPeakDelta)) cov[6] = 1;
  }
  /* PBX */
  { uint32_t il = lo32_i64(PF(spectralVerifierGermanPbxLeftPeakFreq) * r + 0.5L), in = lo32_i64(PF(spectralVerifierGermanPbxNullFreq) * r + 0.5L), ir = lo32_i64(0.5L + r * PF(spectralVerifierGermanPbxRightPeakFreq));
    float spN = get_f(&sp[in]);
    LD t8 = (LD)get_f(&sp[il]) - (LD)spN; float dL = rnd_f(t8);
    LD t1 = (LD)get_f(&sp[ir]) - (LD)spN; float dR = rnd_f(t1);
    model_left(t8, dL, &s, &ip, &fp);  exp_add(l, 'e', "V90SpectralVerifier: German PBX: left peak delta = %c%d.%02d\r\n", s, ip, fp);
    model_right(t1, dR, &s, &ip, &fp); exp_add(l, 'e', "V90SpectralVerifier: German PBX: right peak delta = %c%d.%02d\r\n", s, ip, fp);
    if ((LD)dL > PF(spectralVerifierGermanPbxLeftPeakDelta)) { if ((LD)dR > PF(spectralVerifierGermanPbxRightPeakDelta)) { if (fl) cov[4] = 1; fl = 2; exp_add(l, 'e', "V90SpectralVerifier: German PBX conditions detected!\r\n"); cov[1] = 1; } else cov[9] = 1; }
    if ((LD)dL == PF(spectralVerifierGermanPbxLeftPeakDelta) || (LD)dR == PF(spectralVerifierGermanPbxRightPeakDelta)) cov[6] = 1;
    if (to_i32(t8) != to_i32((LD)dL) || to_i32(t1) != to_i32((LD)dR)) cov[8] = 1;
  }
  /* severe codec */
  { uint32_t iRef = lo32_i64(PF(spectralVerifierSevereCodecRefFreq) * r + 0.5L), i1 = lo32_i64(PF(spectralVerifierSevereCodecTestFreq1) * r + 0.5L), i2 = lo32_i64(0.5L + r * PF(spectralVerifierSevereCodecTestFreq2));
    float spRef = get_f(&sp[iRef]), sp1 = get_f(&sp[i1]), sp2 = get_f(&sp[i2]);
    model_plain((LD)spRef, &s, &ip, &fp); exp_add(l, 'e', "V90SpectralVerifier: Severe Codec: ref freq (%d)  = %c%d.%02d\r\n", to_i32(PF(spectralVerifierSevereCodecRefFreq)), s, ip, fp);
    model_plain((LD)sp1, &s, &ip, &fp);   exp_add(l, 'e', "V90SpectralVerifier: Severe Codec: test freq1 (%d)  = %c%d.%02d\r\n", to_i32(PF(spectralVerifierSevereCodecTestFreq1)), s, ip, fp);
    model_plain((LD)sp2, &s, &ip, &fp);   exp_add(l, 'e', "V90SpectralVerifier: Severe Codec: test freq2 (%d)  = %c%d.%02d\r\n", to_i32(PF(spectralVerifierSevereCodecTestFreq2)), s, ip, fp);
    { LD d1 = (LD)spRef - (LD)sp1, delta = PF(spectralVerifierSevereCodecDelta), d2 = (LD)spRef - (LD)sp2;
      if (!(delta >= d1)) { if (d2 > delta) { if (fl) cov[4] = 1; fl = 3; exp_add(l, 'e', "V90SpectralVerifier: Severe Codec conditions detected!\r\n"); cov[2] = 1; } else cov[5] = 1; }
      if (delta == d1 || delta == d2) cov[6] = 1; }
  }
  if (fl == 0 && level > 1u) exp_add(l, 'd', "V90SpectralVerifier: No special conditions\r\n");
  *flag = fl;
#undef PF
}
static void cov_check(const int *cov) {
  if (cov[0]) h_cov_hit(C_CHK_ISDN);
  if (cov[1]) h_cov_hit(C_CHK_PBX);
  if (cov[2]) h_cov_hit(C_CHK_SEVERE);
  if (cov[3]) h_cov_hit(C_CHK_ISDN_L_ONLY);
  if (cov[9]) h_cov_hit(C_CHK_PBX_L_ONLY);
  if (cov[5]) h_cov_hit(C_CHK_SEV_D1_ONLY);
  if (cov[4]) h_cov_hit(C_CHK_OVERWRITE);
  if (cov[6]) h_cov_hit(C_CHK_EQ);
  if (cov[8]) h_cov_hit(C_CHK_CROSS);
}

/* ------------------------------------------------------------------------------------------------ scenario 1: process (accumulation state machine, the Psd, the automatic check) */
static void data_block(float *dst, unsigned n, int kind) {
  unsigned i;
  for (i = 0; i < n; i++) {
    uint32_t b;
    if (kind == 0) { float f = (float)((int)h_rrange(-20000, 20000)) / 4.0f; memcpy(&b, &f, 4); }                                  /* noise */
    else if (kind == 1) { float f = (float)(((i * 7) % 16) - 8) * 100.0f; memcpy(&b, &f, 4); }                                       /* periodic */
    else if (kind == 2) b = 0;
    else if (kind == 3) { float f = (i & 1) ? 1000.0f : -1000.0f; memcpy(&b, &f, 4); }
    else b = h_rpct(95) ? 0x42c80000u : 0x00000000u;
    memcpy(&dst[i], &b, 4);
  }
}
static void sc_sv_process(void) {
  unsigned trial;
  h_cov_define(C_TRIAL, "trials"); h_cov_define(C_PROC_FULL, "process: block fills the buffer exactly"); h_cov_define(C_PROC_PART, "process: partial block"); h_cov_define(C_PROC_N0, "process: n == 0");
  h_cov_define(C_PROC_OVER, "process: more samples than needed"); h_cov_define(C_PROC_IDLE, "process in state 0 / 2 / other"); h_cov_define(C_PROC_READY, "process: spectrum ready (1)");
  h_cov_define(C_PROC_PRINT, "process: printSpectrum on"); h_cov_define(C_PROC_NOPRINT, "process: printSpectrum off"); h_cov_define(C_CHK_NONE, "check: no condition (flag 0)");
  h_cov_define(C_CHK_ISDN, "check: ISDN"); h_cov_define(C_CHK_PBX, "check: PBX"); h_cov_define(C_CHK_SEVERE, "check: severe codec"); h_cov_define(C_CHK_DBG_LVL, "check: debug print (level > 1)");
  h_cov_define(C_CHK_DBG_LO, "check: no debug print (level <= 1)"); h_cov_define(C_LHI, "level >= 2^31");
  h_scenario_begin(1);
  relax_reserved();
  h_log_map_from = (unsigned)sizeof(PsdObj);
  h_log_map_to = 0x10;
  for (trial = 0; trial < 220; trial++) {
    Geo g;
    V90ParObj *p;
    SvObj *o;
    float *data;
    unsigned mfill, mstate, lvl = pick_level(), calls;
    int dk = (int)h_rmod(5);
    h_cov_hit(C_TRIAL);
    geo_pick(&g);
    p = par_new_sv(&g, 1);
    p->spectralVerifierEnable = 1;
    dsplibs_debug_level = lvl;
    if (lvl >= 0x80000000u) h_cov_hit(C_LHI);
    g_snap_o = NULL;
    o = sv_make(p, h_rpct(15));
    g_snap_o = o;
    data = (float *)h_obj_new((size_t)(g.psdLen * 4 + 64) * sizeof(float));
    /* the starting state: accumulating (the normal way through startAccumulation), idle, ready or odd; sometimes the buffer is already full */
    if (h_rpct(70)) { log_begin(); sv_start(o); mstate = 1; mfill = 0; }
    else { mstate = h_rpct(50) ? h_rmod(3) : h_rnd(); mfill = 0; o->state_ = mstate; }
    o->fill_ = mfill;
    if (h_rpct(8)) { mfill = g.psdLen + (h_rpct(50) ? 0 : h_rmod(3)); o->fill_ = mfill; data_block((float *)o->buf_, g.psdLen, (int)h_rmod(5)); }   /* a buffer that is already full: finite data (the arena pattern could be NaN: payload choice differs between x87 and SSE) */
    for (calls = 0; calls < 8; calls++) {
      unsigned n, ret, room = mfill < g.psdLen ? g.psdLen - mfill : 0;
      uint32_t rr = h_rmod(100);
      ExpList ex;
      unsigned flag = 0;
      int cov[10] = { 0 };
      if (rr < 15) n = 0; else if (rr < 40) n = 1 + h_rmod(room + 2); else if (rr < 60) n = room; else if (rr < 75) n = room + 1 + h_rmod(g.psdLen); else n = 1 + h_rmod(g.psdLen);
      if (n > g.psdLen * 2) n = g.psdLen;
      data_block(data, n, dk);
      log_begin();
      ex.n = 0;
      ret = sv_process(o, data, n);
      if (mstate != 1) {   /* idle (0 / 2 / other): nothing happens */
        EXPECT_EQ("ret (idle)", ret, 0); EXPECT_EQ("prints (idle)", g_nlog, 0); EXPECT_EQ("state (idle)", o->state_, mstate); h_cov_hit(C_PROC_IDLE);
        sv_dump("idle", o);
        continue;
      }
      { unsigned take = 0, i;
        if (mfill < g.psdLen && n > 0) { take = n < g.psdLen - mfill ? n : g.psdLen - mfill; }
        for (i = 0; i < take; i++) if (memcmp((uint8_t *)o->buf_ + 4 * (mfill + i), &data[i], 4)) h_die3("buf_[%u] is not the sample", mfill + i);
        if (take) { mfill += take; EXPECT_EQ("fill_", o->fill_, mfill); }
        if (n == 0) h_cov_hit(C_PROC_N0);
      }
      if (mfill < g.psdLen) {   /* still accumulating */
        EXPECT_EQ("ret (partial)", ret, 0); EXPECT_EQ("prints (partial)", g_nlog, 0); EXPECT_EQ("state (partial)", o->state_, 1); h_cov_hit(C_PROC_PART);
        sv_dump("partial", o);
        continue;
      }
      /* the buffer is full: state 2, the Psd ran, "Ready", maybe the spectrum, then the check */
      EXPECT_EQ("ret (ready)", ret, 1); EXPECT_EQ("state (ready)", o->state_, 2);
      h_cov_hit(C_PROC_READY);
      if (n == room) h_cov_hit(C_PROC_FULL); else if (n > room) h_cov_hit(C_PROC_OVER);
      exp_add(&ex, 'e', "V90SpectralVerifier: Ready\r\n");
      if (p->spectralVerifierPrintSpectrum != 0) { model_print_spectrum(o, &ex); h_cov_hit(C_PROC_PRINT); } else h_cov_hit(C_PROC_NOPRINT);
      model_check(o, p, lvl, &flag, &ex, cov);
      exp_check("process", &ex, 0);
      EXPECT_EQ("flag after process", o->flag_, flag);
      cov_check(cov);
      if (flag == 0) { h_cov_hit(C_CHK_NONE); if (lvl > 1u) h_cov_hit(C_CHK_DBG_LVL); else h_cov_hit(C_CHK_DBG_LO); }
      sv_dump("ready", o);
      /* a process call in state 2 does nothing; startAccumulation goes back to accumulating */
      log_begin(); ret = sv_process(o, data, 3); EXPECT_EQ("ret (state 2)", ret, 0); EXPECT_EQ("prints (state 2)", g_nlog, 0); h_cov_hit(C_PROC_IDLE);
      log_begin(); sv_start(o);
      EXPECT_EQ("restart state", o->state_, 1); EXPECT_EQ("restart fill", o->fill_, 0); mfill = 0; mstate = 1;
    }
    g_snap_o = NULL;
    sv_free(o);
    h_trial_end("sv_process");
    h_log_map_from = (unsigned)sizeof(PsdObj);
  }
}

/* ------------------------------------------------------------------------------------------------ scenario 2: checkSpecialSpectralConditions on designed spectra */
static uint32_t nextf(uint32_t b, int d) { return b + (uint32_t)d; }   /* the float d ulps away (same sign, no wrap cases used) */
static void put_i(float *dst, int v) { float f = (float)v; memcpy(dst, &f, 4); }
/* writes the spectrum values of the three frequency triples so that the deltas land on / around the thresholds, in three flavours:
 * 0 ties (sixteenths), 1 the unrounded-vs-rounded integer crossing (spN = 1 + k 2^-23, integers elsewhere), 2 random with thresholds from the differences */
static void design(SvObj *o, V90ParObj *p, int flavour) {
  LD r = 1.0L / (LD)get_f(&o->resolution_);
  float *sp = o->spec_;
  unsigned nb = o->fftLen_ >> 1;
#define IDX(m) (lo32_i64((LD)get_f(&p->m) * r + 0.5L))
#define IDXR(m) (lo32_i64(0.5L + r * (LD)get_f(&p->m)))
  uint32_t il[2] = { IDX(spectralVerifierIsdnLeftPeakFreq), IDX(spectralVerifierGermanPbxLeftPeakFreq) };
  uint32_t in[2] = { IDX(spectralVerifierIsdnNullFreq), IDX(spectralVerifierGermanPbxNullFreq) };
  uint32_t ir[2] = { IDXR(spectralVerifierIsdnRightPeakFreq), IDXR(spectralVerifierGermanPbxRightPeakFreq) };
  float *thrL[2] = { &p->spectralVerifierIsdnLeftPeakDelta, &p->spectralVerifierGermanPbxLeftPeakDelta };
  float *thrR[2] = { &p->spectralVerifierIsdnRightPeakDelta, &p->spectralVerifierGermanPbxRightPeakDelta };
  unsigned k;
  for (k = 0; k < 2; k++) {
    int ok = il[k] < nb && in[k] < nb && ir[k] < nb && il[k] != in[k] && ir[k] != in[k] && il[k] != ir[k];
    if (flavour == 0) {
      int a = (int)h_rrange(-1600, 1600), dl = (int)h_rrange(-400, 400), dr = (int)h_rrange(-400, 400);
      float *s = sp;
      if (!ok) { put_f(thrL[k], bits_f(f_from(0x3f800000u))); put_f(thrR[k], bits_f(f_from(0x3f800000u))); continue; }
      { float f; f = (float)a / 16.0f; memcpy(&s[in[k]], &f, 4); f = (float)(a + dl) / 16.0f; memcpy(&s[il[k]], &f, 4); f = (float)(a + dr) / 16.0f; memcpy(&s[ir[k]], &f, 4); }
      { float t; int tl = dl + (int)h_rrange(-2, 2), tr = dr + (int)h_rrange(-2, 2); t = (float)tl / 16.0f; memcpy(thrL[k], &t, 4); t = (float)tr / 16.0f; memcpy(thrR[k], &t, 4); }
    } else if (flavour == 1) {
      int n = (int)h_rrange(-200, 200), m = (int)h_rrange(-200, 200);
      uint32_t nb2 = 0x3f800000u + (uint32_t)(2 * h_rmod(4) + 1);        /* 1 + (odd) 2^-23 */
      if (!ok) continue;
      memcpy(&sp[in[k]], &nb2, 4);
      put_i(&sp[il[k]], n);
      put_i(&sp[ir[k]], m);
      { float t = (float)(n - 1) + (h_rpct(50) ? 0.0f : 0.5f); memcpy(thrL[k], &t, 4); t = (float)(m - 1) + (h_rpct(50) ? 0.0f : 0.5f); memcpy(thrR[k], &t, 4); }
    } else {
      LD t8, t1;
      float spN, d;
      if (!ok) continue;
      spN = get_f(&sp[in[k]]);
      t8 = (LD)get_f(&sp[il[k]]) - (LD)spN; t1 = (LD)get_f(&sp[ir[k]]) - (LD)spN;
      d = rnd_f(t8); { uint32_t b = bits_f(d); if (h_rpct(60)) b = nextf(b, h_rrange(-1, 1)); memcpy(thrL[k], &b, 4); }
      d = rnd_f(t1); { uint32_t b = bits_f(d); if (h_rpct(60)) b = nextf(b, h_rrange(-1, 1)); memcpy(thrR[k], &b, 4); }
    }
  }
  /* the severe codec triple */
  { uint32_t iRef = IDX(spectralVerifierSevereCodecRefFreq), i1 = IDX(spectralVerifierSevereCodecTestFreq1), i2 = IDXR(spectralVerifierSevereCodecTestFreq2);
    if (iRef < nb && i1 < nb && i2 < nb && iRef != i1 && iRef != i2 && i1 != i2) {
      LD d1, d2;
      if (flavour == 0) { int a = (int)h_rrange(-1600, 1600), x1 = (int)h_rrange(0, 600), x2 = (int)h_rrange(0, 600);
        float f = (float)a / 16.0f; memcpy(&sp[iRef], &f, 4); f = (float)(a - x1) / 16.0f; memcpy(&sp[i1], &f, 4); f = (float)(a - x2) / 16.0f; memcpy(&sp[i2], &f, 4);
        f = (float)(h_rpct(50) ? x1 : x2) / 16.0f; { float t = f + (float)h_rrange(-1, 1) / 16.0f; memcpy(&p->spectralVerifierSevereCodecDelta, &t, 4); } }
      else if (flavour == 1) { int a = (int)h_rrange(-100, 100);
        put_i(&sp[iRef], a); put_i(&sp[i1], a - (int)h_rrange(0, 40)); put_i(&sp[i2], a - (int)h_rrange(0, 40)); put_i(&p->spectralVerifierSevereCodecDelta, (int)h_rrange(0, 40)); }
      else { d1 = (LD)get_f(&sp[iRef]) - (LD)get_f(&sp[i1]); d2 = (LD)get_f(&sp[iRef]) - (LD)get_f(&sp[i2]);
        { uint32_t b = bits_f(rnd_f(h_rpct(50) ? d1 : d2)); if (h_rpct(60)) b = nextf(b, h_rrange(-1, 1)); memcpy(&p->spectralVerifierSevereCodecDelta, &b, 4); } }
    }
  }
#undef IDX
#undef IDXR
}

/* values just below -2^31 (-(2^31 + 5.4e6 .. 2.1e7)): (v - INT_MIN) * 100 stays inside the int range for |.| >= 2^29, where abs() by `x >> 31` and by a shorter shift differ */
static uint32_t band_bits(void) {
  float f = -(2147483648.0f + 256.0f * (float)(h_rrange(21000, 82000)));
  uint32_t b;
  memcpy(&b, &f, 4);
  return b;
}
/* the spectrum at the three triples: null bins 0, peak bins in the band */
static void band_fill(SvObj *o, V90ParObj *p) {
  LD r = 1.0L / (LD)get_f(&o->resolution_);
  float *sp = (float *)o->spec_;
  unsigned nb = o->fftLen_ >> 1;
#define BIDX(m) (lo32_i64((LD)get_f(&p->m) * r + 0.5L))
  uint32_t idx[9] = { BIDX(spectralVerifierIsdnLeftPeakFreq), BIDX(spectralVerifierIsdnNullFreq), BIDX(spectralVerifierIsdnRightPeakFreq), BIDX(spectralVerifierGermanPbxLeftPeakFreq),
                      BIDX(spectralVerifierGermanPbxNullFreq), BIDX(spectralVerifierGermanPbxRightPeakFreq), BIDX(spectralVerifierSevereCodecRefFreq), BIDX(spectralVerifierSevereCodecTestFreq1),
                      lo32_i64(0.5L + r * (LD)get_f(&p->spectralVerifierSevereCodecTestFreq2)) };
  unsigned k;
  for (k = 0; k < 9; k++) if (idx[k] < nb) put_f(&sp[idx[k]], (k % 3 == 1) ? 0u : band_bits());
#undef BIDX
}

