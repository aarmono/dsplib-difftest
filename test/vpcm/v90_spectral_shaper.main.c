/* ------------------------------------------------------------------------------------------------ models: bins and the float prints */
static int to_i32(LD v) {   /* fist / fistp DWORD with truncation: the integer indefinite for NaN and out-of-range values */
  if (!(v > -2147483649.0L && v < 2147483648.0L)) return (int)0x80000000u;
  return (int)(long long)v;
}
static uint32_t lo32_i64(LD v) {   /* the low word of fistp QWORD (truncating); NaN / |v| >= 2^63: the indefinite 0x8000000000000000 */
  if (!(v > -9223372036854775809.0L && v < 9223372036854775808.0L)) return 0;
  return (uint32_t)(unsigned long long)(long long)v;
}
static int abs_i32(int v) { return v == (int)0x80000000u ? v : (v < 0 ? -v : v); }
/* "%c%d.%02d" arguments of a float printed through the plain recipe (sign, trunc |v|, |trunc((v - trunc v) * 100)|) */
static void model_plain(LD v, int *sign, int *ip, int *fp) {
  int t = to_i32(v);
  LD av = (v < 0) ? -v : v;
  if (v != v) av = v;
  *sign = (v > 0.0L || v != v) ? '+' : '-';
  *ip = to_i32(av);
  *fp = abs_i32(to_i32((v - (LD)t) * 100.0L));
}
static int model_sign(LD v) { return (v > 0.0L || v != v) ? '+' : '-'; }
/* the left delta print: t8 unrounded, d = (float)t8 */
static void model_left(LD t8, float d, int *sign, int *ip, int *fp) {
  int tl = to_i32((LD)d);
  LD a8 = (t8 < 0) ? -t8 : t8;
  if (t8 != t8) a8 = t8;
  *ip = to_i32(a8);
  *fp = abs_i32(to_i32(((LD)d - (LD)tl) * 100.0L));
  *sign = model_sign((LD)d);
}
static void model_right(LD t1, float d, int *sign, int *ip, int *fp) {
  int tt = to_i32(t1);
  LD a1 = (t1 < 0) ? -t1 : t1;
  if (t1 != t1) a1 = t1;
  *ip = to_i32(a1);
  *fp = abs_i32(to_i32(100.0L * ((LD)d - (LD)tt)));
  *sign = model_sign((LD)d);
}

