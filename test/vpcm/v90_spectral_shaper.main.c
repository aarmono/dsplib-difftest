/* ------------------------------------------------------------------------------------------------ the verifier: parameters, objects */
typedef struct { unsigned fftLen, psdLen, overlap; int window; float sf; double res; } Geo;

static float rnd_f(LD v) { volatile float f = (float)v; return f; }   /* an fst to a float slot */
static float dbl_f(double d) { volatile float f = (float)d; return f; }

/* the geometry: power-of-two FFT, a sample rate whose bin width is exact in a double / float, psdLen >= fftLen (a shorter run would divide by zero segments) */
static void geo_pick(Geo *g) {
  static const unsigned fl[] = { 4, 8, 16, 32, 64, 128, 256, 512 };
  static const float sfs[] = { 8000.0f, 9600.0f, 7200.0f, 6400.0f, 16000.0f, 4000.0f, 2400.0f, 8000.0f };
  g->fftLen = fl[h_rmod(8)];
  g->sf = sfs[h_rmod(8)];
  g->res = (double)g->sf / (double)g->fftLen;
  g->psdLen = g->fftLen + (h_rpct(30) ? 0 : h_rmod(2 * g->fftLen + 1));
  if (g->psdLen == 6) g->psdLen = 7;                                     /* a 24-byte block would be mapped by h_log_map_from */
  if (g->fftLen == 4 && g->psdLen * 4 == 24) g->psdLen = 8;
  g->overlap = h_rpct(60) ? 0 : h_rmod(g->fftLen);
  g->window = h_rpct(75) ? (int)h_rmod(4) : (int)h_rrange(-1, 9);
}
/* a frequency at (bin + jit/8) bin widths: exact */
static float bin_freq(const Geo *g, int bin, int jit) { return dbl_f(g->res * ((double)bin + (double)jit / 8.0)); }

static void par_geo(V90ParObj *p, const Geo *g) {
  p->spectralVerifierSampleFreq = g->sf;
  p->spectralVerifierFftLen = (int32_t)g->fftLen;
  p->spectralVerifierFftWindow = g->window;
  p->spectralVerifierPsdLen = (int32_t)g->psdLen;
  p->spectralVerifierPsdOverlapLen = (int32_t)g->overlap;
}
/* the detection parameters: bins of the frequencies chosen so that every bin lies in 0 .. N/2 + 3 (reads past the block end stay inside the red zone) */
static void par_cond(V90ParObj *p, const Geo *g, int wild) {
  unsigned nb = g->fftLen / 2;
  int hi = (int)nb + (h_rpct(10) ? 3 : -1);
  p->spectralVerifierEnable = h_rpct(75) ? 1 : (h_rpct(50) ? 0 : (int32_t)h_rnd());
  p->eia6SpectralVerifierEnable = (int32_t)h_rnd();
  p->spectralVerifierPrintSpectrum = h_rpct(35) ? (h_rpct(80) ? 1 : (int32_t)h_rnd()) : 0;
#define FQ(m) put_f(&p->m, bits_f(bin_freq(g, (int)h_rmod((unsigned)hi + 1), h_rrange(-4, 4))))
  FQ(spectralVerifierIsdnNullFreq); FQ(spectralVerifierIsdnLeftPeakFreq); FQ(spectralVerifierIsdnRightPeakFreq);
  FQ(spectralVerifierGermanPbxNullFreq); FQ(spectralVerifierGermanPbxLeftPeakFreq); FQ(spectralVerifierGermanPbxRightPeakFreq);
  FQ(spectralVerifierSevereCodecRefFreq); FQ(spectralVerifierSevereCodecTestFreq1); FQ(spectralVerifierSevereCodecTestFreq2);
#undef FQ
  {   /* the six thresholds (member-wise: the parameter block's pool fill is NOT the same on i386 and x86-64) */
    float *th[] = { &p->spectralVerifierIsdnLeftPeakDelta, &p->spectralVerifierIsdnRightPeakDelta, &p->spectralVerifierGermanPbxLeftPeakDelta, &p->spectralVerifierGermanPbxRightPeakDelta,
                    &p->spectralVerifierSevereCodecDelta };
    unsigned k;
    for (k = 0; k < 5; k++) {
      uint32_t r = h_rmod(100), b;
      float f;
      if (r < 60) { f = (float)((int)h_rrange(-640, 640)) / 16.0f; memcpy(&b, &f, 4); }
      else if (r < 85) { f = (float)((int)h_rrange(-20000, 20000)) / 1000.0f; memcpy(&b, &f, 4); }
      else if (r < 92) b = (h_rnd() & 0x80000000u) | 0x7f800000u;
      else if (r < 96) b = (h_rnd() & 0x80000000u) | 0x7fc00000u | (h_rnd() & 0x3fffffu);
      else b = h_rnd() & 0x80000000u;
      put_f(th[k], b);
    }
  }
  if (wild) {   /* frequencies whose bin is 0 through the integer indefinite (NaN, inf, huge) or a bin just below 0 */
    static const uint32_t spec[] = { 0x7fc00000u, 0xffc00000u, 0x7f800000u, 0xff800000u, 0x7f7fffffu, 0xff7fffffu, 0x7f000000u, 0xff000000u, 0x80000000u, 0x00000000u, 0xbc000000u };
    float *tgt[] = { &p->spectralVerifierIsdnNullFreq, &p->spectralVerifierIsdnLeftPeakFreq, &p->spectralVerifierIsdnRightPeakFreq, &p->spectralVerifierGermanPbxNullFreq,
                     &p->spectralVerifierGermanPbxLeftPeakFreq, &p->spectralVerifierGermanPbxRightPeakFreq, &p->spectralVerifierSevereCodecRefFreq,
                     &p->spectralVerifierSevereCodecTestFreq1, &p->spectralVerifierSevereCodecTestFreq2 };
    unsigned k;
    for (k = 0; k < 9; k++) if (h_rpct(12)) put_f(tgt[k], spec[h_rmod(sizeof spec / sizeof spec[0])]);
  }
}
static V90ParObj *par_new_sv(const Geo *g, int wild) {
  V90ParObj *p = (V90ParObj *)h_obj_new(sizeof(V90ParObj));
  par_geo(p, g);
  par_cond(p, g, wild);
  return p;
}
static void sv_prefill(SvObj *o) {
  memset(o, 0xa5, sizeof *o);
  o->params_ = NULL; o->psd_ = NULL; put_f(&o->sampleFreq_, h_rnd()); o->fftLen_ = h_rnd(); o->psdLen_ = h_rnd(); put_f(&o->resolution_, h_rnd()); o->buf_ = NULL; o->spec_ = NULL;
  o->fill_ = h_rnd(); o->state_ = h_rnd(); o->flag_ = h_rnd();
}
static unsigned long g_dumpctr;
static void sv_dump(const char *tag, const SvObj *o) {
  SvObj tmp;
  memcpy(&tmp, o, sizeof tmp);
  tmp.params_ = NULL;
  h_dump_obj(h_sample(&g_dumpctr, 40, 97), tag, &tmp, f_SvObj, NF_SvObj);
  if (o->psd_) h_dump_obj(0, "psd", o->psd_, f_PsdObj, NF_PsdObj);
  if (getenv("P21_PSDHEX") && o->psd_) {   /* debugging aid: the Psd's work buffer element by element */
    PsdObj *ps = (PsdObj *)o->psd_;
    unsigned i;
    for (i = 0; ps->buf_ && i <= ps->size_; i++) { uint32_t b; memcpy(&b, (uint8_t *)ps->buf_ + 4 * i, 4); fprintf(stderr, "%s psd.buf[%u]=%08x\n", tag, i, b); }
  }
}
/* a verifier built by the real constructor (C1 / C2) with the store-order probe; the heap Psd block is logged with its i386 size */
static SvObj *sv_make(V90ParObj *p, int c2) {
  SvObj *o = (SvObj *)h_obj_new(sizeof(SvObj));
  sv_prefill(o);
  if (c2) { H_CTOR_PROBE(o, f_SvObj, NF_SvObj, sizeof(SvObj), sv_c2(o, p)); }
  else { H_CTOR_PROBE(o, f_SvObj, NF_SvObj, sizeof(SvObj), sv_c1(o, p)); }
  return o;
}
static void sv_free(SvObj *o) {   /* destructor with a NULL block pointer sometimes (each of the three) */
  if (o->buf_ && h_rpct(15)) { sysdep_free(o->buf_); o->buf_ = NULL; h_cov_hit(C_DT_BUF); h_cov_hit(H_COV_DTOR_NULL); }
  if (o->spec_ && h_rpct(15)) { sysdep_free(o->spec_); o->spec_ = NULL; h_cov_hit(C_DT_SPEC); h_cov_hit(H_COV_DTOR_NULL); }
  if (o->psd_ && h_rpct(15)) { psd_d1(o->psd_); sysdep_free(o->psd_); o->psd_ = NULL; h_cov_hit(C_DT_PSD); h_cov_hit(H_COV_DTOR_NULL); }
  if (h_rpct(25)) { h_cov_hit(C_D2); sv_d2(o); } else sv_d1(o);
}
