#define LOGMAX 2200
typedef struct { char kind; char text[160]; } LogEnt;
static LogEnt g_log[LOGMAX];
static unsigned g_nlog, g_nlog_total_e, g_nlog_total_d;
static int g_show;
static SvObj *g_snap_o;       /* verifier snapshotted at every print */
static unsigned g_hook_k, g_hook_cnt;   /* after the g_hook_k-th print of the current call the verifier's params_ is replaced by g_hook_p (a block with other values): every re-read of params_ is exercised */
