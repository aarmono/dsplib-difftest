/* a targeted poke of one record: sometimes an unsupported coefficient type, then a gain index on a clamp boundary (valid for the type) */
static void poke_boundary(int codec, int rec) {
  uint32_t *w = live_table(k_db_ptr[codec]) + 17 * rec;
  static const int bt[] = { 0, 4, 5, -1, 100 };
  static const int b3[] = { 20, 21, 48, 49, 50, 51, 52, 60 }, b1[] = { 0, 28, 29, 30, 31, 32, 50, 79 };
  if (h_rpct(30)) w[14] = (uint32_t)bt[h_rmod(5)];
  if ((int)w[14] == 3) w[15] = (uint32_t)b3[h_rmod(8)]; else w[15] = (uint32_t)b1[h_rmod(8)];
}
/* random record pokes: coefficient type (also unsupported values), gain index (valid for the type), capability, a duplicated / reshuffled reference vector (ties) */
static void poke_random(int codec, int focus) {
  unsigned nr = k_nref(codec), npk = 1 + h_rmod(3), i, k;
  static const int types[] = { 0, 1, 2, 3, 1, 2, 3, 4, 5, -1, 100, 1, 2, 3 };
  uint32_t *t = live_table(k_db_ptr[codec]);
  for (i = 0; i < npk; i++) {
    unsigned rec = (focus >= 0 && h_rpct(60)) ? (unsigned)focus : h_rmod(nr + 1);
    uint32_t *w = t + 17 * rec;
    switch (h_rmod(5)) {
      case 0: w[14] = (uint32_t)types[h_rmod(sizeof types / sizeof types[0])]; if ((int)w[14] == 3 && (int)w[15] < 20) w[15] = 20 + h_rmod(31); break;
      case 1: w[15] = ((int)w[14] == 3) ? 20 + h_rmod(60) : h_rmod(80); break;
      case 2: w[16] = h_rmod(4); break;
      case 3: if (nr > 1) { unsigned r2 = h_rmod(nr); if (r2 != rec && rec < nr) for (k = 0; k < 6; k++) t[17 * r2 + 8 + k] = w[8 + k]; } break;
      default: for (k = 0; k < 6; k++) { float f = (float)((int)h_rrange(-80, 80)) / 8.0f; memcpy(&w[8 + k], &f, 4); } break;
    }
  }
}
