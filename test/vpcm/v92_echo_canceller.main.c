static int to_i32(LD v) {   /* fist / fistp DWORD with truncation: the integer indefinite for NaN and out-of-range values */
  if (!(v > -2147483649.0L && v < 2147483648.0L)) return (int)0x80000000u;
  return (int)(long long)v;
}
static int abs_i32(int v) { return v == (int)0x80000000u ? v : (v < 0 ? -v : v); }
/* "%c%d.%0Nd" arguments of a float printed without the C library */
static void model_split(LD v, LD scale, int *sign, int *ip, int *fp) {
  int t = to_i32(v);
  LD av = (v < 0) ? -v : v;
  if (v != v) av = v;
  *sign = (v > 0.0L || v != v) ? '+' : '-';
  *ip = to_i32(av);
  *fp = abs_i32(to_i32((v - (LD)t) * scale));
}

