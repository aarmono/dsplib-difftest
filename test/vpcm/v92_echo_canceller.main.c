/* the model's print context: a simulated debug level and the hook (the level drops after the g_hook_k-th dsplibs_debug_printf) */
typedef struct { unsigned lvl; unsigned nd; unsigned n; char kind[200]; char text[200][220]; } MCtx;
static void mc_add(MCtx *c, char kind, const char *fmt, va_list ap) {
  char buf[600];
  vsnprintf(buf, sizeof buf, fmt, ap);
  if (c->n < 200) { c->kind[c->n] = kind; c->text[c->n][0] = 0; esc_cat(c->text[c->n], 220, buf); }
  c->n++;
}
static void mc_ed(MCtx *c, const char *fmt, ...) { va_list ap; va_start(ap, fmt); mc_add(c, 'e', fmt, ap); va_end(ap); }
static void mc_dbg(MCtx *c, const char *fmt, ...) {
  va_list ap;
  va_start(ap, fmt);
  mc_add(c, 'd', fmt, ap);
  va_end(ap);
  c->nd++;
  if (g_hook_k && c->nd == g_hook_k) c->lvl = g_hook_level;
}
