/* ------------------------------------------------------------------------------------------------ scenario 3: process (filter, adaptation, bypass, state sequencing) against an independent model */
typedef struct {
  int state; unsigned limit, count, nCoef, nCoefM1, histLen, pos, delay;
  float beta, decay;
  float *coef, *hist;
} EcM;
static void em_setstate(EcM *m, int ns, const V92ParObj *p) {
  if (m->state == ns) return;
  if (ns == 1) { m->state = 1; m->limit = m->delay + 400; }
  else if (ns == 2) { m->state = 2; m->beta = get_f(&p->v92EchoFastBetaFactor); m->decay = get_f(&p->v92EchoFastDecayFactor); m->limit = (unsigned)p->v92EchoFastUpdateDuration; }
  else if (ns == 3) { m->state = 3; m->beta = get_f(&p->v92EchoSlowBetaFactor); m->decay = get_f(&p->v92EchoSlowDecayFactor); m->limit = (unsigned)p->v92EchoSlowUpdateDuration; }
  else if (ns == 0) { m->state = 0; m->beta = 0.0f; m->decay = 0.0f; }
  m->count = 0;
}
static LD em_dot(const EcM *m) {   /* two extended accumulators: terms 0, 2 (and a remainder) into A, terms 1, 3 into B; est = (B + A) + 0 */
  LD a = 0, b = 0;
  const float *h = m->hist + m->pos, *c = m->coef;
  unsigned k, n4 = m->nCoef & ~3u;
  for (k = 0; k < n4; k += 4) {
    a += (LD)h[k] * (LD)c[k]; b += (LD)h[k + 1] * (LD)c[k + 1]; a += (LD)h[k + 2] * (LD)c[k + 2]; b += (LD)h[k + 3] * (LD)c[k + 3];
  }
  for (; k < m->nCoef; k++) a += (LD)h[k] * (LD)c[k];
  { LD e = b + a; return e + 0.0L; }
}
static int g_em_wrap, g_design;
static void em_process(EcM *m, const float *in, float *out, unsigned n, const V92ParObj *p) {
  unsigned i, k, W = m->histLen - m->nCoefM1;
  { LD mk = (LD)out[0]; if (!(mk < 177.0L || mk > 177.0L)) { for (i = 0; i < n; i++) { memcpy(&out[i], &in[i], 4); if (m->pos + 1 == W) g_em_wrap = 1; m->pos = (m->pos + 1 == W) ? 0 : m->pos + 1; } h_cov_hit(C_PR_BYPASS); return; } }
  if (m->state == 1) {
    for (i = 0; i < n; i++) memcpy(&out[i], &in[i], 4);
    { unsigned t = n + m->pos; if (t >= W) g_em_wrap = 1; m->pos = (t >= W) ? t - W : t; }
    m->count += n;
    if (m->count >= m->limit) em_setstate(m, 2, p);
    return;
  }
  for (i = 0; i < n; i++) {
    LD est = em_dot(m), e = (LD)in[i] - est;
    out[i] = rnd_f(e);
    if (m->state != 0) {
      LD mu = e * (LD)m->beta;
      for (k = 0; k < m->nCoef; k++) m->coef[k] = rnd_f((LD)m->hist[m->pos + k] * mu + (LD)m->coef[k]);
      m->beta = rnd_f((LD)m->beta * (LD)m->decay);
    }
    if (m->pos + 1 == W) g_em_wrap = 1;
    m->pos = (m->pos + 1 == W) ? 0 : m->pos + 1;
  }
  if (m->state == 0) return;
  m->count += n;
  if (m->count >= m->limit) em_setstate(m, m->state == 2 ? 3 : 0, p);
}
