static void sc_pf_eia(void) {
  unsigned trial;
  h_cov_define(C_TRIAL, "trials"); h_cov_define(C_EIA_ZERO, "clock deviation 0 (no timing copy)"); h_cov_define(C_EIA_NONZERO, "clock deviation set"); h_cov_define(C_EIA_NEG, "negative clock deviation");
  h_cov_define(C_EIA_NAN, "float member with a NaN word"); h_cov_define(C_HOOK, "params_ replaced inside the call");
  h_scenario_begin(1);
  relax_reserved();
  pf_tables_init();
  for (trial = 0; trial < 800; trial++) {
    PfEnv e;
    PfObj *o;
    V90ParObj *model = (V90ParObj *)calloc(1, sizeof(V90ParObj));
    MCtx *c = (MCtx *)calloc(1, sizeof *c);
    static const int raws[] = { 0, 1, -1, 7, -7, 999, 1000, -1000, 123456, -123456, 2147483647, (int)0x80000000, 4000, 25, 100000 };
    int raw = h_rpct(60) ? raws[h_rmod(sizeof raws / sizeof raws[0])] : (int)h_rnd();
    unsigned i;
    LD cd;
    float cdF;
    int s, ip, fp;
    unsigned hookk = 0;
    V90ParObj *B = NULL, *modelB = NULL, *hookblk = NULL;
    h_cov_hit(C_TRIAL);
    pf_env_new(&e);
    e.par->hwCodecType = 0;
    dsplibs_debug_level = 0;
    o = pf_new(0, &e, 0);
    for (i = 0; i < sizeof k_eia_always / sizeof k_eia_always[0]; i++) { uint32_t w = h_rnd(); if (h_rpct(10)) w = 0x7f800001u | (h_rnd() & 0x7fffffu); memcpy((uint8_t *)e.par + k_eia_always[i].src, &w, 4); w = h_rnd(); memcpy((uint8_t *)e.par + k_eia_always[i].dst, &w, 4); if (is_nan_b(w)) h_cov_hit(C_EIA_NAN); }
    for (i = 0; i < sizeof k_eia_timing / sizeof k_eia_timing[0]; i++) { uint32_t w = h_rnd(); memcpy((uint8_t *)e.par + k_eia_timing[i].src, &w, 4); w = h_rnd(); memcpy((uint8_t *)e.par + k_eia_timing[i].dst, &w, 4); }
    { uint32_t w = h_rnd(); memcpy((uint8_t *)e.par + offsetof(V90ParObj, initialBaudOffset), &w, 4); }
    memcpy(e.mp->unk4c, &raw, 4);
    if (h_rpct(25)) {   /* params_ replaced inside the call: the second block B gets the copies of every group whose block is read after the swap */
      hookk = 1 + h_rmod(3);
      B = (V90ParObj *)h_obj_new(sizeof(V90ParObj));
      for (i = 0; i < sizeof k_eia_always / sizeof k_eia_always[0]; i++) { uint32_t w = h_rnd(); memcpy((uint8_t *)B + k_eia_always[i].src, &w, 4); w = h_rnd(); memcpy((uint8_t *)B + k_eia_always[i].dst, &w, 4); }
      for (i = 0; i < sizeof k_eia_timing / sizeof k_eia_timing[0]; i++) { uint32_t w = h_rnd(); memcpy((uint8_t *)B + k_eia_timing[i].src, &w, 4); w = h_rnd(); memcpy((uint8_t *)B + k_eia_timing[i].dst, &w, 4); }
      { uint32_t w = h_rnd(); memcpy((uint8_t *)B + offsetof(V90ParObj, initialBaudOffset), &w, 4); }
      B->params = e.mp;
      modelB = (V90ParObj *)calloc(1, sizeof(V90ParObj));
      memcpy(modelB, B, sizeof(V90ParObj));
      h_cov_hit(C_HOOK);
    }
    memcpy(model, e.par, sizeof(V90ParObj));
    cd = (LD)raw * (LD)0.001f;
    cdF = rnd_f(cd);
    { V90ParObj *g1 = (hookk == 1) ? modelB : model;     /* the first 28 pairs: the block read right after print 1 */
      for (i = 0; i < sizeof k_eia_always / sizeof k_eia_always[0] - 4; i++) memcpy((uint8_t *)g1 + k_eia_always[i].dst, (uint8_t *)g1 + k_eia_always[i].src, 4); }
    mc_ed(c, "V90PreFilter: setParamEIA6 called\r\n");
    model_split(cd, 10000.0L, &s, &ip, &fp);
    mc_ed(c, "V90PreFilter: prev params ClockDeviation is = %c%d.%04d\r\n", s, ip, fp);
    { V90ParObj *g3 = (hookk && hookk <= 2) ? modelB : model;   /* the block read after print 2 */
    if (cdF != 0.0f) {
      V90ParObj *g2 = (hookk && hookk <= 3) ? modelB : model;     /* the block read after print 3 */
      mc_ed(c, "V90PreFilter: Setting timing parameters (registry)...\r\n");
      memcpy((uint8_t *)g2 + offsetof(V90ParObj, initialBaudOffset), &cdF, 4);
      for (i = 0; i < sizeof k_eia_timing / sizeof k_eia_timing[0]; i++) memcpy((uint8_t *)g2 + k_eia_timing[i].dst, (uint8_t *)g2 + k_eia_timing[i].src, 4);
      g3 = g2;
      h_cov_hit(C_EIA_NONZERO);
    } else h_cov_hit(C_EIA_ZERO);
    for (i = sizeof k_eia_always / sizeof k_eia_always[0] - 4; i < sizeof k_eia_always / sizeof k_eia_always[0]; i++) memcpy((uint8_t *)g3 + k_eia_always[i].dst, (uint8_t *)g3 + k_eia_always[i].src, 4);
    hookblk = g3; }
    if (raw < 0) h_cov_hit(C_EIA_NEG);
    log_begin();
    g_hookp_obj = o; g_hookp_blk = B; g_hookp_k = hookk;
    pf_setparam(o);
    g_hookp_k = 0; g_hookp_obj = NULL;
    mc_check("setParamEia6", c);
    if (B && memcmp(modelB, B, sizeof(V90ParObj))) h_die3("setParamEia6: the second block differs from the model (hook after print %u)", hookk);
    if (memcmp(model, e.par, sizeof(V90ParObj))) {
      for (i = 0; i < sizeof(V90ParObj); i++) if (((uint8_t *)model)[i] != ((uint8_t *)e.par)[i]) break;
      h_die3("setParamEia6: the parameter block differs from the model at mirror offset 0x%x (raw %d)", i, raw);
    }
    (void)hookblk;
    pf_dump("eia", o);
    pf_free(o);
    free(model);
    if (modelB) free(modelB);
    free(c);
    h_trial_end("pf_eia");
  }
}

