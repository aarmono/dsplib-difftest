  unsigned trial;
  h_cov_define(C_TRIAL, "trials"); h_cov_define(C_PR_BYPASS, "bypass (out[0] == 177)"); h_cov_define(C_PR_ST0, "state 0"); h_cov_define(C_PR_ST1, "state 1"); h_cov_define(C_PR_ST2, "state 2");
  h_cov_define(C_PR_ST3, "state 3"); h_cov_define(C_PR_OTHER, "other state value"); h_cov_define(C_PR_N0, "n == 0"); h_cov_define(C_PR_WRAP, "read position wraps");
  h_cov_define(C_PR_TRANS1, "1 -> 2 transition"); h_cov_define(C_PR_TRANS2, "2 -> 3 transition"); h_cov_define(C_PR_TRANS3, "3 -> 0 transition"); h_cov_define(C_PR_MARKER_NAN, "NaN marker (treated as 177)");
  h_scenario_begin(1);
