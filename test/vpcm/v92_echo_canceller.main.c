      EXPECT_EQ("refLoop_", (unsigned)o->refLoop_, (unsigned)nref);
      if (e.par->loopType == 6) h_cov_hit(C_PF_ISEIA_LOOP6); else if (a) h_cov_hit(C_PF_ISEIA_CAP2); else h_cov_hit(C_PF_ISEIA_NO);
