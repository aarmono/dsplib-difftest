static void esc_cat(char *out, size_t cap, const char *s) {
  size_t n = strlen(out);
  for (; *s && n + 6 < cap; s++) {
    if (*s == '\r') { out[n++] = '\\'; out[n++] = 'r'; }
    else if (*s == '\n') { out[n++] = '\\'; out[n++] = 'n'; }
    else out[n++] = *s;
  }
  out[n] = 0;
}
static void snapshot(void) {
  if (g_snap_o) {
    EcObj tmp;
    memcpy(&tmp, g_snap_o, sizeof tmp);
    tmp.params_ = NULL;
    tmp.arma_ = NULL;
    h_dump_obj(0, "snap", &tmp, f_EcObj, NF_EcObj);
  }
}
static void record(char kind, const char *fmt, va_list ap) {
  char buf[600];
  vsnprintf(buf, sizeof buf, fmt, ap);
  if (g_nlog < LOGMAX) { g_log[g_nlog].kind = kind; g_log[g_nlog].text[0] = 0; esc_cat(g_log[g_nlog].text, sizeof g_log[g_nlog].text, buf); }
  h_emit(g_show, "%cprintf %s", kind, g_nlog < LOGMAX ? g_log[g_nlog].text : "(many)");
  g_nlog++;
  snapshot();
  if (g_hookp_k && ++g_hookp_cnt == g_hookp_k && g_hookp_obj) g_hookp_obj->params_ = g_hookp_blk;
}
void edprintf(const char *fmt, ...) {
  va_list ap;
  va_start(ap, fmt);
  record('e', fmt, ap);
  va_end(ap);
  g_nlog_total_e++;
}
int dsplibs_debug_printf(const char *fmt, ...) {
  va_list ap;
  va_start(ap, fmt);
  record('d', fmt, ap);
  va_end(ap);
  g_nlog_total_d++;
  g_nd_in_call++;
  if (g_hook_k && g_nd_in_call == g_hook_k) dsplibs_debug_level = g_hook_level;
  return 0;
}
static void log_begin(void) { g_nlog = 0; g_nd_in_call = 0; g_hookp_cnt = 0; }

