static void ec_map_on(void) { h_log_map_from = (unsigned)sizeof(ArmaObj); h_log_map_to = 0x34; }
/* a geometry for which no block has the size of the ARMA object on x86-64 */
typedef struct { int flen; unsigned nCoef, delay, off, gran, extra, histLen; } EcGeo;
static void ecgeo_pick(EcGeo *g) {
  static const int fl[] = { 4, 8, 12, 16, 20, 24, 28, 32, 40, 48, 64 };
  for (;;) {
    g->flen = h_rpct(25) ? (int)h_rrange(4, 70) : fl[h_rmod(sizeof fl / sizeof fl[0])];
    g->nCoef = (unsigned)g->flen & ~3u;
    g->delay = h_rpct(30) ? h_rmod(10) : h_rmod(300);
    g->gran = 1 + h_rmod(h_rpct(30) ? 3 : 12);
    g->extra = h_rpct(30) ? 0 : h_rmod(40);
    { unsigned a = g->nCoef - 1 + g->delay;
      g->histLen = a + 2 * g->gran + (a / g->gran) * g->gran + g->extra; }
    g->off = h_rmod(g->nCoef / 2 + 2 * g->gran);
    if (g->histLen == 18 || g->histLen == 13) continue;       /* a 72 / 52-byte block would be remapped by h_log_map_from */
    if (g->nCoef / 2 + g->delay + g->off >= g->histLen) continue;
    return;
  }
}
static EcObj *ec_new(V92ParObj *p, const EcGeo *g, int c2) {
  EcObj *o = (EcObj *)h_obj_new(sizeof(EcObj));
  ec_prefill(o);
  if (c2) { H_CTOR_PROBE(o, f_EcObj, NF_EcObj, sizeof(EcObj), ec_c2(o, p, g->gran, g->extra)); }
  else { H_CTOR_PROBE(o, f_EcObj, NF_EcObj, sizeof(EcObj), ec_c1(o, p, g->gran, g->extra)); }
  { ArmaObj *am = (ArmaObj *)o->arma_; put_f(&am->y_, 0); put_f(&am->w_, 0); }   /* the FloatARMA constructor never writes y_ / w_: they would show the heap pattern at an offset that differs on x86-64 */
  return o;
}
static void ec_free(EcObj *o) {
  if (o->coef_ && h_rpct(15)) { sysdep_free(o->coef_); o->coef_ = NULL; h_cov_hit(C_DT_COEF); h_cov_hit(H_COV_DTOR_NULL); }
  if (o->hist_ && h_rpct(15)) { sysdep_free(o->hist_); o->hist_ = NULL; h_cov_hit(C_DT_HIST); h_cov_hit(H_COV_DTOR_NULL); }
  if (o->arma_ && h_rpct(15)) { arma_d1(o->arma_); sysdep_free(o->arma_); o->arma_ = NULL; h_cov_hit(C_DT_ARMA); h_cov_hit(H_COV_DTOR_NULL); }
  if (h_rpct(25)) { h_cov_hit(C_D2); ec_d2(o); } else ec_d1(o);
  { char a[48], b[48], c[48]; h_fmt_ptr(a, o->coef_); h_fmt_ptr(b, o->hist_); h_fmt_ptr(c, o->arma_); h_emit(0, "dtor coef=%s hist=%s arma=%s", a, b, c); }   /* the destructor clears the pointers it frees */
}
static float rf_val(int regime) {   /* a float for betas / decay / coefficients: finite, +-, 0, big, tiny; quiet NaN / inf in regime 1 */
  uint32_t r = h_rmod(100), b;
  float f;
  if (regime == 1 && r < 8) { b = (h_rnd() & 0x80000000u) | 0x7f800000u; return f_from(b); }
  if (regime == 1 && r < 14) { b = (h_rnd() & 0x80000000u) | 0x7fc00000u | (h_rnd() & 0x3fffffu); return f_from(b); }
  if (r < 50) f = (float)((int)h_rrange(-4000, 4000)) / 4096.0f;
  else if (r < 70) f = (float)((int)h_rrange(-100000, 100000)) / 64.0f;
  else if (r < 85) f = (float)((int)h_rrange(-3000, 3000)) / 1000000.0f;
  else if (r < 92) f = (float)((int)h_rrange(-2000000, 2000000)) * 1024.0f;
  else if (r < 96) f = 0.0f;
  else { b = h_rnd() & 0x80000000u; return f_from(b); }
  return f;
}

/* print the model's "float with six decimals" message */
