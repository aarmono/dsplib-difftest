/* the constructor's prediction: the codec type and the prints (level ladder) */
static int model_pf_ctor(MCtx *c, int hw, int codecArg) {
  int codec;
  unsigned lvl;
  if (hw < 0) { codec = codecArg; lvl = c->lvl; }
  else {
    lvl = c->lvl;
    if (lvl > 1) { mc_dbg(c, "V90PreFilter: HardwareCodecType loaded by configuration parameters\r\n"); lvl = c->lvl; }
    codec = ((unsigned)hw <= 15u) ? hw : 0;
  }
  if (codec > 15) {
    if (lvl > 1) {
      mc_dbg(c, "%s", kStars); lvl = c->lvl;
      if (lvl > 1) { mc_dbg(c, "V90PreFilter: External Hardware Codec Index exceeds table length (codec inx = %d, table length = %d)\r\n", codec, 15); lvl = c->lvl;
        if (lvl > 1) { mc_dbg(c, "%s", kStars); lvl = c->lvl; } }
    }
    codec = 0;
  }
  if (lvl > 1) mc_dbg(c, "V90PreFilter: HardwareCodecType: %s\r\n", k_dbname(codec));
  return codec;
}

