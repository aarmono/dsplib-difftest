/*
 * Differential test harness for port chunk P16 (src/vpcm/v92_tx_coding.cpp): V92ConvolutionEncoder (C1 C2 D1 D2 reset makeStateTtransitionTable inverseMap process + the two
 * tables), V92Precoder (C1 C2 D1 D2 reset() reset(V92MappingParams*) setCoefficients process) and V92PreFilter (C1 C2 D1 D2 reset setCoefficients process) of dsplibs.o:
 * 23 functions.
 *
 * ONE C source, no #ifdef, built by test/vpcm/v92_tx_coding.sh against the blob (dsplibs.o; `dsplibs_debug_printf` is the harness' recorder), against the port (-O0 / -O2;
 * the P02 port object supplies FloatFIR / FloatIIR in the port builds) and for x86-64 (the 64-bit run is diffed against the 32-bit BLOB's output = the golden
 * test/golden/vpcm/v92_tx_coding.blob32.out; -mfpmath=387 build variant in test/vpcm/v92_tx_coding.golden64.sh).  The functions are reached through __asm__ labels with the Itanium-mangled names (C1 AND C2
 * / D1 AND D2).  Mirrors and field tables: GENERATED by tools/layout_gen.py (test/vpcm/v92_tx_coding.layout -> test/vpcm/v92_tx_coding_layout.h; FloatFIR / FloatIIR from p02, V92MappingParams from p11).
 *
 * What is compared: return values, every object (field-wise; the heap FloatFIR / FloatIIR sub-objects through the P02 tables with their history blocks), the malloc / free
 * sequence (the sub-objects are logged with their i386 size 0x14: h_log_map_from / h_log_map_to), the store order of the constructors (malloc-time snapshot), the red zones,
 * the debug prints (text and count, with the unsigned `level > 1` test: levels 0, 1, 2, 3 and >= 2^31).
 *
 * INDEPENDENT MODELS (written from the disassembly facts, not from the port): (1) the three trellis tables as bit equations (XOR / AND of the state and input bits; the port
 * and the decompiler use `% 2` sums), whose written entries are compared with the object and whose untouched entries must keep the garbage the object was filled with; the
 * convolutional encoder's process / inverseMap: the label through plain bit masks (the low two bits of a + 2); (2) the precoder search in int64 / long double with its own
 * enumeration of the candidates and an explicit "unordered counts as below" test; the two feedback FIRs are REFERENCE objects (the same FloatFIR class, already verified by P02)
 * that are fed the model's best values in lock step: the precoder's FIR sub-objects must equal them after every call (history blocks, room, taps); (3) the prefilter's data path:
 * the same two reference stages composed as the blob does (FIR, FIR -> temp -> IIR, IIR, or the integer word copy).
 *
 * Scenarios (each its own process): 0 convolutional encoder tables (reset / makeStateTtransitionTable, all modes, constructors / destructors, tables vs bytes of the blob's
 * .data by hash), 1 encoder process / inverseMap (vs the bit model, mode pokes), 2 V92PreFilter, 3 V92Precoder object behaviour (constructors, reset x2, setCoefficients,
 * destructors, prints), 4 V92Precoder::process vs the model.
 *
 * Excluded because the BLOB itself is undefined there: V92ConvolutionEncoder::process with a mode outside 0 .. 2 (it stores and returns the caller's edi / esi), a state outside
 * the written part of the tables (a garbage next state), V92Precoder::process where the first symbol never finds a candidate (the "best" values are uninitialised stack slots),
 * a zero radix / INT_MIN / -1 (#DE), row > 2 (reads past m_), table indices beyond the 4 KB blocks the harness allocates, a filter stage with 1 .. 3 taps that PROCESSES (0
 * taps: the first sample is stored one element past the history, see P02), a processed stage whose setCoefficients was rejected (NULL coefficient pointer).
 */

