int dsplibs_debug_printf(const char *fmt, ...) {
  char buf[400];
  va_list ap;
  size_t n = 0, i;
  va_start(ap, fmt);
  vsnprintf(buf, sizeof buf, fmt, ap);
  va_end(ap);
  if (g_ndbg_call < TXTMAX) {
    for (i = 0; buf[i] && n < sizeof g_dbg_text[0] - 6; i++) {
      if (buf[i] == '\r') { g_dbg_text[g_ndbg_call][n++] = '\\'; g_dbg_text[g_ndbg_call][n++] = 'r'; }
      else if (buf[i] == '\n') { g_dbg_text[g_ndbg_call][n++] = '\\'; g_dbg_text[g_ndbg_call][n++] = 'n'; }
      else g_dbg_text[g_ndbg_call][n++] = buf[i];
    }
    g_dbg_text[g_ndbg_call][n] = 0;
  }
  h_emit(g_show, "dbgprintf %s", g_ndbg_call < TXTMAX ? g_dbg_text[g_ndbg_call] : "(many)");
  g_ndbg_call++;
  g_ndbg_total++;
  return 0;
}
