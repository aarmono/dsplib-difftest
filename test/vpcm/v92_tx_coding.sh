#!/bin/sh
# Builds the differential test of port chunk P16 (V92ConvolutionEncoder, V92Precoder, V92PreFilter: 23 functions + the two tables of the encoder; src/vpcm/v92_tx_coding.cpp, REAL C++
# compiled with -fno-exceptions -fno-rtti) and runs every scenario in its OWN process:
#   blob      test/vpcm/v92_tx_coding.main.c + dsplibs.o (the harness' recorder defines dsplibs_debug_printf)                             (gcc -m32 -no-pie)
#   port -O0  test/vpcm/v92_tx_coding.main.c + g++ -m32 -O0 P16 port object + the P02 port object (FloatFIR / FloatIIR; LINKED WITH gcc: no libstdc++)
#   port -O2  same at -O2
#   port -m64 (NO64=1 skips) the same harness and the port compiled for x86-64 (SSE float default; FP64_FLAGS="-mfpmath=387" for the x87 variant); its output is diffed
#             against the 32-bit BLOB's output (the golden dump)
# The ONE harness source has no #ifdef around the code under test: the functions are reached through __asm__ labels with the mangled names.  A scenario exits 2 if its own
# coverage counters fail, 3 if a harness assumption / independent model is violated; either fails this script.
# Also checked here: the 23 blob symbols + 2 tables (name + binding) are defined by the port object; the tables' FNV hashes equal the hashes of the bytes read from the blob's
# .data by test/vpcm/v92_tx_coding.table_hash.py (a separate script, not the port); the harness mirror structs (generated by tools/layout_gen.py from test/vpcm/v92_tx_coding.layout) equal the port headers'
# real class layouts (layout probes, every binary).
# "MATCH" is only printed if every scenario matched AND reached its branches.
#
# Env: PORT_P16 (port source under test, mutation testing), SCENARIOS, NOO2=1, NO64=1, TPREFIX (output prefix, parallel mutation runs), P16_SEED (alternative input stream),
# GOLDEN_UPDATE=1 (rewrite test/golden/vpcm/v92_tx_coding.blob32.out from this blob run), FP64_FLAGS (extra flags of the x86-64 port build).
#
# Usage: sh test/vpcm/v92_tx_coding.sh   (run from slmodemd/dsplibs-port/)

set -e
cd "$(dirname "$0")/../.."
lp() { case $1 in p02) echo p02;; p11) echo vpcm/v92_cp;; p16) echo vpcm/v92_tx_coding;; esac; }   # layout probe of a chunk: test/$(lp CHUNK)_layout_probe.cpp
. test/blob.sh   # BLOB_O: the blob oracle (dsplibs.o), see test/blob.sh

PORT_P16="${PORT_P16:-src/vpcm/v92_tx_coding.cpp}"
PORT_P02="${PORT_P02:-src/dsp/dsp_float_filters.cpp}"
T="${TPREFIX:-test/.build/vpcm/v92_tx_coding}"
mkdir -p "$(dirname "$T")"
CF="-m32 -Wall -Wextra -Wno-unused-function -Wno-unused-variable -Wno-unused-but-set-variable -O0 -g"
HCF="-m32 -Wall -Wextra -Wno-unused-function -Wno-unused-variable -Wno-unused-but-set-variable -O2 -g"
CXXF="-Wall -Wextra -fno-exceptions -fno-rtti -fno-stack-protector -Isrc"
LD32="-no-pie"
SCENARIOS="${SCENARIOS:-0 1 2 3 4}"
ALLSC="0 1 2 3 4"
case "$T" in /*) R="";; *) R="./";; esac   # absolute TPREFIX (mutation / coverage tools) needs no "./"

SRENAME="-Dsysdep_malloc=stub_env_unused_malloc -Dsysdep_free=stub_env_unused_free -Ddsplibs_debug_printf=stub_env_unused_dbgprintf"
gcc $CF $SRENAME -c test/stub_env.c -o ${T}_stub_env.o
for c in p02 p11 p16; do g++ -m32 $CXXF -O2 -c test/$(lp $c)_layout_probe.cpp -o ${T}_probe_$c.o; done
PROBES="${T}_probe_p02.o ${T}_probe_p11.o ${T}_probe_p16.o"
gcc $HCF -c test/harness/harness.c -o ${T}_harness.o     # the shared harness library (test/harness/, plain C)

gcc $HCF $LD32 -o ${T}_test_blob test/vpcm/v92_tx_coding.main.c ${T}_harness.o ${T}_stub_env.o $PROBES $BLOB_O

# the P02 port object (FloatFIR / FloatIIR) is cached: rebuilt only when its sources are newer (mutation runs build this script hundreds of times)
P02C=test/.build/vpcm/v92_tx_coding_p02cache
p02dep() { [ ! -f "$1" ] || [ "$PORT_P02" -nt "$1" ] || [ src/dsp/dsp_float_filters.h -nt "$1" ] || [ src/core/dsp_cxx.h -nt "$1" ]; }
g++ -m32 $CXXF -O0 -g -c $PORT_P16 -o ${T}_port_o0.o
p02dep ${P02C}_o0.o && g++ -m32 $CXXF -O0 -g -c $PORT_P02 -o ${P02C}_o0.o
gcc $HCF $LD32 -o ${T}_test_port test/vpcm/v92_tx_coding.main.c ${T}_harness.o ${T}_stub_env.o $PROBES ${T}_port_o0.o ${P02C}_o0.o
if [ -z "$NOO2" ]; then
  g++ -m32 $CXXF -O2 -g -c $PORT_P16 -o ${T}_port_o2.o
  p02dep ${P02C}_o2.o && g++ -m32 $CXXF -O2 -g -c $PORT_P02 -o ${P02C}_o2.o
  gcc $HCF $LD32 -o ${T}_test_port_o2 test/vpcm/v92_tx_coding.main.c ${T}_harness.o ${T}_stub_env.o $PROBES ${T}_port_o2.o ${P02C}_o2.o
fi

# symbol check: every symbol of the three classes in the blob exists, with the same name and binding, in the port object
SYMRE='_Z(N|NK)(21V92ConvolutionEncoder|11V92Precoder|12V92PreFilter)'
BLOBSYMS=$(nm --defined-only $BLOB_O | awk '$3 ~ /^_Z(N|NK)(21V92ConvolutionEncoder|11V92Precoder|12V92PreFilter)/ {print $2" "$3}' | sort)
PORTSYMS=$(nm --defined-only ${T}_port_o2.o 2>/dev/null || nm --defined-only ${T}_port_o0.o)
MISSING=$(echo "$BLOBSYMS" | while read b s; do echo "$PORTSYMS" | grep -q " $b $s\$" || echo "$b $s"; done)
NBLOB=$(echo "$BLOBSYMS" | wc -l)
if [ -n "$MISSING" ]; then echo "SYMBOL MISMATCH (blob symbol missing / different binding in the port object):"; echo "$MISSING"; exit 1; fi
echo "SYMBOLS: all $NBLOB blob symbols (name + binding) are defined by the port object"

if [ -z "$NO64" ]; then
  g++ -m64 $CXXF -O2 $FP64_FLAGS -c $PORT_P16 -o ${T}_port64.o
  if [ ! -f ${P02C}_64.o ] || [ "$FP64_FLAGS" != "$(cat ${P02C}_64.flags 2>/dev/null)" ] || p02dep ${P02C}_64.o; then g++ -m64 $CXXF -O2 $FP64_FLAGS -c $PORT_P02 -o ${P02C}_64.o; echo "$FP64_FLAGS" > ${P02C}_64.flags; fi
  P64=""
  for c in p02 p11 p16; do g++ -m64 $CXXF -O2 -c test/$(lp $c)_layout_probe.cpp -o ${T}_probe64_$c.o; P64="$P64 ${T}_probe64_$c.o"; done
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 $SRENAME -c test/stub_env.c -o ${T}_stub_env64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -O2 -c test/harness/harness.c -o ${T}_harness64.o
  gcc -m64 -Wall -Wextra -Wno-unused-function -Wno-unused-variable -Wno-unused-but-set-variable -O2 -no-pie -o ${T}_test_port64 test/vpcm/v92_tx_coding.main.c ${T}_harness64.o ${T}_stub_env64.o $P64 ${T}_port64.o ${P02C}_64.o
fi

# scenarios are independent processes: run them concurrently in groups, then concatenate in order
rm -f ${T}_s*.out
rc=0
pids=""
njobs=0
for i in $SCENARIOS; do
  ( ${R}${T}_test_blob "$i" > ${T}_s$i.blob.out ) & pids="$pids $!"
  ( ${R}${T}_test_port "$i" > ${T}_s$i.port.out ) & pids="$pids $!"
  if [ -z "$NOO2" ]; then ( ${R}${T}_test_port_o2 "$i" > ${T}_s$i.o2.out ) & pids="$pids $!"; fi
  if [ -z "$NO64" ]; then ( ${R}${T}_test_port64 "$i" > ${T}_s$i.p64.out ) & pids="$pids $!"; fi
  njobs=$((njobs + 1))
  if [ $njobs -ge 2 ]; then for p in $pids; do wait $p || rc=1; done; pids=""; njobs=0; fi
done
for p in $pids; do wait $p || rc=1; done
: > ${T}_blob.out; : > ${T}_port.out; : > ${T}_port_o2.out; : > ${T}_port64.out
for i in $SCENARIOS; do
  cat ${T}_s$i.blob.out >> ${T}_blob.out
  cat ${T}_s$i.port.out >> ${T}_port.out
  if [ -z "$NOO2" ]; then cat ${T}_s$i.o2.out >> ${T}_port_o2.out; fi
  if [ -z "$NO64" ]; then cat ${T}_s$i.p64.out >> ${T}_port64.out; fi
done
rm -f ${T}_s*.out
if [ $rc -ne 0 ]; then echo "SCENARIO FAILURE (non-zero exit: coverage, harness assertion / model violation or crash)"; exit 1; fi

diff -u ${T}_blob.out ${T}_port.out
if [ -z "$NOO2" ]; then diff -u ${T}_blob.out ${T}_port_o2.out; fi
if [ -z "$NO64" ]; then diff -u ${T}_blob.out ${T}_port64.out; fi
# the tables of the encoder: the hashes the harness printed equal the hashes of the bytes of the blob's .data (separate script)
for tb in coset subset; do
  W=$(python3 test/vpcm/v92_tx_coding.table_hash.py $tb)
  G=$(grep "^TABLE $tb " ${T}_blob.out | awk '{print $3}')
  if [ -n "$G" ] && [ "$W" != "$G" ]; then echo "TABLE $tb: the hash of the blob bytes is $W, the harness printed $G"; exit 1; fi
  if [ -n "$G" ] && [ -n "$(grep "^TABLE $tb " ${T}_port.out | grep -v " $W\$")" ]; then echo "TABLE $tb of the port differs from the blob's bytes"; exit 1; fi
done
[ -z "$(grep '^TABLE ' ${T}_blob.out)" ] || echo "TABLES: cosetMapping4D and subsetLabelTable of the port equal the bytes of the blob's .data (FNV hashes from test/vpcm/v92_tx_coding.table_hash.py)"
if [ -n "$GOLDEN_UPDATE" ]; then mkdir -p test/golden; cp ${T}_blob.out test/golden/vpcm/v92_tx_coding.blob32.out; echo "golden updated"; fi
if [ -z "$TPREFIX" ] && [ "$SCENARIOS" = "$ALLSC" ] && [ -f test/golden/vpcm/v92_tx_coding.blob32.out ] && [ -z "$P16_SEED" ]; then
  if diff -u test/golden/vpcm/v92_tx_coding.blob32.out ${T}_blob.out; then echo "GOLDEN: the 32-bit blob run equals test/golden/vpcm/v92_tx_coding.blob32.out"
  else echo "STALE GOLDEN: the blob output differs from test/golden/vpcm/v92_tx_coding.blob32.out (GOLDEN_UPDATE=1 rewrites it)"; exit 1; fi
fi
echo "MATCH: P16 C++ port ($([ -z "$NOO2" ] && echo '-O0 and -O2' || echo '-O0')$([ -z "$NO64" ] && echo " + x86-64 [$FP64_FLAGS] vs the 32-bit blob output")) is behaviorally identical to dsplibs.o for this test"
